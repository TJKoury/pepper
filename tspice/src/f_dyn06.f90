!$Procedure F_DYN06 ( Dynamic Frame Test Family 06 )

      SUBROUTINE F_DYN06 ( OK )
      use pepper_inc_zzdyn

! $ Abstract
!
!     Test family to exercise the logic and code in the third
!     subset of dynamic frame routines.  Only mean ecliptic and
!     equinox of date frames are used in these tests.
!
! $ Required_Reading
!
!     None.
!
! $ Keywords
!
!     TEST FAMILY
!
! $ Declarations

      IMPLICIT NONE


      LOGICAL               OK

! $ Brief_I/O
!
!     VARIABLE  I/O  DESCRIPTION
!     --------  ---  --------------------------------------------------
!     OK         O   logical indicating test status.
!
! $ Detailed_Input
!
!     None.
!
! $ Detailed_Output
!
!     OK         is a logical that indicates the test status to the
!                caller.
!
! $ Parameters
!
!     None.
!
! $ Files
!
!     This test family uses the following kernels:
!
!        LSK generated by tstlsk
!        PCK generated by t_pck08
!        SPK generated by tstspk
!
! $ Exceptions
!
!     This routine does not generate any errors. Routines in its
!     call tree may generate errors that are either intentional and
!     trapped or unintentional and need reporting.  The test family
!     utilities manage this.
!
! $ Particulars
!
!     As the set of mean-of-date frames grows, this routine should
!     be updated to exercise each supported frame model.
!
!     Tests done here include, but are not necessarily limited to:
!
!        - Test state transformation from SXFORM:
!
!            o Make sure upper left and lower right blocks match.
!            o Test determinant of rotation blocks
!            o Test norms of rows and columns
!
!        - Compare SXFORM and PXFORM results.
!
!        - Compare SXFORM derivative to discrete derivative
!          computed using PXFORM.  Check absolute and relative
!          derivative errors.
!
!        - Compute state transformation via a local computation.
!          Compare rotation portion of transformation matrix
!          from SXFORM to locally computed result.
!
!        - Make sure that when rotation state is inertial, when a
!          matrix mapping from base frame to an inertial frame is
!          right-multiplied by matrix produced by SXFORM, resulting
!          matrix has zero derivative.
!
!        - Make sure that when rotation state is frozen, when a
!          matrix produced by SXFORM has zero derivative.
!
!
!     Tests are done using a variety of frame definitions.  Each
!     combination of base frame and rotation state is used, where
!     the types of base frames include:
!
!        - inertial
!        - rotating non-dynamic
!        - dynamic
!
! $ Examples
!
!     None.
!
! $ Restrictions
!
!     None.
!
! $ Author_and_Institution
!
!     N.J. Bachman     (JPL)
!
! $ Literature_References
!
!     None.
!
! $ Version
!
!-    TSPICE Version 1.1.0, 12-JAN-2005 (NJB)
!
!        Parameters KWX, KWY, KWZ were renamed to KVX, KVY, KVZ.
!
!-    TSPICE Version 1.0.0, 10-JAN-2005 (NJB)
!
!
!-&

!
!     SPICELIB functions
!
      DOUBLE PRECISION      VNORMG

      INTEGER               PRODAI
      INTEGER               RTRIM

      LOGICAL               EQSTR

!
!     Local Parameters
!
      CHARACTER*(*)         PCK
      PARAMETER           ( PCK    = 'test_dyn.tpc' )

      CHARACTER*(*)         SPK
      PARAMETER           ( SPK    = 'test_dyn.bsp' )

      CHARACTER*(*)         FRZTOK
      PARAMETER           ( FRZTOK = '@2010-JAN-1/00:00:00' )


!
!     Tolerance levels for various tests.
!
      DOUBLE PRECISION      DM19
      PARAMETER           ( DM19   = 1.D-19 )

      DOUBLE PRECISION      DM14
      PARAMETER           ( DM14   = 1.D-14 )

      DOUBLE PRECISION      DM12
      PARAMETER           ( DM12   = 1.D-12 )

      DOUBLE PRECISION      DM5
      PARAMETER           ( DM5    = 1.D-5  )



      INTEGER               NAMLEN
      PARAMETER           ( NAMLEN = 32 )

      INTEGER               LNSIZE
      PARAMETER           ( LNSIZE = 80 )

      INTEGER               MAXDEF
      PARAMETER           ( MAXDEF = 50 )

      INTEGER               TIMLEN
      PARAMETER           ( TIMLEN = 50 )

      INTEGER               MSGLEN
      PARAMETER           ( MSGLEN = 240 )

!
!     Parameters controlling frame definitions:
!

!
!     The dimensions of the test parameter space are:
!
!         1) Rotation state
!         2) Base frame
!         3) Frame center
!
!     Number of dimensions of the test parameter space:
!
      INTEGER               NDIMS
      PARAMETER           ( NDIMS  = 3 )

!
!     Number of rotation states:
!
      INTEGER               NRSTAT
      PARAMETER           ( NRSTAT = 3 )

!
!     The constant RSTIDX refers to the ordinal position of the
!     dimension corresponding to the rotation state in the parameter
!     space.
!
      INTEGER               RSTIDX
      PARAMETER           ( RSTIDX = 1 )

!
!     Number of base frame cases:
!
      INTEGER               NBASEF
      PARAMETER           ( NBASEF = 3 )

!
!     The constant BFRIDX refers to the ordinal position of the
!     dimension corresponding to base frame in the parameter
!     space.
!
      INTEGER               BFRIDX
      PARAMETER           ( BFRIDX = RSTIDX + 1 )

!
!     Number of frame center cases:
!
      INTEGER               NCENTR
      PARAMETER           ( NCENTR = 1 )

      INTEGER               CTRIDX
      PARAMETER           ( CTRIDX = BFRIDX + 1 )


!
!     Local Variables
!
      CHARACTER*(NAMLEN)    BASEFR ( NBASEF )
      CHARACTER*(NAMLEN)    BFRAME
      CHARACTER*(MSGLEN)    CASMSG
      CHARACTER*(LNSIZE)    DEFTXT ( MAXDEF )
      CHARACTER*(NAMLEN)    FRNAME
      CHARACTER*(TIMLEN)    FRZEPC
      CHARACTER*(LNSIZE)    KEYWRD
      CHARACTER*(LNSIZE)    RSTATE ( NRSTAT )
      CHARACTER*(LNSIZE)    RSTSTR

!
!     We'll use the kernel variable name "stem"
!
!        FRAME_<ID code>_
!
!     The length declared below (18) is the length of such a string
!     where the ID code contains 11 digits.
!
      CHARACTER*(18)        FRSTEM

      DOUBLE PRECISION      DELTA
      DOUBLE PRECISION      DETERR
      DOUBLE PRECISION      DMAG
      DOUBLE PRECISION      DMOB
      DOUBLE PRECISION      DRDIFF ( 3, 3 )
      DOUBLE PRECISION      DRLERR
      DOUBLE PRECISION      DRV2   ( 3, 3 )
      DOUBLE PRECISION      DRVBLK ( 3, 3 )
      DOUBLE PRECISION      DRVERR
      DOUBLE PRECISION      ECLEQN ( 3, 3 )
      DOUBLE PRECISION      ET
      DOUBLE PRECISION      MOB
      DOUBLE PRECISION      NRMERR
      DOUBLE PRECISION      OBLMAT ( 3, 3 )
      DOUBLE PRECISION      PRECM  ( 3, 3 )
      DOUBLE PRECISION      R      ( 3, 3 )
      DOUBLE PRECISION      R2     ( 3, 3 )
      DOUBLE PRECISION      RJ2B   ( 3, 3 )
      DOUBLE PRECISION      RMINUS ( 3, 3 )
      DOUBLE PRECISION      RPLUS  ( 3, 3 )
      DOUBLE PRECISION      T
      DOUBLE PRECISION      T0
      DOUBLE PRECISION      TOL
      DOUBLE PRECISION      XFB2J  ( 6, 6 )
      DOUBLE PRECISION      XFF2J  ( 6, 6 )
      DOUBLE PRECISION      XFORM  ( 6, 6 )
      DOUBLE PRECISION      ZR     ( 3, 3 )

      INTEGER               CASE
      INTEGER               COORDS ( NDIMS  )
      INTEGER               CENTER
      INTEGER               CTRCDE ( NCENTR )
      INTEGER               DIMS   ( NDIMS  )
      INTEGER               DX
      INTEGER               FRCODE
      INTEGER               HANDLE
      INTEGER               I
      INTEGER               J
      INTEGER               NCART

!
!     This variable is used for debugging.
!
      LOGICAL               GO

!
!     Saved variables
!
      SAVE                  BASEFR
      SAVE                  CTRCDE
      SAVE                  RSTATE
      SAVE                  ZR

!
!     Initial values
!
      DATA                  ZR                                       / &
                            9 * 0.D0                                 /

!
!     Rotation states:
!
      DATA                  RSTATE                                   / &
                            KVROTG, &
                            KVINRT, &
                            'FROZEN'                                 /

!
!     We use both inertial, PCK-based, and dynamic base frames.
!
      DATA                  BASEFR                                    / &
                            'J2000', &
                            'IAU_MARS', &
                            'GSE'                                     /

!
!     ID codes of frame centers:
!
      DATA                  CTRCDE                                    / &
                            399                                       /


!
!     DIMS defines the dimensions of the cartesian product of the
!     input parameters.  The cardinality of the set comprising the
!     Nth "factor" of the cartesian product is DIMS(N).  The cardinality
!     of the product itself is the product of the elements of DIMS.
!
      DATA                  DIMS                                      / &
                            NRSTAT, &
                            NBASEF, &
                            NCENTR                                    /


!
!     Open the test family.
!
      CALL TOPEN ( 'F_DYN06' )


!
! --- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Create test inputs for comprehensive true-of' // &
                   '-date test.'                                  )

!
!     Create and load kernels.
!
      CALL TSTLSK
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL TSTSPK  ( SPK, .TRUE., HANDLE  )
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL T_PCK08 ( PCK, .TRUE., .FALSE. )
      CALL CHCKXC  ( .FALSE., ' ', OK )

!
!     Parse the constant string used for the freeze epoch.
!     First remove the '@' and '/' characters from the string.
!     Add TDB token.
!
      CALL CMPRSS ( '@',     0,  FRZTOK, FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL REPLCH ( FRZEPC, '/', ' ',    FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL SUFFIX ( 'TDB',   1,          FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL STR2ET ( FRZEPC, T0 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Define the GSE frame.
!
      DEFTXT(1) = &
      'FRAME_GSE                        =  2399001'
      DEFTXT(2) = &
      'FRAME_2399001_NAME               = ''GSE'''
      DEFTXT(3) = &
      'FRAME_2399001_CLASS              =  5'
      DEFTXT(4) = &
      'FRAME_2399001_CLASS_ID           =  2399001'
      DEFTXT(5) = &
      'FRAME_2399001_CENTER             =  399'
      DEFTXT(6) = &
      'FRAME_2399001_RELATIVE           = ''J2000'''
      DEFTXT(7) = &
      'FRAME_2399001_'//KWSTYL//'       = '''// KVPARM //''''
      DEFTXT(8) = &
      'FRAME_2399001_'//KWFFAM//'             = '''// KV2VEC //''''
      DEFTXT(9) = &
      'FRAME_2399001_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      DEFTXT(10) = &
      'FRAME_2399001_'//KWPRI//KWVCDF//'       = '''//KVPOSV//''''
      DEFTXT(11) = &
      'FRAME_2399001_'//KWPRI//KWVOBS//'       = ''EARTH'''
      DEFTXT(12) = &
      'FRAME_2399001_'//KWPRI//KWVTRG//'         = ''SUN'''
      DEFTXT(13) = &
      'FRAME_2399001_'//KWPRI//KWVABC//'         = ''NONE'''
      DEFTXT(14) = &
      'FRAME_2399001_'//KWSEC//KWVAXI//'       = ''-'//KVY//''''
      DEFTXT(15) = &
      'FRAME_2399001_'//KWSEC//KWVCDF//'       =  '''// KVVELV //''''
      DEFTXT(16) = &
      'FRAME_2399001_'//KWSEC//KWVOBS//'       = ''SUN'''
      DEFTXT(17) = &
      'FRAME_2399001_'//KWSEC//KWVTRG//'       = ''EARTH'''
      DEFTXT(18) = &
      'FRAME_2399001_'//KWSEC//KWVABC//'         = ''NONE'''
      DEFTXT(19) = &
      'FRAME_2399001_'//KWSEC//KWVFRM//'          = ''J2000'''
      DEFTXT(20) = &
      'FRAME_2399001_'//KWRSTA//'       =  '''// KVROTG //''''

!
!     Load the GSE frame definition.
!
      CALL LMPOOL ( DEFTXT, 20 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     We use MULTIX and the array DIMS to define a mapping that allows
!     us to map a test case number to a set of input parameters.
!
!     Compute the number of test cases in the input cartesian product
!     space.
!
      NCART = PRODAI ( DIMS, NDIMS )


      DO CASE = 1, NCART
!
!        Find the multi-dimensional coordinates of the current
!        case in the cartesian product of the test input sets.
!
         CALL MULTIX ( 1, NDIMS, DIMS, CASE, COORDS )
         CALL CHCKXC ( .FALSE., ' ', OK )

!
!        Set the rotation state.
!
         RSTSTR = RSTATE ( COORDS(RSTIDX) )

!
!        Set the base frame.
!
         BFRAME = BASEFR ( COORDS(BFRIDX) )

!
!        Set the frame center.
!
         CENTER = CTRCDE ( COORDS(CTRIDX) )

!
!        For this test family, there are no cases that must be
!        rejected, so the "GO" flag is always .TRUE.  We keep
!        this currently unused flag to simplify maintenance of
!        this code.
!
         GO = .TRUE.

         IF ( GO ) THEN
!
!           We're ready to create a frame definition.
!
!
!           Create a text buffer containing a frame definition that
!           uses the current frame definition
!
!
!           First comes the frame name-to-frame code assignment.
!
            FRNAME     = 'MEAN_ECL_OF_DATE'
            FRCODE     = -2000000000

            DEFTXT(1)  = 'FRAME_#    = #'
            CALL REPMC  ( DEFTXT(1), '#', FRNAME, DEFTXT(1) )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI  ( DEFTXT(1), '#', FRCODE, DEFTXT(1) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           We'll use the kernel variable name "stem"
!
!              FRAME_<ID code>_
!
!           repeatedly, so instead of making thousands of REPMI
!           calls, we just create this stem here.
!
            CALL REPMI ( 'FRAME_#_', '#', FRCODE, FRSTEM )
            CALL CHCKXC ( .FALSE., ' ', OK )


            DEFTXT(2)  =  FRSTEM // 'NAME             = ''#'''
            CALL REPMC  ( DEFTXT(2), '#', FRNAME, DEFTXT(2) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Frame class and class ID come next.
!
            DEFTXT(3)   =  FRSTEM // 'CLASS            = 5'

            DEFTXT(4)   =  FRSTEM // 'CLASS_ID         = #'
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI   ( DEFTXT(4), '#', FRCODE, DEFTXT(4) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           The frame center must be specified via a code.
!
            DEFTXT(5)   =  FRSTEM // 'CENTER           = #'

            CALL REPMI  ( DEFTXT(5), '#',  CENTER, DEFTXT(5) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the base frame.
!
            DEFTXT(6)   =  FRSTEM // 'RELATIVE         = ''#'''
            CALL REPMC  ( DEFTXT(6), '#', BFRAME, DEFTXT(6) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the frame definition style and family.
!
            DEFTXT(7)  = &
               FRSTEM // KWSTYL //'    = ''' // KVPARM // ''''
            CALL REPMI  ( DEFTXT(7), '#', FRCODE,    DEFTXT(7) )
            CALL CHCKXC ( .FALSE., ' ', OK )

            DEFTXT(8)  =  FRSTEM // KWFFAM //'           = '''// &
                          KVMECL //''''
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI  ( DEFTXT(8), '#', FRCODE,    DEFTXT(8) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the frame's precession model.
!
            DEFTXT(9)   =  FRSTEM // KWPRCM // ' = ''' &
                                  // KVM001 // ''''

!
!           Set the frame's obliquity model.
!
            DEFTXT(10)  =  FRSTEM // KWOBQM // ' = ''' &
                                  // KVM003 // ''''

!
!           Set the frame's rotation state or freeze epoch.
!
!
!           Set the frame's rotation state or freeze epoch.
!
            IF ( RSTSTR .EQ. 'FROZEN' ) THEN

               DEFTXT(11)  =  FRSTEM // KWFREZ //'     = ' &
                                     // FRZTOK
            ELSE

               DEFTXT(11)  =  FRSTEM // KWRSTA // '     = ''' &
                                     // RSTSTR(:RTRIM(RSTSTR)) // ''''

            END IF

            DX = 11


!
!           Enter the frame definition into the kernel pool.
!
            CALL LMPOOL ( DEFTXT, DX )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Here's where the testing begins.
!
!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'SXFORM/PXFORM test number #A.  Test ' // &
                          'results against those from PXFORM.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )

!
!           Pick a time value.
!
            ET = 1.D6 * ( CASE - NCART/2 )

            CALL SXFORM ( FRNAME, BFRAME, ET, XFORM )
            CALL CHCKXC ( .FALSE., ' ', OK )

            CALL PXFORM ( FRNAME, BFRAME, ET, R )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Extract the derivative block from XFORM into DRVBLK.
!           We'll use this block later; we're extracting it here
!           to keep this code close to the associated SXFORM call.
!
            DO I = 1, 3
               DO J = 1, 3
                  DRVBLK(J,I) = XFORM(J+3,I)
               END DO
            END DO

            DMAG = VNORMG( DRVBLK, 9 )

!
!           Extract the rotation block from XFORM into R2.
!
            DO I = 1, 3
               DO J = 1, 3
                  R2(J,I) = XFORM(J,I)
               END DO
            END DO

            CALL CHCKAD ( 'SXFORM vs PXFORM', R2, '~', R, 9, DM12, OK )



!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'SXFORM test number #B.  Test derivative ' // &
                          'block.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )

!
!           Perform "sanity checks" on the returned matrix. Make sure
!           the diagonal blocks are identical rotations. Make sure the
!           upper right block is a zero matrix.
!
            DELTA = 1.0D0

            CALL PXFORM ( FRNAME, BFRAME, ET-DELTA, RMINUS )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL PXFORM ( FRNAME, BFRAME, ET+DELTA, RPLUS  )
            CALL CHCKXC ( .FALSE., ' ', OK )

            CALL T_XFORM ( XFORM,  RMINUS, RPLUS,  DELTA, &
                           NRMERR, DETERR, DRVERR, DRLERR, DRDIFF )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Check the error measurements we've made.  First
!           up is the determinant error.
!
            TOL = DM14
            CALL CHCKSD ( 'DETERR', DETERR, '~', 0.D0, TOL, OK )

!
!           Check norms of rows and columns in the rotation
!           blocks.
!
            CALL CHCKSD ( 'NRMERR', NRMERR, '~', 0.D0, TOL, OK )

!
!           If the frame is considered to be rotating, compute a
!           discrete derivative and compare to the lower left block.
!
            IF (  EQSTR( RSTSTR, 'ROTATING' )  ) THEN

!
!              Check the derivative absolute error.
!
               TOL = DM12
               CALL CHCKSD ( 'DRVERR', DRVERR, '~', 0.D0, TOL, OK )

!
!              Check the derivative relative error.
!
               TOL = DM5
               CALL CHCKSD ( 'DRLERR', DRLERR, '~', 0.D0, TOL, OK )

            ELSE IF (  EQSTR( RSTSTR, 'INERTIAL' )  ) THEN
!
!              The frame is supposed to be inertial, so the
!              state transformation mapping from this frame to
!              J2000 ideally should have a zero derivative block.
!              See whether the derivative block of the latter
!              transformation is close to zero.
!
               CALL SXFORM ( BFRAME, 'J2000', ET,      XFB2J )
               CALL CHCKXC ( .FALSE., ' ', OK )
               CALL MXMG   ( XFB2J,  XFORM,   6, 6, 6, XFF2J )

               DO I = 1, 3
                  DO J = 1, 3
                     DRV2(J,I) = XFF2J(J+3,I)
                  END DO
               END DO

               CALL CHCKAD ( 'Derivative block', &
                              DRV2, '~', ZR, 9, DM19, OK )

            ELSE
!
!              The frozen case is quite simple:  the derivative
!              with respect to the base frame is zero.
!
               CALL CHCKAD ( 'Derivative block', &
                              DRVBLK, '=', ZR, 9, 0.D0, OK )
            END IF

!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'PXFORM test number #C. Construct '      // &
                          'position transformation locally; ' // &
                          'compare to PXFORM output.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )

!
!           Pick a time value.  If the rotation state is
!           frozen, use the "freeze" value.
!
            IF (  EQSTR ( RSTSTR, 'FROZEN' )  ) THEN
               T = T0
            ELSE
               T = ET
            END IF

!
!           Get precession matrix.
!
            CALL ZZEPRCSS ( T, PRECM )

!
!           Get mean obliquity.
!
            CALL ZZMOBLIQ ( T, MOB, DMOB )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Form obliquity transformation matrix.
!
            CALL ROTATE ( MOB, 1, OBLMAT )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Form the J2000 to mean-ECL-of-date matrix.
!
            CALL MXM ( OBLMAT, PRECM, ECLEQN )

!
!           Now form the transformation from the mean-ECL-of-date
!           frame to the base frame.
!
            CALL PXFORM ( 'J2000', BFRAME, T, RJ2B )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL MXMT   ( RJ2B,    ECLEQN,    R2   )

!
!           Compare to the rotation from the true-of-date frame to
!           the base frame returned by PXFORM.
!
            CALL PXFORM ( FRNAME, BFRAME, ET, R )
            CALL CHCKXC ( .FALSE., ' ', OK )

            TOL = DM14
            CALL CHCKAD ( 'R2', R2, '~', R, 9, TOL, OK )

         END IF

!
!        Expunge the optional keywords from the kernel pool.
!
         IF ( RSTSTR .EQ. 'FROZEN' ) THEN
            KEYWRD  =  FRSTEM // KWFREZ
         ELSE
            KEYWRD  =  FRSTEM // KWRSTA
         END IF

         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC ( .FALSE., ' ', OK )

      END DO

!
!     Clean up the SPK file.
!
      CALL SPKUEF ( HANDLE )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL DELFIL ( SPK    )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Close out the test family.
!
      CALL T_SUCCESS ( OK )
      RETURN

      END
