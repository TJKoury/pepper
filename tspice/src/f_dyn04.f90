!        "C" cases on the PC-LINUX_C and PC-CYGWIN_C platforms.
!
!-    TSPICE Version 1.2.0, 05-AUG-2005 (NJB)
!
!        Frame centers are now specified by name in the main loop.
!        This is a quick way of exercising new logic in FRAMEX.
!
!        Parameters KWX, KWY, KWZ were renamed to KVX, KVY, KVZ.
!
!-    TSPICE Version 1.0.0, 10-JAN-2005 (NJB)
!
!
!-&

!
!     SPICELIB functions
!
      DOUBLE PRECISION      JYEAR
      DOUBLE PRECISION      VNORMG

      INTEGER               PRODAI
      INTEGER               RTRIM

      LOGICAL               EQSTR

!
!     Local Parameters
!
      CHARACTER*(*)         PCK
      PARAMETER           ( PCK    = 'test_dyn.tpc' )

      CHARACTER*(*)         SPK
      PARAMETER           ( SPK    = 'test_dyn.bsp' )

      CHARACTER*(*)         FRZTOK
      PARAMETER           ( FRZTOK = '@2010-JAN-1/00:00:00' )

!
!     Tolerance levels for various tests.
!
      DOUBLE PRECISION      DM19
      PARAMETER           ( DM19   = 1.D-19 )

      DOUBLE PRECISION      DM16
      PARAMETER           ( DM16   = 1.D-16 )

      DOUBLE PRECISION      DM14
      PARAMETER           ( DM14   = 1.D-14 )

      DOUBLE PRECISION      DM12
      PARAMETER           ( DM12   = 1.D-12 )

      DOUBLE PRECISION      DM11
      PARAMETER           ( DM11   = 1.D-11 )

      DOUBLE PRECISION      DM9
      PARAMETER           ( DM9    = 1.D-9 )

      DOUBLE PRECISION      DM6
      PARAMETER           ( DM6    = 1.D-6  )

      DOUBLE PRECISION      DM4
      PARAMETER           ( DM4    = 1.D-4  )


      INTEGER               NAMLEN
      PARAMETER           ( NAMLEN = 32 )

      INTEGER               LNSIZE
      PARAMETER           ( LNSIZE = 80 )

      INTEGER               MAXDEF
      PARAMETER           ( MAXDEF = 50 )

      INTEGER               MAXTOK
      PARAMETER           ( MAXTOK = 7 )

      INTEGER               TIMLEN
      PARAMETER           ( TIMLEN = 50 )

      INTEGER               MSGLEN
      PARAMETER           ( MSGLEN = 240 )

!
!     Parameters controlling frame definitions:
!

!
!     The dimensions of the test parameter space are:
!
!         1) Coefficient set
!         2) Axis sequence
!         3) Units
!         4) Epoch
!         5) Base frame
!         6) Center
!         7) Rotation state
!
!     Number of dimensions of the test parameter space:
!
      INTEGER               NDIMS
      PARAMETER           ( NDIMS  = 7 )

!
!     Number of coefficient sets:
!
      INTEGER               NCOSET
      PARAMETER           ( NCOSET = 3 )

!
!     The constant COFIDX refers to the ordinal position of the
!     dimension corresponding to the coefficient set in the parameter
!     space.
!
      INTEGER               COFIDX
      PARAMETER           ( COFIDX = 1 )

!
!     Index of coefficient set for Mars test case:
!
      INTEGER               MCOIDX
      PARAMETER           ( MCOIDX = 3 )

!
!     Number of axis sequences:
!
      INTEGER               NSEQ
      PARAMETER           ( NSEQ   = 2 )

      INTEGER               SEQIDX
      PARAMETER           ( SEQIDX  = COFIDX + 1 )

!
!     Index of axis sequence for Mars test case:
!
      INTEGER               MSQIDX
      PARAMETER           ( MSQIDX = 1 )

!
!     Number of unit selections:
!
      INTEGER               NUNITS
      PARAMETER           ( NUNITS = 2 )

      INTEGER               UNTIDX
      PARAMETER           ( UNTIDX = SEQIDX + 1 )

!
!     Number of epoch selections:
!
      INTEGER               NEPOCS
      PARAMETER           ( NEPOCS = 2 )

      INTEGER               EPCIDX
      PARAMETER           ( EPCIDX = UNTIDX + 1 )

!
!     Number of base frame cases:
!
      INTEGER               NBASEF
      PARAMETER           ( NBASEF = 3 )

!
!     The constant BFRIDX refers to the ordinal position of the
!     dimension corresponding to base frame in the parameter
!     space.
!
      INTEGER               BFRIDX
      PARAMETER           ( BFRIDX = EPCIDX + 1 )

!
!     Number of frame center cases:
!
      INTEGER               NCENTR
      PARAMETER           ( NCENTR = 2 )

      INTEGER               CTRIDX
      PARAMETER           ( CTRIDX = BFRIDX + 1 )

!
!     Number of rotation states:
!
      INTEGER               NRSTAT
      PARAMETER           ( NRSTAT = 3 )

!
!     The constant RSTIDX refers to the ordinal position of the
!     dimension corresponding to the rotation state in the parameter
!     space.
!
      INTEGER               RSTIDX
      PARAMETER           ( RSTIDX = CTRIDX + 1 )

!
!     Local Variables
!
      CHARACTER*(LNSIZE)    ANGCOF ( 3 )
      CHARACTER*(LNSIZE)    AXESTR
      CHARACTER*(NAMLEN)    BASEFR ( NBASEF )
      CHARACTER*(NAMLEN)    BFRAME
      CHARACTER*(MSGLEN)    CASMSG
      CHARACTER*(LNSIZE)    COFSTR ( 3, NCOSET )
      CHARACTER*(NAMLEN)    CTRNAM
      CHARACTER*(LNSIZE)    DEFTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    EPCSTR ( NEPOCS )
      CHARACTER*(LNSIZE)    EPOCH
      CHARACTER*(TIMLEN)    FRZEPC
      CHARACTER*(NAMLEN)    FRNAME
      CHARACTER*(LNSIZE)    INUNIT
      CHARACTER*(LNSIZE)    KEYWRD
      CHARACTER*(LNSIZE)    RSTATE ( NRSTAT )
      CHARACTER*(NAMLEN)    RSTSTR
      CHARACTER*(LNSIZE)    TIMSTR
      CHARACTER*(LNSIZE)    TOKENS ( MAXTOK )
      CHARACTER*(LNSIZE)    UNITS  ( NUNITS )
      CHARACTER*(LNSIZE)    UNTSTR

!
!     We'll use the kernel variable name "stem"
!
!        FRAME_<ID code>_
!
!     The length declared below (18) is the length of such a string
!     where the ID code contains 11 digits.
!
      CHARACTER*(18)        FRSTEM

      DOUBLE PRECISION      COEFFS ( 0: MAXTOK-2 )
      DOUBLE PRECISION      DELTA
      DOUBLE PRECISION      DETERR
      DOUBLE PRECISION      DMAG
      DOUBLE PRECISION      DP
      DOUBLE PRECISION      DRDIFF ( 3, 3 )
      DOUBLE PRECISION      DRLERR
      DOUBLE PRECISION      DRV2   ( 3, 3 )
      DOUBLE PRECISION      DRVBLK ( 3, 3 )
      DOUBLE PRECISION      DRVERR
      DOUBLE PRECISION      ET
      DOUBLE PRECISION      EULANG ( 6 )
      DOUBLE PRECISION      NRMERR
      DOUBLE PRECISION      P
      DOUBLE PRECISION      R      ( 3, 3 )
      DOUBLE PRECISION      R2     ( 3, 3 )
      DOUBLE PRECISION      REFEPC
      DOUBLE PRECISION      RMINUS ( 3, 3 )
      DOUBLE PRECISION      RPLUS  ( 3, 3 )
      DOUBLE PRECISION      T
      DOUBLE PRECISION      T0
      DOUBLE PRECISION      TIPM   ( 3, 3 )
      DOUBLE PRECISION      TOL
      DOUBLE PRECISION      TSIPM  ( 6, 6 )
      DOUBLE PRECISION      XF2    ( 6, 6 )
      DOUBLE PRECISION      XFB2J  ( 6, 6 )
      DOUBLE PRECISION      XFF2J  ( 6, 6 )
      DOUBLE PRECISION      XFORM  ( 6, 6 )
      DOUBLE PRECISION      ZR     ( 3, 3 )


      INTEGER               AXES   ( 3 )
      INTEGER               AXESEQ ( 3, NSEQ )
      INTEGER               CASE
      INTEGER               COORDS ( NDIMS  )
      INTEGER               CENTER
      INTEGER               CTRCDE ( NCENTR )
      INTEGER               DIMS   ( NDIMS  )
      INTEGER               DX
      INTEGER               FRCODE
      INTEGER               HANDLE
      INTEGER               I
      INTEGER               J
      INTEGER               N
      INTEGER               NCART

      LOGICAL               FOUND
      LOGICAL               ISMARS
      LOGICAL               GO

!
!     Saved variables
!
      SAVE                  AXESEQ
      SAVE                  BASEFR
      SAVE                  COFSTR
      SAVE                  CTRCDE
      SAVE                  DIMS
      SAVE                  EPCSTR
      SAVE                  RSTATE
      SAVE                  UNITS
      SAVE                  ZR

!
!     Initial values
!


!
!     Euler angle axis sequences:
!
      DATA                  AXESEQ                                    / &
                            3, 1, 3, &
                            2, 3, 1                                   /

!
!     We use both inertial, PCK-based, and dynamic base frames.
!
      DATA                  BASEFR                                    / &
                            'J2000', &
                            'IAU_MARS', &
                            'GSE'                                     /

!
!     Polynomial coefficient sets:
!
!     The last set is based on the coefficient for Mars from
!     pck00008.tpc.  That PCK contains the assignments
!
!        BODY499_POLE_RA          = (  317.68143   -0.1061      0.  )
!        BODY499_POLE_DEC         = (   52.88650   -0.0609      0.  )
!        BODY499_PM               = (  176.630    350.89198226  0.  )
!
!     The angles shown here are obtained from those angles via
!     the transformations
!
!        Angle 1 is -Pi/2 - RA, mapped into the range [0, 360).
!        Angle 2 is -Pi/2 + Dec.
!        Angle 3 is -PM.
!
!     Units have been changed as well:
!
!        RA/Dec terms in the PCK are in degrees and degrees/century;
!        the rates here have been converted to degrees/sec. Prime
!        meridian terms in the PCK are in degrees and degrees/day; the
!        rate here has been converted to degrees/sec.
!
!
      DATA                  COFSTR                                    / &
                            '( 1           2E-8        3E-13 )', &
                            '( 10          2E-7        3E-12 )', &
                            '( 100         2E-6        3E-11 )', &
                            '( 2                             )', &
                            '( 4           5E-7              )', &
                            '( 6           7E-7        8E-12 )', &
                            '(  -47.68143  0.33621061170684714E-10 )', &
                            '(  -37.1135  -0.19298045478743630E-10 )', &
                            '( -176.630   -0.40612497946759260E-02 )'  /

!
!     ID codes of frame centers:
!
      DATA                  CTRCDE                                    / &
                            399, &
                            499                                       /

!
!     Reference epochs for polynomial definitions:
!
      DATA                  EPCSTR                                    / &
                            '@2000-JAN-1/12:00', &
                            '@2001-JAN-1/12:00'                       /

!
!     Angular units:
!
      DATA                  UNITS                                     / &
                            '''DEGREES''', &
                            '''RADIANS'''                             /


!
!     Rotation states:
!
      DATA                  RSTATE                                    / &
                            KVROTG, &
                            KVINRT, &
                            'FROZEN'                                  /

!
!     DIMS defines the dimensions of the cartesian product of the
!     input parameters.  The cardinality of the set comprising the
!     Nth "factor" of the cartesian product is DIMS(N).  The cardinality
!     of the product itself is the product of the elements of DIMS.
!
      DATA                  DIMS                                      / &
                            NCOSET, &
                            NSEQ, &
                            NUNITS, &
                            NEPOCS, &
                            NBASEF, &
                            NCENTR, &
                            NRSTAT                                    /

!
!     Initial values
!
      DATA                  ZR                                       / &
                            9 * 0.D0                                 /

!
!     Open the test family.
!
      CALL TOPEN ( 'F_DYN04' )


!
! --- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Create test inputs for comprehensive Euler ' // &
                   'frame test.'                                    )

!
!     Create and load kernels.
!
      CALL TSTLSK
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL TSTSPK  ( SPK, .TRUE., HANDLE  )
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL T_PCK08 ( PCK, .TRUE., .FALSE. )
      CALL CHCKXC  ( .FALSE., ' ', OK )

!
!     Parse the constant string used for the freeze epoch.
!     First remove the '@' and '/' characters from the string.
!     Add TDB token.
!
      CALL CMPRSS ( '@',     0,  FRZTOK, FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL REPLCH ( FRZEPC, '/', ' ',    FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL SUFFIX ( 'TDB',   1,          FRZEPC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL STR2ET ( FRZEPC, T0 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Define the GSE frame.
!
      DEFTXT(1) = &
      'FRAME_GSE                        =  2399001'
      DEFTXT(2) = &
      'FRAME_2399001_NAME               = ''GSE'''
      DEFTXT(3) = &
      'FRAME_2399001_CLASS              =  5'
      DEFTXT(4) = &
      'FRAME_2399001_CLASS_ID           =  2399001'
      DEFTXT(5) = &
      'FRAME_2399001_CENTER             =  399'
      DEFTXT(6) = &
      'FRAME_2399001_RELATIVE           = ''J2000'''
      DEFTXT(7) = &
      'FRAME_2399001_'//KWSTYL//'       = '''// KVPARM //''''
      DEFTXT(8) = &
      'FRAME_2399001_'//KWFFAM//'             = '''// KV2VEC //''''
      DEFTXT(9) = &
      'FRAME_2399001_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      DEFTXT(10) = &
      'FRAME_2399001_'//KWPRI//KWVCDF//'       = '''//KVPOSV//''''
      DEFTXT(11) = &
      'FRAME_2399001_'//KWPRI//KWVOBS//'       = ''EARTH'''
      DEFTXT(12) = &
      'FRAME_2399001_'//KWPRI//KWVTRG//'         = ''SUN'''
      DEFTXT(13) = &
      'FRAME_2399001_'//KWPRI//KWVABC//'         = ''NONE'''
      DEFTXT(14) = &
      'FRAME_2399001_'//KWSEC//KWVAXI//'       = ''-'//KVY//''''
      DEFTXT(15) = &
      'FRAME_2399001_'//KWSEC//KWVCDF//'       =  '''// KVVELV //''''
      DEFTXT(16) = &
      'FRAME_2399001_'//KWSEC//KWVOBS//'       = ''SUN'''
      DEFTXT(17) = &
      'FRAME_2399001_'//KWSEC//KWVTRG//'       = ''EARTH'''
      DEFTXT(18) = &
      'FRAME_2399001_'//KWSEC//KWVABC//'         = ''NONE'''
      DEFTXT(19) = &
      'FRAME_2399001_'//KWSEC//KWVFRM//'          = ''J2000'''
      DEFTXT(20) = &
      'FRAME_2399001_'//KWRSTA//'       =  '''// KVROTG //''''

!
!     Load the GSE frame definition.
!
      CALL LMPOOL ( DEFTXT, 20 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     We use MULTIX and the array DIMS to define a mapping that allows
!     us to map a test case number to a set of input parameters.
!
!     Compute the number of test cases in the input cartesian product
!     space.
!
      NCART = PRODAI ( DIMS, NDIMS )


      DO CASE = 1, NCART
!
!        Find the multi-dimensional coordinates of the current
!        case in the cartesian product of the test input sets.
!
         CALL MULTIX ( 1, NDIMS, DIMS, CASE, COORDS )
         CALL CHCKXC ( .FALSE., ' ', OK )

!
!        Set frame definition parameters defined by COORDS.
!        Start out with the coefficient sets.
!
         DO I = 1, 3
            ANGCOF(I) = COFSTR( I, COORDS(COFIDX) )
         END DO

!
!        Set the axis sequence.
!
         DO I = 1, 3
            AXES(I)  = AXESEQ ( I, COORDS(SEQIDX) )
         END DO

!
!        Set the angular units.
!
         UNTSTR = UNITS  ( COORDS(UNTIDX) )

!
!        Set the epoch.
!
         EPOCH  = EPCSTR ( COORDS(EPCIDX) )

!
!        Set the base frame.
!
         BFRAME = BASEFR ( COORDS(BFRIDX) )

!
!        Set the frame center.  Obtain the center as a name.
!
         CENTER = CTRCDE ( COORDS(CTRIDX) )

         CALL BODC2N ( CENTER, CTRNAM, FOUND )

         CALL CHCKXC ( .FALSE., ' ', OK )
         CALL CHCKSL ( 'FOUND', FOUND, .TRUE., OK )

!
!        Set the rotation state.
!
         RSTSTR = RSTATE ( COORDS(RSTIDX) )

!
!        Decide whether the current test case is the special case
!        for Mars.
!
         ISMARS =         ( CENTER         .EQ. 499                  ) &
                   .AND.  ( BFRAME         .EQ. 'J2000'              ) &
                   .AND.  ( EPOCH          .EQ. '@2000-JAN-1/12:00'  ) &
                   .AND.  ( UNTSTR         .EQ. '''DEGREES'''        ) &
                   .AND.  ( COORDS(SEQIDX) .EQ. MSQIDX               ) &
                   .AND.  ( COORDS(COFIDX) .EQ. MCOIDX               )

!
!        For this test family, there are no cases that must be
!        rejected, so the "GO" flag is always .TRUE.  We keep
!        this currently unused flag to simplify maintenance of
!        this code.
!
         GO = .TRUE.

         IF ( GO ) THEN
!
!           We're ready to create a frame definition.
!
!
!           Create a text buffer containing a frame definition that
!           uses the current frame definition
!
!
!           First comes the frame name-to-frame code assignment.
!
            FRNAME     = 'EULER_DYN_FRAME'
            FRCODE     = -2000000000

            DEFTXT(1)  = 'FRAME_#           = #'
            CALL REPMC  ( DEFTXT(1), '#', FRNAME, DEFTXT(1) )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI  ( DEFTXT(1), '#', FRCODE, DEFTXT(1) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           We'll use the kernel variable name "stem"
!
!              FRAME_<ID code>_
!
!           repeatedly, so instead of making thousands of REPMI
!           calls, we just create this stem here.
!
            CALL REPMI ( 'FRAME_#_', '#', FRCODE, FRSTEM )
            CALL CHCKXC ( .FALSE., ' ', OK )


            DEFTXT(2)  =  FRSTEM // 'NAME             = ''#'''
            CALL REPMC  ( DEFTXT(2), '#', FRNAME, DEFTXT(2) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Frame class and class ID come next.
!
            DEFTXT(3)   =  FRSTEM // 'CLASS            = 5'

            DEFTXT(4)   =  FRSTEM // 'CLASS_ID         = #'
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI   ( DEFTXT(4), '#', FRCODE, DEFTXT(4) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           The frame center is specified via a name.
!
            DEFTXT(5)   =  FRSTEM // 'CENTER           = ''#'''

            CALL REPMC  ( DEFTXT(5), '#',  CTRNAM, DEFTXT(5) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the base frame.
!
            DEFTXT(6)   =  FRSTEM // 'RELATIVE         = ''#'''
            CALL REPMC  ( DEFTXT(6), '#', BFRAME, DEFTXT(6) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the frame definition style and family.
!
            DEFTXT(7)  = &
               FRSTEM // KWSTYL //'    = ''' // KVPARM // ''''
            CALL REPMI  ( DEFTXT(7), '#', FRCODE,    DEFTXT(7) )
            CALL CHCKXC ( .FALSE., ' ', OK )

            DEFTXT(8)  =  FRSTEM // KWFFAM //'           = '''// &
                          KVEULR //''''

            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL REPMI  ( DEFTXT(8), '#', FRCODE,    DEFTXT(8) )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Set the epoch for the polynomials.
!
            DEFTXT(9)  =  FRSTEM // KWEPOC // &
                          '            = ' // EPOCH

!
!           Set the units for the polynomial coefficients.
!
            DEFTXT(10) =  FRSTEM // KWUNIT // &
                          '            = ' // UNTSTR

!
!           Set the axis sequence.
!
            AXESTR = '( # # # )'

            DO I = 1, 3
               CALL REPMI  ( AXESTR, '#',  AXES(I), AXESTR )
               CALL CHCKXC ( .FALSE., ' ', OK )
            END DO

            DEFTXT(11) =  FRSTEM // KWEUAX // &
                          '             = ' // AXESTR

!
!           Set the coefficients.
!
            DEFTXT(12) =  FRSTEM // KWEAC1 // '   = ' // ANGCOF(1)
            DEFTXT(13) =  FRSTEM // KWEAC2 // '   = ' // ANGCOF(2)
            DEFTXT(14) =  FRSTEM // KWEAC3 // '   = ' // ANGCOF(3)

!
!           Set the frame's rotation state or freeze epoch.
!
            IF ( RSTSTR .EQ. 'FROZEN' ) THEN

               DEFTXT(15)  =  FRSTEM // KWFREZ //'     = ' &
                                     // FRZTOK
            ELSE

               DEFTXT(15)  =  FRSTEM // KWRSTA // '     = ''' &
                                     // RSTSTR(:RTRIM(RSTSTR)) // ''''
            END IF

            DX = 15

!
!           Enter the frame definition into the kernel pool.
!
            CALL LMPOOL ( DEFTXT, DX )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Here's where the testing begins.
!
!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'SXFORM/PXFORM test number #A.  Test ' // &
                          'results against those from PXFORM.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )

!
!           Pick a time value.
!
            ET = 1.D3 * ( CASE - 100 )

            CALL SXFORM ( FRNAME, BFRAME, ET, XFORM )
            CALL CHCKXC ( .FALSE., ' ', OK )


            CALL PXFORM ( FRNAME, BFRAME, ET, R )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Extract the derivative block from XFORM into DRVBLK.
!           We'll use this block later; we're extracting it here
!           to keep this code close to the associated SXFORM call.
!
            DO I = 1, 3
               DO J = 1, 3
                  DRVBLK(J,I) = XFORM(J+3,I)
               END DO
            END DO

            DMAG = VNORMG( DRVBLK, 9 )

!
!           Extract the rotation block from XFORM into R2.
!
            DO I = 1, 3
               DO J = 1, 3
                  R2(J,I) = XFORM(J,I)
               END DO
            END DO

            CALL CHCKAD ( 'SXFORM vs PXFORM', R2, '~', R, 9, DM12, OK )



!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'SXFORM test number #B.  Test derivative ' // &
                          'block.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )

!
!           Pick a time value.
!
            ET = 1.D3 * ( CASE - 100 )

            CALL SXFORM ( FRNAME, BFRAME, ET, XFORM )
            CALL CHCKXC ( .FALSE., ' ', OK )

!
!           Perform "sanity checks" on the returned matrix.
!           Make sure the diagonal blocks are identical rotations,
!           compute a discrete derivative and compare to the
!           lower left block, and make sure the upper right
!           block is a zero matrix.
!
!           The value of DELTA (1/16) was determined by experimentation.
!
            DELTA = 0.0625D0

            CALL PXFORM ( FRNAME, BFRAME, ET-DELTA, RMINUS )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL PXFORM ( FRNAME, BFRAME, ET+DELTA, RPLUS  )
            CALL CHCKXC ( .FALSE., ' ', OK )

            CALL T_XFORM ( XFORM,  RMINUS, RPLUS,  DELTA, &
                           NRMERR, DETERR, DRVERR, DRLERR, DRDIFF )
            CALL CHCKXC ( .FALSE., ' ', OK )


!           Check the error measurements we've made.  First
!           up is the determinant error.
!
            TOL = DM14
            CALL CHCKSD ( 'DETERR', DETERR, '~', 0.D0, TOL, OK )

!
!           Check norms of rows and columns in the rotation
!           blocks.
!
            CALL CHCKSD ( 'NRMERR', NRMERR, '~', 0.D0, TOL, OK )

!
!           If the frame is considered to be rotating, compare the
!           discrete derivative to the lower left block.
!
            IF (  EQSTR( RSTSTR, KVROTG )  ) THEN
!
!              Check the derivative absolute error.
!
               TOL = DM6
               CALL CHCKSD ( 'DRVERR', DRVERR, '~', 0.D0, TOL, OK )

!
!              Check the derivative relative error.
!
               TOL = DM4
               CALL CHCKSD ( 'DRLERR', DRLERR, '~', 0.D0, TOL, OK )


            ELSE IF (  EQSTR( RSTSTR, KVINRT )  ) THEN
!
!              The frame is supposed to be inertial, so the
!              state transformation mapping from this frame to
!              J2000 ideally should have a zero derivative block.
!              See whether the derivative block of the latter
!              transformation is close to zero.
!
               CALL SXFORM ( BFRAME, 'J2000', ET,      XFB2J )
               CALL CHCKXC ( .FALSE., ' ', OK )

               CALL MXMG   ( XFB2J,  XFORM,   6, 6, 6, XFF2J )

               DO I = 1, 3
                  DO J = 1, 3
                     DRV2(J,I) = XFF2J(J+3,I)
                  END DO
               END DO

               CALL CHCKAD ( 'Derivative block', &
                              DRV2, '~', ZR, 9, DM19, OK )

            ELSE
!
!              The frozen case is quite simple:  the derivative
!              with respect to the base frame is zero.
!
               CALL CHCKAD ( 'Derivative block', &
                              DRVBLK, '=', ZR, 9, 0.D0, OK )

            END IF


!
!--- Case: ------------------------------------------------------
!
            CALL REPMI  ( 'SXFORM test number #C. Construct '      // &
                          'state transformation locally; compare ' // &
                          'to XFORM output.', &
                          '#', CASE, CASMSG )
            CALL CHCKXC ( .FALSE., ' ', OK )
            CALL TCASE  ( CASMSG )



!
!           Parse the reference epoch; compute the evaluation epoch. If
!           the rotation state is frozen, use the "freeze" value.
!
            CALL CMPRSS ( '@', 0, EPOCH, TIMSTR )
            CALL SUFFIX ( 'TDB',  1,     TIMSTR )

            CALL STR2ET ( TIMSTR, REFEPC )

            IF (  EQSTR ( RSTSTR, 'FROZEN' )  ) THEN
               T = T0 - REFEPC
            ELSE
               T = ET - REFEPC
            END IF

!
!           Compute the Euler angles and their derivatives;
!           scale to radians and radians/sec.
!
            DO I = 1, 3
!
!              Parse the string '( <coeff 0> <coeff 1> ... <coeff n> )'
!
               CALL LPARSM ( ANGCOF(I), ' ()', MAXTOK, N, TOKENS )

!
!              The first token will be the null token preceding
!              the first parenthesis.  The next 1-3 tokens are
!              numbers.  The last token is also null.
!
               DO J = 2, N-1
                  CALL PRSDP ( TOKENS(J), COEFFS(J-2) )
               END DO

!               WRITE (*,*) '-------------------------------------'
!               WRITE (*,*) ( COEFFS(J), J = 0, N-3 )
!               WRITE (*,*) '-------------------------------------'

!
!              Evaluate the polynomial P representing the angle
!              and its time derivative DP at T.
!
               P  = 0.D0

               DO J = N-3, 0, -1

                  P = COEFFS(J) + T * P

               END DO

               DP = 0.D0

               DO J = N-3, 1, -1

                  DP =  J * ( COEFFS(J) + T * DP )

               END DO

!
!              Convert angular units to radians.
!
               CALL CMPRSS ( '''', 0, UNTSTR, INUNIT )

               CALL CONVRT ( P,  INUNIT, KVRADN, EULANG(I)   )
               CALL CONVRT ( DP, INUNIT, KVRADN, EULANG(I+3) )

            END DO

!
!           Compute the state transformation matrix.
!
            CALL EUL2XF ( EULANG, AXES(1), AXES(2), AXES(3), XF2 )

!
!           Now compare XF2 to XFORM.
!
!           Extract the derivative block from XF2.
!
            DO I = 1, 3
               DO J = 1, 3
                  DRV2(J,I) = XF2(J+3,I)
               END DO
            END DO

!
!           Extract the rotation block and compare to
!           that for our dynamic frame.
!
            DO I = 1, 3
               DO J = 1, 3
                  R2(J,I) = XF2(J,I)
               END DO
            END DO

!
!           Compare to the rotation from the Euler frame to
!           the base frame returned by PXFORM.
!
            CALL PXFORM ( FRNAME, BFRAME, ET, R )

            TOL = DM14

            CALL CHCKAD ( 'R2', R2, '~', R, 9, TOL, OK )


!
!           Check the derivative block of the state transformation
!           matrix.
!
            CALL SXFORM ( FRNAME, BFRAME, ET, XFORM )

            DO I = 1, 3
               DO J = 1, 3
                  DRVBLK(J,I) = XFORM(J+3,I)
               END DO
            END DO

!
!           Our locally derivative is relevant only if the frame's
!           rotation state is KVROTG.
!
            IF ( RSTSTR .EQ. KVROTG ) THEN

               TOL = DM14
               CALL CHCKAD ( 'd(R2)/dt', &
                             DRV2, '~', DRVBLK, 9, TOL, OK )
            END IF

!
!--- Case: ------------------------------------------------------
!
!
!           We've finished the generic tests.  If our frame is
!           the pseudo IAU_MARS frame, compare the frame to that
!           defined by our PCK.
!
            IF ( ISMARS .AND. ( RSTSTR .EQ. KVROTG )  ) THEN

               CALL TCASE  ( 'IAU_MARS test case' )

!
!              Get the PCK-defined state transformation matrix.
!              Set the epoch to ~2030; this will allow velocity
!              errors to accumulate.
!
               ET = JYEAR() * 30
               CALL SXFORM ( 'J2000', 'IAU_MARS', ET, TSIPM )

!
!              Extract the derivative block.
!
               DO I = 1, 3
                  DO J = 1, 3
                     DRV2(J,I) = TSIPM(J+3,I)
                  END DO
               END DO

!
!              Extract the rotation block and compare to
!              that for our dynamic frame.
!
               DO I = 1, 3
                  DO J = 1, 3
                     TIPM(J,I) = TSIPM(J,I)
                  END DO
               END DO

               CALL PXFORM ( 'J2000', FRNAME, ET, R )

               TOL = DM11
               CALL CHCKAD ( 'Mars TIPM', R, '~', TIPM, 9, TOL, OK )

!
!              Check the derivative block of the state transformation
!              matrix.
!
               CALL SXFORM ( 'J2000', FRNAME, ET, XFORM )

               DO I = 1, 3
                  DO J = 1, 3
                     DRVBLK(J,I) = XFORM(J+3,I)
                  END DO
               END DO

               CALL CHCKAD ( 'Mars d(TIPM)/dt', &
                              DRVBLK, '~', DRV2, 9, TOL, OK )

            END IF

         END IF
!
!        Expunge the optional keywords from the kernel pool.
!
         IF ( RSTSTR .EQ. 'FROZEN' ) THEN
            KEYWRD  =  FRSTEM // KWFREZ
         ELSE
            KEYWRD  =  FRSTEM // KWRSTA
         END IF

         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC ( .FALSE., ' ', OK )

      END DO

!
!     Clean up the SPK file.
!
      CALL SPKUEF ( HANDLE )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL DELFIL ( SPK    )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Close out the test family.
!
      CALL T_SUCCESS ( OK )
      RETURN

      END
