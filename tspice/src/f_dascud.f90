!$Procedure      F_DASCUD ( DASCUD routine tests )

      SUBROUTINE F_DASCUD ( OK )
      use pepper_legacy

! $ Abstract
!
!     This routine tests the SPICELIB routine
!
!        DASCUD
!
! $ Required_Reading
!
!     None.
!
! $ Keywords
!
!     TEST FAMILY
!
! $ Declarations

      IMPLICIT NONE

      LOGICAL               OK

! $ Brief_I/O
!
!     VARIABLE  I/O  DESCRIPTION
!     --------  ---  --------------------------------------------------
!     OK         O   logical indicating test status.
!
! $ Detailed_Input
!
!     None.
!
! $ Detailed_Output
!
!     OK         is a logical that indicates the test status to the
!                caller.
!
! $ Parameters
!
!     None.
!
! $ Exceptions
!
!     This routine does not generate any errors. Routines in its
!     call tree may generate errors that are either intentional and
!     trapped or unintentional and need reporting.  The test family
!     utilities manage this.
!
! $ Files
!
!     None.
!
! $ Particulars
!
!     This routine tests some of the more complex aspects of the SPICE
!     DAS subsystem.  The DAS Required Reading and thorough
!     knowledge of the DAS routines are prerequisites for understanding
!     this test family.
!
!     This file contains source code for the following utility
!     routines:
!
!        PACKFS
!        CHKFS
!        CHKCDR
!
! $ Examples
!
!     None.
!
! $ Restrictions
!
!     None.
!
! $ Literature_References
!
!     None.
!
! $ Author_and_Institution
!
!     N.J. Bachman   (JPL)
!     B.V. Semenov   (JPL)
!
! $ Version
!
!-    SPICELIB Version 1.1.0, 09-OCT-2013 (BVS)
!
!        Declared LASTLA, LASTRC, and LASTWD in PACKFS as arrays to
!        eliminate warning generated by some compilers. Added missing
!        header sections.
!
!-    SPICELIB Version 1.0.0, 22-FEB-2003 (NJB)
!
!-&


!
!     Test Utility Functions
!


!
!     SPICELIB Functions
!

!
!     Local Parameters
!
!
!     Words per data record, for each data type:
!
      INTEGER               NWC
      PARAMETER           ( NWC    = 1024 )

      INTEGER               NWD
      PARAMETER           ( NWD    =  128 )

      INTEGER               NWI
      PARAMETER           ( NWI    =  256 )

!
!     DAS type codes:
!
      INTEGER               CHAR
      PARAMETER           ( CHAR   =  1  )

      INTEGER               DP
      PARAMETER           ( DP     =  2  )

      INTEGER               INT
      PARAMETER           ( INT    =  3  )

!
!     Directory pointer locations (backward and forward):
!
      INTEGER               BWDLOC
      PARAMETER           ( BWDLOC = 1 )

      INTEGER               FWDLOC
      PARAMETER           ( FWDLOC = 2 )

!
!     Directory address range locations
!
      INTEGER               CHRRNG
      PARAMETER           ( CHRRNG =          3 )

      INTEGER               DPRNG
      PARAMETER           ( DPRNG  = CHRRNG + 2 )

      INTEGER               INTRNG
      PARAMETER           ( INTRNG = DPRNG  + 2 )

      INTEGER               CRNGMX
      PARAMETER           ( CRNGMX = CHRRNG + 1 )

      INTEGER               DRNGMX
      PARAMETER           ( DRNGMX = DPRNG  + 1 )

      INTEGER               IRNGMX
      PARAMETER           ( IRNGMX = INTRNG + 1 )

!
!     Location of first type descriptor
!
      INTEGER               BEGDSC
      PARAMETER           ( BEGDSC = 9 )

!
!     DAS file summary size:
!
      INTEGER               FSDIM
      PARAMETER           ( FSDIM  = 14 )

!
!     Local Variables
!
      INTEGER               CLREC  ( NWI )
      INTEGER               DSCLOC
      INTEGER               DTYPE
      INTEGER               FREE
      INTEGER               FSUM   ( FSDIM )
      INTEGER               LASTLA ( 3 )
      INTEGER               LASTRC ( 3 )
      INTEGER               LASTWD ( 3 )
      INTEGER               NADD
      INTEGER               NRESVR
      INTEGER               NCOMR
      INTEGER               NRESVC
      INTEGER               NCOMC
      INTEGER               PRVCLR
      INTEGER               PRVTYP
      INTEGER               RECNO
      INTEGER               RNGMAX ( 3 )
      INTEGER               RNGMIN ( 3 )
      INTEGER               SCRHAN
      INTEGER               SIZES  ( 3 )
      INTEGER               XCLREC ( NWI )
      INTEGER               XFSUM  ( FSDIM )

!
!     Saved variables
!
      SAVE                  RNGMAX
      SAVE                  RNGMIN
      SAVE                  SIZES

!
!     Initial values
!
      DATA                  RNGMAX / CRNGMX, DRNGMX, IRNGMX /
      DATA                  RNGMIN / CHRRNG, DPRNG,  INTRNG /
      DATA                  SIZES  / NWC,    NWD,    NWI    /


!
!     Begin every test family with an open call.
!
      CALL TOPEN ( 'F_DASCUD' )

!
!     Our approach to testing will be to create a scratch DAS
!     file by successive additions, such that the set of states
!     of the scratch DAS' file summary and directory contents span the
!     range of possibilities handled by DASCUD.  For each data addition
!     case, we'll verify that the addition results in the expected
!     update of the cluster directory structure and the file summary.
!
!     We don't actually write data to the files in these tests; we
!     simply update metadata to indicate where the data would be if
!     they were there.  Below, when we say we're "adding data" to
!     the file, we're lying to DASCUD.  But as long as the free
!     record pointer FREE is updated correctly, the DAS system is
!     none the wiser.
!


      CALL TCASE ( 'Tell DASCUD we''re adding one integer datum.' // &
                   'to an empty file.'                            )

      CALL DASOPS ( SCRHAN )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Update the file.  Note that the file update is generally made
!     to buffered records; these records might not be written to
!     the physical file.
!
      CALL DASCUD ( SCRHAN, INT, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.  Note that the first cluster
!     record should follow the file record, reserved records, and
!     comment records.  The last integer logical address is 1.
!     The cluster record containing a descriptor for the last
!     integer cluster is the only cluster record.  The first
!     data record follows the cluster directory.  The first free
!     record follows the data record.
!
      NRESVR        = 0
      NCOMR         = 0
      NRESVC        = 0
      NCOMC         = 0
      FREE          = 1 + NRESVR + NCOMR + 1 + 1 + 1
      LASTLA (CHAR) = 0
      LASTLA (DP)   = 0
      LASTLA (INT)  = 1
      LASTRC (CHAR) = 0
      LASTRC (DP)   = 0
      LASTRC (INT)  = 1 + NRESVR + NCOMR + 1
      LASTWD (CHAR) = 0
      LASTWD (DP)   = 0
      LASTWD (INT)  = BEGDSC + 1

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      CALL CLEARI ( NWI, XCLREC )

      XCLREC(BWDLOC  ) = 0
      XCLREC(FWDLOC  ) = 0
      XCLREC(CHRRNG  ) = 0
      XCLREC(CHRRNG+1) = 0
      XCLREC(DPRNG   ) = 0
      XCLREC(DPRNG+1 ) = 0
      XCLREC(INTRNG  ) = 1
      XCLREC(INTRNG+1) = 1
      XCLREC(BEGDSC  ) = INT
      XCLREC(BEGDSC+1) = 1

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add one d.p. datum to the file.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, DP, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE        = FREE + 1
      LASTLA (DP) = 1
      LASTRC (DP) = 1 + NRESVR + NCOMR + 1
      LASTWD (DP) = BEGDSC + 2

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(DPRNG   ) =  1
      XCLREC(DPRNG+1 ) =  1
      XCLREC(BEGDSC+2) = -1

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )




      CALL TCASE ( 'Add one character datum to the file.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, CHAR, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE          = FREE + 1
      LASTLA (CHAR) = 1
      LASTRC (CHAR) = 1 + NRESVR + NCOMR + 1
      LASTWD (CHAR) = BEGDSC + 3

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(CHRRNG  ) =  1
      XCLREC(CHRRNG+1) =  1
      XCLREC(BEGDSC+3) = -1

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )




      CALL TCASE ( 'Add data to fill up the first integer data ' // &
                   'record.'                                      )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, INT, NWI-1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
!
!     Note:  FREE is unchanged.
!
      LASTLA (INT) = NWI

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(INTRNG+1) =  NWI

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )






      CALL TCASE ( 'Add data to fill up 3 1/2 new integer data '     // &
                   'records.  This creates a second integer cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, INT, 7*NWI/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE       = FREE + 4
      LASTLA (INT) = LASTLA (INT)  +  7*NWI/2
      LASTWD (INT) = BEGDSC + 4

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 7*NWI/2
      XCLREC(BEGDSC+4) = -4

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 3 new integer data records. ' // &
                   'This extends the second integer cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, INT, 3*NWI )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE       = FREE + 3
      LASTLA (INT) = LASTLA(3) + 3*NWI

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 3*NWI
      XCLREC(BEGDSC+4) = -7

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )





      CALL TCASE ( 'Add data to fill up 1 1/2 new integer data ' // &
                   'records. This extends the second integer cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, INT, 3*NWI/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
!
!     Recall the last integer data record is half full.  We only need
!     one new integer data record.
!
      FREE         = FREE + 1
      LASTLA (INT) = LASTLA(INT) + 3*NWI/2

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 3*NWI/2
      XCLREC(BEGDSC+4) = -8

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )

!
!     We're now going to repeat the integer data additions for
!     the double precision and character cases.
!



      CALL TCASE ( 'Add data to fill up the first d.p. data ' // &
                   'record.'                                      )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, DP, NWD-1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
!
!     Note:  FREE is unchanged.
!
      LASTLA (DP) = NWD

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(DPRNG+1 ) =  NWD


!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )






      CALL TCASE ( 'Add data to fill up 3 1/2 new d.p. data '     // &
                   'records.  This creates a second d.p. cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, DP, 7*NWD/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE        = FREE + 4
      LASTLA (DP) = LASTLA(DP) + 7*NWD/2
      LASTWD (DP) = BEGDSC + 5

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(DPRNG+1 ) =  XCLREC(DPRNG+1)  + 7*NWD/2
      XCLREC(INTRNG  ) =  1
      XCLREC(BEGDSC+5) = -4

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 3 new d.p. data records. ' // &
                   'This extends the second d.p. cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, DP, 3*NWD )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
      FREE        = FREE + 3
      LASTLA (DP) = LASTLA(DP) + 3*NWD

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(DPRNG+1 ) = XCLREC(DPRNG+1) + 3*NWD
      XCLREC(BEGDSC+5) = -7

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 1 1/2 new d.p. data ' // &
                   'records. This extends the second d.p. cluster.' )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, DP, 3*NWD/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
!
!     Recall the last d.p. data record is half full.  We only need
!     one new d.p. data record.
!
      FREE        = FREE + 1
      LASTLA (DP) = LASTLA(DP) + 3*NWD/2

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(DPRNG+1 ) =  XCLREC(DPRNG+1 ) + 3*NWD/2
      XCLREC(BEGDSC+5) = -8

!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )





      CALL TCASE ( 'Add data to fill up the first char data ' // &
                   'record.'                                      )

!
!     Update the file.
!
      CALL DASCUD ( SCRHAN, CHAR, NWC-1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Set up the expected file summary.
!
!
!     Note:  FREE is unchanged.
!
      LASTLA (CHAR) = NWC

      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE, &
                    LASTLA, LASTRC, LASTWD, XFSUM       )

!
!     Look up the file summary, pack into a summary array, and compare.
!
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR, &
                    NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE, &
                    LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



!
!     Set up the expected first cluster record.
!
      XCLREC(CHRRNG+1) =  NWC


!
!     Read the cluster record and compare.
!
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

