!$Procedure      T_RANDSIGN ( Random sign )

      INTEGER FUNCTION T_RANDSIGN ( SEED )
      use pepper_legacy

! $ Abstract
!
!     Return a psudorandom -1 or 1.
!
! $ Required_Reading
!
!     None.
!
! $ Keywords
!
!     MATH
!     NUMBERS
!
! $ Declarations

      INTEGER               SEED

! $ Brief_I/O
!
!     Variable  I/O  Description
!     --------  ---  --------------------------------------------------
!     SEED      I-O  Seed for random number generation.
!
!     The function returns either 1 or -1.
!
! $ Detailed_Input
!
!     SEED           is a seed for the random number generator. On the
!                    first call to T_URAND, SEED should be set equal to
!                    a negative number.  After the first call, SEED
!                    should not be modified by the caller, except to
!                    start a new sequence of random numbers.
!
! $ Detailed_Output
!
!     SEED           is the seed value to be used as input on the next
!                    call to T_URAND to produce the next random number
!                    in the sequence.
!
!     The function returns values that are approximately uniformly
!     distributed over the open interval (0, 1).
!
! $ Parameters
!
!     None.
!
! $ Exceptions
!
!     Error free.
!
! $ Files
!
!     None.
!
! $ Particulars
!
!     Please see T_URAND for more details.
!
! $ Examples
!
!     None.
!
! $ Restrictions
!
!     1) Users must verify that the pseudo-random number sequences
!        generated by this routine are suitable for their applications.
!
! $ Literature_References
!
!     None.
!
! $ Author_and_Institution
!
!     S.C. Krening   (JPL)
!
! $ Version
!
!-    Testutil Version 1.0.0, 6-JAN-2012 (SCK)
!
!-&

!
!     Other functions
!
      DOUBLE PRECISION      T_URAND

!
!     Local parameters
!
      DOUBLE PRECISION      BND
      PARAMETER           ( BND = 0.5D0 )

!
!     Call T_URAND to retrieve a random number between 0 and 1.
!     If the random number is greater than or equal to BND, return 1.
!     Otherwise, return -1.
!
      IF ( T_URAND ( SEED ) .GE. BND ) THEN
         T_RANDSIGN = 1
      ELSE
         T_RANDSIGN = -1
      END IF

      RETURN
      END

