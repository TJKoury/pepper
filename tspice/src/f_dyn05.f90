      CALL MXVG   ( XFORM, STATE1, 6, 6, STATE2 )

      CALL CHCKAD ( 'STATE0 position', &
                     STATE0,    '~/', STATE2,    3, EX13, OK )
      CALL CHCKAD ( 'STATE0 velocity', &
                     STATE0(4), '~/', STATE2(4), 3, EX13, OK )


!
!     Now create a CK containing a segment with dynamic base
!     frame.
!
!
!--- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Create a CK for tests using dynamic ' // &
                   'base frames.'                            )

!
!     Start with the CK file.  Create but don't load the file.
!
      CALL TSTCK3 ( CK2, SCLK, .FALSE., .FALSE., .FALSE., HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Locate the segment for the instrument -9901; change the descriptor
!     to make the base frame RECUR_2. Change the ID code of the
!     instrument at the same time, so we can compare pointing from the
!     new segments with those from the old.
!
!     Change the frame for the instrument -10000 to RECUR_3.  This
!     segment should become unusable; we'll check this later.
!
      CALL DAFOPW ( CK2, HANDLE(4)   )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL DAFBFS ( HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL DAFFNA  ( FOUND )
      CALL CHCKXC  ( .FALSE., ' ', OK )

      DO WHILE ( FOUND )

         CALL DAFGS  ( SUM )
         CALL CHCKXC ( .FALSE., ' ', OK )

         CALL DAFUS ( SUM, ND, NI, DC, IC )
         CALL CHCKXC  ( .FALSE., ' ', OK )

         IF ( IC(1) .EQ. -10001 ) THEN
!
!           Update the descriptor.  For CK descriptors, the frame
!           ID is in the second element of the integer component.
!
            CALL NAMFRM ( 'RECUR_2', IC(2) )
            CALL CHCKXC ( .FALSE., ' ', OK )
            IC(1) = IC(1) + 100

            CALL DAFPS  ( ND, NI, DC, IC, SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
!
!           Write the new descriptor.
!
            CALL DAFRS  ( SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )

         ELSE IF ( IC(1) .EQ. -10000 ) THEN
!
!           Update the descriptor.
!
            CALL NAMFRM ( 'RECUR_3', IC(2) )
            IC(1) = IC(1) + 100

            CALL DAFPS  ( ND, NI, DC, IC, SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
!
!           Write the new descriptor.
!
            CALL DAFRS  ( SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )

         END IF

         CALL DAFFNA ( FOUND )
         CALL CHCKXC ( .FALSE., ' ', OK )

      END DO

!
!     Close the modified CK file.
!
      CALL DAFCLS ( HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!--- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Look up pointing of instrument -9901 ' // &
                   'in frame RECUR_2.'                      )

!
!     Load the CK containing data of interest.
!
      CALL CKLPF  ( CK2, HANDLE(4)   )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Look up the pointing and angular velocity of instrument -9901 in
!     the dynamic frame RECUR_2. The data should match those of the
!     instrument -10001 in frame J2000.
!
      INSTID = -9901
      CLKID  = -9

      CALL STR2ET ( '2005 JAN 1 12:00 TDB', ET )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL SCE2C  ( CLKID,   ET,     SCLKDP )
      CALL CHCKXC ( .FALSE., ' ',    OK     )

!
!     Look up pointing relative to frame RECUR_2.
!
      CALL CKGPAV ( INSTID,  SCLKDP, 0.D0,   'RECUR_2', &
                    CMAT0,   AV0,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                )
      CALL CHCKSL ( '-9901 FOUND',  FOUND, .TRUE., OK  )

!
!     Look up the same data for instrument -10001 using the
!     J2000 frame (base frame for instrument -10001).
!     Compare.
!
      CALL CKGPAV ( -10001,   SCLKDP, 0.D0,   'J2000', &
                    CMAT1,    AV1,    CLKOUT, FOUND      )
      CALL CHCKXC ( .FALSE., ' ',    OK                 )
      CALL CHCKSL ( '-10001 FOUND',  FOUND, .TRUE., OK  )

!
!     Compare C-matrices.
!
      CALL CHCKAD ( 'CMAT0', CMAT0, '~', CMAT1, 9, EX13, OK )

!
!     Compare angular velocity vectors.
!
      CALL CHCKAD ( 'AV0', AV0, '~', AV1, 3, EX13, OK )

!
!--- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Look up pointing of instrument -9901 ' // &
                   'in frame J2000.  This forces the CK '  // &
                   'subsystem to do a dynamic frame '      // &
                   'transformation.'                       )

!
!     Load the CK containing data of interest.
!
      CALL CKLPF  ( CK2, HANDLE(4)   )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Look up the pointing and angular velocity of instrument -9901 in
!     the dynamic frame J2000.  The data should match those of the
!     instrument -10001 after the RECUR_2 to J2000 state transformation
!     is applied.
!
      INSTID = -9901
      CLKID  = -9

      CALL STR2ET ( '2005 JAN 1 12:00 TDB', ET )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL SCE2C  ( CLKID,   ET,     SCLKDP )
      CALL CHCKXC ( .FALSE., ' ',    OK     )

!
!     Look up pointing relative to frame J2000.
!
      CALL CKGPAV ( INSTID,  SCLKDP, 0.D0,   'J2000', &
                    CMAT0,   AV0,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                )
      CALL CHCKSL ( '-9901 FOUND',  FOUND, .TRUE., OK  )

!
!     Look up the same data for instrument -10001 using the
!     J2000 frame (base frame for instrument -10001).
!     Compare.
!
      CALL CKGPAV ( -10001,   SCLKDP, 0.D0,   'J2000', &
                    CMAT1,    AV1,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                 )
      CALL CHCKSL ( '-10001 FOUND',  FOUND, .TRUE., OK  )

!
!     Get the  J2000 to RECUR_2 position transformation matrix.
!     Right-multiply CMAT1 by this.
!
      CALL PXFORM ( 'J2000', 'RECUR_2', ET, R )
      CALL CHCKXC ( .FALSE., ' ',    OK       )

      CALL MXM    ( CMAT1,    R,        CMAT2 )

!
!     Compare C-matrices.
!
      CALL CHCKAD ( 'CMAT0', CMAT0, '~', CMAT2, 9, EX13, OK )

!
!     Compare angular velocity vectors. To simplify the computations,
!     we'll work with state transformations. Construct the J2000 to
!     CK_-10001 state transformation XF2 from the corresponding
!     C-matrix and angular velocity vector. Right-multiply this by the
!     J2000 to RECUR_2 state transformation XF3. This should yield a
!     transformation XF4 equivalent to XFORM, since XFORM was
!     effectively created by the same right-multiplication of the state
!     transformation matrix mapping RECUR_2 to CK_-9901.  The angular
!     velocity vector AV2 extracted from XF4 can then be compared to
!     the original angular velocity vector AV0.
!
      CALL RAV2XF ( CMAT1, AV1, XF2 )

      CALL SXFORM ( 'J2000', 'RECUR_2', ET, XF3 )
      CALL CHCKXC ( .FALSE., ' ',    OK         )

      CALL MXMG   ( XF2, XF3, 6, 6, 6, XF4 )

!
!     Extract angular velocity from XF4.
!
      CALL XF2RAV ( XF4, CMAT2, AV2 )

!
!     Check AV0.
!
      CALL CHCKAD ( 'AV0', AV0, '~', AV2, 3, EX13, OK )

!
!--- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Look up pointing of instrument -9900 '     // &
                   'in frame J2000.  The segment for -9900 '   // &
                   'has a dynamic base frame requiring three ' // &
                   'levels of recursion for evaluation.'       )

!
!     PEPPER: the segment's base frame RECUR_3 needs three levels of
!     dynamic frames, which PEPPER evaluates (SPICELIB signaled
!     SPICE(RECURSIONTOODEEP)). The segment holds the data of
!     instrument -10000, whose base frame is FK4: the pointing relative
!     to FK4, after the J2000 to RECUR_3 transformation (as for -9901
!     and -10001 above, whose base frame is J2000).
!
      CALL CKGPAV ( -9900,   SCLKDP, 0.D0,   'J2000', &
                    CMAT0,   AV0,    CLKOUT, FOUND           )
      CALL CHCKXC ( .FALSE., ' ',    OK                )
      CALL CHCKSL ( '-9900 FOUND',  FOUND, .TRUE., OK  )

      CALL CKGPAV ( -10000,   SCLKDP, 0.D0,   'FK4',   &
                    CMAT1,    AV1,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                 )
      CALL CHCKSL ( '-10000 FOUND',  FOUND, .TRUE., OK  )

      CALL PXFORM ( 'J2000', 'RECUR_3', ET, R )
      CALL CHCKXC ( .FALSE., ' ',    OK       )
      CALL MXM    ( CMAT1,    R,        CMAT2 )
      CALL CHCKAD ( 'CMAT0', CMAT0, '~', CMAT2, 9, EX13, OK )

      CALL RAV2XF ( CMAT1, AV1, XF2 )
      CALL SXFORM ( 'J2000', 'RECUR_3', ET, XF3 )
      CALL CHCKXC ( .FALSE., ' ',    OK         )
      CALL MXMG   ( XF2, XF3, 6, 6, 6, XF4 )
      CALL XF2RAV ( XF4, CMAT2, AV2 )
      CALL CHCKAD ( 'AV0', AV0, '~', AV2, 3, EX13, OK )

!
!     End of test cases.
!


!
!     Clean up the SPK and CK files.
!
      CALL SPKUEF ( HANDLE(1) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( SPK       )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CKUPF  ( HANDLE(2) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( CKNM      )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL SPKUEF ( HANDLE(3) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( SPK2      )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CKUPF  ( HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( CK2       )
      CALL CHCKXC ( .FALSE., ' ', OK )

!
!     Close out the test family.
!
      CALL T_SUCCESS ( OK )
      RETURN

      END
