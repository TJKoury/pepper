!$Procedure F_DYN07 ( Dynamic Frame Test Family 07 )

      SUBROUTINE F_DYN07 ( OK )
      use pepper_legacy
      use pepper_inc_zzdyn
      use pepper_inc_errhnd

! $ Abstract
!
!     Test family to exercise the logic and code used to handle
!     frame kernel errors.
!
! $ Required_Reading
!
!     None.
!
! $ Keywords
!
!     TEST FAMILY
!
! $ Declarations

      IMPLICIT NONE


      LOGICAL               OK

! $ Brief_I/O
!
!     VARIABLE  I/O  DESCRIPTION
!     --------  ---  --------------------------------------------------
!     OK         O   logical indicating test status.
!
! $ Detailed_Input
!
!     None.
!
! $ Detailed_Output
!
!     OK         is a logical that indicates the test status to the
!                caller.
!
! $ Parameters
!
!     None.
!
! $ Files
!
!     This test family uses the following kernels:
!
!        LSK generated by tstlsk
!        PCK generated by t_pck08
!        SPK generated by tstspk
!
! $ Exceptions
!
!     This routine does not generate any errors. Routines in its
!     call tree may generate errors that are either intentional and
!     trapped or unintentional and need reporting.  The test family
!     utilities manage this.
!
! $ Particulars
!
!     None.
!
! $ Examples
!
!     None.
!
! $ Restrictions
!
!     None.
!
! $ Author_and_Institution
!
!     N.J. Bachman     (JPL)
!
! $ Literature_References
!
!     None.
!
! $ Version
!
!-    TSPICE Version 2.0.0, 23-JUL-2007 (NJB)
!
!        Updated for compatibility with new SPK
!        aberration-corrected velocity computations.
!
!-    TSPICE Version 1.1.0, 12-JAN-2005 (NJB)
!
!        Parameters KWX, KWY, KWZ were renamed to KVX, KVY, KVZ.
!
!-    TSPICE Version 1.0.0, 10-JAN-2005 (NJB)
!
!
!-&

!
!     SPICELIB functions
!
!
!     Local Parameters
!
      CHARACTER*(*)         PCK
      PARAMETER           ( PCK    = 'test_dyn.tpc' )

      CHARACTER*(*)         SPK
      PARAMETER           ( SPK    = 'test_dyn.bsp' )


      INTEGER               LNSIZE
      PARAMETER           ( LNSIZE = 80 )

      INTEGER               MAXDEF
      PARAMETER           ( MAXDEF = 50 )

      INTEGER               TIMLEN
      PARAMETER           ( TIMLEN = 50 )


!
!     Parameters controlling frame definitions:
!

!
!     Local Variables
!
      CHARACTER*(LNSIZE)    DEFTX2 ( MAXDEF )
      CHARACTER*(LMSGLN)    ERRMSG
      CHARACTER*(LNSIZE)    GSETXT ( MAXDEF )
      CHARACTER*(LNSIZE)    GSMTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    KEYWRD
      CHARACTER*(LNSIZE)    MARTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    MCQTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    MQQTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    TQQTXT ( MAXDEF )

      DOUBLE PRECISION      R      ( 3, 3 )
      DOUBLE PRECISION      XFORM  ( 6, 6 )

      INTEGER               DX
      INTEGER               HANDLE
      INTEGER               I
      INTEGER               J

!
!     Saved variables
!

!
!     Initial values
!

!
!     Open the test family.
!
      CALL TOPEN ( 'F_DYN07' )


! **************************************************************
! **************************************************************
! **************************************************************
!     TWO-VECTOR CASES
! **************************************************************
! **************************************************************
! **************************************************************

!
! --- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Create and load kernels.' )


!
!     Create and load kernels.
!
      CALL TSTLSK
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL TSTSPK  ( SPK, .TRUE., HANDLE  )
      CALL CHCKXC  ( .FALSE., ' ', OK )

      CALL T_PCK08 ( PCK, .TRUE., .FALSE. )
      CALL CHCKXC  ( .FALSE., ' ', OK )

!
!     Define the GSE frame.
!
      GSETXT(1) = &
      'FRAME_GSE                        =  2399001'
      GSETXT(2) = &
      'FRAME_2399001_NAME               = ''GSE'''
      GSETXT(3) = &
      'FRAME_2399001_CLASS              =  5'
      GSETXT(4) = &
      'FRAME_2399001_CLASS_ID           =  2399001'
      GSETXT(5) = &
      'FRAME_2399001_CENTER             =  399'
      GSETXT(6) = &
      'FRAME_2399001_RELATIVE           = ''J2000'''
      GSETXT(7) = &
      'FRAME_2399001_'//KWSTYL//'       = '''// KVPARM //''''
      GSETXT(8) = &
      'FRAME_2399001_'//KWFFAM//'             = '''// KV2VEC //''''
      GSETXT(9) = &
      'FRAME_2399001_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      GSETXT(10) = &
      'FRAME_2399001_'//KWPRI//KWVCDF//'       = '''//KVPOSV//''''
      GSETXT(11) = &
      'FRAME_2399001_'//KWPRI//KWVOBS//'       = ''EARTH'''
      GSETXT(12) = &
      'FRAME_2399001_'//KWPRI//KWVTRG//'         = ''SUN'''
      GSETXT(13) = &
      'FRAME_2399001_'//KWPRI//KWVABC//'         = ''NONE'''
      GSETXT(14) = &
      'FRAME_2399001_'//KWSEC//KWVAXI//'       = ''-'//KVY//''''
      GSETXT(15) = &
      'FRAME_2399001_'//KWSEC//KWVCDF//'       =  '''// KVVELV //''''
      GSETXT(16) = &
      'FRAME_2399001_'//KWSEC//KWVOBS//'       = ''SUN'''
      GSETXT(17) = &
      'FRAME_2399001_'//KWSEC//KWVTRG//'       = ''EARTH'''
      GSETXT(18) = &
      'FRAME_2399001_'//KWSEC//KWVABC//'         = ''NONE'''
      GSETXT(19) = &
      'FRAME_2399001_'//KWSEC//KWVFRM//'          = ''J2000'''
      GSETXT(20) = &
      'FRAME_2399001_'//KWATOL//'       =  1.E-04'
      GSETXT(21) = &
      'FRAME_2399001_'//KWRSTA//'       =  '''// KVROTG //''''

      DX = 21



!
! --- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Check handling of missing keywords in ' // &
                   'GSE (two-vector) frame definition.' )
!
!     First set of tests:  delete required variables from the GSE
!     definition.  Make sure we get the expected error messages
!     when we refer to the GSE frame in an SXFORM or PXFORM call.
!     We currently restrict the testing to the keywords applicable
!     to dynamic frames.  These are keywords 7 through DX.
!
      DO I = 7, DX
!
!        Make a copy of the GSE definition.
!
         CALL MOVEC ( GSETXT, DX, DEFTX2 )
!
!        Lose the Ith element of the definition.
!
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
!
!
!        Load the modified GSE frame definition.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Delete the Ith element of the frame definition from
!        the kernel pool.
!
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSE SXFORM case: deleting keyword '//KEYWRD  )
!
!        Try an SXFORM call.
!
         CALL SXFORM ( 'GSE', 'J2000', 1.D6, XFORM )

         IF ( ( I .LT. DX ) .AND. ( I .NE. 20 ) )  THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The ROTATION STATE keyword is optional.
!
            CALL CHCKXC  ( .FALSE., ' ', OK )

         END IF

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSE PXFORM case: deleting keyword '//KEYWRD  )
!
!        Try a PXFORM call.
!
         CALL PXFORM ( 'GSE', 'J2000', 1.D6, R )

         IF ( ( I .LT. DX ) .AND. ( I .NE. 20 ) )  THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The ROTATION STATE keyword is optional.
!
            CALL CHCKXC  ( .FALSE., ' ', OK )

         END IF

      END DO

!
!     Second set of tests:  assign bogus values to variables from the
!     GSE definition.  Make sure we get the expected error messages
!     when we refer to the GSE frame in an SXFORM or PXFORM call. We
!     currently restrict the testing to the keywords applicable to
!     dynamic frames. These are keywords 7 through DX.
!
      DO I = 7, DX
!
!        Make a copy of the GSE definition.
!
         CALL MOVEC ( GSETXT, DX, DEFTX2 )

         J       = INDEX ( DEFTX2(I), '=' )

         KEYWRD  =  DEFTX2(I)(:J-1)

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSE SXFORM case: Changing RHS value ' // &
                      'for keyword ' //  KEYWRD )


         DEFTX2(I)(J+1:) = '''ABC'''

!
!        Load the modified GSE frame definition.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Set the expected error message resulting from an SXFORM
!        call relying on this frame definition.
!
!        Start with the most common error message.
!
         ERRMSG = 'SPICE(NOTSUPPORTED)'

!
!        Handle body name errors.
!
         IF (      ( INDEX ( KEYWRD, KWVTRG ) .GT. 0  ) &
              .OR. ( INDEX ( KEYWRD, KWVOBS ) .GT. 0  )  ) THEN

            ERRMSG = 'SPICE(NOTRANSLATION)'

         END IF

!
!        Handle aberration correction errors.
!
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(INVALIDOPTION)'

         END IF

!
!        Handle axis name errors.
!
         IF (  INDEX ( KEYWRD, KWVAXI ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(INVALIDAXIS)'

         END IF

!
!        Handle velocity frame name errors.  (Careful, the
!        substring 'FRAME' is at the start of each keyword.)
!
         IF (  INDEX ( KEYWRD, '_'//KWVFRM ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(NOTRANSLATION)'

         END IF

!
!        Handle minimum anglular separation errors.
!
         IF (  INDEX ( KEYWRD, KWATOL ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF

!
!        Try an SXFORM call.
!
         CALL SXFORM ( 'GSE', 'J2000', 1.D6, XFORM )
         CALL CHCKXC ( .TRUE., ERRMSG, OK )


!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSE PXFORM case: changing value for ' // &
                      'keyword '//KEYWRD  )


!
!        Try a PXFORM call.
!
!
!        Handle aberration correction errors.
!
         IF (      ( INDEX( KEYWRD, KWVABC ) .GT. 0 ) &
             .AND. ( INDEX( KEYWRD, 'PRI'  ) .GT. 0 )  ) THEN
!
!           For this PXFORM case, the error is caught in ZZSPKPA0,
!           which uses the following short error message:
!
            ERRMSG = 'SPICE(SPKINVALIDOPTION)'

         END IF

         CALL PXFORM ( 'GSE', 'J2000', 1.D6, R )
         CALL CHCKXC  ( .TRUE., ERRMSG, OK )


      END DO



! **************************************************************
! **************************************************************
! **************************************************************
!     TWO-VECTOR CASE:  GSM
! **************************************************************
! **************************************************************
! **************************************************************


!
!     Define the GSM frame.
!
      GSMTXT(1) = &
      'FRAME_GSM                        =  2399002'
      GSMTXT(2) = &
      'FRAME_2399002_NAME               = ''GSM'''
      GSMTXT(3) = &
      'FRAME_2399002_CLASS              =  5'
      GSMTXT(4) = &
      'FRAME_2399002_CLASS_ID           =  2399002'
      GSMTXT(5) = &
      'FRAME_2399002_CENTER             =  399'
      GSMTXT(6) = &
      'FRAME_2399002_RELATIVE           = ''J2000'''
      GSMTXT(7) = &
      'FRAME_2399002_'//KWSTYL//'       = '''// KVPARM //''''
      GSMTXT(8) = &
      'FRAME_2399002_'//KWFFAM//'             = '''// KV2VEC //''''
      GSMTXT(9) = &
      'FRAME_2399002_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      GSMTXT(10) = &
      'FRAME_2399002_'//KWPRI//KWVCDF//'       =  '''// KVPOSV //''''
      GSMTXT(11) = &
      'FRAME_2399002_'//KWPRI//KWVOBS//'       = ''EARTH'''
      GSMTXT(12) = &
      'FRAME_2399002_'//KWPRI//KWVTRG//'       = ''SUN'''
      GSMTXT(13) = &
      'FRAME_2399002_'//KWPRI//KWVABC//'         = ''NONE'''
      GSMTXT(14) = &
      'FRAME_2399002_'//KWSEC//KWVAXI//'       = '''//KVZ//''''
      GSMTXT(15) = &
      'FRAME_2399002_'//KWSEC//KWVCDF//'       = '''//KVCONS//''''
      GSMTXT(16) = &
      'FRAME_2399002_'//KWSEC//KWVSPC//'         = '''//KVLATC//''''
      GSMTXT(17) = &
      'FRAME_2399002_'//KWSEC//KWUNIT//'         = '''//KVDEGR//''''
      GSMTXT(18) = &
      'FRAME_2399002_'//KWSEC//KWLON//'          =   288.43'
      GSMTXT(19) = &
      'FRAME_2399002_'//KWSEC//KWLAT//'          =    79.54'
      GSMTXT(20) = &
      'FRAME_2399002_'//KWSEC//KWVFRM//'          = ''J2000'''
      GSMTXT(21) = &
      'FRAME_2399002_'//KWATOL//'       =  1.E-4'

      DX = 21


!
! --- Case: ------------------------------------------------------
!
      CALL TCASE ( 'Check handling of missing keywords in ' // &
                   'GSM (two-vector) frame definition.' )
!
!     First set of tests:  delete required variables from the GSM
!     definition.  Make sure we get the expected error messages
!     when we refer to the GSM frame in an SXFORM or PXFORM call.
!     We currently restrict the testing to the keywords applicable
!     to dynamic frames.  These are keywords 7 through DX.
!
      DO I = 7, DX
!
!        Make a copy of the GSM definition.
!
         CALL MOVEC ( GSMTXT, DX, DEFTX2 )
!
!        Lose the Ith element of the definition.
!
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
!
!
!        Load the modified GSM frame definition.  We don't
!        want to clear the kernel pool here because we'd have
!        to keep re-loading the PCK.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Delete the Ith element of the frame definition from
!        the kernel pool.
!
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSM SXFORM case: deleting keyword '//KEYWRD  )
!
!        Try an SXFORM call.
!
         CALL SXFORM ( 'GSM', 'J2000', 1.D6, XFORM )

         IF ( ( I .LT. DX ) .AND. ( I .NE. 21 ) )  THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The MIN_ANG_SEP keyword is optional.
!
            CALL CHCKXC  ( .FALSE., ' ', OK )

         END IF

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSM PXFORM case: deleting keyword '//KEYWRD  )
!
!        Try a PXFORM call.
!
         CALL PXFORM ( 'GSM', 'J2000', 1.D6, R )

         IF ( ( I .LT. DX ) .AND. ( I .NE. 21 ) )  THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The MIN_ANG_SEP keyword is optional.
!
            CALL CHCKXC  ( .FALSE., ' ', OK )

         END IF

      END DO

!
!     Second set of tests:  assign bogus values to variables from the
!     GSM definition.  Make sure we get the expected error messages
!     when we refer to the GSM frame in an SXFORM or PXFORM call. We
!     currently restrict the testing to the keywords applicable to
!     dynamic frames. These are keywords 7 through DX.
!
      DO I = 7, DX

!
!        Make a copy of the GSM definition.
!
         CALL MOVEC ( GSMTXT, DX, DEFTX2 )

         J       = INDEX ( DEFTX2(I), '=' )

         KEYWRD  =  DEFTX2(I)(:J-1)
!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSM SXFORM case: Changing RHS value ' // &
                      'for keyword ' //  KEYWRD )

         DEFTX2(I)(J+1:) = '''ABC'''

!
!        Load the modified GSM frame definition.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Set the expected error message resulting from an SXFORM
!        call relying on this frame definition.
!
!        Start with the most common error message.
!
         ERRMSG = 'SPICE(NOTSUPPORTED)'

!
!        Handle body name errors.
!
         IF (      ( INDEX ( KEYWRD, KWVTRG ) .GT. 0  ) &
              .OR. ( INDEX ( KEYWRD, KWVOBS ) .GT. 0  )  ) THEN

            ERRMSG = 'SPICE(NOTRANSLATION)'

         END IF

!
!        Handle aberration correction errors.
!
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(INVALIDOPTION)'

         END IF

!
!        Handle axis name errors.
!
         IF (  INDEX ( KEYWRD, KWVAXI ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(INVALIDAXIS)'

         END IF

!
!        Handle constant frame name errors.
!
         IF (  INDEX ( KEYWRD, '_'//KWVFRM ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(NOTRANSLATION)'

         END IF

!
!        Handle minimum anglular separation errors.
!
         IF (  INDEX ( KEYWRD, KWATOL ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF

!
!        Handle latitude and longitude errors.
!
         IF (  INDEX ( KEYWRD, 'LATITUDE' ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF

         IF (  INDEX ( KEYWRD, 'LONGITUDE' ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF

!
!        Handle unit errors.
!
         IF (  INDEX ( KEYWRD, KWUNIT ) .GT. 0  ) THEN

            ERRMSG = 'SPICE(UNITSNOTREC)'

         END IF


!
!        Try an SXFORM call.
!
         CALL SXFORM ( 'GSM', 'J2000', 1.D6, XFORM )
         CALL CHCKXC ( .TRUE., ERRMSG, OK )


!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'GSM PXFORM case: changing value for ' // &
                      'keyword '//KEYWRD  )
!
!        Try a PXFORM call.
!
!
!        Handle aberration correction errors.
!
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN
!
!           For PXFORM, the error is caught in ZZSPKPA0,
!           which uses the following short error message:
!
            ERRMSG = 'SPICE(SPKINVALIDOPTION)'

         END IF


         CALL PXFORM ( 'GSM', 'J2000', 1.D6, R )
         CALL CHCKXC  ( .TRUE., ERRMSG, OK )


      END DO



! **************************************************************
! **************************************************************
! **************************************************************
!     MEAN EQUATOR AND EQUINOX OF DATE CASES
! **************************************************************
! **************************************************************
! **************************************************************

!
!     First set of tests:  delete required variables from the MQQ
!     definition.  Make sure we get the expected error messages
!     when we refer to the MQQ frame in an SXFORM or PXFORM call.
!     We currently restrict the testing to the keywords applicable
!     to dynamic frames.  These are keywords 7 through DX.
!
      MQQTXT(1) = &
      'FRAME_MQQ                        =  2399003'
      MQQTXT(2) = &
      'FRAME_2399003_NAME               = ''MQQ'''
      MQQTXT(3) = &
      'FRAME_2399003_CLASS              =  5'
      MQQTXT(4) = &
      'FRAME_2399003_CLASS_ID           =  2399003'
      MQQTXT(5) = &
      'FRAME_2399003_CENTER             =  399'
      MQQTXT(6) = &
      'FRAME_2399003_RELATIVE           = ''J2000'''
      MQQTXT(7) = &
      'FRAME_2399003_' // KWSTYL // '   = ''' // KVPARM // ''''
      MQQTXT(8) = &
      'FRAME_2399003_' // KWFFAM // '             = '''// KVMEQT //''''
      MQQTXT(9) = &
      'FRAME_2399003_' // KWPRCM // '   = ''' // KVM001 // ''''
      MQQTXT(10) = &
      'FRAME_2399003_' // KWRSTA // '    = ''' // KVROTG //''''

      DX = 10


      DO I = 7, DX
!
!        Make a copy of the MQQ definition.
!
         CALL MOVEC ( MQQTXT, DX, DEFTX2 )
!
!        Lose the Ith element of the definition.
!
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
!
!
!        Load the modified MQQ frame definition.  We don't
!        want to clear the kernel pool here because we'd have
!        to keep re-loading the PCK.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Delete the Ith element of the frame definition from
!        the kernel pool.
!
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'MQQ SXFORM case: deleting keyword '//KEYWRD  )
!
!        Try an SXFORM call.
!
         CALL SXFORM ( 'MQQ', 'J2000', 1.D6, XFORM )

         IF ( I .LT. DX ) THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The ROTATION_STATE keyword or the FREEZE_EPOCH keyword
!           must be present.
!
            CALL CHCKXC ( .TRUE., 'SPICE(FRAMEDEFERROR)', OK )

         END IF

!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'MQQ PXFORM case: deleting keyword '//KEYWRD  )
!
!        Try a PXFORM call.
!
         CALL PXFORM ( 'MQQ', 'J2000', 1.D6, R )

         IF ( I .LT. DX ) THEN
!
!           We've deleted a required keyword.
!
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )

         ELSE
!
!           The ROTATION_STATE keyword or the FREEZE_EPOCH keyword
!           must be present.
!
            CALL CHCKXC ( .TRUE., 'SPICE(FRAMEDEFERROR)', OK )

         END IF

      END DO

!
!     Second set of tests:  assign bogus values to variables from the
!     MQQ definition.  Make sure we get the expected error messages
!     when we refer to the MQQ frame in an SXFORM or PXFORM call. We
!     currently restrict the testing to the keywords applicable to
!     dynamic frames. These are keywords 7 through DX.
!
      DO I = 7, DX

!
!        Make a copy of the MQQ definition.
!
         CALL MOVEC ( MQQTXT, DX, DEFTX2 )

         J       = INDEX ( DEFTX2(I), '=' )

         KEYWRD  =  DEFTX2(I)(:J-1)
!
! --- Case: ------------------------------------------------------
!
         CALL TCASE ( 'MQQ SXFORM case: Changing RHS value ' // &
                      'for keyword ' //  KEYWRD )

         DEFTX2(I)(J+1:) = '''ABC'''

!
!        Load the modified MQQ frame definition.
!
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )

!
!        Set the expected error message resulting from an SXFORM
!        call relying on this frame definition.
!
!        Start with the most common error message.
!
         ERRMSG = 'SPICE(NOTSUPPORTED)'


!
