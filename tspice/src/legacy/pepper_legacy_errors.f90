! Legacy interface to pepper_errors: external procedures with SPICELIB's names
! and argument lists, calling the module procedures. Generated by
! tools/modularize.py when the routines moved to src/pepper_errors.f90.
!
! These keep the original SPICELIB interface for existing callers (such as
! the tspice tests). New code should use pepper_errors directly.

       !> Return the explanation of a short error message.
       !>
       !> Legacy interface: calls expln of module pepper_errors.
       subroutine expln ( msg, expl )
      use pepper_errors, only: pepper_expln => expln
      implicit none
      character(*)                  msg  !! A short error message.
      character(*)                  expl  !! The explanation of the short error message.
      call pepper_expln ( msg, expl )
      end subroutine expln
