"""Write python/COVERAGE.md: SpiceyPy's functions, and which PepperyPy has
(generated from PEPPER's interfaces, or written in _compat.py), with the
reason for the others.

    pixi run -e python py-coverage
"""

import inspect
from pathlib import Path

import pepperypy
from pepperypy import _compat
from pepperypy._generated_names import ALIGNED, GENERATED, SKIPPED
from spiceypy import spiceypy as sp

OUT = Path(__file__).resolve().parent.parent / 'COVERAGE.md'


def main():
    names = sorted(n for n, f in vars(sp).items() if inspect.isfunction(f) and not n.startswith('_')
                   and f.__module__ == sp.__name__)
    compat = {n for n, f in vars(_compat).items() if callable(f) and not n.startswith('_')}
    generated = set(GENERATED)
    aligned = set(ALIGNED)
    have, missing = [], []
    for n in names:
        if hasattr(pepperypy, n):
            how = 'written for SpiceyPy\'s signature' if n in compat else (
                'generated' + ('' if n in aligned else ' (Fortran argument order)'))
            have.append((n, how))
        else:
            why = SKIPPED.get(n, 'no SPICELIB routine of this name in PEPPER (a CSPICE-only function)')
            missing.append((n, why))
    extra = sorted(n for n in generated if not hasattr(sp, n))
    lines = [
        '# PepperyPy: coverage of SpiceyPy\'s functions',
        '',
        'Generated by `python/tools/coverage.py` (`pixi run -e python py-coverage`); do not edit.',
        '',
        f'Of SpiceyPy\'s {len(names)} functions, PepperyPy has **{len(have)}** '
        f'({100 * len(have) // len(names)}%); it also has {len(extra)} functions SpiceyPy does not '
        '(PEPPER\'s, such as `spk_coverage` and `gf_distance`, and SPICELIB routines CSPICE does not wrap).',
        '',
        '- *generated*: from PEPPER\'s interface by `tools/gen_capi.py`, with SpiceyPy\'s parameters.',
        '- *generated (Fortran argument order)*: SpiceyPy\'s parameters differ (its function takes',
        '  sizes, or omits arguments); the Fortran routine\'s inputs, in order.',
        '- *written for SpiceyPy\'s signature*: `pepperypy/_compat.py`, on PEPPER\'s results of any',
        '  size (`pool_values`, `gf_distance`, ...).',
        '',
        f'## Missing ({len(missing)})',
        '',
        '| Function | Why |',
        '|---|---|',
    ]
    lines += [f'| `{n}` | {why} |' for n, why in missing]
    lines += ['', f'## Available ({len(have)})', '', '| Function | How |', '|---|---|']
    lines += [f'| `{n}` | {how} |' for n, how in have]
    lines += ['', f'## Not in SpiceyPy ({len(extra)})', '', ', '.join(f'`{n}`' for n in extra), '']
    OUT.write_text('\n'.join(lines))
    print(f'{OUT}: {len(have)} of {len(names)} SpiceyPy functions; {len(extra)} more')


if __name__ == '__main__':
    main()
