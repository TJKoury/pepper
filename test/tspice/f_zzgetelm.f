C     Call the user level routine. Expect no errors.
C
      CALL GETELM ( FRSTYR, LINES, EPOCH, ELEMS )
      CALL CHCKXC ( .FALSE., ' ', OK )


C
C     Now test the error checks. Too long. Longest allowed line: 69.
C
