      CALL CHCKSL ( 'OK 3', ERRSIG, .FALSE.,  OK )

      CALL GETELM ( FRSTYR, LINES, EPOCH, ELEMS )
      CALL CHCKXC ( .TRUE., 'SPICE(BADTLE)', OK )


C
C     Now test the error checks. Too short. Shortest allowed line: 68.
C
