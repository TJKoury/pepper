      LINES(1) = '1 25544U 98067A   98324.89267077  .00616830'
     .         //'  11572-4  29139-3 0    84'
      LINES(2) = '2 25544  51.5947 165.1012 0122649  89.2072 '
     .         //'272.3014 16.05443269       101'

