!$Procedure      FILREG ( File Registry )

      SUBROUTINE FILREG ( FILE )

! $ Abstract
!
!     This routine is an umbrella for a pair of entry points that
!     maintains/deletes a list of files created within a test family.
!
! $ Required_Reading
!
!     None.
!
! $ Keywords
!
!     Testing
!
! $ Declarations

      IMPLICIT NONE
      CHARACTER*(*)         FILE

      INTEGER               MAXFIL
      PARAMETER           ( MAXFIL = 100 )

! $ Brief_I/O
!
!     VARIABLE  I/O  ENTRY POINT
!     --------  ---  --------------------------------------------------
!     FILE       I   TFILES
!     MAXFIL     P   Maximum number of files that can be maintained.
!
! $ Detailed_Input
!
!     FILE       is some file that should be registered as a file
!                created by a Test Utility routine.  This file
!                will be "killed" (through a call to KILFIL)
!                when the entry point KFILES is called.
!
! $ Detailed_Output
!
!     None.
!
! $ Parameters
!
!     MAXFIL     is the maximum number of files that can be maintained
!                by the file registry.
!
! $ Files
!
!     None.
!
! $ Exceptions
!
!     Error free.
!
!     1) All files supplied to TFILES after the MAXFILth file
!        has been supplied without a call to KFILES will be
!        ignored.
!
! $ Particulars
!
!     This is a utility routine that allows test utility routines
!     that create files, to register these files with a central
!     manager.
!
!     This allows TOPEN and TCLOSE to delete all such files so that
!     test families organized into a test program (as in tspice) will
!     automatically clean up after themselves without leaving
!     test files on disk as part of the debris of performing a test.
!
!     ==========================================================
!     ==========================================================
!
!     NOTE: If the user supplied the debugging flag '-D' in the
!     invocation of the test program, or if the user explicitely
!     turns on debugging by calling the function SETON as
!     shown below
!
!        DUMMY = SETON ( 'DEBUGGING' )
!
!     Files supplied to TFILES are ignored and as such will not
!     be deleted.
!
!     By placing function invocations
!
!          SETON/SETOFF ( 'DEBUGGING' )
!
!     in balanced pairs within a test family, programmers can override
!     the normal clean up activities of TOPEN and TCLOSE.
!
!
! $ Examples
!
!     If you create a new test file generator, you should insert
!     the following call somewhere in the file.
!
!        CALL TFILE ( <name of the test file> )
!
!     By so doing, all files generated by the test utilities will
!     be cleaned up by the test program alleviating programmers
!     from the error prone responsibility of cleaning up test files
!     at the end of a test family.
!
! $ Restrictions
!
!     None.
!
! $ Author_and_Institution
!
!     W.L. Taber      (JPL)
!
! $ Literature_References
!
!     None.
!
! $ Version
!
!-    Test Utilities Version 1.0.0, 28-JUL-1999 (WLT)
!
!
!-&
      INTEGER               RTRIM
      LOGICAL               ISON


      INTEGER               FILSIZ
      PARAMETER           ( FILSIZ = 255 )

      CHARACTER*(FILSIZ)    FILES ( MAXFIL )
      SAVE                  FILES

      INTEGER               NFILE
      SAVE                  NFILE

      INTEGER               I
      INTEGER               R

      DATA                  NFILE / 0 /

      RETURN
!
!     The next entry point registers a file.
!
      ENTRY TFILES ( FILE )
!
!        Don't register files when we are in DEBUGGING mode.
!
         IF ( ISON ( 'DEBUGGING' ) ) THEN
            RETURN
         END IF

         IF ( NFILE .LT. MAXFIL ) THEN
            NFILE           = NFILE + 1
            FILES ( NFILE ) = FILE
         END IF

         RETURN

!
!     This entry point deletes all registered files.
!
      ENTRY KFILES


         DO I = 1, NFILE

            R = RTRIM( FILES(I) )
            CALL KILFIL ( FILES(I)(1:R) )

         END DO

         NFILE = 0

         RETURN

      END
