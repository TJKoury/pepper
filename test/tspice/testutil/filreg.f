      INTEGER               RTRIM
      LOGICAL               ISON
 
 
      INTEGER               FILSIZ
      PARAMETER           ( FILSIZ = 255 )
 
      CHARACTER*(FILSIZ)    FILES ( MAXFIL )
      SAVE                  FILES
 
      INTEGER               NFILE
      SAVE                  NFILE
 
      INTEGER               I
      INTEGER               R
 
      DATA                  NFILE / 0 /

      RETURN 
C
C     The next entry point registers a file.
C
      ENTRY TFILES ( FILE )
C
C        Don't register files when we are in DEBUGGING mode.
C
         IF ( ISON ( 'DEBUGGING' ) ) THEN
            RETURN
         END IF
 
         IF ( NFILE .LT. MAXFIL ) THEN
            NFILE           = NFILE + 1
            FILES ( NFILE ) = FILE
         END IF
 
         RETURN
 
C
C     This entry point deletes all registered files.
C
      ENTRY KFILES
 
 
         DO I = 1, NFILE
 
            R = RTRIM( FILES(I) )
            CALL KILFIL ( FILES(I)(1:R) )
 
         END DO
 
         NFILE = 0
 
         RETURN
 
      END
