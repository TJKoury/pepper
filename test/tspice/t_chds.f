      SUBROUTINE T_CHDS ( NAME, ARRAY, COMP, EXP, SIZE, TOL, OK )  
C
C     Check segment descriptors for BSR test families.
C
C        10-NOV-2001 (NJB)
C

      IMPLICIT NONE

      CHARACTER*(*)         NAME
      DOUBLE PRECISION      ARRAY ( * )
      CHARACTER*(*)         COMP
      DOUBLE PRECISION      EXP   ( * )
      INTEGER               SIZE
      DOUBLE PRECISION      TOL
      LOGICAL               OK

C
C     Local parameters
C  
      INTEGER               NDC
      PARAMETER           ( NDC    = 2 )

      INTEGER               MAXIC
      PARAMETER           ( MAXIC  = 6 )
C
C     Local variables
C
      DOUBLE PRECISION      DC  ( NDC )
      DOUBLE PRECISION      XDC ( NDC )

      INTEGER               NIC
      INTEGER               IC  ( MAXIC )
      INTEGER               XIC ( MAXIC )



      NIC = ( SIZE - 2 ) * 2

      CALL DAFUS ( ARRAY, NDC, NIC, DC,  IC  )
      CALL DAFUS ( EXP,   NDC, NIC, XDC, XIC )
C
C     Check the d.p. components.
C
      CALL CHCKAD ( NAME, DC, COMP, XDC, NDC, TOL, OK )

      IF ( .NOT. OK ) THEN
         RETURN
      END IF

C
C     Check the integer components.
C
      CALL CHCKAI ( NAME, IC, COMP, XIC, NIC, OK )

      RETURN
      END
      
