      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL DAFFNA  ( FOUND )
      CALL CHCKXC  ( .FALSE., ' ', OK )
 
      DO WHILE ( FOUND )
 
         CALL DAFGS  ( SUM )
         CALL CHCKXC ( .FALSE., ' ', OK )
 
         CALL DAFUS ( SUM, ND, NI, DC, IC )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
         IF ( IC(1) .EQ. -10001 ) THEN
C
C           Update the descriptor.  For CK descriptors, the frame
C           ID is in the second element of the integer component.
C
            CALL NAMFRM ( 'RECUR_2', IC(2) )
            CALL CHCKXC ( .FALSE., ' ', OK )
            IC(1) = IC(1) + 100
 
            CALL DAFPS  ( ND, NI, DC, IC, SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
C
C           Write the new descriptor.
C
            CALL DAFRS  ( SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
 
         ELSE IF ( IC(1) .EQ. -10000 ) THEN
C
C           Update the descriptor.
C
            CALL NAMFRM ( 'RECUR_3', IC(2) )
            IC(1) = IC(1) + 100
 
            CALL DAFPS  ( ND, NI, DC, IC, SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
C
C           Write the new descriptor.
C
            CALL DAFRS  ( SUM )
            CALL CHCKXC ( .FALSE., ' ', OK )
 
         END IF
 
         CALL DAFFNA ( FOUND )
         CALL CHCKXC ( .FALSE., ' ', OK )
 
      END DO
 
C
C     Close the modified CK file.
C
      CALL DAFCLS ( HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
C
C--- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Look up pointing of instrument -9901 ' //
     .             'in frame RECUR_2.'                      )
 
C
C     Load the CK containing data of interest.
C
      CALL CKLPF  ( CK2, HANDLE(4)   )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
C
C     Look up the pointing and angular velocity of instrument -9901 in
C     the dynamic frame RECUR_2. The data should match those of the
C     instrument -10001 in frame J2000.
C
      INSTID = -9901
      CLKID  = -9
 
      CALL STR2ET ( '2005 JAN 1 12:00 TDB', ET )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL SCE2C  ( CLKID,   ET,     SCLKDP )
      CALL CHCKXC ( .FALSE., ' ',    OK     )
 
C
C     Look up pointing relative to frame RECUR_2.
C
      CALL CKGPAV ( INSTID,  SCLKDP, 0.D0,   'RECUR_2',
     .              CMAT0,   AV0,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                )
      CALL CHCKSL ( '-9901 FOUND',  FOUND, .TRUE., OK  )
 
C
C     Look up the same data for instrument -10001 using the
C     J2000 frame (base frame for instrument -10001).
C     Compare.
C
      CALL CKGPAV ( -10001,   SCLKDP, 0.D0,   'J2000',
     .              CMAT1,    AV1,    CLKOUT, FOUND      )
      CALL CHCKXC ( .FALSE., ' ',    OK                 )
      CALL CHCKSL ( '-10001 FOUND',  FOUND, .TRUE., OK  )
 
C
C     Compare C-matrices.
C
      CALL CHCKAD ( 'CMAT0', CMAT0, '~', CMAT1, 9, EX13, OK )
 
C
C     Compare angular velocity vectors.
C
      CALL CHCKAD ( 'AV0', AV0, '~', AV1, 3, EX13, OK )
 
C
C--- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Look up pointing of instrument -9901 ' //
     .             'in frame J2000.  This forces the CK '  //
     .             'subsystem to do a dynamic frame '      //
     .             'transformation.'                       )
 
C
C     Load the CK containing data of interest.
C
      CALL CKLPF  ( CK2, HANDLE(4)   )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
C
C     Look up the pointing and angular velocity of instrument -9901 in
C     the dynamic frame J2000.  The data should match those of the
C     instrument -10001 after the RECUR_2 to J2000 state transformation
C     is applied.
C
      INSTID = -9901
      CLKID  = -9
 
      CALL STR2ET ( '2005 JAN 1 12:00 TDB', ET )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL SCE2C  ( CLKID,   ET,     SCLKDP )
      CALL CHCKXC ( .FALSE., ' ',    OK     )
 
C
C     Look up pointing relative to frame J2000.
C
      CALL CKGPAV ( INSTID,  SCLKDP, 0.D0,   'J2000',
     .              CMAT0,   AV0,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                )
      CALL CHCKSL ( '-9901 FOUND',  FOUND, .TRUE., OK  )
 
C
C     Look up the same data for instrument -10001 using the
C     J2000 frame (base frame for instrument -10001).
C     Compare.
C
      CALL CKGPAV ( -10001,   SCLKDP, 0.D0,   'J2000',
     .              CMAT1,    AV1,    CLKOUT, FOUND     )
      CALL CHCKXC ( .FALSE., ' ',    OK                 )
      CALL CHCKSL ( '-10001 FOUND',  FOUND, .TRUE., OK  )
 
C
C     Get the  J2000 to RECUR_2 position transformation matrix.
C     Right-multiply CMAT1 by this.
C
      CALL PXFORM ( 'J2000', 'RECUR_2', ET, R )
      CALL CHCKXC ( .FALSE., ' ',    OK       )
 
      CALL MXM    ( CMAT1,    R,        CMAT2 )
 
C
C     Compare C-matrices.
C
      CALL CHCKAD ( 'CMAT0', CMAT0, '~', CMAT2, 9, EX13, OK )
 
C
C     Compare angular velocity vectors. To simplify the computations,
C     we'll work with state transformations. Construct the J2000 to
C     CK_-10001 state transformation XF2 from the corresponding
C     C-matrix and angular velocity vector. Right-multiply this by the
C     J2000 to RECUR_2 state transformation XF3. This should yield a
C     transformation XF4 equivalent to XFORM, since XFORM was
C     effectively created by the same right-multiplication of the state
C     transformation matrix mapping RECUR_2 to CK_-9901.  The angular
C     velocity vector AV2 extracted from XF4 can then be compared to
C     the original angular velocity vector AV0.
C
      CALL RAV2XF ( CMAT1, AV1, XF2 )
 
      CALL SXFORM ( 'J2000', 'RECUR_2', ET, XF3 )
      CALL CHCKXC ( .FALSE., ' ',    OK         )
 
      CALL MXMG   ( XF2, XF3, 6, 6, 6, XF4 )
 
C
C     Extract angular velocity from XF4.
C
      CALL XF2RAV ( XF4, CMAT2, AV2 )
 
C
C     Check AV0.
C
      CALL CHCKAD ( 'AV0', AV0, '~', AV2, 3, EX13, OK )
 
C
C--- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Look up pointing of instrument -9900 '     //
     .             'in frame J2000.  The segment for -9900 '   //
     .             'has a dynamic base frame requiring three ' //
     .             'levels of recursion for evaluation.'       )
 
C
C     Look up the state of body 700 relative to the solar system
C     barycenter in the dynamic frame RECUR_3.  We expect an error
C     to be signaled.
C
      CALL CKGPAV ( -9900,   SCLKDP, 0.D0,   'J2000',
     .              CMAT0,   AV0,    CLKOUT, FOUND           )
      CALL CHCKXC ( .TRUE.,  'SPICE(RECURSIONTOODEEP)',   OK )
 
C
C     End of test cases.
C
 
 
C
C     Clean up the SPK and CK files.
C
      CALL SPKUEF ( HANDLE(1) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( SPK       )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL CKUPF  ( HANDLE(2) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( CKNM      )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL SPKUEF ( HANDLE(3) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( SPK2      )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
      CALL CKUPF  ( HANDLE(4) )
      CALL CHCKXC ( .FALSE., ' ', OK )
      CALL DELFIL ( CK2       )
      CALL CHCKXC ( .FALSE., ' ', OK )
 
C
C     Close out the test family.
C
      CALL T_SUCCESS ( OK )
      RETURN
 
      END
