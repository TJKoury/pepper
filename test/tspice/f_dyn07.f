C
      LOGICAL               EQSTR
C
C     Local Parameters
C
      CHARACTER*(*)         PCK
      PARAMETER           ( PCK    = 'test_dyn.tpc' )
 
      CHARACTER*(*)         SPK
      PARAMETER           ( SPK    = 'test_dyn.bsp' )
 
 
      INTEGER               LNSIZE
      PARAMETER           ( LNSIZE = 80 )
 
      INTEGER               MAXDEF
      PARAMETER           ( MAXDEF = 50 )
 
      INTEGER               TIMLEN
      PARAMETER           ( TIMLEN = 50 )
 
 
C
C     Parameters controlling frame definitions:
C
 
C
C     Local Variables
C
      CHARACTER*(LNSIZE)    DEFTX2 ( MAXDEF )
      CHARACTER*(LMSGLN)    ERRMSG
      CHARACTER*(LNSIZE)    GSETXT ( MAXDEF )
      CHARACTER*(LNSIZE)    GSMTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    KEYWRD
      CHARACTER*(LNSIZE)    MARTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    MCQTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    MQQTXT ( MAXDEF )
      CHARACTER*(LNSIZE)    TQQTXT ( MAXDEF )
 
      DOUBLE PRECISION      R      ( 3, 3 )
      DOUBLE PRECISION      XFORM  ( 6, 6 )
 
      INTEGER               DX
      INTEGER               HANDLE
      INTEGER               I
      INTEGER               J
 
C
C     Saved variables
C
 
C
C     Initial values
C
 
C
C     Open the test family.
C
      CALL TOPEN ( 'F_DYN07' )
 
 
C **************************************************************
C **************************************************************
C **************************************************************
C     TWO-VECTOR CASES
C **************************************************************
C **************************************************************
C **************************************************************
 
C
C --- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Create and load kernels.' )
 
 
C
C     Create and load kernels.
C
      CALL TSTLSK
      CALL CHCKXC  ( .FALSE., ' ', OK )
 
      CALL TSTSPK  ( SPK, .TRUE., HANDLE  )
      CALL CHCKXC  ( .FALSE., ' ', OK )
 
      CALL T_PCK08 ( PCK, .TRUE., .FALSE. )
      CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C     Define the GSE frame.
C
      GSETXT(1) =
     .'FRAME_GSE                        =  2399001'
      GSETXT(2) =
     .'FRAME_2399001_NAME               = ''GSE'''
      GSETXT(3) =
     .'FRAME_2399001_CLASS              =  5'
      GSETXT(4) =
     .'FRAME_2399001_CLASS_ID           =  2399001'
      GSETXT(5) =
     .'FRAME_2399001_CENTER             =  399'
      GSETXT(6) =
     .'FRAME_2399001_RELATIVE           = ''J2000'''
      GSETXT(7) =
     .'FRAME_2399001_'//KWSTYL//'       = '''// KVPARM //''''
      GSETXT(8) =
     .'FRAME_2399001_'//KWFFAM//'             = '''// KV2VEC //''''
      GSETXT(9) =
     .'FRAME_2399001_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      GSETXT(10) =
     .'FRAME_2399001_'//KWPRI//KWVCDF//'       = '''//KVPOSV//''''
      GSETXT(11) =
     .'FRAME_2399001_'//KWPRI//KWVOBS//'       = ''EARTH'''
      GSETXT(12) =
     .'FRAME_2399001_'//KWPRI//KWVTRG//'         = ''SUN'''
      GSETXT(13) =
     .'FRAME_2399001_'//KWPRI//KWVABC//'         = ''NONE'''
      GSETXT(14) =
     .'FRAME_2399001_'//KWSEC//KWVAXI//'       = ''-'//KVY//''''
      GSETXT(15) =
     .'FRAME_2399001_'//KWSEC//KWVCDF//'       =  '''// KVVELV //''''
      GSETXT(16) =
     .'FRAME_2399001_'//KWSEC//KWVOBS//'       = ''SUN'''
      GSETXT(17) =
     .'FRAME_2399001_'//KWSEC//KWVTRG//'       = ''EARTH'''
      GSETXT(18) =
     .'FRAME_2399001_'//KWSEC//KWVABC//'         = ''NONE'''
      GSETXT(19) =
     .'FRAME_2399001_'//KWSEC//KWVFRM//'          = ''J2000'''
      GSETXT(20) =
     .'FRAME_2399001_'//KWATOL//'       =  1.E-04'
      GSETXT(21) =
     .'FRAME_2399001_'//KWRSTA//'       =  '''// KVROTG //''''
 
      DX = 21
 
 
 
C
C --- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Check handling of missing keywords in ' //
     .             'GSE (two-vector) frame definition.' )
C
C     First set of tests:  delete required variables from the GSE
C     definition.  Make sure we get the expected error messages
C     when we refer to the GSE frame in an SXFORM or PXFORM call.
C     We currently restrict the testing to the keywords applicable
C     to dynamic frames.  These are keywords 7 through DX.
C
      DO I = 7, DX
C
C        Make a copy of the GSE definition.
C
         CALL MOVEC ( GSETXT, DX, DEFTX2 )
C
C        Lose the Ith element of the definition.
C
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
C
C
C        Load the modified GSE frame definition.
C
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C        Delete the Ith element of the frame definition from
C        the kernel pool.
C
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSE SXFORM case: deleting keyword '//KEYWRD  )
C
C        Try an SXFORM call.
C
         CALL SXFORM ( 'GSE', 'J2000', 1.D6, XFORM )
 
         IF ( ( I .LT. DX ) .AND. ( I .NE. 20 ) )  THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
         ELSE
C
C           The ROTATION STATE keyword is optional.
C
            CALL CHCKXC  ( .FALSE., ' ', OK )
 
         END IF
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSE PXFORM case: deleting keyword '//KEYWRD  )
C
C        Try a PXFORM call.
C
         CALL PXFORM ( 'GSE', 'J2000', 1.D6, R )
 
         IF ( ( I .LT. DX ) .AND. ( I .NE. 20 ) )  THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
         ELSE
C
C           The ROTATION STATE keyword is optional.
C
            CALL CHCKXC  ( .FALSE., ' ', OK )
 
         END IF
 
      END DO
 
C
C     Second set of tests:  assign bogus values to variables from the
C     GSE definition.  Make sure we get the expected error messages
C     when we refer to the GSE frame in an SXFORM or PXFORM call. We
C     currently restrict the testing to the keywords applicable to
C     dynamic frames. These are keywords 7 through DX.
C
      DO I = 7, DX
C
C        Make a copy of the GSE definition.
C
         CALL MOVEC ( GSETXT, DX, DEFTX2 )
 
         J       = INDEX ( DEFTX2(I), '=' )
 
         KEYWRD  =  DEFTX2(I)(:J-1)
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSE SXFORM case: Changing RHS value ' //
     .                'for keyword ' //  KEYWRD )
 
 
         DEFTX2(I)(J+1:) = '''ABC'''
 
C
C        Load the modified GSE frame definition.
C
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C        Set the expected error message resulting from an SXFORM
C        call relying on this frame definition.
C
C        Start with the most common error message.
C
         ERRMSG = 'SPICE(NOTSUPPORTED)'
 
C
C        Handle body name errors.
C
         IF (      ( INDEX ( KEYWRD, KWVTRG ) .GT. 0  )
     .        .OR. ( INDEX ( KEYWRD, KWVOBS ) .GT. 0  )  ) THEN
 
            ERRMSG = 'SPICE(NOTRANSLATION)'
 
         END IF
 
C
C        Handle aberration correction errors.
C
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(INVALIDOPTION)'
 
         END IF
 
C
C        Handle axis name errors.
C
         IF (  INDEX ( KEYWRD, KWVAXI ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(INVALIDAXIS)'
 
         END IF
 
C
C        Handle velocity frame name errors.  (Careful, the
C        substring 'FRAME' is at the start of each keyword.)
C
         IF (  INDEX ( KEYWRD, '_'//KWVFRM ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(NOTRANSLATION)'
 
         END IF
 
C
C        Handle minimum anglular separation errors.
C
         IF (  INDEX ( KEYWRD, KWATOL ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF
 
C
C        Try an SXFORM call.
C
         CALL SXFORM ( 'GSE', 'J2000', 1.D6, XFORM )
         CALL CHCKXC ( .TRUE., ERRMSG, OK )
 
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSE PXFORM case: changing value for ' //
     .                'keyword '//KEYWRD  )
 
 
C
C        Try a PXFORM call.
C
C
C        Handle aberration correction errors.
C
         IF (      ( INDEX( KEYWRD, KWVABC ) .GT. 0 )
     .       .AND. ( INDEX( KEYWRD, 'PRI'  ) .GT. 0 )  ) THEN
C
C           For this PXFORM case, the error is caught in ZZSPKPA0,
C           which uses the following short error message:
C
            ERRMSG = 'SPICE(SPKINVALIDOPTION)'
 
         END IF
 
         CALL PXFORM ( 'GSE', 'J2000', 1.D6, R )
         CALL CHCKXC  ( .TRUE., ERRMSG, OK )
 
 
      END DO
 
 
 
C **************************************************************
C **************************************************************
C **************************************************************
C     TWO-VECTOR CASE:  GSM
C **************************************************************
C **************************************************************
C **************************************************************
 
 
C
C     Define the GSM frame.
C
      GSMTXT(1) =
     .'FRAME_GSM                        =  2399002'
      GSMTXT(2) =
     .'FRAME_2399002_NAME               = ''GSM'''
      GSMTXT(3) =
     .'FRAME_2399002_CLASS              =  5'
      GSMTXT(4) =
     .'FRAME_2399002_CLASS_ID           =  2399002'
      GSMTXT(5) =
     .'FRAME_2399002_CENTER             =  399'
      GSMTXT(6) =
     .'FRAME_2399002_RELATIVE           = ''J2000'''
      GSMTXT(7) =
     .'FRAME_2399002_'//KWSTYL//'       = '''// KVPARM //''''
      GSMTXT(8) =
     .'FRAME_2399002_'//KWFFAM//'             = '''// KV2VEC //''''
      GSMTXT(9) =
     .'FRAME_2399002_'//KWPRI//KWVAXI//'       = '''//KVX//''''
      GSMTXT(10) =
     .'FRAME_2399002_'//KWPRI//KWVCDF//'       =  '''// KVPOSV //''''
      GSMTXT(11) =
     .'FRAME_2399002_'//KWPRI//KWVOBS//'       = ''EARTH'''
      GSMTXT(12) =
     .'FRAME_2399002_'//KWPRI//KWVTRG//'       = ''SUN'''
      GSMTXT(13) =
     .'FRAME_2399002_'//KWPRI//KWVABC//'         = ''NONE'''
      GSMTXT(14) =
     .'FRAME_2399002_'//KWSEC//KWVAXI//'       = '''//KVZ//''''
      GSMTXT(15) =
     .'FRAME_2399002_'//KWSEC//KWVCDF//'       = '''//KVCONS//''''
      GSMTXT(16) =
     .'FRAME_2399002_'//KWSEC//KWVSPC//'         = '''//KVLATC//''''
      GSMTXT(17) =
     .'FRAME_2399002_'//KWSEC//KWUNIT//'         = '''//KVDEGR//''''
      GSMTXT(18) =
     .'FRAME_2399002_'//KWSEC//KWLON//'          =   288.43'
      GSMTXT(19) =
     .'FRAME_2399002_'//KWSEC//KWLAT//'          =    79.54'
      GSMTXT(20) =
     .'FRAME_2399002_'//KWSEC//KWVFRM//'          = ''J2000'''
      GSMTXT(21) =
     .'FRAME_2399002_'//KWATOL//'       =  1.E-4'
 
      DX = 21
 
 
C
C --- Case: ------------------------------------------------------
C
      CALL TCASE ( 'Check handling of missing keywords in ' //
     .             'GSM (two-vector) frame definition.' )
C
C     First set of tests:  delete required variables from the GSM
C     definition.  Make sure we get the expected error messages
C     when we refer to the GSM frame in an SXFORM or PXFORM call.
C     We currently restrict the testing to the keywords applicable
C     to dynamic frames.  These are keywords 7 through DX.
C
      DO I = 7, DX
C
C        Make a copy of the GSM definition.
C
         CALL MOVEC ( GSMTXT, DX, DEFTX2 )
C
C        Lose the Ith element of the definition.
C
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
C
C
C        Load the modified GSM frame definition.  We don't
C        want to clear the kernel pool here because we'd have
C        to keep re-loading the PCK.
C
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C        Delete the Ith element of the frame definition from
C        the kernel pool.
C
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSM SXFORM case: deleting keyword '//KEYWRD  )
C
C        Try an SXFORM call.
C
         CALL SXFORM ( 'GSM', 'J2000', 1.D6, XFORM )
 
         IF ( ( I .LT. DX ) .AND. ( I .NE. 21 ) )  THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
         ELSE
C
C           The MIN_ANG_SEP keyword is optional.
C
            CALL CHCKXC  ( .FALSE., ' ', OK )
 
         END IF
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSM PXFORM case: deleting keyword '//KEYWRD  )
C
C        Try a PXFORM call.
C
         CALL PXFORM ( 'GSM', 'J2000', 1.D6, R )
 
         IF ( ( I .LT. DX ) .AND. ( I .NE. 21 ) )  THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
         ELSE
C
C           The MIN_ANG_SEP keyword is optional.
C
            CALL CHCKXC  ( .FALSE., ' ', OK )
 
         END IF
 
      END DO
 
C
C     Second set of tests:  assign bogus values to variables from the
C     GSM definition.  Make sure we get the expected error messages
C     when we refer to the GSM frame in an SXFORM or PXFORM call. We
C     currently restrict the testing to the keywords applicable to
C     dynamic frames. These are keywords 7 through DX.
C
      DO I = 7, DX
 
C
C        Make a copy of the GSM definition.
C
         CALL MOVEC ( GSMTXT, DX, DEFTX2 )
 
         J       = INDEX ( DEFTX2(I), '=' )
 
         KEYWRD  =  DEFTX2(I)(:J-1)
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSM SXFORM case: Changing RHS value ' //
     .                'for keyword ' //  KEYWRD )
 
         DEFTX2(I)(J+1:) = '''ABC'''
 
C
C        Load the modified GSM frame definition.
C
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C        Set the expected error message resulting from an SXFORM
C        call relying on this frame definition.
C
C        Start with the most common error message.
C
         ERRMSG = 'SPICE(NOTSUPPORTED)'
 
C
C        Handle body name errors.
C
         IF (      ( INDEX ( KEYWRD, KWVTRG ) .GT. 0  )
     .        .OR. ( INDEX ( KEYWRD, KWVOBS ) .GT. 0  )  ) THEN
 
            ERRMSG = 'SPICE(NOTRANSLATION)'
 
         END IF
 
C
C        Handle aberration correction errors.
C
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(INVALIDOPTION)'
 
         END IF
 
C
C        Handle axis name errors.
C
         IF (  INDEX ( KEYWRD, KWVAXI ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(INVALIDAXIS)'
 
         END IF
 
C
C        Handle constant frame name errors.
C
         IF (  INDEX ( KEYWRD, '_'//KWVFRM ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(NOTRANSLATION)'
 
         END IF
 
C
C        Handle minimum anglular separation errors.
C
         IF (  INDEX ( KEYWRD, KWATOL ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF
 
C
C        Handle latitude and longitude errors.
C
         IF (  INDEX ( KEYWRD, 'LATITUDE' ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF
 
         IF (  INDEX ( KEYWRD, 'LONGITUDE' ) .GT. 0  ) THEN
            ERRMSG = 'SPICE(BADVARIABLETYPE)'
         END IF
 
C
C        Handle unit errors.
C
         IF (  INDEX ( KEYWRD, KWUNIT ) .GT. 0  ) THEN
 
            ERRMSG = 'SPICE(UNITSNOTREC)'
 
         END IF
 
 
C
C        Try an SXFORM call.
C
         CALL SXFORM ( 'GSM', 'J2000', 1.D6, XFORM )
         CALL CHCKXC ( .TRUE., ERRMSG, OK )
 
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'GSM PXFORM case: changing value for ' //
     .                'keyword '//KEYWRD  )
C
C        Try a PXFORM call.
C
C
C        Handle aberration correction errors.
C
         IF (  INDEX ( KEYWRD, KWVABC ) .GT. 0  ) THEN
C
C           For PXFORM, the error is caught in ZZSPKPA0,
C           which uses the following short error message:
C
            ERRMSG = 'SPICE(SPKINVALIDOPTION)'
 
         END IF
 
 
         CALL PXFORM ( 'GSM', 'J2000', 1.D6, R )
         CALL CHCKXC  ( .TRUE., ERRMSG, OK )
 
 
      END DO
 
 
 
C **************************************************************
C **************************************************************
C **************************************************************
C     MEAN EQUATOR AND EQUINOX OF DATE CASES
C **************************************************************
C **************************************************************
C **************************************************************
 
C
C     First set of tests:  delete required variables from the MQQ
C     definition.  Make sure we get the expected error messages
C     when we refer to the MQQ frame in an SXFORM or PXFORM call.
C     We currently restrict the testing to the keywords applicable
C     to dynamic frames.  These are keywords 7 through DX.
C
      MQQTXT(1) =
     .'FRAME_MQQ                        =  2399003'
      MQQTXT(2) =
     .'FRAME_2399003_NAME               = ''MQQ'''
      MQQTXT(3) =
     .'FRAME_2399003_CLASS              =  5'
      MQQTXT(4) =
     .'FRAME_2399003_CLASS_ID           =  2399003'
      MQQTXT(5) =
     .'FRAME_2399003_CENTER             =  399'
      MQQTXT(6) =
     .'FRAME_2399003_RELATIVE           = ''J2000'''
      MQQTXT(7) =
     .'FRAME_2399003_' // KWSTYL // '   = ''' // KVPARM // ''''
      MQQTXT(8) =
     .'FRAME_2399003_' // KWFFAM // '             = '''// KVMEQT //''''
      MQQTXT(9) =
     .'FRAME_2399003_' // KWPRCM // '   = ''' // KVM001 // ''''
      MQQTXT(10) =
     .'FRAME_2399003_' // KWRSTA // '    = ''' // KVROTG //''''
 
      DX = 10
 
 
      DO I = 7, DX
C
C        Make a copy of the MQQ definition.
C
         CALL MOVEC ( MQQTXT, DX, DEFTX2 )
C
C        Lose the Ith element of the definition.
C
         J      = INDEX ( DEFTX2(I), '=' )
         KEYWRD = DEFTX2(I)(:J-1)
C
C
C        Load the modified MQQ frame definition.  We don't
C        want to clear the kernel pool here because we'd have
C        to keep re-loading the PCK.
C
         CALL LMPOOL ( DEFTX2, DX )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C        Delete the Ith element of the frame definition from
C        the kernel pool.
C
         CALL DVPOOL ( KEYWRD )
         CALL CHCKXC  ( .FALSE., ' ', OK )
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'MQQ SXFORM case: deleting keyword '//KEYWRD  )
C
C        Try an SXFORM call.
C
         CALL SXFORM ( 'MQQ', 'J2000', 1.D6, XFORM )
 
         IF ( I .LT. DX ) THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
         ELSE
C
C           The ROTATION_STATE keyword or the FREEZE_EPOCH keyword
C           must be present.
C
            CALL CHCKXC ( .TRUE., 'SPICE(FRAMEDEFERROR)', OK )
 
         END IF
 
C
C --- Case: ------------------------------------------------------
C
         CALL TCASE ( 'MQQ PXFORM case: deleting keyword '//KEYWRD  )
C
C        Try a PXFORM call.
C
         CALL PXFORM ( 'MQQ', 'J2000', 1.D6, R )
 
         IF ( I .LT. DX ) THEN
C
C           We've deleted a required keyword.
C
            CALL CHCKXC ( .TRUE., 'SPICE(KERNELVARNOTFOUND)', OK )
 
