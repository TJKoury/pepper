      IMPLICIT NONE
 
      LOGICAL               OK

C$ Brief_I/O
C
C     VARIABLE  I/O  DESCRIPTION
C     --------  ---  --------------------------------------------------
C     OK         O   logical indicating test status.
C
C$ Detailed_Input
C
C     None.
C
C$ Detailed_Output
C
C     OK         is a logical that indicates the test status to the
C                caller.
C
C$ Parameters
C
C     None.
C
C$ Exceptions
C
C     This routine does not generate any errors. Routines in its
C     call tree may generate errors that are either intentional and
C     trapped or unintentional and need reporting.  The test family
C     utilities manage this.
C
C$ Files
C
C     None.
C
C$ Particulars
C
C     This routine tests some of the more complex aspects of the SPICE
C     DAS subsystem.  The DAS Required Reading and thorough 
C     knowledge of the DAS routines are prerequisites for understanding
C     this test family.
C
C     This file contains source code for the following utility
C     routines:
C
C        PACKFS
C        CHKFS
C        CHKCDR
C
C$ Examples
C
C     None.
C
C$ Restrictions
C
C     None.
C
C$ Literature_References
C
C     None.
C
C$ Author_and_Institution
C
C     N.J. Bachman   (JPL)
C     B.V. Semenov   (JPL)
C
C$ Version
C
C-    SPICELIB Version 1.1.0, 09-OCT-2013 (BVS)
C
C        Declared LASTLA, LASTRC, and LASTWD in PACKFS as arrays to
C        eliminate warning generated by some compilers. Added missing
C        header sections.
C
C-    SPICELIB Version 1.0.0, 22-FEB-2003 (NJB)
C
C-&
 
 
C
C     Test Utility Functions
C
 
 
C
C     SPICELIB Functions
C     

C
C     Local Parameters
C
C
C     Words per data record, for each data type:
C
      INTEGER               NWC
      PARAMETER           ( NWC    = 1024 )
 
      INTEGER               NWD
      PARAMETER           ( NWD    =  128 )
 
      INTEGER               NWI
      PARAMETER           ( NWI    =  256 )
 
C
C     DAS type codes:
C
      INTEGER               CHAR
      PARAMETER           ( CHAR   =  1  )
      
      INTEGER               DP
      PARAMETER           ( DP     =  2  )
 
      INTEGER               INT
      PARAMETER           ( INT    =  3  )

C
C     Directory pointer locations (backward and forward):
C
      INTEGER               BWDLOC
      PARAMETER           ( BWDLOC = 1 )
 
      INTEGER               FWDLOC
      PARAMETER           ( FWDLOC = 2 )
 
C
C     Directory address range locations
C
      INTEGER               CHRRNG
      PARAMETER           ( CHRRNG =          3 )
 
      INTEGER               DPRNG
      PARAMETER           ( DPRNG  = CHRRNG + 2 )
 
      INTEGER               INTRNG
      PARAMETER           ( INTRNG = DPRNG  + 2 )

      INTEGER               CRNGMX
      PARAMETER           ( CRNGMX = CHRRNG + 1 )
 
      INTEGER               DRNGMX
      PARAMETER           ( DRNGMX = DPRNG  + 1 )

      INTEGER               IRNGMX
      PARAMETER           ( IRNGMX = INTRNG + 1 )

C
C     Location of first type descriptor
C
      INTEGER               BEGDSC
      PARAMETER           ( BEGDSC = 9 )

C
C     DAS file summary size:
C
      INTEGER               FSDIM
      PARAMETER           ( FSDIM  = 14 )

C
C     Local Variables
C      
      INTEGER               CLREC  ( NWI )
      INTEGER               DSCLOC
      INTEGER               DTYPE
      INTEGER               FREE
      INTEGER               FSUM   ( FSDIM )
      INTEGER               LASTLA ( 3 )
      INTEGER               LASTRC ( 3 )
      INTEGER               LASTWD ( 3 )
      INTEGER               NADD
      INTEGER               NRESVR
      INTEGER               NCOMR
      INTEGER               NRESVC
      INTEGER               NCOMC
      INTEGER               PRVCLR
      INTEGER               PRVTYP
      INTEGER               RECNO
      INTEGER               RNGMAX ( 3 )
      INTEGER               RNGMIN ( 3 )
      INTEGER               SCRHAN
      INTEGER               SIZES  ( 3 )
      INTEGER               XCLREC ( NWI )
      INTEGER               XFSUM  ( FSDIM )

C
C     Saved variables
C     
      SAVE                  RNGMAX
      SAVE                  RNGMIN
      SAVE                  SIZES

C
C     Initial values
C
      DATA                  RNGMAX / CRNGMX, DRNGMX, IRNGMX /
      DATA                  RNGMIN / CHRRNG, DPRNG,  INTRNG /
      DATA                  SIZES  / NWC,    NWD,    NWI    /


C
C     Begin every test family with an open call.
C
      CALL TOPEN ( 'F_DASCUD' )      

C
C     Our approach to testing will be to create a scratch DAS 
C     file by successive additions, such that the set of states
C     of the scratch DAS' file summary and directory contents span the
C     range of possibilities handled by DASCUD.  For each data addition
C     case, we'll verify that the addition results in the expected
C     update of the cluster directory structure and the file summary.
C
C     We don't actually write data to the files in these tests; we
C     simply update metadata to indicate where the data would be if
C     they were there.  Below, when we say we're "adding data" to
C     the file, we're lying to DASCUD.  But as long as the free
C     record pointer FREE is updated correctly, the DAS system is
C     none the wiser.
C

      
      CALL TCASE ( 'Tell DASCUD we''re adding one integer datum.' //
     .             'to an empty file.'                            )

      CALL DASOPS ( SCRHAN )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Update the file.  Note that the file update is generally made
C     to buffered records; these records might not be written to
C     the physical file.
C
      CALL DASCUD ( SCRHAN, INT, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.  Note that the first cluster
C     record should follow the file record, reserved records, and 
C     comment records.  The last integer logical address is 1.  
C     The cluster record containing a descriptor for the last 
C     integer cluster is the only cluster record.  The first
C     data record follows the cluster directory.  The first free
C     record follows the data record.
C
      NRESVR        = 0
      NCOMR         = 0
      NRESVC        = 0
      NCOMC         = 0
      FREE          = 1 + NRESVR + NCOMR + 1 + 1 + 1
      LASTLA (CHAR) = 0
      LASTLA (DP)   = 0
      LASTLA (INT)  = 1
      LASTRC (CHAR) = 0
      LASTRC (DP)   = 0
      LASTRC (INT)  = 1 + NRESVR + NCOMR + 1
      LASTWD (CHAR) = 0
      LASTWD (DP)   = 0
      LASTWD (INT)  = BEGDSC + 1
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      CALL CLEARI ( NWI, XCLREC )

      XCLREC(BWDLOC  ) = 0 
      XCLREC(FWDLOC  ) = 0 
      XCLREC(CHRRNG  ) = 0 
      XCLREC(CHRRNG+1) = 0 
      XCLREC(DPRNG   ) = 0 
      XCLREC(DPRNG+1 ) = 0 
      XCLREC(INTRNG  ) = 1
      XCLREC(INTRNG+1) = 1
      XCLREC(BEGDSC  ) = INT 
      XCLREC(BEGDSC+1) = 1 

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add one d.p. datum to the file.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, DP, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE        = FREE + 1
      LASTLA (DP) = 1
      LASTRC (DP) = 1 + NRESVR + NCOMR + 1
      LASTWD (DP) = BEGDSC + 2
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(DPRNG   ) =  1 
      XCLREC(DPRNG+1 ) =  1 
      XCLREC(BEGDSC+2) = -1 

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )




      CALL TCASE ( 'Add one character datum to the file.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, CHAR, 1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE          = FREE + 1
      LASTLA (CHAR) = 1
      LASTRC (CHAR) = 1 + NRESVR + NCOMR + 1
      LASTWD (CHAR) = BEGDSC + 3
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(CHRRNG  ) =  1 
      XCLREC(CHRRNG+1) =  1 
      XCLREC(BEGDSC+3) = -1 

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )




      CALL TCASE ( 'Add data to fill up the first integer data ' //
     .             'record.'                                      )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, INT, NWI-1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
C
C     Note:  FREE is unchanged.
C
      LASTLA (INT) = NWI
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(INTRNG+1) =  NWI

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )






      CALL TCASE ( 'Add data to fill up 3 1/2 new integer data '     //
     .             'records.  This creates a second integer cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, INT, 7*NWI/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE       = FREE + 4
      LASTLA (INT) = LASTLA (INT)  +  7*NWI/2
      LASTWD (INT) = BEGDSC + 4
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 7*NWI/2
      XCLREC(BEGDSC+4) = -4

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 3 new integer data records. ' //
     .             'This extends the second integer cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, INT, 3*NWI )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE       = FREE + 3
      LASTLA (INT) = LASTLA(3) + 3*NWI
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 3*NWI
      XCLREC(BEGDSC+4) = -7

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )





      CALL TCASE ( 'Add data to fill up 1 1/2 new integer data ' //
     .             'records. This extends the second integer cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, INT, 3*NWI/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
C
C     Recall the last integer data record is half full.  We only need
C     one new integer data record.
C
      FREE         = FREE + 1
      LASTLA (INT) = LASTLA(INT) + 3*NWI/2
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(INTRNG+1) =  XCLREC(INTRNG+1) + 3*NWI/2
      XCLREC(BEGDSC+4) = -8

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )

C
C     We're now going to repeat the integer data additions for
C     the double precision and character cases.
C



      CALL TCASE ( 'Add data to fill up the first d.p. data ' //
     .             'record.'                                      )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, DP, NWD-1 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
C
C     Note:  FREE is unchanged.
C
      LASTLA (DP) = NWD
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.  
C
      XCLREC(DPRNG+1 ) =  NWD


C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )






      CALL TCASE ( 'Add data to fill up 3 1/2 new d.p. data '     //
     .             'records.  This creates a second d.p. cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, DP, 7*NWD/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE        = FREE + 4
      LASTLA (DP) = LASTLA(DP) + 7*NWD/2
      LASTWD (DP) = BEGDSC + 5
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(DPRNG+1 ) =  XCLREC(DPRNG+1)  + 7*NWD/2
      XCLREC(INTRNG  ) =  1
      XCLREC(BEGDSC+5) = -4

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 3 new d.p. data records. ' //
     .             'This extends the second d.p. cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, DP, 3*NWD )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
      FREE        = FREE + 3
      LASTLA (DP) = LASTLA(DP) + 3*NWD
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(DPRNG+1 ) = XCLREC(DPRNG+1) + 3*NWD 
      XCLREC(BEGDSC+5) = -7

C
C     Read the cluster record and compare.
C
      RECNO = 1 + NRESVR + NCOMR + 1
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )



      CALL TCASE ( 'Add data to fill up 1 1/2 new d.p. data ' //
     .             'records. This extends the second d.p. cluster.' )

C
C     Update the file. 
C
      CALL DASCUD ( SCRHAN, DP, 3*NWD/2 )
      CALL CHCKXC ( .FALSE., ' ', OK )

C
C     Set up the expected file summary.
C
C
C     Recall the last d.p. data record is half full.  We only need
C     one new d.p. data record.
C
      FREE        = FREE + 1
      LASTLA (DP) = LASTLA(DP) + 3*NWD/2
 
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )



C
C     Set up the expected first cluster record.
C
      XCLREC(DPRNG+1 ) =  XCLREC(DPRNG+1 ) + 3*NWD/2
      XCLREC(BEGDSC+5) = -8

C
C     Read the cluster record and compare.
