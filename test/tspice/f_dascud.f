         PRVTYP = DTYPE
         DSCLOC = DSCLOC + 1

         IF ( MOD(DSCLOC,10) .EQ. 0 ) THEN
C
C           Read the cluster record and compare.
C   
            CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
            CALL CHCKXC ( .FALSE., ' ', OK )

            CALL CHKCDS ( CLREC, XCLREC, OK )

         END IF

      END DO


C
C     Now check the file summary.
C
      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC, FREE,  
     .              LASTLA, LASTRC, LASTWD, XFSUM       )

C
C     Look up the file summary, pack into a summary array, and 
C     compare.
C
      CALL DASHFS ( SCRHAN, NRESVR, NRESVC, NCOMR,    
     .              NCOMC,  FREE,   LASTLA, LASTRC, LASTWD )

      CALL CHCKXC ( .FALSE., ' ', OK )


      CALL PACKFS ( NRESVR, NRESVC, NCOMR,  NCOMC,  FREE,  
     .              LASTLA, LASTRC, LASTWD, FSUM           )

      CALL CHKFS  ( FSUM, XFSUM, OK )

C
C     The forward pointer of the cluster directory record will point to
C     the newly allocated cluster directory record.
C
      XCLREC(FWDLOC) = PRVCLR


C     Read the cluster record and compare.
C
      CALL DASRRI ( SCRHAN, RECNO, 1, NWI, CLREC )
      CALL CHCKXC ( .FALSE., ' ', OK )

      CALL CHKCDS ( CLREC, XCLREC, OK )

      PRVCLR = RECNO


      CALL T_SUCCESS ( OK )
      RETURN
      END




C
C     PACKFS is a utility subroutine which packs DAS file summary
C     information into an integer array.
C
      SUBROUTINE PACKFS ( NRESVR,
     .                    NRESVC,
     .                    NCOMR,
     .                    NCOMC,
     .                    FREE,
     .                    LASTLA,
     .                    LASTRC,
     .                    LASTWD,
     .                    FSUM     )
      IMPLICIT NONE

      INTEGER               NRESVR
      INTEGER               NRESVC
      INTEGER               NCOMR
      INTEGER               NCOMC
      INTEGER               FREE
      INTEGER               LASTLA ( * )
      INTEGER               LASTRC ( * )
      INTEGER               LASTWD ( * )
      INTEGER               FSUM   ( * )


      FSUM(1) =  NRESVR
      FSUM(2) =  NRESVC
      FSUM(3) =  NCOMR
      FSUM(4) =  NCOMC
      FSUM(5) =  FREE

      CALL MOVEI ( LASTLA, 3, FSUM(6)  )
      CALL MOVEI ( LASTRC, 3, FSUM(9)  )
      CALL MOVEI ( LASTWD, 3, FSUM(12) )

      RETURN
      END


C
C     CHKFS is a utility subroutine which compares a DAS file summary
C     to an expected summary.  Both summaries are packed into integer
C     arrays.
C

      SUBROUTINE CHKFS ( FSUM, XFSUM, OK )
      IMPLICIT NONE

      INTEGER               FSUM   ( * )
      INTEGER               XFSUM  ( * )
      LOGICAL               OK


      CALL CHCKSI( 'NRESVR',           FSUM(1),  '=', XFSUM(1),  0, OK )
      CALL CHCKSI( 'NRESVC',           FSUM(2),  '=', XFSUM(2),  0, OK )
      CALL CHCKSI( 'NCOMR',            FSUM(3),  '=', XFSUM(3),  0, OK )
      CALL CHCKSI( 'NCOMC',            FSUM(4),  '=', XFSUM(4),  0, OK )
      CALL CHCKSI( 'FREE',             FSUM(5),  '=', XFSUM(5),  0, OK )
      CALL CHCKSI( 'LASTLA(1) (CHAR)', FSUM(6),  '=', XFSUM(6),  0, OK )
      CALL CHCKSI( 'LASTLA(2) (DP)',   FSUM(7),  '=', XFSUM(7),  0, OK )
      CALL CHCKSI( 'LASTLA(3) (INT)',  FSUM(8),  '=', XFSUM(8),  0, OK )
      CALL CHCKSI( 'LASTRC(1) (CHAR)', FSUM(9),  '=', XFSUM(9),  0, OK )
      CALL CHCKSI( 'LASTRC(2) (DP)',   FSUM(10), '=', XFSUM(10), 0, OK )
      CALL CHCKSI( 'LASTRC(3) (INT)',  FSUM(11), '=', XFSUM(11), 0, OK )
      CALL CHCKSI( 'LASTWD(1) (CHAR)', FSUM(12), '=', XFSUM(12), 0, OK )
      CALL CHCKSI( 'LASTWD(2) (DP)',   FSUM(13), '=', XFSUM(13), 0, OK )
      CALL CHCKSI( 'LASTWD(3) (INT)',  FSUM(14), '=', XFSUM(14), 0, OK )

      RETURN
      END



C
C     CHKCDS is a utility subroutine which compares a DAS cluster
C     directory record to an expected cluster directory record.
C

      SUBROUTINE CHKCDS ( CDREC, XCDREC, OK )
      IMPLICIT NONE

      INTEGER               CDREC  ( * )
      INTEGER               XCDREC ( * )
      LOGICAL               OK

C
C     Local parameters
C
      INTEGER               NWI
      PARAMETER           ( NWI    =  256 )

      INTEGER               LNSIZE
      PARAMETER           ( LNSIZE =   80 )

C
C     Local variables
C
      CHARACTER*(LNSIZE)    TITLE
      INTEGER               I


      CALL CHCKSI( 'BWD ptr',       CDREC(1),  '=', XCDREC(1),  0, OK )
      CALL CHCKSI( 'FWD ptr',       CDREC(2),  '=', XCDREC(2),  0, OK )
      CALL CHCKSI( 'Min CHAR addr', CDREC(3),  '=', XCDREC(3),  0, OK )
      CALL CHCKSI( 'Max CHAR addr', CDREC(4),  '=', XCDREC(4),  0, OK )
      CALL CHCKSI( 'Min DP addr',   CDREC(5),  '=', XCDREC(5),  0, OK )
      CALL CHCKSI( 'Max DP addr',   CDREC(6),  '=', XCDREC(6),  0, OK )
      CALL CHCKSI( 'Min INT addr',  CDREC(7),  '=', XCDREC(7),  0, OK )
      CALL CHCKSI( 'Max INT addr',  CDREC(8),  '=', XCDREC(8),  0, OK )
      CALL CHCKSI( '1st type',      CDREC(9),  '=', XCDREC(9),  0, OK )
      CALL CHCKSI( '1st count',     CDREC(10), '=', XCDREC(10), 0, OK )

      DO I = 11, NWI

         TITLE = 'the # cluster count'
         CALL REPMOT ( TITLE, '#', I-9, 'L', TITLE )

         CALL CHCKSI( TITLE,  CDREC(I), '=', XCDREC(I), 0, OK )

      END DO

      RETURN
      END


