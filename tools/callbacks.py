#!/usr/bin/env python3
"""
Generate the callback interfaces from modules.CALLBACKS.

    python tools/callbacks.py

SPICELIB passes procedures as arguments (EXTERNAL arguments): GF step and
refinement routines, user-defined functions, the DSK segment selectors, ...
In PEPPER a callback takes the context as its first argument (most of
SPICELIB's callbacks use saved state, which is in the context now). For each
callback this writes

- an abstract interface with the context, in the "callbacks" region of
  src/pepper_instance.f90 (the dummy procedures of the module procedures are
  declared with it: modules.PROCEDURE_ARGS);
- for the legacy interface, in the callbacks section of
  src/legacy/pepper_legacy.f90 (merged there from pepper_legacy_callbacks.f90;
  this tool no longer writes it: edit the module): an
  abstract interface of SPICELIB's form (without the context), a procedure
  pointer to the legacy caller's routine, and a bridge with the context
  that calls it. A legacy wrapper of a routine with a callback argument
  points the pointer at the caller's routine and passes the bridge (saving
  and restoring the pointer around the call). The legacy interface has one
  context and is not for concurrent use, so module variables are fine there.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from modules import CALLBACKS  # noqa: E402

INSTANCE = ROOT / "src" / "pepper_instance.f90"
LEGACY = ROOT / "tspice" / "src" / "legacy" / "pepper_legacy_callbacks.f90"


def wrap_doc(text: str, indent: str) -> list:
    words, lines, cur = text.split(), [], ""
    for w in words:
        if len(cur) + len(w) > 72:
            lines.append(cur)
            cur = ""
        cur = (cur + " " + w).strip()
    lines.append(cur)
    return [f"{indent}!> {l}" for l in lines]


def declarations(cb: dict, indent: str, intents=True, legacy=False) -> list:
    out = []
    if any("lbcell" in a[3] for a in cb["args"]):
        out.append(f"{indent}integer(ip), parameter :: lbcell = -5  !! lower bound of a SPICE cell")
    for name, typ, intent, dims, doc in cb["args"]:
        it = f", intent({intent})" if intents and intent else ""
        if legacy and typ.startswith("procedure("):
            typ = "procedure(legacy_" + typ[len("procedure("):]
        out.append(f"{indent}{typ}{it} :: {name}{(' ' + dims) if dims else ''}  !! {doc}")
    return out


def procedure_args(cb: dict) -> list:
    """The callbacks that are arguments of a callback."""
    return [typ[len("procedure("):-1] for _, typ, _, _, _ in cb["args"] if typ.startswith("procedure(")]


def ordered() -> list:
    """The callbacks, each after those it takes as arguments."""
    out = []
    def add(n):
        if n not in out:
            for m in procedure_args(CALLBACKS[n]):
                add(m)
            out.append(n)
    for n in CALLBACKS:
        add(n)
    return out


def head(name: str, cb: dict, args: list) -> tuple:
    kind = cb["kind"]
    return (f"{kind} {name} ( {', '.join(args)} )", f"end {kind.split()[-1]} {name}")


def abstract_interfaces() -> str:
    out = [f"   public :: {n}" for n in CALLBACKS] + ["", "   abstract interface"]
    for name in ordered():
        cb = CALLBACKS[name]
        args = ["ctx"] + [a[0] for a in cb["args"]]
        h, e = head(name, cb, args)
        out += wrap_doc(cb["doc"] + " PEPPER: the context is its first argument.", "      ")
        imports = ", ".join(["pepper_context", "ip", "wp"] + procedure_args(cb))
        out += [f"      {h}", f"         import :: {imports}",
                "         class(pepper_context), intent(inout) :: ctx  !! the context"]
        out += declarations(cb, "         ")
        out += [f"      {e}", ""]
    out[-1] = "   end interface"
    return "\n".join(out)


def legacy_module() -> str:
    out = ["! Legacy interface: the callbacks in SPICELIB's form (without the context)",
           "! and their bridges. Generated by tools/callbacks.py from modules.CALLBACKS.",
           "!",
           "! A legacy wrapper of a routine with a callback argument points",
           "! current_<callback> at the caller's routine and passes bridge_<callback>",
           "! (which has the context) to the module procedure. The legacy interface has",
           "! one context and is not for concurrent use, so module variables are fine.",
           "module pepper_legacy_callbacks", "",
           "   use pepper_kinds, only: ip, wp",
           "   use pepper_instance, only: pepper_context, " + ", ".join(CALLBACKS), "",
           "   implicit none", "", "   private", ""]
    for name in CALLBACKS:
        out.append(f"   public :: legacy_{name}, current_{name}, bridge_{name}")
    out += ["", "   abstract interface"]
    for name in ordered():
        cb = CALLBACKS[name]
        h, e = head(f"legacy_{name}", cb, [a[0] for a in cb["args"]])
        out += wrap_doc(f"{name.upper()} in SPICELIB's form (without the context).", "      ")
        imports = ", ".join(["ip", "wp"] + [f"legacy_{m}" for m in procedure_args(cb)])
        out += [f"      {h}", f"         import :: {imports}"] + \
            declarations(cb, "         ", intents=False, legacy=True)
        out += [f"      {e}", ""]
    out[-1] = "   end interface"
    out.append("")
    for name in CALLBACKS:
        out += [f"   !> The legacy caller's {name.upper()} routine (during a call).",
                f"   procedure(legacy_{name}), pointer :: current_{name} => null()"]
    out += ["", "contains", ""]
    for name, cb in CALLBACKS.items():
        args = [a[0] for a in cb["args"]]
        h, e = head(f"bridge_{name}", cb, ["ctx"] + args)
        out += [f"   !> A {name} that calls the legacy caller's routine (current_{name}).",
                f"   {h}",
                "      class(pepper_context), intent(inout) :: ctx  !! the context (not used)"]
        out += declarations(cb, "      ")
        # a callback argument: the legacy caller's routine of that kind
        # (the module procedure passes the bridge it was given)
        call = ", ".join(f"current_{typ[len('procedure('):-1]}" if typ.startswith("procedure(") else n
                         for n, typ, _, _, _ in cb["args"])
        if cb["kind"] == "subroutine":
            out.append(f"      call current_{name} ( {call} )")
        else:
            out.append(f"      bridge_{name} = current_{name} ( {call} )")
        out += [f"   {e}", ""]
    out.append("end module pepper_legacy_callbacks")
    return "\n".join(out) + "\n"


def write() -> None:
    text = INSTANCE.read_text(encoding="ascii")
    start = "   ! >>> generated callbacks (tools/callbacks.py)\n"
    end = "   ! <<< generated callbacks\n"
    body = start + abstract_interfaces() + "\n" + end
    if start in text:
        text = re.sub(re.escape(start) + ".*?" + re.escape(end), lambda m: body, text, flags=re.S)
    else:
        anchor = "   end type pepper_context\n"
        text = text.replace(anchor, anchor + "\n" + body, 1)
    INSTANCE.write_text(text, encoding="ascii")
    # The legacy callbacks are part of src/legacy/pepper_legacy.f90 now
    # (tools/make_legacy_module.py merged them): not written here.


if __name__ == "__main__":
    write()
    print("callbacks: wrote the interfaces (the legacy callbacks are in src/legacy/pepper_legacy.f90)")
