!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFOCU routines (entry points zzgfocin, zzgfocst),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfocu.f90.
module pepper_state_zzgfocu

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dsk.inc'
   include 'gf.inc'
   include 'zzabcorr.inc'
   include 'zzdsk.inc'
   include 'zzocced.inc'
   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_zzgfocu_state

   !> The saved variables of ZZGFOCU.
   type, public :: zzgfocu_state
      integer(ip) :: ncalls  !! number of SINCPT calls made by ZZGFOCST (diagnostic count only)
      integer(ip) :: svback  !! back body ID code saved by ZZGFOCIN
      character(frnmln) :: svbfrm  !! back body-fixed frame name (blank for a point)
      character(mthlen) :: svbmth  !! back body shape/method string saved by ZZGFOCIN
      character(bdnmln) :: svbnam  !! back body name saved by ZZGFOCIN
      real(wp) :: svbrad ( 3 )  !! back body ellipsoid radii (zero for a point)
      character(shplen) :: svbshp  !! back body shape: point, ellipsoid or DSK
      character(corlen) :: svcorr  !! aberration correction for SPKEZP (stellar aberration removed)
      character(frnmln) :: svffrm  !! front body-fixed frame name (blank for a point)
      character(mthlen) :: svfmth  !! front body shape/method string saved by ZZGFOCIN
      character(bdnmln) :: svfnam  !! front body name saved by ZZGFOCIN
      real(wp) :: svfrad ( 3 )  !! front body ellipsoid radii (zero for a point)
      integer(ip) :: svfrnt  !! front body ID code saved by ZZGFOCIN
      character(shplen) :: svfshp  !! front body shape: point, ellipsoid or DSK
      real(wp) :: svmnbr  !! minimum radius of the back body (bounding radius for DSK shapes)
      real(wp) :: svmnfr  !! minimum radius of the front body (bounding radius for DSK shapes)
      real(wp) :: svmxbr  !! maximum radius of the back body (bounding radius for DSK shapes)
      real(wp) :: svmxfr  !! maximum radius of the front body (bounding radius for DSK shapes)
      integer(ip) :: svobs  !! observer ID code saved by ZZGFOCIN
      character(bdnmln) :: svonam  !! observer name saved by ZZGFOCIN
      real(wp) :: svorig ( 3 )  !! origin (zero vector): the observer position (constant)
      character(oclln) :: svtype  !! occultation type saved by ZZGFOCIN
      character(oclln) :: svtyps ( noctyp )  !! recognized occultation types (constant)
   end type zzgfocu_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfocu_state(state)
      type(zzgfocu_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ncalls = 0
      state%svback = 0
      state%svbfrm = ' '
      state%svbmth = ' '
      state%svbnam = ' '
      state%svbrad = 0.0_wp
      state%svbshp = ' '
      state%svcorr = ' '
      state%svffrm = ' '
      state%svfmth = ' '
      state%svfnam = ' '
      state%svfrad = 0.0_wp
      state%svfrnt = 0
      state%svfshp = ' '
      state%svmnbr = 0.0_wp
      state%svmnfr = 0.0_wp
      state%svmxbr = 0.0_wp
      state%svmxfr = 0.0_wp
      state%svobs = 0
      state%svonam = ' '
      state%svorig = 0.0_wp
      state%svtype = ' '
      state%svtyps = ' '
      state%ncalls = 0
      state%svorig = 0.0_wp
      state%svtyps = [ character(len(state%svtyps)) :: annulr, any, partl, full ]
   end subroutine init_zzgfocu_state

end module pepper_state_zzgfocu
