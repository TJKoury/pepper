!> Find the rotation from a user specified frame to another frame at
!> a user specified epoch.
!>
!> The state of SPICELIB's ZZROTGT1 routines (entry points zzrotgt1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzrotgt1.f90.
module pepper_state_zzrotgt1

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'frmtyp.inc'

   public :: init_zzrotgt1_state

   !> The saved variables of ZZROTGT1.
   type, public :: zzrotgt1_state
      character(6) :: versn  !! version string quoted in the unsupported-frame-class error message
   end type zzrotgt1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzrotgt1_state(state)
      type(zzrotgt1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%versn = ' '
      state%versn = '4.0.0'
   end subroutine init_zzrotgt1_state

end module pepper_state_zzrotgt1
