!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZEKSEMC routines (entry points zzeksemc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzeksemc.f90.
module pepper_state_zzeksemc

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekattdsc.inc'
   include 'ekbool.inc'
   include 'ekcnamsz.inc'
   include 'ekopcd.inc'
   include 'ekquery.inc'
   include 'ektnamsz.inc'
   include 'ektype.inc'
   integer(ip), parameter :: short = 32

   public :: init_zzeksemc_state

   !> The saved variables of ZZEKSEMC.
   type, public :: zzeksemc_state
      character(short) :: typstr ( 4 )  !! names of the EK data types, indexed by type code (for error messages)
   end type zzeksemc_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzeksemc_state(state)
      type(zzeksemc_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%typstr = ' '
      state%typstr = [ character(len(state%typstr)) :: 'CHARACTER', 'DOUBLE PRECISION', 'INTEGER', 'TIME' ]
   end subroutine init_zzeksemc_state

end module pepper_state_zzeksemc
