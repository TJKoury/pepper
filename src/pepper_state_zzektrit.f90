!> Initialize an EK tree, returning the root of the tree.
!>
!> The state of SPICELIB's ZZEKTRIT routines (entry points zzektrit),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzektrit.f90.
module pepper_state_zzektrit

   use pepper_kinds, only: ip, wp
      use pepper_inc_ekpage
      use pepper_inc_ektree
      use pepper_inc_ektype

   implicit none

   private


   public :: init_zzektrit_state

   !> The saved variables of ZZEKTRIT.
   type, public :: zzektrit_state
      integer(ip) :: page  ( pgsizi )  !! work: integer page image of the new tree root node, written to the file
   end type zzektrit_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzektrit_state(state)
      type(zzektrit_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%page = 0
      state%page = 0
   end subroutine init_zzektrit_state

end module pepper_state_zzektrit
