!> Load and unload files for use by the readers. Buffer segments
!> for readers.
!>
!> The state of SPICELIB's SPKBSR routines (entry points spklef, spkuef, spksfs),
!> held in pepper_spice (and, for some variables, in pepper_context). Generated by tools/modularize_ctx.py from the
!> saved variables of spkbsr.f90.
module pepper_state_spkbsr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: ftsize = 5000
   integer(ip), parameter :: btsize = 10000
   integer(ip), parameter :: lbpool = -5
   integer(ip), parameter :: stsize = 100000
   integer(ip), parameter :: dscsiz = 5
   integer(ip), parameter :: sidlen = 40

   public :: init_spkbsr_state
   public :: init_spkbsr_context_state

   !> The saved variables of SPKBSR.
   type, public :: spkbsr_state
      integer(ip) :: fthan    ( ftsize )  !! handle of each loaded file (in load order)
      integer(ip) :: ftnum    ( ftsize )  !! file number of each loaded file: its place in the load (and search) order
      integer(ip) :: next  !! the file number of the file loaded last
      integer(ip) :: nft  !! number of loaded files
   end type spkbsr_state

   !> The saved variables of SPKBSR that are per context.
   type, public :: spkbsr_context_state
      integer(ip) :: btbeg    ( btsize )  !! head of the segment list of each body
      integer(ip) :: btbod    ( btsize )  !! each body's code
      logical :: btchkp   ( btsize )  !! the segment returned last for each body is to be checked first (its re-use interval is valid)
      integer(ip) :: btexp    ( btsize )  !! expense (number of segment descriptors examined) of the segment list of each body
      integer(ip) :: bthfs    ( btsize )  !! highest file number searched for the segment list of each body
      real(wp) :: btlb     ( btsize )  !! lower bound of the re-use interval of the segment returned last for each body
      integer(ip) :: btlfs    ( btsize )  !! lowest file number searched for the segment list of each body
      real(wp) :: btprvd   ( dscsiz, btsize )  !! descriptor of the segment returned last for each body
      integer(ip) :: btprvh   ( btsize )  !! handle of the file of the segment returned last for each body
      character(sidlen) :: btprvi   ( btsize )  !! identifier of the segment returned last for each body
      integer(ip) :: btruex   ( btsize )  !! expense of the re-use interval of each body
      real(wp) :: btub     ( btsize )  !! upper bound of the re-use interval of the segment returned last for each body
      integer(ip) :: nbt  !! number of bodies in the body table
      real(wp) :: stdes  ( dscsiz,     stsize )  !! descriptor of each segment in the segment table
      integer(ip) :: sthan  (             stsize )  !! handle of the file of each segment in the segment table
      character(sidlen) :: stidnt (             stsize )  !! identifier of each segment in the segment table
      integer(ip) :: stpool ( 2, lbpool : stsize )  !! doubly linked list pool of the segment table (one list per body, in priority order)
      integer(ip) :: epoch  !! the instance's segment_epoch this cache reflects
   end type spkbsr_context_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkbsr_state(state)
      type(spkbsr_state), intent(inout) :: state  !! the state
      state%next = 0
      state%nft = 0
   end subroutine init_spkbsr_state

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkbsr_context_state(state)
      type(spkbsr_context_state), intent(inout) :: state  !! the state
      state%nbt = 0
      state%epoch = 0
   end subroutine init_spkbsr_context_state

end module pepper_state_spkbsr
