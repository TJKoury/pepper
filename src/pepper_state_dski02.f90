!> Fetch integer data from a type 2 DSK segment.
!>
!> The state of SPICELIB's DSKI02 routines (entry points dski02),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dski02.f90.
module pepper_state_dski02

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dla.inc'
   include 'dskdsc.inc'
   include 'dsk02.inc'

   public :: init_dski02_state

   !> The saved variables of DSKI02.
   type, public :: dski02_state
      integer(ip) :: cgscal  !! coarse voxel scale of the segment read last
      logical :: first  !! no segment has been read yet
      integer(ip) :: np  !! number of plates of the segment read last
      integer(ip) :: nv  !! number of vertices of the segment read last
      integer(ip) :: nvxtot  !! number of voxels of the segment read last
      integer(ip) :: prvbas  !! DLA base address of the segment read last
      integer(ip) :: prvhan  !! handle of the DSK file of the segment read last
      integer(ip) :: voxnpl  !! size of the voxel-plate pointer array of the segment read last
      integer(ip) :: voxnpt  !! size of the voxel-plate correspondence list of the segment read last
      integer(ip) :: vtxnpl  !! size of the vertex-plate correspondence list of the segment read
                             !! last
   end type dski02_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dski02_state(state)
      type(dski02_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%cgscal = 0
      state%first = .false.
      state%np = 0
      state%nv = 0
      state%nvxtot = 0
      state%prvbas = 0
      state%prvhan = 0
      state%voxnpl = 0
      state%voxnpt = 0
      state%vtxnpl = 0
      state%first = .true.
   end subroutine init_dski02_state

end module pepper_state_dski02
