!> Write or rewrite the double precision data bounded by two
!> addresses within a DAF.
!>
!> The state of SPICELIB's DAFWDA routines (entry points dafwda),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dafwda.f90.
module pepper_state_dafwda

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: bsize = 128

   public :: init_dafwda_state

   !> The saved variables of DAFWDA.
   type, public :: dafwda_state
      real(wp) :: buffer   ( bsize )  !! work buffer of one record (saved in SPICELIB to keep it off
                                      !! the stack)
   end type dafwda_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dafwda_state(state)
      type(dafwda_state), intent(inout) :: state  !! the state
      state%buffer = 0.0_wp
   end subroutine init_dafwda_state

end module pepper_state_dafwda
