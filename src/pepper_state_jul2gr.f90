!> Convert Year Month and Day on the Julian Calendar
!> to the Gregorian Calendar
!>
!> The state of SPICELIB's JUL2GR routines (entry points jul2gr, gr2jul),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of jul2gr.f90.
module pepper_state_jul2gr

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_jul2gr_state

   !> The saved variables of JUL2GR.
   type, public :: jul2gr_state
      logical :: first  !! the first call has not set up the constants yet
      integer(ip) :: rdayg  !! Gregorian day number of the reference day Oct 15, 1582
      integer(ip) :: rdayj  !! Julian day number of the reference day Oct 5, 1582 (the same day)
      integer(ip) :: offstj  !! offset from Gregorian to Julian calendar day numbers (RDAYJ - RDAYG)
      integer(ip) :: offstg  !! offset from Julian to Gregorian calendar day numbers (RDAYG - RDAYJ)
   end type jul2gr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_jul2gr_state(state)
      type(jul2gr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%rdayg = 0
      state%rdayj = 0
      state%offstj = 0
      state%offstg = 0
      state%first = .true.
   end subroutine init_jul2gr_state

end module pepper_state_jul2gr
