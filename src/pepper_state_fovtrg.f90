!> Determine if a specified ephemeris object is within the
!> field-of-view (FOV) of a specified instrument at a given time.
!>
!> The state of SPICELIB's FOVTRG routines (entry points fovtrg),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of fovtrg.f90.
module pepper_state_fovtrg

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'gf.inc'

   public :: init_fovtrg_state

   !> The saved variables of FOVTRG.
   type, public :: fovtrg_state
      real(wp) :: raydir ( 3 )  !! ray direction vector required by ZZGFFVIN. This is an unused variable as far is this routine is concerned: the target is an ephemeris object. We initialize the ray to prevent portability problems.
   end type fovtrg_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_fovtrg_state(state)
      type(fovtrg_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%raydir = 0.0_wp
      state%raydir = 0.0_wp
   end subroutine init_fovtrg_state

end module pepper_state_fovtrg
