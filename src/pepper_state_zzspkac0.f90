!> Return the state (position and velocity) of a target body
!> relative to an observer, optionally corrected for light time
!> and stellar aberration, expressed relative to an inertial
!> reference frame.
!>
!> The state of SPICELIB's ZZSPKAC0 routines (entry points zzspkac0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkac0.f90.
module pepper_state_zzspkac0

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzspkac0_state

   !> The saved variables of ZZSPKAC0.
   type, public :: zzspkac0_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usestl  !! the saved correction includes stellar aberration
   end type zzspkac0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkac0_state(state)
      type(zzspkac0_state), intent(inout) :: state  !! the state
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_zzspkac0_state

end module pepper_state_zzspkac0
