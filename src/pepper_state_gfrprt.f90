!> The entry points contained under this routine provide users
!> information regarding the status of a GF search in progress.
!>
!> The state of SPICELIB's GFRPRT routines (entry points gfrepi, gfrepu, gfrepf),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of gfrprt.f90.
module pepper_state_gfrprt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzgf.inc'

   public :: init_gfrprt_state

   !> The saved variables of GFRPRT.
   type, public :: gfrprt_state
      character(mxbegm) :: copyb  !! progress report begin message saved by GFREPI for GFREPF
      character(mxendm) :: copye  !! progress report end message saved by GFREPI for GFREPF
      real(wp) :: t0  !! time of the last progress update (start of the search window at first)
      real(wp) :: remain  !! measure of the current interval remaining after t0
   end type gfrprt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_gfrprt_state(state)
      type(gfrprt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%copyb = ' '
      state%copye = ' '
      state%t0 = 0.0_wp
      state%remain = 0.0_wp
   end subroutine init_gfrprt_state

end module pepper_state_gfrprt
