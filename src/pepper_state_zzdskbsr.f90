!> Load and unload DSK files for use by the readers. Buffer segments
!> for readers.
!>
!> The state of SPICELIB's ZZDSKBSR routines (entry points zzdsklsf, zzdskusf, zzdskbss, zzdsksns, zzdskchk),
!> held in pepper_spice (and, for some variables, in pepper_context). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdskbsr.f90.
module pepper_state_zzdskbsr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dla.inc'
   include 'dskdsc.inc'
   include 'zzctr.inc'
   integer(ip), parameter :: ftsize = 5000
   integer(ip), parameter :: btsize = 100
   integer(ip), parameter :: lbpool = -5
   integer(ip), parameter :: stsize = 10000
   integer(ip), parameter :: slen = 40

   public :: init_zzdskbsr_state
   public :: init_zzdskbsr_context_state

   !> The saved variables of ZZDSKBSR.
   type, public :: zzdskbsr_state
      integer(ip) :: fthan    ( ftsize )  !! handle of each loaded file (in load order)
      integer(ip) :: ftnum    ( ftsize )  !! file number of each loaded file: its place in the load (and search) order
      integer(ip) :: next  !! the file number of the file loaded last
      integer(ip) :: nft  !! number of loaded files
      integer(ip) :: dskctr ( ctrsiz )  !! counter of changes of the loaded DSK set (checked by ZZDSKCHK)
      logical :: pass1  !! the counter has not been set up yet
   end type zzdskbsr_state

   !> The saved variables of ZZDSKBSR that are per context.
   type, public :: zzdskbsr_context_state
      logical :: begsch  !! a search was begun by ZZDSKBSS
      integer(ip) :: findex  !! index in the file table of the file being searched
      logical :: fnd  !! a segment was found by the last search
      integer(ip) :: bindex  !! index in the body table of the body being searched
      integer(ip) :: btbeg    ( btsize )  !! head of the segment list of each body
      integer(ip) :: btexp    ( btsize )  !! expense (number of segment descriptors examined) of the segment list of each body
      integer(ip) :: bthfs    ( btsize )  !! highest file number searched for the segment list of each body
      integer(ip) :: btbod    ( btsize )  !! each body's code
      integer(ip) :: btlfs    ( btsize )  !! lowest file number searched for the segment list of each body
      integer(ip) :: nbt  !! number of bodies in the body table
      integer(ip) :: savep  !! the segment list node to continue the search from
      integer(ip) :: svbody  !! the body of the search
      character(slen) :: status  !! the state of the search in progress
      integer(ip) :: stdlad  ( dladsz,     stsize )  !! DLA descriptor of each segment in the segment table
      real(wp) :: stdskd  ( dskdsz,     stsize )  !! DSK descriptor of each segment in the segment table
      integer(ip) :: sthan   (             stsize )  !! handle of the file of each segment in the segment table
      integer(ip) :: stpool ( 2,  lbpool : stsize )  !! doubly linked list pool of the segment table (one list per body, in priority order)
      integer(ip) :: top  !! depth of the stack of interrupted states of the search
      integer(ip) :: epoch  !! the instance's segment_epoch this cache reflects
   end type zzdskbsr_context_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdskbsr_state(state)
      type(zzdskbsr_state), intent(inout) :: state  !! the state
      state%next = 0
      state%nft = 0
      state%pass1 = .true.
   end subroutine init_zzdskbsr_state

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdskbsr_context_state(state)
      type(zzdskbsr_context_state), intent(inout) :: state  !! the state
      state%nbt = 0
      state%savep = 0
      state%status = 'BOGUS ENTRY'
      state%epoch = 0
   end subroutine init_zzdskbsr_context_state

end module pepper_state_zzdskbsr
