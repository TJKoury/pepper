!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZINPDT routines (entry points zzinpdt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzinpdt.f90.
module pepper_state_zzinpdt

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsktol

   implicit none

   private


   public :: init_zzinpdt_state

   !> The saved variables of ZZINPDT.
   type, public :: zzinpdt_state
      real(wp) :: altbds ( 2, 3 )  !! bounds for the altitude-only test: full lat/lon range, altitudes expanded by the margin
      logical :: first  !! first call: hpi, pi2 and the lat/lon parts of altbds not yet set
      real(wp) :: hpi  !! pi/2, set on the first call
      real(wp) :: pi2  !! 2 pi, set on the first call
   end type zzinpdt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzinpdt_state(state)
      type(zzinpdt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%altbds = 0.0_wp
      state%first = .false.
      state%hpi = 0.0_wp
      state%pi2 = 0.0_wp
      state%first = .true.
      state%hpi = -1.0_wp
   end subroutine init_zzinpdt_state

end module pepper_state_zzinpdt
