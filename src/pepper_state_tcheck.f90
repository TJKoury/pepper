!> Determine whether the components of a time vector are in the
!> "usual" range for the components, if component checking is
!> enabled.
!>
!> The state of SPICELIB's TCHECK routines (entry points tcheck, tparch, tchckd),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of tcheck.f90.
module pepper_state_tcheck

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_tcheck_state

   !> The saved variables of TCHECK.
   type, public :: tcheck_state
      logical :: dochck  !! check the components of parsed times (set by TPARCH)
   end type tcheck_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_tcheck_state(state)
      type(tcheck_state), intent(inout) :: state  !! the state
      state%dochck = .false.
   end subroutine init_tcheck_state

end module pepper_state_tcheck
