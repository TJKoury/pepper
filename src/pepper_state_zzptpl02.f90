!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZPTPL02 routines (entry points zzptpl02),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzptpl02.f90.
module pepper_state_zzptpl02

   use pepper_kinds, only: ip, wp
      use pepper_inc_dla
      use pepper_inc_dskdsc
      use pepper_inc_dsk02
      use pepper_inc_dsktol

   implicit none

   private


   public :: init_zzptpl02_state

   !> The saved variables of ZZPTPL02.
   type, public :: zzptpl02_state
      integer(ip) :: cgrscl  !! coarse voxel grid scale of the saved segment
      integer(ip) :: corsys  !! coordinate system code of the saved segment, from its DSK descriptor
      real(wp) :: maxr  !! radius of the saved segment's bounding box (ZZSEGBOX), scales the search distance limit
      logical :: pass1  !! first call: no segment parameters saved yet
      integer(ip) :: prvhan  !! DAS handle of the segment whose parameters are saved
      integer(ip) :: prvdsc ( dladsz )  !! DLA descriptor of the segment whose parameters are saved
      integer(ip) :: vgrext ( 3 )  !! voxel grid extents (voxel counts in x, y, z) of the saved segment
      real(wp) :: voxori ( 3 )  !! voxel grid origin of the saved segment
      real(wp) :: voxsiz  !! voxel size of the saved segment
   end type zzptpl02_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzptpl02_state(state)
      type(zzptpl02_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%cgrscl = 0
      state%corsys = 0
      state%maxr = 0.0_wp
      state%pass1 = .false.
      state%prvhan = 0
      state%prvdsc = 0
      state%vgrext = 0
      state%voxori = 0.0_wp
      state%voxsiz = 0.0_wp
      state%pass1 = .true.
      state%prvhan = 0
      state%prvdsc = 0
   end subroutine init_zzptpl02_state

end module pepper_state_zzptpl02
