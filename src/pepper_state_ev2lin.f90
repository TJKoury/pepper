!> **Deprecated:** This routine has been superseded by the SPICELIB
!> routine EVSGP4. *ALL* TLE evaluations should use that routine.
!> NAIF supports EV2LIN only for backward compatibility.
!>
!> The state of SPICELIB's EV2LIN routines (entry points ev2lin),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ev2lin.f90.
module pepper_state_ev2lin

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: nmodl = 6
   integer(ip), parameter :: kae = 8
   integer(ip), parameter :: ngeocn = kae
   integer(ip), parameter :: kepoch = 10
   integer(ip), parameter :: nelems = kepoch
   integer(ip), parameter :: prsize = 29

   public :: init_ev2lin_state

   !> The saved variables of EV2LIN.
   type, public :: ev2lin_state
      real(wp) :: ke  !! sqrt(GM) of the earth in (earth radii)^1.5/min, from the geophysical constants
      real(wp) :: er  !! equatorial radius of the earth (km), from the geophysical constants
      real(wp) :: ae  !! distance units per earth radius, from the geophysical constants
      real(wp) :: ck2  !! J2 coefficient term J2*ae^2/2
      real(wp) :: a3ovk2  !! J3/J2 term -2*J3*ae/J2
      real(wp) :: ck4  !! J4 coefficient term -3/8*J4*ae^4
      real(wp) :: qoms2t  !! atmospheric density parameter ((QO-SO)*ae/er)^4
      real(wp) :: s  !! atmospheric density parameter ae*(1+SO/er)
      real(wp) :: d2  !! work: drag coefficient D2 of the current elements (t^2 term, perigee >= 220 km)
      real(wp) :: d3  !! work: drag coefficient D3 of the current elements (t^3 term, perigee >= 220 km)
      real(wp) :: d4  !! work: drag coefficient D4 of the current elements (t^4 term, perigee >= 220 km)
      real(wp) :: elemnt ( nelems, nmodl )  !! element sets of the cached models (matched against the input to reuse PRELIM)
      real(wp) :: fl  !! work: Kepler equation residual at the lower bisection bound
      real(wp) :: fu  !! work: Kepler equation residual at the upper bisection bound
      real(wp) :: lower  !! work: lower bracket of the Kepler equation bisection
      real(wp) :: lstgeo ( ngeocn )  !! geophysical constants of the previous call (derived constants recomputed on change)
      real(wp) :: pix2  !! 2*pi, set on the first call
      real(wp) :: prelim ( prsize, nmodl )  !! element-dependent preliminary quantities of each cached model
      real(wp) :: t3cof  !! work: t^3 mean longitude coefficient of the current elements (perigee >= 220 km)
      real(wp) :: t4cof  !! work: t^4 mean longitude coefficient of the current elements (perigee >= 220 km)
      real(wp) :: t5cof  !! work: t^5 mean longitude coefficient of the current elements (perigee >= 220 km)
      real(wp) :: tokm  !! kilometers per distance unit (er/ae)
      real(wp) :: tokmps  !! conversion from distance units/min to km/s (tokm/60)
      real(wp) :: upper  !! work: upper bracket of the Kepler equation bisection
      integer(ip) :: head  !! head of the most-recently-used list of cached models
      integer(ip) :: last  !! work: last model visited in the cache search (reused when no match)
      integer(ip) :: list ( 2, nmodl )  !! previous/next links of the most-recently-used list of cached models
      logical :: doinit  !! first call: the model cache and list are not yet initialized
      logical :: recog  !! work: the input elements match a cached model
   end type ev2lin_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ev2lin_state(state)
      type(ev2lin_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ke = 0.0_wp
      state%er = 0.0_wp
      state%ae = 0.0_wp
      state%ck2 = 0.0_wp
      state%a3ovk2 = 0.0_wp
      state%ck4 = 0.0_wp
      state%qoms2t = 0.0_wp
      state%s = 0.0_wp
      state%d2 = 0.0_wp
      state%d3 = 0.0_wp
      state%d4 = 0.0_wp
      state%elemnt = 0.0_wp
      state%fl = 0.0_wp
      state%fu = 0.0_wp
      state%lower = 0.0_wp
      state%lstgeo = 0.0_wp
      state%pix2 = 0.0_wp
      state%prelim = 0.0_wp
      state%t3cof = 0.0_wp
      state%t4cof = 0.0_wp
      state%t5cof = 0.0_wp
      state%tokm = 0.0_wp
      state%tokmps = 0.0_wp
      state%upper = 0.0_wp
      state%head = 0
      state%last = 0
      state%list = 0
      state%doinit = .false.
      state%recog = .false.
      state%doinit = .true.
   end subroutine init_ev2lin_state

end module pepper_state_ev2lin
