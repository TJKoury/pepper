!> Map array of planetocentric longitude/latitude coordinate pairs
!> to surface points on a specified target body.
!>
!> The state of SPICELIB's LATSRF routines (entry points latsrf),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of latsrf.f90.
module pepper_state_latsrf

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsk
      use pepper_inc_gf
      use pepper_inc_zzctr
      use pepper_inc_zzdsk

   implicit none

   private

   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_latsrf_state

   !> The saved variables of LATSRF.
   type, public :: latsrf_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(bdnmln) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame looked up last (ZZNAMFRM)
      integer(ip) :: svfxfc  !! ID code of the body-fixed frame looked up last
      integer(ip) :: svctr3 ( ctrsiz )  !! saved target radius values.
      integer(ip) :: svprvt  !! ID code of the target whose radii were looked up last
      real(wp) :: svradi ( 3 )  !! radii of the target body (from the kernel pool, ZZBODVCD)
      integer(ip) :: nsurf  !! number of surface IDs in the previous METHOD string
      logical :: first  !! first call: counters not yet initialized and no METHOD parsed yet
      character(mthlen) :: prvmth  !! METHOD string of the previous call
      integer(ip) :: shape  !! target shape code parsed from the previous METHOD (ellipsoid or DSK)
      integer(ip) :: srfctr ( ctrsiz )  !! surface name-ID mapping state counter (ZZSRFTRK)
      integer(ip) :: srflst ( maxsrf )  !! surface ID list parsed from the previous METHOD string
   end type latsrf_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_latsrf_state(state)
      type(latsrf_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svfref = ' '
      state%svfxfc = 0
      state%svctr3 = 0
      state%svprvt = 0
      state%svradi = 0.0_wp
      state%nsurf = 0
      state%first = .false.
      state%prvmth = ' '
      state%shape = 0
      state%srfctr = 0
      state%srflst = 0
      state%svprvt = 0
      state%first = .true.
      state%prvmth = ' '
   end subroutine init_latsrf_state

end module pepper_state_latsrf
