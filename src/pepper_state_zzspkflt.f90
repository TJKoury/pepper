!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKFLT routines (entry points zzspkflt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkflt.f90.
module pepper_state_zzspkflt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzspkflt_state

   !> The saved variables of ZZSPKFLT.
   type, public :: zzspkflt_state
      logical :: pass1  !! first call: aberration correction flags not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: uselt  !! the saved correction includes light time correction
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkflt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkflt_state(state)
      type(zzspkflt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%pass1 = .false.
      state%prvcor = ' '
      state%usecn = .false.
      state%uselt = .false.
      state%xmit = .false.
      state%pass1 = .true.
      state%prvcor = ' '
   end subroutine init_zzspkflt_state

end module pepper_state_zzspkflt
