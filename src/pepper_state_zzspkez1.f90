!> Return the state (position and velocity) of a target body
!> relative to an observing body, optionally corrected for light
!> time (planetary aberration) and stellar aberration.
!>
!> The state of SPICELIB's ZZSPKEZ1 routines (entry points zzspkez1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkez1.f90.
module pepper_state_zzspkez1

   use pepper_kinds, only: ip, wp
      use pepper_inc_frmtyp
      use pepper_inc_zzabcorr
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: frnmln = 32

   public :: init_zzspkez1_state

   !> The saved variables of ZZSPKEZ1.
   type, public :: zzspkez1_state
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      integer(ip) :: fj2000  !! frame ID code of J2000
      logical :: usegeo  !! the saved correction is geometric (no aberration correction)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the reference frame
      character(frnmln) :: svref  !! saved output frame name for the zznamfrm lookup
      integer(ip) :: svreqf  !! saved output frame ID code for the zznamfrm lookup
      logical :: first  !! first call: counter, correction flags and J2000 code not yet set up
   end type zzspkez1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkez1_state(state)
      type(zzspkez1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%prvcor = ' '
      state%fj2000 = 0
      state%usegeo = .false.
      state%xmit = .false.
      state%svctr1 = 0
      state%svref = ' '
      state%svreqf = 0
      state%first = .false.
      state%prvcor = ' '
      state%first = .true.
   end subroutine init_zzspkez1_state

end module pepper_state_zzspkez1
