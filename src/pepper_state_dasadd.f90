!> Add an array of double precision numbers to a DAS file.
!>
!> The state of SPICELIB's DASADD routines (entry points dasadd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dasadd.f90.
module pepper_state_dasadd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: nwd = 128

   public :: init_dasadd_state

   !> The saved variables of DASADD.
   type, public :: dasadd_state
      real(wp) :: record ( nwd )  !! work buffer of one double precision record (saved in SPICELIB
                                  !! to keep it off the stack)
   end type dasadd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dasadd_state(state)
      type(dasadd_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%record = 0.0_wp
      state%record = 0.0_wp
   end subroutine init_dasadd_state

end module pepper_state_dasadd
