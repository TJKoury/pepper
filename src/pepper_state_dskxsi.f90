!> Compute a ray-surface intercept using data provided by
!> multiple loaded DSK segments. Return information about
!> the source of the data defining the surface on which the
!> intercept was found: DSK handle, DLA and DSK descriptors,
!> and DSK data type-dependent parameters.
!>
!> The state of SPICELIB's DSKXSI routines (entry points dskxsi),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dskxsi.f90.
module pepper_state_dskxsi

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsk
      use pepper_inc_dsktol
      use pepper_inc_dsksrc
      use pepper_inc_srftrn
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_dskxsi_state

   !> The saved variables of DSKXSI.
   type, public :: dskxsi_state
      logical :: first  !! first call: the counters are not yet initialized
      integer(ip) :: fixfid  !! ID code of the body-fixed frame FIXREF of the previous call
      integer(ip) :: frmctr ( ctrsiz )  !! pool counter of the frame name lookup of FIXREF (ZZPCTRCK)
      character(frnmln) :: prvfrm  !! body-fixed frame name of the previous call
      integer(ip) :: prvtcd  !! target ID code of the previous call
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svtfnd  !! found flag of the last target name lookup
      character(bdnmln) :: svtnam  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: trgctr ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the target
   end type dskxsi_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dskxsi_state(state)
      type(dskxsi_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%fixfid = 0
      state%frmctr = 0
      state%prvfrm = ' '
      state%prvtcd = 0
      state%svtcde = 0
      state%svtfnd = .false.
      state%svtnam = ' '
      state%trgctr = 0
      state%first = .true.
      state%prvfrm = ' '
      state%prvtcd = 0
   end subroutine init_dskxsi_state

end module pepper_state_dskxsi
