!> Return the state (position and velocity) of a target body
!> relative to some center of motion in a specified frame.
!>
!> The state of SPICELIB's SPKPV routines (entry points spkpv),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkpv.f90.
module pepper_state_spkpv

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: frnmln = 32

   public :: init_spkpv_state

   !> The saved variables of SPKPV.
   type, public :: spkpv_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svref  !! name of the reference frame looked up last (ZZNAMFRM)
      integer(ip) :: svirfr  !! ID code of the reference frame looked up last
      logical :: first  !! first call: the pool counter is not yet initialized
   end type spkpv_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkpv_state(state)
      type(spkpv_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svref = ' '
      state%svirfr = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_spkpv_state

end module pepper_state_spkpv
