!> **Deprecated:** This routine has been superseded by SPKAPS. This
!> routine is supported for purposes of backward compatibility only.
!>
!> The state of SPICELIB's ZZSPKAP1 routines (entry points zzspkap1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkap1.f90.
module pepper_state_zzspkap1

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: corlen = 5
   integer(ip), parameter :: nflags = 9

   public :: init_zzspkap1_state

   !> The saved variables of ZZSPKAP1.
   type, public :: zzspkap1_state
      logical :: first  !! first call: the aberration correction flags are not yet parsed
      character(corlen) :: flags  ( nflags )  !! constant list of the recognized aberration correction strings
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usecn  !! the saved correction uses converged Newtonian light time (CN)
      logical :: usestl  !! the saved correction includes stellar aberration (+S)
      logical :: uselt  !! the saved correction uses one-iteration light time (LT)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkap1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkap1_state(state)
      type(zzspkap1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%flags = ' '
      state%prvcor = ' '
      state%usecn = .false.
      state%usestl = .false.
      state%uselt = .false.
      state%xmit = .false.
      state%first = .true.
      state%flags = [ character(len(state%flags)) :: 'NONE', 'LT', 'LT+S', 'CN', 'CN+S', 'XLT', 'XLT+S', 'XCN', 'XCN+S' ]
      state%prvcor = ' '
   end subroutine init_zzspkap1_state

end module pepper_state_zzspkap1
