!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDDHMNM routines (entry points zzddhmnm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzddhmnm.f90.
module pepper_state_zzddhmnm

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzddhmnm_state

   !> The saved variables of ZZDDHMNM.
   type, public :: zzddhmnm_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      integer(ip) :: natbff  !! code of the native binary file format
      integer(ip) :: supbff ( numbff )  !! codes of the supported binary file formats
      integer(ip) :: numsup  !! number of supported binary file formats
   end type zzddhmnm_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzddhmnm_state(state)
      type(zzddhmnm_state), intent(inout) :: state  !! the state
      state%first = .true.
      state%natbff = 0
   end subroutine init_zzddhmnm_state

end module pepper_state_zzddhmnm
