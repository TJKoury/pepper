!> Get pointing (attitude) for a specified spacecraft clock time.
!>
!> The state of SPICELIB's CKGP routines (entry points ckgp),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ckgp.f90.
module pepper_state_ckgp

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'frmtyp.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_ckgp_state

   !> The saved variables of CKGP.
   type, public :: ckgp_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svref  !! name of the reference frame looked up last (ZZNAMFRM)
      integer(ip) :: svrefr  !! ID code of the reference frame looked up last
      logical :: first  !! first call: the pool counter is not yet initialized
   end type ckgp_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ckgp_state(state)
      type(ckgp_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_ckgp_state

end module pepper_state_ckgp
