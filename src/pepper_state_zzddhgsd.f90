!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDDHGSD routines (entry points zzddhgsd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzddhgsd.f90.
module pepper_state_zzddhgsd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'
   integer(ip), parameter :: locsiz = 8
   integer(ip), parameter :: numcls = 3

   public :: init_zzddhgsd_state

   !> The saved variables of ZZDDHGSD.
   type, public :: zzddhgsd_state
      character(locsiz) :: clslst ( numcls )  !! saved between calls by ZZDDHGSD
      character(strsiz) :: stramh ( numamh )  !! saved between calls by ZZDDHGSD
      character(strsiz) :: strarc ( numarc )  !! saved between calls by ZZDDHGSD
      character(strsiz) :: strbff ( numbff )  !! saved between calls by ZZDDHGSD
   end type zzddhgsd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzddhgsd_state(state)
      type(zzddhgsd_state), intent(inout) :: state  !! the state
      state%clslst = [ character(len(state%clslst)) :: 'METHOD', 'ARCH', 'BFF' ]
      state%stramh = [ character(len(state%stramh)) :: 'READ', 'WRITE', 'SCRATCH', 'NEW' ]
      state%strarc = [ character(len(state%strarc)) :: 'DAF', 'DAS' ]
      state%strbff = [ character(len(state%strbff)) :: 'BIG-IEEE', 'LTL-IEEE', 'VAX-GFLT', 'VAX-DFLT' ]
   end subroutine init_zzddhgsd_state

end module pepper_state_zzddhgsd
