!> Umbrella for the SGP4 initializer and evaluator routines.
!>
!> The state of SPICELIB's ZZSGP4 routines (entry points xxsgp4i, xxsgp4e),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsgp4.f90.
module pepper_state_zzsgp4

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzsgp4.inc'

   public :: init_zzsgp4_state

   !> The saved variables of ZZSGP4.
   type, public :: zzsgp4_state
      real(wp) :: a  !! mean semi-major axis at epoch from the TLE mean motion (earth radii)
      real(wp) :: alta  !! apogee altitude at epoch (earth radii)
      real(wp) :: altp  !! perigee altitude at epoch (earth radii)
      real(wp) :: argpdot  !! secular rate of the argument of perigee (rad/min)
      real(wp) :: argpo  !! argument of perigee at epoch (rad), from the TLE
      real(wp) :: atime  !! deep-space resonance integrator: time of the current integration step (min)
      real(wp) :: aycof  !! J3 long-period coefficient of the axN/ayN term (recomputed by XXSGP4E for deep space)
      real(wp) :: bstar  !! B* drag term (1/earth radii), from the TLE
      real(wp) :: cc1  !! drag coefficient C1 (secular decay of the semi-major axis)
      real(wp) :: cc4  !! drag coefficient C4 (secular decay of the eccentricity)
      real(wp) :: cc5  !! drag coefficient C5 (periodic eccentricity term, near-earth only)
      real(wp) :: con41  !! 3 cos^2(inclination) - 1 at epoch
      real(wp) :: d2  !! drag coefficient D2 (t^2 term of the semi-major axis, near-earth only)
      real(wp) :: d2201  !! deep-space resonance term d2201 (half-day resonance)
      real(wp) :: d2211  !! deep-space resonance term d2211 (half-day resonance)
      real(wp) :: d3  !! drag coefficient D3 (t^3 term of the semi-major axis, near-earth only)
      real(wp) :: d3210  !! deep-space resonance term d3210 (half-day resonance)
      real(wp) :: d3222  !! deep-space resonance term d3222 (half-day resonance)
      real(wp) :: d4  !! drag coefficient D4 (t^4 term of the semi-major axis, near-earth only)
      real(wp) :: d4410  !! deep-space resonance term d4410 (half-day resonance)
      real(wp) :: d4422  !! deep-space resonance term d4422 (half-day resonance)
      real(wp) :: d5220  !! deep-space resonance term d5220 (half-day resonance)
      real(wp) :: d5232  !! deep-space resonance term d5232 (half-day resonance)
      real(wp) :: d5421  !! deep-space resonance term d5421 (half-day resonance)
      real(wp) :: d5433  !! deep-space resonance term d5433 (half-day resonance)
      real(wp) :: dedt  !! deep-space secular rate of the eccentricity (lunar-solar, 1/min)
      real(wp) :: del1  !! deep-space resonance term del1 (one-day resonance)
      real(wp) :: del2  !! deep-space resonance term del2 (one-day resonance)
      real(wp) :: del3  !! deep-space resonance term del3 (one-day resonance)
      real(wp) :: delmo  !! (1 + eta cos(mean anomaly at epoch))^3, for the drag mean anomaly term
      real(wp) :: didt  !! deep-space secular rate of the inclination (lunar-solar, rad/min)
      real(wp) :: dmdt  !! deep-space secular rate of the mean anomaly (lunar-solar, rad/min)
      real(wp) :: dnodt  !! deep-space secular rate of the right ascension of the node (lunar-solar, rad/min)
      logical :: dodeep  !! the orbit is deep space (period >= 225 min): apply lunar-solar terms
      real(wp) :: domdt  !! deep-space secular rate of the argument of perigee (lunar-solar, rad/min)
      logical :: dosimp  !! use the simplified drag model (perigee below 220 km, or deep space)
      real(wp) :: e3  !! deep-space lunar long-period eccentricity coefficient e3
      real(wp) :: ecco  !! eccentricity at epoch, from the TLE
      real(wp) :: ee2  !! deep-space lunar long-period eccentricity coefficient ee2
      real(wp) :: er  !! equatorial radius of the earth (km), from GEOPHS
      real(wp) :: eta  !! SGP4 eta: a0 e0 / (a0 - s) at epoch
      real(wp) :: gsto  !! Greenwich sidereal time at epoch (rad)
      real(wp) :: inclo  !! inclination at epoch (rad), from the TLE
      integer(ip) :: irez  !! deep-space resonance flag: 0 none, 1 one-day, 2 half-day
      real(wp) :: j2  !! J2 zonal harmonic, from GEOPHS
      real(wp) :: j3oj2  !! J3/J2 ratio of the zonal harmonics, from GEOPHS
      real(wp) :: mdot  !! secular rate of the mean anomaly (rad/min), including J2 and J4 terms
      real(wp) :: mo  !! mean anomaly at epoch (rad), from the TLE
      real(wp) :: no  !! mean motion at epoch (rad/min), from the TLE (un-Kozai'd by ZZINIL)
      real(wp) :: nodedot  !! secular rate of the right ascension of the ascending node (rad/min)
      real(wp) :: nodeo  !! right ascension of the ascending node at epoch (rad), from the TLE
      real(wp) :: omgcof  !! drag coefficient of the argument of perigee correction (B* C3 cos(argpo))
      real(wp) :: peo  !! deep-space long-period eccentricity perturbation at epoch
      real(wp) :: pgho  !! deep-space long-period argument of perigee perturbation at epoch
      real(wp) :: pho  !! deep-space long-period node perturbation at epoch
      real(wp) :: pinco  !! deep-space long-period inclination perturbation at epoch
      real(wp) :: plo  !! deep-space long-period mean longitude perturbation at epoch
      real(wp) :: se2  !! deep-space solar long-period eccentricity coefficient se2
      real(wp) :: se3  !! deep-space solar long-period eccentricity coefficient se3
      real(wp) :: sgh2  !! deep-space solar long-period argument of perigee coefficient sgh2
      real(wp) :: sgh3  !! deep-space solar long-period argument of perigee coefficient sgh3
      real(wp) :: sgh4  !! deep-space solar long-period argument of perigee coefficient sgh4
      real(wp) :: sh2  !! deep-space solar long-period node coefficient sh2
      real(wp) :: sh3  !! deep-space solar long-period node coefficient sh3
      real(wp) :: si2  !! deep-space solar long-period inclination coefficient si2
      real(wp) :: si3  !! deep-space solar long-period inclination coefficient si3
      real(wp) :: sinmao  !! sin(mean anomaly at epoch), for the drag eccentricity term
      real(wp) :: sl2  !! deep-space solar long-period mean longitude coefficient sl2
      real(wp) :: sl3  !! deep-space solar long-period mean longitude coefficient sl3
      real(wp) :: sl4  !! deep-space solar long-period mean longitude coefficient sl4
      integer(ip) :: svmode  !! operation mode (OPMODE of XXSGP4I: AFSPC or improved), used by XXSGP4E
      real(wp) :: t2cof  !! coefficient of the t^2 term of the mean anomaly, times no (1.5 C1)
      real(wp) :: t3cof  !! coefficient of the t^3 term of the mean anomaly, times no (near-earth only)
      real(wp) :: t4cof  !! coefficient of the t^4 term of the mean anomaly, times no (near-earth only)
      real(wp) :: t5cof  !! coefficient of the t^5 term of the mean anomaly, times no (near-earth only)
      real(wp) :: x1mth2  !! 1 - cos^2(inclination) at epoch
      real(wp) :: x7thm1  !! 7 cos^2(inclination) - 1 at epoch
      real(wp) :: xfact  !! deep-space resonance: rate of the resonance angle minus the mean motion
      real(wp) :: xgh2  !! deep-space lunar long-period argument of perigee coefficient xgh2
      real(wp) :: xgh3  !! deep-space lunar long-period argument of perigee coefficient xgh3
      real(wp) :: xgh4  !! deep-space lunar long-period argument of perigee coefficient xgh4
      real(wp) :: xh2  !! deep-space lunar long-period node coefficient xh2
      real(wp) :: xh3  !! deep-space lunar long-period node coefficient xh3
      real(wp) :: xi2  !! deep-space lunar long-period inclination coefficient xi2
      real(wp) :: xi3  !! deep-space lunar long-period inclination coefficient xi3
      real(wp) :: xke  !! sqrt(GM) of the earth in earth radii^1.5/min, from GEOPHS
      real(wp) :: xl2  !! deep-space lunar long-period mean longitude coefficient xl2
      real(wp) :: xl3  !! deep-space lunar long-period mean longitude coefficient xl3
      real(wp) :: xl4  !! deep-space lunar long-period mean longitude coefficient xl4
      real(wp) :: xlamo  !! deep-space resonance angle (lambda) at epoch (rad)
      real(wp) :: xlcof  !! J3 long-period coefficient of the mean longitude (recomputed by XXSGP4E for deep space)
      real(wp) :: xli  !! deep-space resonance integrator: resonance angle at atime (rad)
      real(wp) :: xmcof  !! drag coefficient of the mean anomaly correction (-2/3 coef B* / (e eta))
      real(wp) :: xni  !! deep-space resonance integrator: mean motion at atime (rad/min)
      real(wp) :: xnodcf  !! coefficient of the t^2 drag term of the node (3.5 beta0^2 xhdot1 C1)
      real(wp) :: zmol  !! lunar mean anomaly at epoch (rad)
      real(wp) :: zmos  !! solar mean anomaly at epoch (rad)
   end type zzsgp4_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsgp4_state(state)
      type(zzsgp4_state), intent(inout) :: state  !! the state
   end subroutine init_zzsgp4_state

end module pepper_state_zzsgp4
