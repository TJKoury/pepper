!> SPICE private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFRELX routines (entry points zzgfrelx),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfrelx.f90.
module pepper_state_zzgfrelx

   use pepper_kinds, only: ip, wp
      use pepper_inc_gf

   implicit none

   private

   integer(ip), parameter :: maxcln = 80
   integer(ip), parameter :: nc = 7

   public :: init_zzgfrelx_state

   !> The saved variables of ZZGFRELX.
   type, public :: zzgfrelx_state
      character(maxcln) :: cnames ( nc )  !! recognized relational operators (constant)
      logical :: cstep  !! constant step size flag passed to ZZGFSOLVX: always false (constant)
   end type zzgfrelx_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfrelx_state(state)
      type(zzgfrelx_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%cnames = ' '
      state%cstep = .false.
      state%cnames = [ character(len(state%cnames)) :: '<', '=', '>', 'LOCMIN', 'ABSMIN', 'LOCMAX', 'ABSMAX' ]
      state%cstep = .false.
   end subroutine init_zzgfrelx_state

end module pepper_state_zzgfrelx
