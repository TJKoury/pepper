!> Return the position of a target body relative to an observer,
!> optionally corrected for light time and stellar aberration.
!>
!> The state of SPICELIB's ZZSPKPA1 routines (entry points zzspkpa1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkpa1.f90.
module pepper_state_zzspkpa1

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: corlen = 5
   integer(ip), parameter :: nflags = 9

   public :: init_zzspkpa1_state

   !> The saved variables of ZZSPKPA1.
   type, public :: zzspkpa1_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: flags  ( nflags )  !! list of recognized aberration correction flags ('NONE', 'LT', 'LT+S', ...)
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: usestl  !! the saved correction includes stellar aberration
      logical :: uselt  !! the saved correction uses (single-iteration) light time
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkpa1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkpa1_state(state)
      type(zzspkpa1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%flags = ' '
      state%prvcor = ' '
      state%usecn = .false.
      state%usestl = .false.
      state%uselt = .false.
      state%xmit = .false.
      state%first = .true.
      state%flags = [ character(len(state%flags)) :: 'NONE', 'LT', 'LT+S', 'CN', 'CN+S', 'XLT', 'XLT+S', 'XCN', 'XCN+S' ]
      state%prvcor = ' '
   end subroutine init_zzspkpa1_state

end module pepper_state_zzspkpa1
