!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFRRU routines (entry points zzgfrrin, zzgfrrdc, zzgfrrgq, zzgfrrx),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfrru.f90.
module pepper_state_zzgfrru

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_zzgfrru_state

   !> The saved variables of ZZGFRRU.
   type, public :: zzgfrru_state
      character(corlen) :: svabco  !! aberration correction saved by ZZGFRRIN
      integer(ip) :: svtarg  !! target ID code saved by ZZGFRRIN
      character(32) :: svref  !! reference frame for the states: J2000
      integer(ip) :: svobs  !! observer ID code saved by ZZGFRRIN
      real(wp) :: svdt  !! time step of the numerical derivative of range rate
   end type zzgfrru_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfrru_state(state)
      type(zzgfrru_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svabco = ' '
      state%svtarg = 0
      state%svref = ' '
      state%svobs = 0
      state%svdt = 0.0_wp
   end subroutine init_zzgfrru_state

end module pepper_state_zzgfrru
