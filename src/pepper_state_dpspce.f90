!> Deprecated: This routine has been superseded by the SPICELIB
!> routine EVSGP4. *ALL* TLE evaluations should use that routine.
!> NAIF supports DPSPCE only for backward compatibility.
!>
!> The state of SPICELIB's DPSPCE routines (entry points dpspce),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dpspce.f90.
module pepper_state_dpspce

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: numgeo = 8
   integer(ip), parameter :: numelm = 10

   public :: init_dpspce_state

   !> The saved variables of DPSPCE.
   type, public :: dpspce_state
      real(wp) :: ae  !! distance units per Earth radius (GEOPHS(8))
      real(wp) :: ck2  !! J2 term coefficient: 0.5 * J2 * AE**2
      real(wp) :: xke  !! square root of GM, in Earth radii**1.5 per minute (GEOPHS(4))
      real(wp) :: xkmper  !! km per Earth radius (GEOPHS(7))
      real(wp) :: lstphs ( numgeo )  !! geophysical constants (GEOPHS) of the last initialization
      real(wp) :: bstar  !! elements
      real(wp) :: epoch  !! epoch of the elements (ET)
      real(wp) :: omegao  !! argument of perigee at epoch (radians)
      real(wp) :: xmo  !! mean anomaly at epoch (radians)
      real(wp) :: xnodeo  !! right ascension of the ascending node at epoch (radians)
      real(wp) :: lstelm ( numelm )  !! two-line elements (ELEMS) of the last initialization
      real(wp) :: aodp  !! original (un-Kozai) semi-major axis, from the initialization
      real(wp) :: aycof  !! long-period periodic coefficient of the AYN term
      real(wp) :: c1  !! drag coefficient C1 (BSTAR * C2)
      real(wp) :: c4  !! drag coefficient C4
      real(wp) :: cosepw  !! work: cosine of (E + omega) in the Kepler iteration
      real(wp) :: cosio  !! cosine of the inclination at epoch
      real(wp) :: omgdot  !! secular rate of the argument of perigee (radians/minute)
      real(wp) :: pio2  !! pi/2, set on the first call
      real(wp) :: pix2  !! 2*pi, set on the first call
      real(wp) :: sinepw  !! work: sine of (E + omega) in the Kepler iteration
      real(wp) :: sinio  !! sine of the inclination at epoch
      real(wp) :: t2cof  !! coefficient of the t**2 drag term of the mean longitude (1.5 * C1)
      real(wp) :: temp3  !! work: temporary of the initialization and the Kepler iteration
      real(wp) :: temp4  !! work: temporary of the Kepler iteration
      real(wp) :: temp5  !! work: temporary of the Kepler iteration
      real(wp) :: temp6  !! work: temporary of the Kepler iteration
      real(wp) :: x1mth2  !! 1 - cos(i)**2
      real(wp) :: x3thm1  !! 3*cos(i)**2 - 1
      real(wp) :: x7thm1  !! 7*cos(i)**2 - 1
      real(wp) :: xlcof  !! long-period periodic coefficient of the mean longitude
      real(wp) :: xmdot  !! secular rate of the mean anomaly (radians/minute)
      real(wp) :: xnodcf  !! coefficient of the t**2 drag term of the node
      real(wp) :: xnodot  !! secular rate of the ascending node (radians/minute)
      real(wp) :: xnodp  !! original (un-Kozai) mean motion, from the initialization (radians/minute)
      logical :: doinit  !! the derived quantities must be recomputed (first call or new GEOPHS/ELEMS)
      logical :: first  !! first call: PIO2 and PIX2 not yet set
   end type dpspce_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dpspce_state(state)
      type(dpspce_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ae = 0.0_wp
      state%ck2 = 0.0_wp
      state%xke = 0.0_wp
      state%xkmper = 0.0_wp
      state%lstphs = 0.0_wp
      state%bstar = 0.0_wp
      state%epoch = 0.0_wp
      state%omegao = 0.0_wp
      state%xmo = 0.0_wp
      state%xnodeo = 0.0_wp
      state%lstelm = 0.0_wp
      state%aodp = 0.0_wp
      state%aycof = 0.0_wp
      state%c1 = 0.0_wp
      state%c4 = 0.0_wp
      state%cosepw = 0.0_wp
      state%cosio = 0.0_wp
      state%omgdot = 0.0_wp
      state%pio2 = 0.0_wp
      state%pix2 = 0.0_wp
      state%sinepw = 0.0_wp
      state%sinio = 0.0_wp
      state%t2cof = 0.0_wp
      state%temp3 = 0.0_wp
      state%temp4 = 0.0_wp
      state%temp5 = 0.0_wp
      state%temp6 = 0.0_wp
      state%x1mth2 = 0.0_wp
      state%x3thm1 = 0.0_wp
      state%x7thm1 = 0.0_wp
      state%xlcof = 0.0_wp
      state%xmdot = 0.0_wp
      state%xnodcf = 0.0_wp
      state%xnodot = 0.0_wp
      state%xnodp = 0.0_wp
      state%doinit = .false.
      state%first = .false.
      state%doinit = .true.
      state%first = .true.
   end subroutine init_dpspce_state

end module pepper_state_dpspce
