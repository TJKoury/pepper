!> Compute L_s, the planetocentric longitude of the sun, as seen
!> from a specified body.
!>
!> The state of SPICELIB's LSPCN routines (entry points lspcn),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of lspcn.f90.
module pepper_state_lspcn

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: maxl = 36

   public :: init_lspcn_state

   !> The saved variables of LSPCN.
   type, public :: lspcn_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svbody  !! name of the body looked up last (ZZBODS2C)
      integer(ip) :: svidcd  !! ID code of the body looked up last
      logical :: svfnd1  !! found flag of the last body name lookup
      logical :: first  !! first call: the pool counter is not yet initialized
   end type lspcn_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_lspcn_state(state)
      type(lspcn_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svbody = ' '
      state%svidcd = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_lspcn_state

end module pepper_state_lspcn
