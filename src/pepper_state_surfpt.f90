!> Determine the intersection of a line-of-sight vector with the
!> surface of an ellipsoid.
!>
!> The state of SPICELIB's SURFPT routines (entry points surfpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of surfpt.f90.
module pepper_state_surfpt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: msgdim = 7
   integer(ip), parameter :: msglen = 32

   public :: init_surfpt_state

   !> The saved variables of SURFPT.
   type, public :: surfpt_state
      character(msglen) :: mssg  ( msgdim )  !! error messages for each combination of nonpositive axes, constant
   end type surfpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_surfpt_state(state)
      type(surfpt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%mssg = ' '
      state%mssg = [ character(len(state%mssg)) :: 'Axis A was nonpositive.', 'Axis B was nonpositive.', 'Axes A and B were nonpositive.', 'Axis C was nonpositive.', 'Axes A and C were nonpositive.', 'Axes B and C were nonpositive.', 'All three axes were nonpositive.' ]
   end subroutine init_surfpt_state

end module pepper_state_surfpt
