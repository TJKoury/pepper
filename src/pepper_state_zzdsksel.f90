!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDSKSEL routines (entry points zzdsksbd, zzdskbdc, zzdsknot, zzdsksit, zzdskcit, zzdskusc, zzdskumc, zzdskmsc, zzdskmmc, zzdsksrc, zzdskmrc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdsksel.f90.
module pepper_state_zzdsksel

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsk
      use pepper_inc_dskdsc

   implicit none

   private


   public :: init_zzdsksel_state

   !> The saved variables of ZZDSKSEL.
   type, public :: zzdsksel_state
      integer(ip) :: savbid  !! saved body ID code (surface ID code when set by ZZDSKMSC/ZZDSKSRC) to match segments against
      integer(ip) :: savcls  !! saved DSK data class to match segments against
      real(wp) :: savco1  !! saved first coordinate of the point to match against segment coverage
      real(wp) :: savco2  !! saved second coordinate of the point to match against segment coverage
      real(wp) :: savet  !! saved epoch (TDB seconds past J2000) to match against segment time coverage
      integer(ip) :: savfid  !! saved frame ID code of the input coordinates or position
      integer(ip) :: savnsf  !! number of surface IDs in the saved surface list
      real(wp) :: savpar ( nsypar )  !! saved coordinate system parameters of the input coordinates
      real(wp) :: savpos ( 3 )  !! saved body-centered position whose lat/lon must lie within the segment bounds
      integer(ip) :: savsrf ( maxsrf )  !! saved surface ID list (sorted) to match segments against
      integer(ip) :: savsys  !! saved coordinate system code of the input coordinates
      integer(ip) :: savtrg  !! saved target body ID code to match segments against
   end type zzdsksel_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdsksel_state(state)
      type(zzdsksel_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%savbid = 0
      state%savcls = 0
      state%savco1 = 0.0_wp
      state%savco2 = 0.0_wp
      state%savet = 0.0_wp
      state%savfid = 0
      state%savnsf = 0
      state%savpar = 0.0_wp
      state%savpos = 0.0_wp
      state%savsrf = 0
      state%savsys = 0
      state%savtrg = 0
   end subroutine init_zzdsksel_state

end module pepper_state_zzdsksel
