!> Parse a declaration of a new EK column.
!>
!> The state of SPICELIB's ZZEKPDEC routines (entry points zzekpdec),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzekpdec.f90.
module pepper_state_zzekpdec

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekbool.inc'
   include 'ekcoldsc.inc'
   include 'ektype.inc'
   integer(ip), parameter :: nattr = 5
   integer(ip), parameter :: toklen = 32
   integer(ip), parameter :: nrkey = 1

   public :: init_zzekpdec_state

   !> The saved variables of ZZEKPDEC.
   type, public :: zzekpdec_state
      character(toklen) :: attkey ( nattr )  !! recognized column attribute keywords (DATATYPE, SIZE, INDEXED, ...)
      integer(ip) :: reqkey ( nrkey  )  !! indices in attkey of the required attributes (DATATYPE)
   end type zzekpdec_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzekpdec_state(state)
      type(zzekpdec_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%attkey = ' '
      state%reqkey = 0
      state%attkey = [ character(len(state%attkey)) :: 'DATATYPE', 'SIZE', 'INDEXED', 'NULLS_OK', 'FIXED_COUNT' ]
      state%reqkey = 1
   end subroutine init_zzekpdec_state

end module pepper_state_zzekpdec
