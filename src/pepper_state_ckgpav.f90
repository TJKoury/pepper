!> Get pointing (attitude) and angular velocity for a specified
!> spacecraft clock time.
!>
!> The state of SPICELIB's CKGPAV routines (entry points ckgpav),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ckgpav.f90.
module pepper_state_ckgpav

   use pepper_kinds, only: ip, wp
      use pepper_inc_frmtyp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: frnmln = 32

   public :: init_ckgpav_state

   !> The saved variables of CKGPAV.
   type, public :: ckgpav_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svref  !! name of the reference frame looked up last (ZZNAMFRM)
      integer(ip) :: svrefr  !! ID code of the reference frame looked up last
      logical :: first  !! first call: the pool counter is not yet initialized
   end type ckgpav_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ckgpav_state(state)
      type(ckgpav_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svref = ' '
      state%svrefr = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_ckgpav_state

end module pepper_state_ckgpav
