!> Return platform ID and various attributes of the intended
!> environment
!>
!> The state of SPICELIB's ZZPLATFM routines (entry points zzplatfm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzplatfm.F90.
module pepper_state_zzplatfm

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: kysize = 64
   integer(ip), parameter :: wdsize = 32
   integer(ip), parameter :: nattr = 6

   public :: init_zzplatfm_state

   !> The saved variables of ZZPLATFM.
   type, public :: zzplatfm_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      character(wdsize) :: attcpy ( 0 : nattr )  !! copy of the attribute names (uppercase)
      character(kysize) :: keyval ( nattr )  !! value of each platform attribute (system, compiler,
                                             !! format, ...)
   end type zzplatfm_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzplatfm_state(state)
      type(zzplatfm_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%attcpy = ' '
      state%keyval = ' '
      state%first = .true.
   end subroutine init_zzplatfm_state

end module pepper_state_zzplatfm
