!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFLONG routines (entry points zzgflong),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgflong.f90.
module pepper_state_zzgflong

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'gf.inc'
   include               'zzgf.inc'
   integer(ip), parameter :: nc = 7
   integer(ip), parameter :: oplen = 6

   public :: init_zzgflong_state

   !> The saved variables of ZZGFLONG.
   type, public :: zzgflong_state
      character(oplen) :: ops    ( nc )  !! recognized relational operators (constant)
      real(wp) :: y      ( 3 )  !! +Y unit vector used to find the planetographic longitude sense (constant)
   end type zzgflong_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgflong_state(state)
      type(zzgflong_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ops = ' '
      state%y = 0.0_wp
      state%ops = [ character(len(state%ops)) :: '<', '=', '>', 'LOCMIN', 'ABSMIN', 'LOCMAX', 'ABSMAX' ]
      state%y = [ 0.0_wp, 1.0_wp, 0.0_wp ]
   end subroutine init_zzgflong_state

end module pepper_state_zzgflong
