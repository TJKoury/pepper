!> Transform a state between coordinate systems.
!>
!> The state of SPICELIB's XFMSTA routines (entry points xfmsta),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of xfmsta.f90.
module pepper_state_xfmsta

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_xfmsta_state

   !> The saved variables of XFMSTA.
   type, public :: xfmsta_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svbody  !! name of the body looked up last (ZZBODS2C)
      integer(ip) :: svbdid  !! ID code of the body looked up last
      logical :: svfnd1  !! found flag of the last body name lookup
      logical :: first  !! first call: the pool counter is not yet initialized
   end type xfmsta_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_xfmsta_state(state)
      type(xfmsta_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svbody = ' '
      state%svbdid = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_xfmsta_state

end module pepper_state_xfmsta
