!> Transform time from one uniform scale to another. The uniform
!> time scales are TAI, GPS, TT, TDT, TDB, ET, JED, JDTDB, JDTDT.
!>
!> The state of SPICELIB's UNITIM routines (entry points unitim),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of unitim.f90.
module pepper_state_unitim

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: lbcell = -5
   integer(ip), parameter :: needed = 4
   integer(ip), parameter :: lngvar = 16
   integer(ip), parameter :: mislen = 20
   integer(ip), parameter :: typlen = 8
   integer(ip), parameter :: ntdt = 5
   integer(ip), parameter :: ntdb = 4
   integer(ip), parameter :: nrecog = ntdb + ntdt

   public :: init_unitim_state

   !> The saved variables of UNITIM.
   type, public :: unitim_state
      character(1) :: bslash  !! the backslash character
      real(wp) :: dta  !! TDT - TAI offset, in seconds (DELTET/DELTA_T_A from the kernel pool)
      real(wp) :: eb  !! eccentricity of the heliocentric orbit of the Earth-Moon barycenter (DELTET/EB)
      logical :: first  !! the first call has not set up the tables yet
      real(wp) :: jd2000  !! Julian date of J2000
      real(wp) :: k  !! amplitude of the TDB - TDT periodic term, in seconds (DELTET/K)
      real(wp) :: m     ( 0:1 )  !! mean anomaly of the Earth-Moon barycenter at J2000 and its rate (DELTET/M)
      character(mislen) :: missed ( needed )  !! names of the needed kernel pool variables, for the missing-variable message
      logical :: nodata  !! the DELTET variables have not been read (successfully) from the kernel pool
      character(typlen) :: recog  ( lbcell : nrecog    )  !! set of all the recognized time types (union of TYPTDB and TYPTDT)
      real(wp) :: secspd  !! number of seconds in a day
      character(typlen) :: typtdb ( lbcell : ntdb      )  !! set of the time types based on TDB (ET, JDTDB, JED, TDB)
      character(typlen) :: typtdt ( lbcell : ntdt      )  !! set of the time types based on TDT (GPS, JDTDT, TAI, TDT, TT)
      character(lngvar) :: vars   ( needed )  !! names of the watched kernel pool variables (DELTET/...)
      integer(ip) :: usrctr ( ctrsiz )  !! counter of the kernel pool's state when the DELTET variables were read
   end type unitim_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_unitim_state(state)
      type(unitim_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%bslash = ' '
      state%dta = 0.0_wp
      state%eb = 0.0_wp
      state%first = .false.
      state%jd2000 = 0.0_wp
      state%k = 0.0_wp
      state%m = 0.0_wp
      state%missed = ' '
      state%nodata = .false.
      state%recog = ' '
      state%secspd = 0.0_wp
      state%typtdb = ' '
      state%typtdt = ' '
      state%vars = ' '
      state%usrctr = 0
      state%first = .true.
      state%missed = [ character(len(state%missed)) :: 'DELTET/DELTA_T_A, #', 'DELTET/K, #', 'DELTET/EB, #', 'DELTET/M, #' ]
      state%nodata = .true.
      state%vars = [ character(len(state%vars)) :: 'DELTET/DELTA_T_A', 'DELTET/K', 'DELTET/EB', 'DELTET/M' ]
   end subroutine init_unitim_state

end module pepper_state_unitim
