!> Read a single CK data record from a segment of type 05
!> (MEX/Rosetta Attitude file interpolation).
!>
!> The state of SPICELIB's CKR05 routines (entry points ckr05),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ckr05.f90.
module pepper_state_ckr05

   use pepper_kinds, only: ip, wp
      use pepper_inc_ck05
      use pepper_inc_ckparam

   implicit none

   private


   public :: init_ckr05_state

   !> The saved variables of CKR05.
   type, public :: ckr05_state
      real(wp) :: prevs  !! start time of the interpolation interval found on the last search
      real(wp) :: prevn  !! start time of the interpolation interval following the one starting at prevs
      real(wp) :: prevnn  !! start time of the interpolation interval following the one starting at prevn
      integer(ip) :: lhand  !! handle of the file of the segment searched last
      integer(ip) :: lbeg  !! begin address of the segment searched last
      integer(ip) :: lend  !! end address of the segment searched last
   end type ckr05_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ckr05_state(state)
      type(ckr05_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%prevs = 0.0_wp
      state%prevn = 0.0_wp
      state%prevnn = 0.0_wp
      state%lhand = 0
      state%lbeg = 0
      state%lend = 0
      state%prevs = -1.0_wp
      state%prevn = -1.0_wp
      state%prevnn = -1.0_wp
      state%lhand = 0
      state%lbeg = -1
      state%lend = -1
   end subroutine init_ckr05_state

end module pepper_state_ckr05
