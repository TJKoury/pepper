!> Compute the points of intersection of a specified nappe of a cone
!> and a line segment.
!>
!> The state of SPICELIB's INCNSG routines (entry points incnsg),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of incnsg.f90.
module pepper_state_incnsg

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_incnsg_state

   !> The saved variables of INCNSG.
   type, public :: incnsg_state
      real(wp) :: origin ( 3 )  !! the zero vector
      real(wp) :: z      ( 3 )  !! the +Z unit vector
   end type incnsg_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_incnsg_state(state)
      type(incnsg_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%origin = 0.0_wp
      state%z = 0.0_wp
      state%origin = 0.0_wp
      state%z = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_incnsg_state

end module pepper_state_incnsg
