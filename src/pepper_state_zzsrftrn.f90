!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSRFTRN routines (entry points zzsrfn2c, zzsrfc2n, zzsrftrk),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsrftrn.f90.
module pepper_state_zzsrftrn

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'srftrn.inc'
   include 'zzctr.inc'
   include 'zzsrftrn.inc'

   public :: init_zzsrftrn_state

   !> The saved variables of ZZSRFTRN.
   type, public :: zzsrftrn_state
      integer(ip) :: kersid ( mxnsrf )  !! input names:                 KERNAM Input surface IDs:           KERSID Input body IDs:              KERBID
      integer(ip) :: kerbid ( mxnsrf )  !! body ID codes from the kernel pool (NAIF_SURFACE_BODY)
      character(sfnmln) :: kernam ( mxnsrf )  !! surface names from the kernel pool (NAIF_SURFACE_NAME)
      character(sfnmln) :: nornam ( mxnsrf )  !! the surface names, normalized (uppercase, left-justified, single blanks)
      integer(ip) :: sidhls ( nroom )  !! surface ID list heads:       SIDHLS Surface ID pool:             SIDPOL Surface ID name pointers:    SIDIDX
      integer(ip) :: sidpol ( lbsngl : nroom )  !! hash table of the surface IDs: collision lists
      integer(ip) :: sididx ( nroom )  !! hash table of the surface IDs: index of each node's entry in kersid
      integer(ip) :: snmhls ( nroom )  !! surface name list heads:     SNMHLS Surface name pool:           SNMPOL Surface name ID pointers:    SNMIDP
      integer(ip) :: snmpol ( lbsngl : nroom )  !! hash table of the surface names: collision lists
      integer(ip) :: snmidx ( nroom )  !! hash table of the surface names: index of each node's entry in nornam
      integer(ip) :: itemat  !! work: hash table node of the matching entry found by a lookup
      integer(ip) :: polctr ( ctrsiz )  !! POLCTR tracks the state of the kernel pool. SRFCTR tracks the state of the surface mapping kernel variables.
      integer(ip) :: srfctr ( ctrsiz )  !! surface mapping state counter (incremented when the tables are rebuilt)
      logical :: extker  !! the kernel pool defines surface name/ID mappings
      logical :: pass1  !! first call: counters and tables not yet initialized
   end type zzsrftrn_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsrftrn_state(state)
      type(zzsrftrn_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%kersid = 0
      state%kerbid = 0
      state%kernam = ' '
      state%nornam = ' '
      state%sidhls = 0
      state%sidpol = 0
      state%sididx = 0
      state%snmhls = 0
      state%snmpol = 0
      state%snmidx = 0
      state%itemat = 0
      state%polctr = 0
      state%srfctr = 0
      state%extker = .false.
      state%pass1 = .false.
      state%polctr = 0
      state%srfctr = 0
      state%extker = .false.
      state%pass1 = .true.
   end subroutine init_zzsrftrn_state

end module pepper_state_zzsrftrn
