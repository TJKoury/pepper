!> Compute, for a given observer and a ray emanating from the
!> observer, the surface intercept of the ray on a target body at
!> a specified epoch, optionally corrected for light time and
!> stellar aberration.
!>
!> The state of SPICELIB's SINCPT routines (entry points sincpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of sincpt.f90.
module pepper_state_sincpt

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsk
      use pepper_inc_frmtyp
      use pepper_inc_gf
      use pepper_inc_zzabcorr
      use pepper_inc_zzctr
      use pepper_inc_zzdsk

   implicit none

   private

   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_sincpt_state

   !> The saved variables of SINCPT.
   type, public :: sincpt_state
      logical :: first  !! first call: pool counters not initialized, correction and method not yet parsed
      integer(ip) :: nsurf  !! number of surface IDs in the surface list parsed from the saved method
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      character(mthlen) :: prvmth  !! method string of the previous call
      integer(ip) :: shape  !! target shape parsed from the saved method (ellipsoid or DSK)
      integer(ip) :: srflst ( maxsrf )  !! surface ID list parsed from the saved method
      logical :: usecn  !! the saved correction uses converged Newtonian light time (CN)
      logical :: uselt  !! the saved correction uses light time (LT or CN)
      logical :: usestl  !! the saved correction includes stellar aberration (+S)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame looked up last (ZZNAMFRM)
      integer(ip) :: svfxfc  !! ID code of the body-fixed frame looked up last
      integer(ip) :: svctr4 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the ray frame dref
      character(frnmln) :: svdref  !! name of the ray frame dref looked up last
      integer(ip) :: svdfrc  !! ID code of the ray frame dref looked up last
      integer(ip) :: svctr5 ( ctrsiz )  !! saved surface name/ID item declarations.
   end type sincpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_sincpt_state(state)
      type(sincpt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%nsurf = 0
      state%prvcor = ' '
      state%prvmth = ' '
      state%shape = 0
      state%srflst = 0
      state%usecn = .false.
      state%uselt = .false.
      state%usestl = .false.
      state%xmit = .false.
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svfref = ' '
      state%svfxfc = 0
      state%svctr4 = 0
      state%svdref = ' '
      state%svdfrc = 0
      state%svctr5 = 0
      state%first = .true.
      state%prvcor = ' '
      state%prvmth = ' '
      state%usecn = .false.
      state%uselt = .false.
      state%usestl = .false.
      state%xmit = .false.
   end subroutine init_sincpt_state

end module pepper_state_sincpt
