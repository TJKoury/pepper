!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZXLATEI routines (entry points zzxlatei),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzxlatei.F90.
module pepper_state_zzxlatei

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzddhman

   implicit none

   private


   public :: init_zzxlatei_state

   !> The saved variables of ZZXLATEI.
   type, public :: zzxlatei_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      integer(ip) :: natbff  !! code of the native binary file format
      character(strsiz) :: strbff ( numbff )  !! names of the binary file formats
      integer(ip) :: smlint  !! smallest integer
      integer(ip) :: bigint  !! largest integer
   end type zzxlatei_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzxlatei_state(state)
      type(zzxlatei_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%natbff = 0
      state%strbff = ' '
      state%smlint = 0
      state%bigint = 0
      state%first = .true.
      state%natbff = 0
   end subroutine init_zzxlatei_state

end module pepper_state_zzxlatei
