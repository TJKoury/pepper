!> Write the file record to a new DAF file.
!>
!> The state of SPICELIB's ZZDAFNFR routines (entry points zzdafnfr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdafnfr.f90.
module pepper_state_zzdafnfr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzftprms.inc'
   integer(ip), parameter :: preftp = 603
   integer(ip), parameter :: pstftp = 297

   public :: init_zzdafnfr_state

   !> The saved variables of ZZDAFNFR.
   type, public :: zzdafnfr_state
      logical :: first  !! saved between calls by ZZDAFNFR
      character(sizftp) :: ftpstr  !! saved between calls by ZZDAFNFR
      character(preftp) :: prenul  !! saved between calls by ZZDAFNFR
      character(pstftp) :: pstnul  !! saved between calls by ZZDAFNFR
   end type zzdafnfr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdafnfr_state(state)
      type(zzdafnfr_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzdafnfr_state

end module pepper_state_zzdafnfr
