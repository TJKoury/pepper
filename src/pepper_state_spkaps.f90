!> Return the state (position and velocity) of a target body
!> relative to an observer specified by its state and
!> acceleration relative to the solar system barycenter. The
!> returned state may be optionally corrected for light time
!> and stellar aberration. All input and output vectors are
!> expressed relative to an inertial reference frame.
!>
!> The state of SPICELIB's SPKAPS routines (entry points spkaps),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkaps.f90.
module pepper_state_spkaps

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_spkaps_state

   !> The saved variables of SPKAPS.
   type, public :: spkaps_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usestl  !! the saved correction includes stellar aberration
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type spkaps_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkaps_state(state)
      type(spkaps_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%prvcor = ' '
      state%usestl = .false.
      state%xmit = .false.
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_spkaps_state

end module pepper_state_spkaps
