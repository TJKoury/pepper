!> Given a the "lines" of a two-line element set, parse the
!> lines and return the elements in units suitable for use
!> in SPICE software.
!>
!> The state of SPICELIB's ZZGETELM routines (entry points zzgetelm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgetelm.f90.
module pepper_state_zzgetelm

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: wdsize = 32
   integer(ip), parameter :: lnsize = 160
   integer(ip), parameter :: maxp = 37
   integer(ip), parameter :: minp = -maxp

   public :: init_zzgetelm_state

   !> The saved variables of ZZGETELM.
   type, public :: zzgetelm_state
      character(lnsize) :: errprs ( 13 )  !! work: parse error messages for each of the 13 TLE terms
      character(lnsize) :: term  ( 13 )  !! descriptions (name and character columns) of the 13 TLE terms, set on the first call
      real(wp) :: d2r  !! radians per degree, set on the first call
      real(wp) :: pi2  !! 2 pi, set on the first call
      real(wp) :: power  ( minp:maxp )  !! powers of ten 10**minp ... 10**maxp, set on the first call
      real(wp) :: tvec   ( 8 )  !! work: epoch time vector (year, day) converted by TTRANS from YD.D to TDB
      logical :: first  !! first call: constants, powers of ten and term descriptions not yet set
   end type zzgetelm_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgetelm_state(state)
      type(zzgetelm_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%errprs = ' '
      state%term = ' '
      state%d2r = 0.0_wp
      state%pi2 = 0.0_wp
      state%power = 0.0_wp
      state%tvec = 0.0_wp
      state%first = .false.
      state%first = .true.
   end subroutine init_zzgetelm_state

end module pepper_state_zzgetelm
