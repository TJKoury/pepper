!> Return the Euler angles needed to compute the transformation from
!> inertial to body-fixed coordinates for any body in the kernel
!> pool.
!>
!> The state of SPICELIB's BODEUL routines (entry points bodeul),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of bodeul.f90.
module pepper_state_bodeul

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: maxang = 200
   integer(ip), parameter :: mxphas = 4
   integer(ip), parameter :: mxpoly = 3
   integer(ip), parameter :: namlen = 32

   public :: init_bodeul_state

   !> The saved variables of BODEUL.
   type, public :: bodeul_state
      real(wp) :: ac     ( maxang )  !! coefficients of the nutation/precession terms of the pole RA (NUT_PREC_RA)
      real(wp) :: costh  ( maxang )  !! work: cosines of the nutation/precession angles at the epoch
      real(wp) :: dc     ( maxang   )  !! coefficients of the nutation/precession terms of the pole Dec (NUT_PREC_DEC)
      real(wp) :: sinth  ( maxang )  !! work: sines of the nutation/precession angles at the epoch
      real(wp) :: tcoef  ( mxphas * maxang )  !! polynomial coefficients of the nutation/precession angles (NUT_PREC_ANGLES)
      real(wp) :: wc     ( maxang )  !! coefficients of the nutation/precession terms of the prime meridian (NUT_PREC_PM)
      integer(ip) :: j2code  !! inertial frame code (IRFNUM) of J2000
      integer(ip) :: nphase  !! number of nutation/precession angles (phase polynomials) last loaded
      integer(ip) :: nphsco  !! number of coefficients per nutation/precession angle (max phase degree + 1)
      logical :: first  !! first call: J2000 frame code not yet looked up
   end type bodeul_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_bodeul_state(state)
      type(bodeul_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ac = 0.0_wp
      state%costh = 0.0_wp
      state%dc = 0.0_wp
      state%sinth = 0.0_wp
      state%tcoef = 0.0_wp
      state%wc = 0.0_wp
      state%j2code = 0
      state%nphase = 0
      state%nphsco = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_bodeul_state

end module pepper_state_bodeul
