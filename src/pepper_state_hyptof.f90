!> Solve the time of flight equation MA = e sinh(F) - F for the
!> hyperbolic eccentric anomaly F, given the mean anomaly, MA,
!> and the eccentricity, e.
!>
!> The state of SPICELIB's HYPTOF routines (entry points hyptof),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of hyptof.f90.
module pepper_state_hyptof

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_hyptof_state

   !> The saved variables of HYPTOF.
   type, public :: hyptof_state
      logical :: first  !! first call: maxlog not yet computed
      real(wp) :: maxlog  !! log(dpmax), the natural log of the largest double precision number
   end type hyptof_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_hyptof_state(state)
      type(hyptof_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%maxlog = 0.0_wp
      state%first = .true.
   end subroutine init_hyptof_state

end module pepper_state_hyptof
