!> Return (depending upon the user's request) the ID code of either
!> the spacecraft or spacecraft clock associated with a C-Kernel ID
!> code.
!>
!> The state of SPICELIB's CKMETA routines (entry points ckmeta),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ckmeta.f90.
module pepper_state_ckmeta

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: wdsize = 32
   integer(ip), parameter :: nck = 30

   public :: init_ckmeta_state

   !> The saved variables of CKMETA.
   type, public :: ckmeta_state
      character(wdsize) :: lookup ( 2, nck )  !! names of the kernel variables CK_<id>_SCLK and CK_<id>_SPK of each buffered CK ID
      character(wdsize) :: agent  (    nck )  !! kernel pool watcher (agent) name of each buffered CK ID
      integer(ip) :: cks    (    nck )  !! buffered CK IDs
      integer(ip) :: cksord (    nck )  !! order vector of cks (for the binary search)
      integer(ip) :: currnt  !! number of buffered CK IDs
      integer(ip) :: last  !! buffer slot filled last (slots are reused round-robin when the buffer is full)
      integer(ip) :: sclks  (    nck )  !! SCLK ID of each buffered CK ID
      integer(ip) :: spks   (    nck )  !! SPK ID of each buffered CK ID
      integer(ip) :: usrctr ( ctrsiz, nck )  !! kernel pool state counter of each buffered CK ID
      logical :: first  !! this is the first call (the counters and agents are not initialized yet)
      logical :: found  (    2   )  !! SCLK and SPK kernel variables were found (a work variable; not used between calls)
      logical :: nodata  !! the last kernel pool lookup failed (the buffered IDs must be fetched again)
   end type ckmeta_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ckmeta_state(state)
      type(ckmeta_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%lookup = ' '
      state%agent = ' '
      state%cks = 0
      state%cksord = 0
      state%currnt = 0
      state%last = 0
      state%sclks = 0
      state%spks = 0
      state%usrctr = 0
      state%first = .false.
      state%found = .false.
      state%nodata = .false.
      state%currnt = 0
      state%last = 0
      state%first = .true.
      state%nodata = .true.
   end subroutine init_ckmeta_state

end module pepper_state_ckmeta
