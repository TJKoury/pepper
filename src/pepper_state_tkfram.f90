!> Find the position rotation matrix from a Text Kernel (TK) frame
!> with the specified frame class ID to its base frame.
!>
!> The state of SPICELIB's TKFRAM routines (entry points tkfram),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of tkfram.f90.
module pepper_state_tkfram

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: bufsiz = 200
   integer(ip), parameter :: lbpool = -5
   integer(ip), parameter :: wdsize = 32
   integer(ip), parameter :: nitems = 14
   integer(ip), parameter :: nvars = 14
   integer(ip), parameter :: ndps = 9
   integer(ip), parameter :: nints = 1

   public :: init_tkfram_state

   !> The saved variables of TKFRAM.
   type, public :: tkfram_state
      character(wdsize) :: alt    ( nitems )  !! work: alternate (frame name based) kernel variable names for the frame
      character(wdsize) :: item   ( nvars  )  !! work: kernel variable names for the frame (ID based, or the alternates if found)
      character(wdsize) :: oldagt  !! work: watcher agent name of the frame dropped from the full buffer
      real(wp) :: buffd  ( ndps, bufsiz )  !! buffered rotation matrix (column order) of each frame
      integer(ip) :: at  !! buffer index of the frame looked up last
      integer(ip) :: buffi  ( nints,     bufsiz )  !! buffered ID of the frame each buffered rotation is relative to
      integer(ip) :: idents ( 1,         bufsiz )  !! frame ID codes of the buffered frames
      integer(ip) :: idnt   ( 1 )  !! work: frame ID to look up in the buffer
      integer(ip) :: pool   ( 2, lbpool: bufsiz )  !! linked list pool of the buffer (in order of use)
      logical :: first  !! true until the buffer pool is initialized
   end type tkfram_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_tkfram_state(state)
      type(tkfram_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%alt = ' '
      state%item = ' '
      state%oldagt = ' '
      state%buffd = 0.0_wp
      state%at = 0
      state%buffi = 0
      state%idents = 0
      state%idnt = 0
      state%pool = 0
      state%first = .false.
      state%buffd = 0.0_wp
      state%at = 0
      state%buffi = 0
      state%idents = 0
      state%first = .true.
   end subroutine init_tkfram_state

end module pepper_state_tkfram
