!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFCOU routines (entry points zzgfcoin, zzgfcog, zzgfcodc, zzgfcoex, zzgfcocg, zzgfcosg, zzgfcocd, zzgfcosd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfcou.f90.
module pepper_state_zzgfcou

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'gf.inc'
   include               'zzgf.inc'
   include               'zzabcorr.inc'
   integer(ip), parameter :: abclen = 20
   integer(ip), parameter :: frnmln = 32
   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: syslen = 32
   integer(ip), parameter :: vdflen = 32
   integer(ip), parameter :: nsys = 7
   integer(ip), parameter :: crdlen = 32
   integer(ip), parameter :: metlen = 200

   public :: init_zzgfcou_state

   !> The saved variables of ZZGFCOU.
   type, public :: zzgfcou_state
      integer(ip) :: svcidx  !! index of the coordinate within its coordinate system
      character(abclen) :: svcorr  !! aberration correction saved by ZZGFCOIN
      character(crdlen) :: svcrd  !! coordinate name saved by ZZGFCOIN
      character(syslen) :: svcsys  !! coordinate system name saved by ZZGFCOIN
      integer(ip) :: svdctr  !! ID code of the center of the ray frame svdref (intercept searches)
      character(frnmln) :: svdref  !! ray direction frame name (intercept searches; blank otherwise)
      real(wp) :: svdvec ( 3 )  !! ray direction vector (intercept searches; zero otherwise)
      real(wp) :: svf  !! flattening coefficient of the frame center body (geodetic/planetographic)
      character(metlen) :: svmeth  !! subpoint/intercept computation method saved by ZZGFCOIN
      integer(ip) :: svobs  !! observer ID code saved by ZZGFCOIN
      real(wp) :: svradi ( 3 )  !! radii of the frame center body (sub-observer, intercept, geodetic, planetographic)
      character(bdnmln) :: svrcnm  !! name of the frame center body (planetographic only)
      integer(ip) :: svrctr  !! ID code of the center of the coordinate frame svref
      real(wp) :: svre  !! equatorial radius of the frame center body (geodetic/planetographic)
      character(frnmln) :: svref  !! coordinate reference frame name saved by ZZGFCOIN
      integer(ip) :: svsens  !! planetographic longitude sense: 1 east, -1 west, 0 not planetographic
      integer(ip) :: svtarg  !! target ID code saved by ZZGFCOIN
      character(vdflen) :: svvdef  !! vector definition (position, sub-observer point, surface intercept)
      character(syslen) :: sysnms ( nsys )  !! recognized coordinate system names (constant)
      real(wp) :: y      ( 3 )  !! +Y unit vector used to find the planetographic longitude sense (constant)
   end type zzgfcou_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfcou_state(state)
      type(zzgfcou_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svcidx = 0
      state%svcorr = ' '
      state%svcrd = ' '
      state%svcsys = ' '
      state%svdctr = 0
      state%svdref = ' '
      state%svdvec = 0.0_wp
      state%svf = 0.0_wp
      state%svmeth = ' '
      state%svobs = 0
      state%svradi = 0.0_wp
      state%svrcnm = ' '
      state%svrctr = 0
      state%svre = 0.0_wp
      state%svref = ' '
      state%svsens = 0
      state%svtarg = 0
      state%svvdef = ' '
      state%sysnms = ' '
      state%y = 0.0_wp
      state%sysnms = [ character(len(state%sysnms)) :: recsys, latsys, radsys, sphsys, cylsys, geosys, pgrsys ]
      state%y = [ 0.0_wp, 1.0_wp, 0.0_wp ]
   end subroutine init_zzgfcou_state

end module pepper_state_zzgfcou
