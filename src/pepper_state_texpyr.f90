!> Expand an abbreviated year to a full year specification.
!>
!> The state of SPICELIB's TEXPYR routines (entry points texpyr, tsetyr),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of texpyr.f90.
module pepper_state_texpyr

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_texpyr_state

   !> The saved variables of TEXPYR.
   type, public :: texpyr_state
      integer(ip) :: centry  !! the century assumed for two-digit years
      integer(ip) :: lbound  !! the lower bound of the 100-year window for two-digit years
   end type texpyr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_texpyr_state(state)
      type(texpyr_state), intent(inout) :: state  !! the state
      state%centry = 1900
      state%lbound = 1969
   end subroutine init_texpyr_state

end module pepper_state_texpyr
