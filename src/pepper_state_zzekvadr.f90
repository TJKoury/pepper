!> Compute the EK scratch area base address of the row vector having
!> a specified index, given a union of EK join row sets and a row
!> vector index. Also return the base address of the row
!> vector's parent segment vector.
!>
!> The state of SPICELIB's ZZEKVADR routines (entry points zzekvset, zzekvcal),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzekvadr.f90.
module pepper_state_zzekvadr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: mxjrs = 200

   public :: init_zzekvadr_state

   !> The saved variables of ZZEKVADR.
   type, public :: zzekvadr_state
      integer(ip) :: begidx ( mxjrs )  !! index of the first row vector of each join row set in the union
      integer(ip) :: j  !! work: table or row count read from a join row set
      integer(ip) :: maxrwv  !! largest valid row vector index of the union (computed one too large by zzekvset)
      integer(ip) :: ntabs  !! number of tables in each join row set of the union
      integer(ip) :: rbas   ( mxjrs )  !! scratch-area base address of the row vectors of each join row set
      integer(ip) :: svbas  ( mxjrs )  !! scratch-area base address of each join row set
      integer(ip) :: svnjrs  !! number of join row sets in the union
   end type zzekvadr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzekvadr_state(state)
      type(zzekvadr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%begidx = 0
      state%j = 0
      state%maxrwv = 0
      state%ntabs = 0
      state%rbas = 0
      state%svbas = 0
      state%svnjrs = 0
   end subroutine init_zzekvadr_state

end module pepper_state_zzekvadr
