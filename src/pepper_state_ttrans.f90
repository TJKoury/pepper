!> Transform a time vector from one representation and system
!> to another.
!>
!> The state of SPICELIB's TTRANS routines (entry points ttrans),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ttrans.f90.
module pepper_state_ttrans

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: maxlp = 140
   integer(ip), parameter :: maxvar = 1
   integer(ip), parameter :: daysec = 1
   integer(ip), parameter :: dayp2 = daysec + 1
   integer(ip), parameter :: et = dayp2 + 1
   integer(ip), parameter :: frml = et     + 1
   integer(ip), parameter :: jdtdb = frml + 1
   integer(ip), parameter :: jdtdt = jdtdb  + 1
   integer(ip), parameter :: jdutc = jdtdt  + 1
   integer(ip), parameter :: jed = jdutc  + 1
   integer(ip), parameter :: ttai = jed    + 1
   integer(ip), parameter :: tdb = ttai   + 1
   integer(ip), parameter :: tdt = tdb    + 1
   integer(ip), parameter :: yd = tdt    + 1
   integer(ip), parameter :: ydd = yd     + 1
   integer(ip), parameter :: yddf = ydd    + 1
   integer(ip), parameter :: ydf = yddf   + 1
   integer(ip), parameter :: ymd = ydf    + 1
   integer(ip), parameter :: ymdf = ymd    + 1
   integer(ip), parameter :: ymwd = ymdf   + 1
   integer(ip), parameter :: ymwdf = ymwd   + 1
   integer(ip), parameter :: ywd = ymwdf  + 1
   integer(ip), parameter :: ywdf = ywd    + 1
   integer(ip), parameter :: nrec = ywdf
   integer(ip), parameter :: lbcell = -5
   integer(ip), parameter :: typlen = 8

   public :: init_ttrans_state

   !> The saved variables of TTRANS.
   type, public :: ttrans_state
      character(typlen) :: unifrm (lbcell : nrec )  !! set of the uniform time systems, which UNITIM converts
      character(typlen) :: recog   ( nrec )  !! sorted names of the recognized time vector representations
      integer(ip) :: parsed  ( nrec )  !! integer code of each recognized representation (parallel to RECOG)
      logical :: needy   ( nrec )  !! the representation has a year (parallel to RECOG)
      logical :: forml   ( nrec )  !! the representation is a formal (not UTC-based) time system (parallel to RECOG)
      character(32) :: vars   ( maxvar )  !! name of the watched kernel pool variable (DELTET/DELTA_AT)
      real(wp) :: halfd  !! number of seconds in half a day
      real(wp) :: jd1101  !! Julian date UTC of Jan 1, 1 AD (computed on the first call)
      real(wp) :: secspd  !! number of seconds in a day
      real(wp) :: taitab ( 2*maxlp )  !! TAI at the starts of the UTC days around each leapsecond (from DELTET/DELTA_AT)
      real(wp) :: tsecs  !! scratch: seconds into the day, then into the minute, of the time being converted
      integer(ip) :: daytab ( 2*maxlp )  !! day numbers past 1 Jan 1 AD of the days in TAITAB
      integer(ip) :: dn2000  !! day number past 1 Jan 1 AD of Jan 1, 2000 (computed on the first call)
      integer(ip) :: dofyr  !! scratch: day of year of the time being converted
      integer(ip) :: nref  !! number of entries in TAITAB and DAYTAB
      integer(ip) :: sunday  !! day number past 1 Jan 1 AD of Sunday, Jan 6, 1991 (computed on the first call)
      integer(ip) :: usrctr ( ctrsiz )  !! counter of the kernel pool's state when the leapseconds were read
      logical :: first  !! the first call has not set up the tables yet
      logical :: nodata  !! the leapseconds have not been read (successfully) from the kernel pool
   end type ttrans_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ttrans_state(state)
      type(ttrans_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%unifrm = ' '
      state%recog = ' '
      state%parsed = 0
      state%needy = .false.
      state%forml = .false.
      state%vars = ' '
      state%halfd = 0.0_wp
      state%jd1101 = 0.0_wp
      state%secspd = 0.0_wp
      state%taitab = 0.0_wp
      state%tsecs = 0.0_wp
      state%daytab = 0
      state%dn2000 = 0
      state%dofyr = 0
      state%nref = 0
      state%sunday = 0
      state%usrctr = 0
      state%first = .false.
      state%nodata = .false.
      state%first = .true.
      state%nodata = .true.
   end subroutine init_ttrans_state

end module pepper_state_ttrans
