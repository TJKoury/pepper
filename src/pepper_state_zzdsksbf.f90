!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDSKSBF routines (entry points zzsbfxr, zzsbfxri, zzsbfnrm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdsksbf.f90.
module pepper_state_zzdsksbf

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dla.inc'
   include 'dskdsc.inc'
   include 'zzctr.inc'
   integer(ip), parameter :: stsize = 10000
   integer(ip), parameter :: btsize = 10

   public :: init_zzdsksbf_state

   !> The saved variables of ZZDSKSBF.
   type, public :: zzdsksbf_state
      integer(ip) :: bsrctr ( ctrsiz )  !! DSK BSR loaded kernel state counter when the tables were last validated
      integer(ip) :: btbody ( btsize )  !! body table: body ID codes
      integer(ip) :: btnbod  !! BTSTSZ  is an array of segment table entry counts. The Ith element of BTSTSZ is the number of entries in the segment table for the Ith body.
      integer(ip) :: btsegp ( btsize )  !! body table: start index of each body's segment list in the segment table
      integer(ip) :: btstsz ( btsize )  !! body table: number of segment table entries of each body
      logical :: first  !! first call: BSRCTR not yet initialized
      real(wp) :: stctr  ( 3,      stsize )  !! segment table: outer bounding sphere centers (km, segment frame)
      integer(ip) :: stdlad ( dladsz, stsize )  !! segment table: DLA descriptors
      real(wp) :: stdscr ( dskdsz, stsize )  !! segment table: DSK descriptors
      integer(ip) :: stfree  !! segment table: index of the first free entry
      integer(ip) :: sthan  ( stsize )  !! segment table variables
      real(wp) :: stoff  ( 3,      stsize )  !! segment table: offsets of segment frame centers from the central body (km)
      real(wp) :: strad  ( stsize )  !! segment table: outer bounding sphere radii (km)
   end type zzdsksbf_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdsksbf_state(state)
      type(zzdsksbf_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%bsrctr = 0
      state%btbody = 0
      state%btnbod = 0
      state%btsegp = 0
      state%btstsz = 0
      state%first = .false.
      state%stctr = 0.0_wp
      state%stdlad = 0
      state%stdscr = 0.0_wp
      state%stfree = 0
      state%sthan = 0
      state%stoff = 0.0_wp
      state%strad = 0.0_wp
      state%bsrctr = 0
      state%btbody = 0
      state%btnbod = 0
      state%first = .true.
      state%stfree = 1
   end subroutine init_zzdsksbf_state

end module pepper_state_zzdsksbf
