!> Read a single SPK data record from a segment of type 19
!> (ESOC/DDID Piecewise Interpolation).
!>
!> The state of SPICELIB's SPKR19 routines (entry points spkr19),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkr19.f90.
module pepper_state_spkr19

   use pepper_kinds, only: ip, wp
      use pepper_inc_spk19
      use pepper_inc_spkrec

   implicit none

   private


   public :: init_spkr19_state

   !> The saved variables of SPKR19.
   type, public :: spkr19_state
      logical :: pass1  !! this is the first call (the record size check has not been done yet)
      integer(ip) :: svbeg  !! begin address of the segment used last
      real(wp) :: svbtim  !! start time of the mini-segment interval used last
      real(wp) :: svetim  !! end time of the mini-segment interval used last
      integer(ip) :: svhan  !! handle of the file of the segment used last
      logical :: svlast  !! interval selection flag of the segment used last (select the last applicable interval)
      integer(ip) :: svmiix  !! index of the mini-segment (interval) used last
      integer(ip) :: svminb  !! begin address of the mini-segment used last
      integer(ip) :: svn  !! number of mini-segments in the segment used last
      integer(ip) :: svnpkt  !! number of packets in the mini-segment used last
      logical :: svok  !! the last call succeeded (the saved values are valid only if true)
      integer(ip) :: svpkdb  !! base address of the packet directory of the mini-segment used last
      integer(ip) :: svpknd  !! number of packet directory entries of the mini-segment used last
      integer(ip) :: svpksz  !! packet size of the mini-segment used last
      integer(ip) :: svstyp  !! subtype of the mini-segment used last
      integer(ip) :: svwnsz  !! interpolation window size of the mini-segment used last
   end type spkr19_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkr19_state(state)
      type(spkr19_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%pass1 = .false.
      state%svbeg = 0
      state%svbtim = 0.0_wp
      state%svetim = 0.0_wp
      state%svhan = 0
      state%svlast = .false.
      state%svmiix = 0
      state%svminb = 0
      state%svn = 0
      state%svnpkt = 0
      state%svok = .false.
      state%svpkdb = 0
      state%svpknd = 0
      state%svpksz = 0
      state%svstyp = 0
      state%svwnsz = 0
      state%pass1 = .true.
      state%svbeg = -1
      state%svbtim = 0.0_wp
      state%svetim = -1.0_wp
      state%svhan = 0
      state%svlast = .false.
      state%svmiix = -1
      state%svminb = -1
      state%svn = -1
      state%svnpkt = -1
      state%svok = .false.
      state%svpkdb = -1
      state%svpknd = -1
      state%svpksz = -1
      state%svstyp = -1
      state%svwnsz = -1
   end subroutine init_spkr19_state

end module pepper_state_spkr19
