!> SPICE private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFSSIN routines (entry points zzgfssin),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfssin.f90.
module pepper_state_zzgfssin

   use pepper_kinds, only: ip, wp
      use pepper_inc_gf
      use pepper_inc_zzgf
      use pepper_inc_zzabcorr

   implicit none

   private

   integer(ip), parameter :: bdnmln = 36

   public :: init_zzgfssin_state

   !> The saved variables of ZZGFSSIN.
   type, public :: zzgfssin_state
      logical :: first  !! first call: target and observer names not yet looked up
      character(bdnmln) :: svobs  !! name of the observer with ID prvobs
      integer(ip) :: prvobs  !! observer ID code of the previous call
      integer(ip) :: prvtrg  !! target ID code of the previous call
      character(bdnmln) :: svtarg  !! name of the target with ID prvtrg
   end type zzgfssin_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfssin_state(state)
      type(zzgfssin_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%svobs = ' '
      state%prvobs = 0
      state%prvtrg = 0
      state%svtarg = ' '
      state%first = .true.
      state%svobs = ' '
      state%prvobs = 0
      state%prvtrg = 0
      state%svtarg = ' '
   end subroutine init_zzgfssin_state

end module pepper_state_zzgfssin
