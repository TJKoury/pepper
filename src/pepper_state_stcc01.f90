!> Check whether a file is a type 1 star catalog and return the
!> catalog's table name if it is.
!>
!> The state of SPICELIB's STCC01 routines (entry points stcc01),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of stcc01.f90.
module pepper_state_stcc01

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekcnamsz.inc'
   include 'ektnamsz.inc'
   include 'ekglimit.inc'

   public :: init_stcc01_state

   !> The saved variables of STCC01.
   type, public :: stcc01_state
      character(4) :: dtypes ( mxclsg )  !! work: data type of each column of the current segment (from EKSSUM)
      character(cnamsz) :: cnames ( mxclsg )  !! work: names of the columns of the current segment
      character(tnamsz) :: tmptnm  !! work: table name of the current segment
      character(tnamsz) :: tnmprv  !! work: table name of the previous segment
      integer(ip) :: ncols  !! work: number of columns in the current segment
      logical :: nullok ( mxclsg )  !! work: whether each column of the current segment allows null values
   end type stcc01_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_stcc01_state(state)
      type(stcc01_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%dtypes = ' '
      state%cnames = ' '
      state%tmptnm = ' '
      state%tnmprv = ' '
      state%ncols = 0
      state%nullok = .false.
   end subroutine init_stcc01_state

end module pepper_state_stcc01
