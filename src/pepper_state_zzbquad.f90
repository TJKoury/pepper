!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZBQUAD routines (entry points zzbquad),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzbquad.f90.
module pepper_state_zzbquad

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzbquad_state

   !> The saved variables of ZZBQUAD.
   type, public :: zzbquad_state
      real(wp) :: big  !! bound on the magnitude of the coefficients: sqrt(dpmax)/100, set on the first call
      logical :: first  !! first call: big not yet computed
   end type zzbquad_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzbquad_state(state)
      type(zzbquad_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%big = 0.0_wp
      state%first = .false.
      state%big = 0.0_wp
      state%first = .true.
   end subroutine init_zzbquad_state

end module pepper_state_zzbquad
