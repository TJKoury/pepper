!> Return the state (position and velocity) of a target body
!> relative to an observing body, optionally corrected for light
!> time (planetary aberration) and stellar aberration.
!>
!> The state of SPICELIB's SPKEZR routines (entry points spkezr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkezr.f90.
module pepper_state_spkezr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_spkezr_state

   !> The saved variables of SPKEZR.
   type, public :: spkezr_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtgid  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsn  !! name of the observer looked up last
      integer(ip) :: svobsi  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      logical :: first  !! first call: the pool counters are not yet initialized
   end type spkezr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkezr_state(state)
      type(spkezr_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_spkezr_state

end module pepper_state_spkezr
