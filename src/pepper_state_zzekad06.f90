!> Add a column entry to a specified record in a class 6 column.
!> The entries of class 6 columns are arrays of character string
!> values.
!>
!> The state of SPICELIB's ZZEKAD06 routines (entry points zzekad06),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzekad06.f90.
module pepper_state_zzekad06

   use pepper_kinds, only: ip, wp
      use pepper_inc_ekbool
      use pepper_inc_ekcoldsc
      use pepper_inc_ekdatpag
      use pepper_inc_ekrecptr
      use pepper_inc_eksegdsc
      use pepper_inc_ektype

   implicit none

   private

   integer(ip), parameter :: maxpad = 100

   public :: init_zzekad06_state

   !> The saved variables of ZZEKAD06.
   type, public :: zzekad06_state
      character(maxpad) :: padbuf  !! blanks used to pad entry elements shorter than the column string length
      integer(ip) :: datptr  !! work: DAS character address where the next character of the entry goes
      integer(ip) :: p  !! work: number of the character data page being written
      integer(ip) :: padlen  !! work: number of trailing blanks that pad each element to the column string length
      logical :: first  !! padbuf has not been blanked yet
   end type zzekad06_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzekad06_state(state)
      type(zzekad06_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%padbuf = ' '
      state%datptr = 0
      state%p = 0
      state%padlen = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_zzekad06_state

end module pepper_state_zzekad06
