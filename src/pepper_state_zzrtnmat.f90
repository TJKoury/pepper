!> Given a vector, return a transformation matrix that maps from the
!> vector's base reference frame to the RTN
!> (radial-tangential-normal) frame associated with the vector.
!>
!> The state of SPICELIB's ZZRTNMAT routines (entry points zzrtnmat),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzrtnmat.f90.
module pepper_state_zzrtnmat

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzrtnmat_state

   !> The saved variables of ZZRTNMAT.
   type, public :: zzrtnmat_state
      real(wp) :: z ( 3 )  !! constant +Z unit vector (0,0,1)
   end type zzrtnmat_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzrtnmat_state(state)
      type(zzrtnmat_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%z = 0.0_wp
      state%z = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_zzrtnmat_state

end module pepper_state_zzrtnmat
