!> Read the next line of text from a text file.
!>
!> The state of SPICELIB's RDTEXT routines (entry points rdtext, cltext),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of rdtext.f90.
module pepper_state_rdtext

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip) :: maxlen
   parameter ( maxlen = 255 )
   integer(ip) :: maxopn
   parameter ( maxopn =  96 )

   public :: init_rdtext_state

   !> The saved variables of RDTEXT.
   type, public :: rdtext_state
      integer(ip) :: units   ( maxopn )  !! units of the files open for reading
      integer(ip) :: n  !! number of files open
      character(maxlen) :: lstfil  !! the file read last
      integer(ip) :: lstunt  !! the unit of the file read last
      integer(ip) :: index  !! index in units of the file read last
   end type rdtext_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_rdtext_state(state)
      type(rdtext_state), intent(inout) :: state  !! the state
      state%n = 0
      state%lstfil = ' '
   end subroutine init_rdtext_state

end module pepper_state_rdtext
