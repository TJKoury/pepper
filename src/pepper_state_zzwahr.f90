!> Calculates nutation angles delta psi and delta epsilon,  and
!> their rates of change, referred to the ecliptic of date, from
!> the Wahr series (Table 1,'Proposal to the IAU Working Group
!> on Nutation', John M. Wahr and Martin L. Smith 1979)
!>
!> The state of SPICELIB's ZZWAHR routines (entry points zzwahr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzwahr.f90.
module pepper_state_zzwahr

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzwahr_state

   !> The saved variables of ZZWAHR.
   type, public :: zzwahr_state
      real(wp) :: angle(5)  !! fundamental arguments l, l', F, D, Omega at the epoch of the last call (radians)
      real(wp) :: angrt(5)  !! rates of the fundamental arguments at the epoch of the last call (radians/day)
      real(wp) :: dtwopi  !! two pi
      real(wp) :: factr  !! conversion from units of 0.0001 arcseconds to radians (divisor)
      real(wp) :: oneday  !! number of seconds in a day
      real(wp) :: radian  !! degrees per radian
      real(wp) :: d0  !! D (Moon minus Sun mean longitude): constant term (degrees)
      real(wp) :: d1  !! D: linear coefficient (degrees/day)
      real(wp) :: d2  !! D: quadratic coefficient (degrees/(0.0001 days)**2)
      real(wp) :: d3  !! D: cubic coefficient (degrees/(0.0001 days)**3)
      real(wp) :: f0  !! F (Moon minus Moon node mean longitude): constant term (degrees)
      real(wp) :: f1  !! F: linear coefficient (degrees/day)
      real(wp) :: f2  !! F: quadratic coefficient (degrees/(0.0001 days)**2)
      real(wp) :: f3  !! F: cubic coefficient (degrees/(0.0001 days)**3)
      real(wp) :: l0  !! l (Moon mean anomaly): constant term (degrees)
      real(wp) :: l1  !! l: linear coefficient (degrees/day)
      real(wp) :: l2  !! l: quadratic coefficient (degrees/(0.0001 days)**2)
      real(wp) :: l3  !! l: cubic coefficient (degrees/(0.0001 days)**3)
      real(wp) :: lp0  !! l' (Sun mean anomaly): constant term (degrees)
      real(wp) :: lp1  !! l': linear coefficient (degrees/day)
      real(wp) :: lp2  !! l': quadratic coefficient (degrees/(0.0001 days)**2)
      real(wp) :: lp3  !! l': cubic coefficient (degrees/(0.0001 days)**3)
      real(wp) :: mg0  !! Omega (lunar mean ascending node longitude): constant term (degrees)
      real(wp) :: mg1  !! Omega: linear coefficient (degrees/day)
      real(wp) :: mg2  !! Omega: quadratic coefficient (degrees/(0.0001 days)**2)
      real(wp) :: mg3  !! Omega: cubic coefficient (degrees/(0.0001 days)**3)
      logical :: first  !! true until the constants above have been computed
   end type zzwahr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzwahr_state(state)
      type(zzwahr_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzwahr_state

end module pepper_state_zzwahr
