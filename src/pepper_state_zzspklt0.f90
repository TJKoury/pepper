!> Return the state (position and velocity) of a target body
!> relative to an observer, optionally corrected for light time,
!> expressed relative to an inertial reference frame.
!>
!> The state of SPICELIB's ZZSPKLT0 routines (entry points zzspklt0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspklt0.f90.
module pepper_state_zzspklt0

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzspklt0_state

   !> The saved variables of ZZSPKLT0.
   type, public :: zzspklt0_state
      logical :: pass1  !! first call: no aberration correction has been parsed yet
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: uselt  !! the saved correction includes light time (normal or converged Newtonian)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspklt0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspklt0_state(state)
      type(zzspklt0_state), intent(inout) :: state  !! the state
      state%pass1 = .true.
      state%prvcor = ' '
   end subroutine init_zzspklt0_state

end module pepper_state_zzspklt0
