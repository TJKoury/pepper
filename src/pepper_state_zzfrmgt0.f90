!> Find the transformation from a user specified frame to
!> another frame at a user specified epoch.
!>
!> The state of SPICELIB's ZZFRMGT0 routines (entry points zzfrmgt0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzfrmgt0.f90.
module pepper_state_zzfrmgt0

   use pepper_kinds, only: ip, wp
      use pepper_inc_frmtyp

   implicit none

   private


   public :: init_zzfrmgt0_state

   !> The saved variables of ZZFRMGT0.
   type, public :: zzfrmgt0_state
      real(wp) :: idnt66 ( 6, 6 )  !! 6x6 identity matrix, built on the first call
      logical :: pass1  !! first call: the identity matrix has not been built yet
      character(6) :: versn  !! version string quoted in the unsupported-frame-class error message
   end type zzfrmgt0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzfrmgt0_state(state)
      type(zzfrmgt0_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%idnt66 = 0.0_wp
      state%pass1 = .false.
      state%versn = ' '
      state%pass1 = .true.
      state%versn = '4.0.0'
   end subroutine init_zzfrmgt0_state

end module pepper_state_zzfrmgt0
