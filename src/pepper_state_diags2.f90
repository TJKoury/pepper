!> Diagonalize a symmetric 2x2 matrix.
!>
!> The state of SPICELIB's DIAGS2 routines (entry points diags2),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of diags2.f90.
module pepper_state_diags2

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_diags2_state

   !> The saved variables of DIAGS2.
   type, public :: diags2_state
      real(wp) :: ident  ( 2, 2 )  !! the 2x2 identity matrix, constant
   end type diags2_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_diags2_state(state)
      type(diags2_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ident = 0.0_wp
      state%ident = reshape ( [ 1.0_wp, 0.0_wp, 0.0_wp, 1.0_wp ], shape ( state%ident ) )
   end subroutine init_diags2_state

end module pepper_state_diags2
