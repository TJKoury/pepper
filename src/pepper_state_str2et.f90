!> Convert a string representing an epoch to a double precision
!> value representing the number of TDB seconds past the J2000
!> epoch corresponding to the input epoch.
!>
!> The state of SPICELIB's STR2ET routines (entry points str2et),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of str2et.f90.
module pepper_state_str2et

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: smwdsz = 16
   integer(ip), parameter :: lnsize = 80
   integer(ip), parameter :: msgsiz = 400
   integer(ip), parameter :: era = 1
   integer(ip), parameter :: wkday = era    + 1
   integer(ip), parameter :: zone = wkday  + 1
   integer(ip), parameter :: ampm = zone   + 1
   integer(ip), parameter :: system = ampm   + 1

   public :: init_str2et_state

   !> The saved variables of STR2ET.
   type, public :: str2et_state
      character(smwdsz) :: calndr  !! scratch: the default calendar, from TIMDEF
      character(smwdsz) :: defsys  !! scratch: the default time system, from TIMDEF
      character(smwdsz) :: defzon  !! scratch: the default time zone, from TIMDEF
      character(smwdsz) :: mname  ( 12 )  !! names of the months, for error messages
      real(wp) :: hoff  !! scratch: hour offset of the time zone of the string
      real(wp) :: mdy    ( 2 )  !! scratch: last days of June and December (months that can have leapseconds)
      real(wp) :: moff  !! scratch: minute offset of the time zone of the string
      real(wp) :: mon    ( 2 )  !! scratch: the months (June, December) that can have leapseconds
      integer(ip) :: mm  !! scratch: index of the month in the time vector
   end type str2et_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_str2et_state(state)
      type(str2et_state), intent(inout) :: state  !! the state
      state%defsys = 'UTC'
      state%defzon = ' '
      state%mname = [ character(len(state%mname)) :: 'January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December' ]
   end subroutine init_str2et_state

end module pepper_state_str2et
