!> Write a line of text to standard output.
!>
!> The state of SPICELIB's TOSTDO routines (entry points tostdo),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of tostdo.f90.
module pepper_state_tostdo

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_tostdo_state

   !> The saved variables of TOSTDO.
   type, public :: tostdo_state
      integer(ip) :: stdout  !! logical unit of standard output (from STDIO)
      logical :: first  !! first call: the standard output unit not yet obtained
   end type tostdo_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_tostdo_state(state)
      type(tostdo_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%stdout = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_tostdo_state

end module pepper_state_tostdo
