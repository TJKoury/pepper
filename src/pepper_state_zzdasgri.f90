!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDASGRI routines (entry points zzdasgri),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdasgri.f90.
module pepper_state_zzdasgri

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'das.inc'

   public :: init_zzdasgri_state

   !> The saved variables of ZZDASGRI.
   type, public :: zzdasgri_state
      logical :: first  !! saved between calls by ZZDASGRI
      integer(ip) :: intbff  !! saved between calls by ZZDASGRI
      integer(ip) :: natbff  !! saved between calls by ZZDASGRI
   end type zzdasgri_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdasgri_state(state)
      type(zzdasgri_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzdasgri_state

end module pepper_state_zzdasgri
