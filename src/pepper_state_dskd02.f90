!> Fetch double precision data from a type 2 DSK segment.
!>
!> The state of SPICELIB's DSKD02 routines (entry points dskd02),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dskd02.f90.
module pepper_state_dskd02

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dla.inc'
   include 'dskdsc.inc'
   include 'dsk02.inc'

   public :: init_dskd02_state

   !> The saved variables of DSKD02.
   type, public :: dskd02_state
      logical :: first  !! no segment has been read yet
      integer(ip) :: prvbas  !! DLA base address of the segment read last
      integer(ip) :: prvhan  !! handle of the DSK file of the segment read last
      integer(ip) :: nv  !! number of vertices of the segment read last
   end type dskd02_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dskd02_state(state)
      type(dskd02_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_dskd02_state

end module pepper_state_dskd02
