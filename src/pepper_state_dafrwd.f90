!> Read, write, and rewrite double precision records to and
!> from DAFs.
!>
!> The state of SPICELIB's DAFRWD routines (entry points dafgdr, dafgsr, dafrdr, dafwdr, dafnrr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dafrwd.f90.
module pepper_state_dafrwd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: rbsize = 100

   public :: init_dafrwd_state

   !> The saved variables of DAFRWD.
   type, public :: dafrwd_state
      integer(ip) :: rbhan    (      rbsize )  !! saved between calls by DAFRWD
      integer(ip) :: rbrec    (      rbsize )  !! saved between calls by DAFRWD
      integer(ip) :: rbreq    (      rbsize )  !! saved between calls by DAFRWD
      real(wp) :: rbdat    ( 128, rbsize )  !! saved between calls by DAFRWD
      integer(ip) :: rbnbr  !! saved between calls by DAFRWD
      integer(ip) :: nread  !! saved between calls by DAFRWD
      integer(ip) :: nreq  !! saved between calls by DAFRWD
   end type dafrwd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dafrwd_state(state)
      type(dafrwd_state), intent(inout) :: state  !! the state
      state%rbhan = 0
      state%rbrec = 0
      state%rbreq = 0
      state%rbdat = 0.0_wp
      state%rbnbr = 1
      state%nread = 0
      state%nreq = 0
   end subroutine init_dafrwd_state

end module pepper_state_dafrwd
