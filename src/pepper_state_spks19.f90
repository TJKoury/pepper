!> Extract a subset of the data in an SPK segment of type 19
!> into a new segment.
!>
!> The state of SPICELIB's SPKS19 routines (entry points spks19),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spks19.f90.
module pepper_state_spks19

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'spk19.inc'
   integer(ip), parameter :: bufsiz = 100
   integer(ip), parameter :: ctrlsz = 3
   integer(ip), parameter :: filsiz = 255

   public :: init_spks19_state

   !> The saved variables of SPKS19.
   type, public :: spks19_state
      real(wp) :: iv1beg  !! work: start time of the first output interpolation interval
      real(wp) :: iv1end  !! work: end time of the first output interpolation interval
      real(wp) :: ivfbeg  !! work: start time of the final output interpolation interval
      real(wp) :: ivfend  !! work: end time of the final output interpolation interval
      integer(ip) :: minfsz  !! work: size in DAF addresses of the final output mini-segment
      integer(ip) :: shift  !! work: shift of the middle group mini-segment pointers
   end type spks19_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spks19_state(state)
      type(spks19_state), intent(inout) :: state  !! the state
   end subroutine init_spks19_state

end module pepper_state_spks19
