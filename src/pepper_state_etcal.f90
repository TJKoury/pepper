!> Convert from an ephemeris epoch measured in seconds past
!> the epoch of J2000 to a calendar string format using a
!> formal calendar free of leapseconds.
!>
!> The state of SPICELIB's ETCAL routines (entry points etcal),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of etcal.f90.
module pepper_state_etcal

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: strsiz = 16
   integer(ip), parameter :: lngsiz = 180

   public :: init_etcal_state

   !> The saved variables of ETCAL.
   type, public :: etcal_state
      real(wp) :: dmnint  !! smallest integer, as a double precision number (computed on the first call)
      real(wp) :: dmxint  !! largest integer, as a double precision number (computed on the first call)
      real(wp) :: halfd  !! number of seconds in half a day
      real(wp) :: secspd  !! number of seconds in a day
      integer(ip) :: dn2000  !! day number past 1 Jan 1 AD of Jan 1, 2000 (computed on the first call)
      integer(ip) :: offset  !! scratch: number of 400-year periods by which a B.C. day number was shifted
      logical :: first  !! the first call has not set up the constants yet
   end type etcal_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_etcal_state(state)
      type(etcal_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_etcal_state

end module pepper_state_etcal
