!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZTANUTL routines (entry points zztanini, zztansta),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zztanutl.f90.
module pepper_state_zztanutl

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzdsk

   implicit none

   private


   public :: init_zztanutl_state

   !> The saved variables of ZZTANUTL.
   type, public :: zztanutl_state
      real(wp) :: svaxis ( 3 )  !! unit vector along the axis (AXIS) saved by ZZTANINI
      integer(ip) :: svcurv  !! curve type code (limb, umbral or penumbral terminator) saved by ZZTANINI
      real(wp) :: svet  !! evaluation epoch (ET, used for DSK segment selection) saved by ZZTANINI
      real(wp) :: svirad  !! illumination source radius (km) saved by ZZTANINI
      real(wp) :: svnrml ( 3 )  !! unit normal of the half-plane of AXIS and PLNVEC, saved by ZZTANINI
      real(wp) :: svvrtx ( 3 )  !! the axis vector as given, used as the ray vertex; saved by ZZTANINI
   end type zztanutl_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zztanutl_state(state)
      type(zztanutl_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svaxis = 0.0_wp
      state%svcurv = 0
      state%svet = 0.0_wp
      state%svirad = 0.0_wp
      state%svnrml = 0.0_wp
      state%svvrtx = 0.0_wp
   end subroutine init_zztanutl_state

end module pepper_state_zztanutl
