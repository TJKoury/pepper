!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZRYTLAT routines (entry points zzrytlat),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzrytlat.f90.
module pepper_state_zzrytlat

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dsktol.inc'

   public :: init_zzrytlat_state

   !> The saved variables of ZZRYTLAT.
   type, public :: zzrytlat_state
      real(wp) :: origin ( 3 )  !! constant origin vector (0,0,0), vertex of the latitude cones
      real(wp) :: z      ( 3 )  !! constant +Z unit vector (0,0,1), axis of the latitude cones
   end type zzrytlat_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzrytlat_state(state)
      type(zzrytlat_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%origin = 0.0_wp
      state%z = 0.0_wp
      state%origin = 0.0_wp
      state%z = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_zzrytlat_state

end module pepper_state_zzrytlat
