!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZVSTRNG routines (entry points zzvststr, zzvsbstr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzvstrng.f90.
module pepper_state_zzvstrng

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: maxsig = 14
   integer(ip), parameter :: wdsize = maxsig + 16

   public :: init_zzvstrng_state

   !> The saved variables of ZZVSTRNG.
   type, public :: zzvstrng_state
      character(wdsize) :: string  !! the decimal string (from DPSTR) of the number set by ZZVSTSTR
      character(1) :: myfill  !! the fill character for the digits before the first significant one
      integer(ip) :: code0  !! the character code of '0'
      integer(ip) :: exp  !! the exponent of the number set by ZZVSTSTR
   end type zzvstrng_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzvstrng_state(state)
      type(zzvstrng_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%string = ' '
      state%myfill = ' '
      state%code0 = 0
      state%exp = 0
      state%string = ' 0.0000000000000E+00 '
      state%myfill = ' '
      state%exp = 0
   end subroutine init_zzvstrng_state

end module pepper_state_zzvstrng
