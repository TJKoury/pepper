!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSRFKER routines (entry points zzsrfker),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsrfker.f90.
module pepper_state_zzsrfker

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'srftrn.inc'
   include              'zzsrftrn.inc'
   character(*), parameter :: kvsfbd = 'NAIF_SURFACE_BODY'
   character(*), parameter :: kvsfcd = 'NAIF_SURFACE_CODE'
   character(*), parameter :: kvsfnm = 'NAIF_SURFACE_NAME'
   integer(ip), parameter :: kvnmln = 32
   integer(ip), parameter :: nnames = 3

   public :: init_zzsrfker_state

   !> The saved variables of ZZSRFKER.
   type, public :: zzsrfker_state
      logical :: pass1  !! first call: the kernel pool watch on the surface variables is not yet set
      character(kvnmln) :: names  ( nnames )  !! names of the surface name-ID kernel variables (watched by ZZSRFTRN)
   end type zzsrfker_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsrfker_state(state)
      type(zzsrfker_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%pass1 = .false.
      state%names = ' '
      state%pass1 = .true.
      state%names = [ character(len(state%names)) :: kvsfbd, kvsfcd, kvsfnm ]
   end subroutine init_zzsrfker_state

end module pepper_state_zzsrfker
