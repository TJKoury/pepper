!> Return the 3x3 matrix that transforms position vectors from one
!> specified frame at a specified epoch to another specified
!> frame at another specified epoch.
!>
!> The state of SPICELIB's PXFRM2 routines (entry points pxfrm2),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of pxfrm2.f90.
module pepper_state_pxfrm2

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: frnmln = 32

   public :: init_pxfrm2_state

   !> The saved variables of PXFRM2.
   type, public :: pxfrm2_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfrom  !! name of the "from" frame looked up last
      integer(ip) :: svfcod  !! ID code of the "from" frame looked up last
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the "to" frame
      character(frnmln) :: svto  !! name of the "to" frame looked up last
      integer(ip) :: svtcde  !! ID code of the "to" frame looked up last
      logical :: first  !! first call: the pool counters are not yet initialized
   end type pxfrm2_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_pxfrm2_state(state)
      type(pxfrm2_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svfrom = ' '
      state%svfcod = 0
      state%svctr2 = 0
      state%svto = ' '
      state%svtcde = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_pxfrm2_state

end module pepper_state_pxfrm2
