!> This subroutine is a shell for the routines needed by DPSPCE
!> for calculating deep space effects on a vehicle.
!>
!> The state of SPICELIB's ZZNRDDP routines (entry points zzdpinit, zzdpsec, zzdpper),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zznrddp.f90.
module pepper_state_zznrddp

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zznrddp_state

   !> The saved variables of ZZNRDDP.
   type, public :: zznrddp_state
      real(wp) :: atime  !! resonance integrator: time of the current integration step (min from epoch)
      real(wp) :: cosiq  !! cosine of the inclination at epoch
      real(wp) :: delt  !! work: step (+/-720 min) of the resonance integrator
      real(wp) :: e3  !! lunar long-period eccentricity coefficient e3
      real(wp) :: ee2  !! lunar long-period eccentricity coefficient ee2
      real(wp) :: omegao  !! argument of perigee at epoch (rad)
      real(wp) :: pe0  !! long-period eccentricity perturbation at epoch, subtracted in ZZDPPER (never set)
      real(wp) :: pgh0  !! long-period argument of perigee perturbation at epoch, subtracted in ZZDPPER (never set)
      real(wp) :: ph0  !! long-period node perturbation at epoch, subtracted in ZZDPPER (never set)
      real(wp) :: pinc0  !! long-period inclination perturbation at epoch, subtracted in ZZDPPER (never set)
      real(wp) :: pix1  !! pi
      real(wp) :: pix2  !! 2 pi
      real(wp) :: pl0  !! long-period mean longitude perturbation at epoch, subtracted in ZZDPPER (never set)
      real(wp) :: preep  !! epoch day (days since 1900 Jan 0.5) of the last lunar orbit computation
      real(wp) :: se  !! work: secular eccentricity rate of the current (solar or lunar) pass of ZZDPINIT
      real(wp) :: se2  !! solar long-period eccentricity coefficient se2
      real(wp) :: se3  !! solar long-period eccentricity coefficient se3
      real(wp) :: sgh  !! work: secular argument of perigee rate of the current (solar or lunar) pass of ZZDPINIT
      real(wp) :: sgh2  !! solar long-period argument of perigee coefficient sgh2
      real(wp) :: sgh3  !! solar long-period argument of perigee coefficient sgh3
      real(wp) :: sgh4  !! solar long-period argument of perigee coefficient sgh4
      real(wp) :: sh  !! work: secular node rate of the current (solar or lunar) pass of ZZDPINIT
      real(wp) :: sh2  !! solar long-period node coefficient sh2
      real(wp) :: sh3  !! solar long-period node coefficient sh3
      real(wp) :: si  !! work: secular inclination rate of the current (solar or lunar) pass of ZZDPINIT
      real(wp) :: si2  !! solar long-period inclination coefficient si2
      real(wp) :: si3  !! solar long-period inclination coefficient si3
      real(wp) :: siniq  !! sine of the inclination at epoch
      real(wp) :: sl  !! work: secular mean anomaly rate of the current (solar or lunar) pass of ZZDPINIT
      real(wp) :: sl2  !! solar long-period mean longitude coefficient sl2
      real(wp) :: sl3  !! solar long-period mean longitude coefficient sl3
      real(wp) :: sl4  !! solar long-period mean longitude coefficient sl4
      real(wp) :: thgr  !! Greenwich sidereal angle at epoch (rad)
      real(wp) :: xfact  !! resonance term: rate of the resonance angle minus the mean motion at epoch (rad/min)
      real(wp) :: xgh2  !! lunar long-period argument of perigee coefficient xgh2
      real(wp) :: xgh3  !! lunar long-period argument of perigee coefficient xgh3
      real(wp) :: xgh4  !! lunar long-period argument of perigee coefficient xgh4
      real(wp) :: xh2  !! lunar long-period node coefficient xh2
      real(wp) :: xh3  !! lunar long-period node coefficient xh3
      real(wp) :: xi2  !! lunar long-period inclination coefficient xi2
      real(wp) :: xi3  !! lunar long-period inclination coefficient xi3
      real(wp) :: xl2  !! lunar long-period mean longitude coefficient xl2
      real(wp) :: xl3  !! lunar long-period mean longitude coefficient xl3
      real(wp) :: xl4  !! lunar long-period mean longitude coefficient xl4
      real(wp) :: xlamo  !! resonance angle lambda at epoch (rad)
      real(wp) :: xli  !! resonance integrator: resonance angle lambda at time atime (rad)
      real(wp) :: xni  !! resonance integrator: mean motion at time atime (rad/min)
      real(wp) :: xnq  !! mean motion at epoch (rad/min, un-Kozai'd)
      real(wp) :: xqncl  !! inclination at epoch (rad)
      real(wp) :: zcosgl  !! cosine of the lunar argument of perigee angle (epoch preep)
      real(wp) :: zcoshl  !! cosine of the right ascension of the lunar node (epoch preep)
      real(wp) :: zcosil  !! cosine of the inclination of the lunar orbit to the equator (epoch preep)
      real(wp) :: zmol  !! lunar mean anomaly at the epoch day preep (rad)
      real(wp) :: zmos  !! solar mean anomaly at the epoch day preep (rad)
      real(wp) :: zsingl  !! sine of the lunar argument of perigee angle (epoch preep)
      real(wp) :: zsinhl  !! sine of the right ascension of the lunar node (epoch preep)
      real(wp) :: zsinil  !! sine of the inclination of the lunar orbit to the equator (epoch preep)
      real(wp) :: del   ( 3  )  !! one-day (synchronous) resonance coefficients del1, del2, del3
      real(wp) :: dg    ( 10 )  !! half-day resonance coefficients d2201, d2211, d3210, ..., d5433 (in that order)
      real(wp) :: ssx   ( 5  )  !! lunar-solar secular rates of the mean anomaly, perigee, node, eccentricity, inclination (/min)
      integer(ip) :: iresfl  !! resonance flag: 1 if the orbit is resonant (one-day or half-day), else 0
      integer(ip) :: isynfl  !! synchronous flag: 1 for one-day (synchronous) resonance, else 0
      logical :: return  !! unused (name of the SPICELIB RETURN function in the original declarations)
   end type zznrddp_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zznrddp_state(state)
      type(zznrddp_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%atime = 0.0_wp
      state%cosiq = 0.0_wp
      state%delt = 0.0_wp
      state%e3 = 0.0_wp
      state%ee2 = 0.0_wp
      state%omegao = 0.0_wp
      state%pe0 = 0.0_wp
      state%pgh0 = 0.0_wp
      state%ph0 = 0.0_wp
      state%pinc0 = 0.0_wp
      state%pix1 = 0.0_wp
      state%pix2 = 0.0_wp
      state%pl0 = 0.0_wp
      state%preep = 0.0_wp
      state%se = 0.0_wp
      state%se2 = 0.0_wp
      state%se3 = 0.0_wp
      state%sgh = 0.0_wp
      state%sgh2 = 0.0_wp
      state%sgh3 = 0.0_wp
      state%sgh4 = 0.0_wp
      state%sh = 0.0_wp
      state%sh2 = 0.0_wp
      state%sh3 = 0.0_wp
      state%si = 0.0_wp
      state%si2 = 0.0_wp
      state%si3 = 0.0_wp
      state%siniq = 0.0_wp
      state%sl = 0.0_wp
      state%sl2 = 0.0_wp
      state%sl3 = 0.0_wp
      state%sl4 = 0.0_wp
      state%thgr = 0.0_wp
      state%xfact = 0.0_wp
      state%xgh2 = 0.0_wp
      state%xgh3 = 0.0_wp
      state%xgh4 = 0.0_wp
      state%xh2 = 0.0_wp
      state%xh3 = 0.0_wp
      state%xi2 = 0.0_wp
      state%xi3 = 0.0_wp
      state%xl2 = 0.0_wp
      state%xl3 = 0.0_wp
      state%xl4 = 0.0_wp
      state%xlamo = 0.0_wp
      state%xli = 0.0_wp
      state%xni = 0.0_wp
      state%xnq = 0.0_wp
      state%xqncl = 0.0_wp
      state%zcosgl = 0.0_wp
      state%zcoshl = 0.0_wp
      state%zcosil = 0.0_wp
      state%zmol = 0.0_wp
      state%zmos = 0.0_wp
      state%zsingl = 0.0_wp
      state%zsinhl = 0.0_wp
      state%zsinil = 0.0_wp
      state%del = 0.0_wp
      state%dg = 0.0_wp
      state%ssx = 0.0_wp
      state%iresfl = 0
      state%isynfl = 0
      state%return = .false.
   end subroutine init_zznrddp_state

end module pepper_state_zznrddp
