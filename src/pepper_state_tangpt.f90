!> Compute, for a given observer, ray emanating from the observer,
!> and target, the "tangent point": the point on the ray nearest
!> to the target's surface. Also compute the point on the target's
!> surface nearest to the tangent point.
!>
!> The state of SPICELIB's TANGPT routines (entry points tangpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of tangpt.f90.
module pepper_state_tangpt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'frmtyp.inc'
   include               'zzabcorr.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32
   integer(ip), parameter :: loclen = 15

   public :: init_tangpt_state

   !> The saved variables of TANGPT.
   type, public :: tangpt_state
      logical :: first  !! first call: counters, correction and locus not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      character(loclen) :: prvloc  !! aberration correction locus string (CORLOC) of the previous call
      integer(ip) :: prvtcd  !! saved body name/ID item declarations.
      logical :: tanloc  !! the saved locus is TANGENT POINT (false: SURFACE POINT)
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: uselt  !! the saved correction includes light time
      logical :: usestl  !! the saved correction includes stellar aberration
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the target
      character(bdnmln) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(bdnmln) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame (FIXREF) looked up last (ZZNAMFRM)
      integer(ip) :: svfxfc  !! ID code of the body-fixed frame looked up last
      integer(ip) :: svctr4 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the ray frame (DREF)
      character(frnmln) :: svdref  !! name of the ray direction frame (DREF) looked up last
      integer(ip) :: svdfrc  !! ID code of the ray direction frame looked up last
      integer(ip) :: svctr5 ( ctrsiz )  !! saved target radii declarations.
      real(wp) :: svradi ( 3 )  !! target radii (km) returned by the last ZZBODVCD lookup
      integer(ip) :: svnrad  !! number of target radii returned by the last ZZBODVCD lookup
   end type tangpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_tangpt_state(state)
      type(tangpt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%prvcor = ' '
      state%prvloc = ' '
      state%prvtcd = 0
      state%tanloc = .false.
      state%usecn = .false.
      state%uselt = .false.
      state%usestl = .false.
      state%xmit = .false.
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svfref = ' '
      state%svfxfc = 0
      state%svctr4 = 0
      state%svdref = ' '
      state%svdfrc = 0
      state%svctr5 = 0
      state%svradi = 0.0_wp
      state%svnrad = 0
      state%first = .true.
      state%prvcor = ' '
      state%prvloc = ' '
      state%prvtcd = 0
      state%tanloc = .false.
      state%usecn = .false.
      state%uselt = .false.
      state%usestl = .false.
      state%xmit = .false.
   end subroutine init_tangpt_state

end module pepper_state_tangpt
