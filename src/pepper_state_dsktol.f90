!> Umbrella routine for DSK tolerance and margin parameter access
!> routines.
!>
!> The state of SPICELIB's DSKTOL routines (entry points dskgtl, dskstl),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of dsktol.f90.
module pepper_state_dsktol

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dsktol.inc'
   integer(ip), parameter :: ndspar = 6

   public :: init_dsktol_state

   !> The saved variables of DSKTOL.
   type, public :: dsktol_state
      real(wp) :: dppars ( ndspar )  !! the values of the DSK tolerance and margin parameters
   end type dsktol_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dsktol_state(state)
      type(dsktol_state), intent(inout) :: state  !! the state
      state%dppars = [ xfract, sgreed, sgpadm, ptmemm, angmrg, lonali ]
   end subroutine init_dsktol_state

end module pepper_state_dsktol
