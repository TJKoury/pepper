!> Return the matrix that transforms position vectors from one
!> specified frame to another at a specified epoch.
!>
!> The state of SPICELIB's PXFORM routines (entry points pxform),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of pxform.f90.
module pepper_state_pxform

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_pxform_state

   !> The saved variables of PXFORM.
   type, public :: pxform_state
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the "from" frame
      character(frnmln) :: svfrom  !! name of the "from" frame looked up last
      integer(ip) :: svfcod  !! ID code of the "from" frame looked up last
      integer(ip) :: svctr2 ( ctrsiz )  !! kernel pool state counter for the "to" frame name lookup
      character(frnmln) :: svto  !! name of the "to" frame looked up last
      integer(ip) :: svtcde  !! ID code of the "to" frame looked up last
      logical :: first  !! true until the pool state counters are initialized
   end type pxform_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_pxform_state(state)
      type(pxform_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svfrom = ' '
      state%svfcod = 0
      state%svctr2 = 0
      state%svto = ' '
      state%svtcde = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_pxform_state

end module pepper_state_pxform
