!> Write the file record to a new DAS file.
!>
!> The state of SPICELIB's ZZDASNFR routines (entry points zzdasnfr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdasnfr.f90.
module pepper_state_zzdasnfr

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzftprms

   implicit none

   private

   integer(ip), parameter :: preftp = 607
   integer(ip), parameter :: pstftp = 297

   public :: init_zzdasnfr_state

   !> The saved variables of ZZDASNFR.
   type, public :: zzdasnfr_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      character(sizftp) :: ftpstr  !! the FTP validation string
      character(preftp) :: prenul  !! the bytes before the FTP validation string (nulls)
      character(pstftp) :: pstnul  !! the bytes after the FTP validation string (nulls)
   end type zzdasnfr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdasnfr_state(state)
      type(zzdasnfr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%ftpstr = ' '
      state%prenul = ' '
      state%pstnul = ' '
      state%first = .true.
   end subroutine init_zzdasnfr_state

end module pepper_state_zzdasnfr
