!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFILU routines (entry points zzgfilin, zzgfildc, zzgfilgq),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfilu.f90.
module pepper_state_zzgfilu

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'
   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32
   integer(ip), parameter :: mthlen = 200
   integer(ip), parameter :: namlen = 50

   public :: init_zzgfilu_state

   !> The saved variables of ZZGFILU.
   type, public :: zzgfilu_state
      character(namlen) :: angnms ( 3 )  !! recognized illumination angle names (constant)
      integer(ip) :: svaidx  !! index of the angle type in angnms
      character(corlen) :: svcorr  !! aberration correction saved by ZZGFILIN
      character(bdnmln) :: svinam  !! illumination source name saved by ZZGFILIN
      character(mthlen) :: svmeth  !! computation method saved by ZZGFILIN
      real(wp) :: svnrml ( 3 )  !! outward surface normal at the surface point svsspt
      character(bdnmln) :: svonam  !! observer name saved by ZZGFILIN
      character(frnmln) :: svref  !! target body-fixed frame name saved by ZZGFILIN
      real(wp) :: svsspt ( 3 )  !! surface point on the target saved by ZZGFILIN
      character(bdnmln) :: svtnam  !! target name saved by ZZGFILIN
   end type zzgfilu_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfilu_state(state)
      type(zzgfilu_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%angnms = ' '
      state%svaidx = 0
      state%svcorr = ' '
      state%svinam = ' '
      state%svmeth = ' '
      state%svnrml = 0.0_wp
      state%svonam = ' '
      state%svref = ' '
      state%svsspt = 0.0_wp
      state%svtnam = ' '
      state%angnms = [ character(len(state%angnms)) :: 'PHASE', 'INCIDENCE', 'EMISSION' ]
   end subroutine init_zzgfilu_state

end module pepper_state_zzgfilu
