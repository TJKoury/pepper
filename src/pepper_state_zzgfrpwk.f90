!> The entry points under this routine allows one to easily monitor
!> the status of job in progress.
!>
!> The state of SPICELIB's ZZGFRPWK routines (entry points zzgftswk, zzgfwkin, zzgfwkad, zzgfwkun, zzgfwkmo),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfrpwk.f90.
module pepper_state_zzgfrpwk

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzgf.inc'

   public :: init_zzgfrpwk_state

   !> The saved variables of ZZGFRPWK.
   type, public :: zzgfrpwk_state
      integer(ip) :: calls  !! ZZGFWKIN calls since the last time check
      integer(ip) :: check  !! number of ZZGFWKIN calls between system time checks
      real(wp) :: done  !! amount of work done so far
      real(wp) :: entire  !! total amount of work to be done
      character(mxendm) :: finish  !! progress report end message
      logical :: first  !! first call: standard output unit not yet looked up
      integer(ip) :: ls  !! nonblank length of the begin message (set by ZZGFTSWK)
      real(wp) :: lstsec  !! system time of the last report, seconds past midnight
      character(mxbegm) :: start  !! progress report begin message
      integer(ip) :: stdout  !! logical unit of standard output
      real(wp) :: step  !! minimum seconds between progress reports (0 to 3600)
      real(wp) :: svincr  !! last increment passed to ZZGFWKIN
      integer(ip) :: svunit  !! logical unit the progress report is written to
   end type zzgfrpwk_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfrpwk_state(state)
      type(zzgfrpwk_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%calls = 0
      state%check = 0
      state%done = 0.0_wp
      state%entire = 0.0_wp
      state%finish = ' '
      state%first = .false.
      state%ls = 0
      state%lstsec = 0.0_wp
      state%start = ' '
      state%stdout = 0
      state%step = 0.0_wp
      state%svincr = 0.0_wp
      state%svunit = 0
      state%calls = 0
      state%check = 1
      state%done = 0.0_wp
      state%entire = 0.0_wp
      state%finish = ' '
      state%first = .true.
      state%ls = 1
      state%lstsec = 0.0_wp
      state%start = ' '
      state%stdout = 6
      state%step = 0.0_wp
      state%svincr = 0.0_wp
      state%svunit = 6
   end subroutine init_zzgfrpwk_state

end module pepper_state_zzgfrpwk
