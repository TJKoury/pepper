!> Add character data to a DAS file.
!>
!> The state of SPICELIB's DASADC routines (entry points dasadc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dasadc.f90.
module pepper_state_dasadc

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: nwc = 1024

   public :: init_dasadc_state

   !> The saved variables of DASADC.
   type, public :: dasadc_state
      character(nwc) :: record  !! saved between calls by DASADC
   end type dasadc_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dasadc_state(state)
      type(dasadc_state), intent(inout) :: state  !! the state
      state%record = ' '
   end subroutine init_dasadc_state

end module pepper_state_dasadc
