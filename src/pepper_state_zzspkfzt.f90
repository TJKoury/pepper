!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKFZT routines (entry points zzspkfzt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkfzt.f90.
module pepper_state_zzspkfzt

   use pepper_kinds, only: ip, wp
      use pepper_inc_frmtyp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_zzspkfzt_state

   !> The saved variables of ZZSPKFZT.
   type, public :: zzspkfzt_state
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      real(wp) :: sttctr   ( 6    )  !! work: state of the target relative to its center (from TRGSUB)
      integer(ip) :: fj2000  !! frame ID code of J2000
      integer(ip) :: trgctr  !! work: ID code of the target's center (from TRGSUB)
      logical :: first  !! first call: correction flags and J2000 code not yet set up
      logical :: usegeo  !! the saved correction is geometric (no aberration correction)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkfzt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkfzt_state(state)
      type(zzspkfzt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%prvcor = ' '
      state%sttctr = 0.0_wp
      state%fj2000 = 0
      state%trgctr = 0
      state%first = .false.
      state%usegeo = .false.
      state%xmit = .false.
      state%prvcor = ' '
      state%first = .true.
   end subroutine init_zzspkfzt_state

end module pepper_state_zzspkfzt
