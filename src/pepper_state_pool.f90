!> Maintain a pool of variables read from SPICE ASCII kernel files.
!>
!> The state of SPICELIB's POOL routines (entry points clpool, ldpool, rtpool, expool, wrpool,
!> swpool, cvpool, gcpool, gdpool, gipool, dtpool, pcpool, pdpool, pipool, lmpool, szpool, dvpool,
!> gnpool, dwpool, zzvupool, zzpctrck),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of pool.f90.
module pepper_state_pool

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzctr.inc'
   integer(ip) :: maxvar
   parameter ( maxvar =  26003 )
   integer(ip) :: maxval
   parameter ( maxval = 400000 )
   integer(ip) :: maxlin
   parameter ( maxlin =  15000 )
   integer(ip) :: maxchr
   parameter ( maxchr =     80 )
   integer(ip) :: maxlen
   parameter ( maxlen =     32 )
   integer(ip) :: mxnote
   parameter ( mxnote =  maxvar * 5 )
   integer(ip) :: lbcell
   parameter ( lbcell = -5 )
   integer(ip) :: lbpool
   parameter ( lbpool = -5 )
   integer(ip) :: mrklen
   parameter ( mrklen = 10 )

   public :: init_pool_state

   !> The saved variables of POOL.
   type, public :: pool_state
      character(maxlen) :: pnames   (           maxvar )  !! names of the kernel pool variables
      integer(ip) :: namlst   (           maxvar )  !! heads of the hash collision lists (by hash
                                                    !! value of the name)
      integer(ip) :: nmpool   ( 2, lbpool:maxvar )  !! linked-list pool of the name collision lists
      integer(ip) :: datlst   (           maxvar )  !! heads of the value lists of the variables
                                                    !! (positive: numeric, negative: character)
      integer(ip) :: chpool   ( 2, lbpool:maxlin )  !! linked-list pool of the character values
      integer(ip) :: dppool   ( 2, lbpool:maxval )  !! linked-list pool of the numeric values
      character(maxchr) :: chvals   (           maxlin )  !! character values
      real(wp) :: dpvals   (           maxval )  !! numeric values
      character(maxlen) :: wtvars   (    lbcell : maxvar )  !! watcher table: the watched variables
                                                            !! (a set)
      integer(ip) :: wtpool   ( 2, lbpool : mxnote )  !! linked-list pool of the watcher table
      character(maxlen) :: wtagnt   ( mxnote )  !! watcher table: the agents watching each variable
      integer(ip) :: wtptrs   ( maxvar )  !! watcher table: pointers into wtpool for each watched
                                          !! variable
      character(maxlen) :: active   ( lbcell:mxnote )  !! set of the agents that have watchers
      character(maxlen) :: agents   ( lbcell:mxnote )  !! work set of agents
      character(maxlen) :: notify   ( lbcell:mxnote )  !! set of the agents to notify of an update
      logical :: first  !! the pool has not been initialized yet
      integer(ip) :: subctr ( ctrsiz )  !! pool state counter (changes when the pool changes)
      character(mrklen) :: begdat  !! the begin-data marker of text kernels
      character(mrklen) :: begtxt  !! the begin-text marker of text kernels
   end type pool_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_pool_state(state)
      type(pool_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_pool_state

end module pepper_state_pool
