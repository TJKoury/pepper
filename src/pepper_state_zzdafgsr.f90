!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDAFGSR routines (entry points zzdafgsr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdafgsr.f90.
module pepper_state_zzdafgsr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzdafgsr_state

   !> The saved variables of ZZDAFGSR.
   type, public :: zzdafgsr_state
      logical :: first  !! saved between calls by ZZDAFGSR
      integer(ip) :: natbff  !! saved between calls by ZZDAFGSR
      character(strsiz) :: strbff ( numbff )  !! saved between calls by ZZDAFGSR
   end type zzdafgsr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdafgsr_state(state)
      type(zzdafgsr_state), intent(inout) :: state  !! the state
      state%first = .true.
      state%natbff = 0
   end subroutine init_zzdafgsr_state

end module pepper_state_zzdafgsr
