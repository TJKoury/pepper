!> Safely calculate the value A*B, avoiding the possibility
!> of floating point exceptions (FPE) due to numeric underflow
!> or numeric overflow.
!>
!> The state of SPICELIB's ZZMULT routines (entry points zzmult),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzmult.f90.
module pepper_state_zzmult

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzmult_state

   !> The saved variables of ZZMULT.
   type, public :: zzmult_state
      real(wp) :: expnt  !! the bounds on the potential result of the calculation.
      logical :: first  !! first entry flag.
   end type zzmult_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzmult_state(state)
      type(zzmult_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%expnt = 0.0_wp
      state%first = .false.
      state%first = .true.
   end subroutine init_zzmult_state

end module pepper_state_zzmult
