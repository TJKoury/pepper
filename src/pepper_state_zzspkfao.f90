!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKFAO routines (entry points zzspkfao),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkfao.f90.
module pepper_state_zzspkfao

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_zzspkfao_state

   !> The saved variables of ZZSPKFAO.
   type, public :: zzspkfao_state
      logical :: pass1  !! first call: aberration correction flags not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usestl  !! the saved correction includes stellar aberration correction
   end type zzspkfao_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkfao_state(state)
      type(zzspkfao_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%pass1 = .false.
      state%prvcor = ' '
      state%usestl = .false.
      state%pass1 = .true.
      state%prvcor = ' '
   end subroutine init_zzspkfao_state

end module pepper_state_zzspkfao
