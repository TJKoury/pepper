!> Start a new segment in an E-kernel.
!>
!> The state of SPICELIB's EKBSEG routines (entry points ekbseg),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ekbseg.f90.
module pepper_state_ekbseg

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekbool.inc'
   include 'ekcoldsc.inc'
   include 'ekcnamsz.inc'
   include 'ekdatpag.inc'
   include 'ekfilpar.inc'
   include 'ekglimit.inc'
   include 'ekpage.inc'
   include 'ekrecptr.inc'
   include 'eksegdsc.inc'
   include 'ektnamsz.inc'
   include 'ektype.inc'
   integer(ip), parameter :: lbcell = -5
   integer(ip), parameter :: mxspec = 512

   public :: init_ekbseg_state

   !> The saved variables of EKBSEG.
   type, public :: ekbseg_state
      logical :: first  !! idspec is not set yet
      integer(ip) :: idspec ( lbcell : mxspec )  !! default identifier specification (lxdfid), to check table/column names
   end type ekbseg_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ekbseg_state(state)
      type(ekbseg_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%idspec = 0
      state%first = .true.
   end subroutine init_ekbseg_state

end module pepper_state_ekbseg
