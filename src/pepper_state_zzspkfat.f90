!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKFAT routines (entry points zzspkfat),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkfat.f90.
module pepper_state_zzspkfat

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzspkfat_state

   !> The saved variables of ZZSPKFAT.
   type, public :: zzspkfat_state
      logical :: pass1  !! first call: aberration correction flags not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usestl  !! the saved correction includes stellar aberration correction
   end type zzspkfat_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkfat_state(state)
      type(zzspkfat_state), intent(inout) :: state  !! the state
      state%pass1 = .true.
      state%prvcor = ' '
   end subroutine init_zzspkfat_state

end module pepper_state_zzspkfat
