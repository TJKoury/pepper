!> Determine the set of osculating conic orbital elements that
!> corresponds to the state (position, velocity) of a body at
!> some epoch.
!>
!> The state of SPICELIB's OSCELT routines (entry points oscelt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of oscelt.f90.
module pepper_state_oscelt

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_oscelt_state

   !> The saved variables of OSCELT.
   type, public :: oscelt_state
      real(wp) :: zvec   ( 3 )  !! the +Z unit vector
   end type oscelt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_oscelt_state(state)
      type(oscelt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%zvec = 0.0_wp
      state%zvec = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_oscelt_state

end module pepper_state_oscelt
