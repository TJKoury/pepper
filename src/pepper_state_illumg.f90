!> Find the illumination angles (phase, incidence, and
!> emission) at a specified surface point of a target body.
!>
!> The state of SPICELIB's ILLUMG routines (entry points illumg),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of illumg.f90.
module pepper_state_illumg

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'dsk.inc'
   include               'gf.inc'
   include               'zzabcorr.inc'
   include               'zzctr.inc'
   include               'zzdsk.inc'
   integer(ip), parameter :: lnsize = 80
   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_illumg_state

   !> The saved variables of ILLUMG.
   type, public :: illumg_state
      logical :: first  !! first call: counters, correction and method not yet set up
      integer(ip) :: nsurf  !! number of surface IDs in the saved method's surface list
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      character(lnsize) :: prvmth  !! method string of the previous call (blank after a parse error)
      integer(ip) :: shape  !! target shape parsed from the saved method (ellipsoid or DSK)
      integer(ip) :: srflst ( maxsrf )  !! surface ID list parsed from the saved method
      logical :: uselt  !! the saved correction includes light time
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame (FIXREF) looked up last (ZZNAMFRM)
      integer(ip) :: svrefc  !! ID code of the body-fixed frame looked up last
      integer(ip) :: svctr4 ( ctrsiz )  !! saved surface name/ID item declarations.
   end type illumg_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_illumg_state(state)
      type(illumg_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%nsurf = 0
      state%prvcor = ' '
      state%prvmth = ' '
      state%shape = 0
      state%srflst = 0
      state%uselt = .false.
      state%xmit = .false.
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svfref = ' '
      state%svrefc = 0
      state%svctr4 = 0
      state%first = .true.
      state%prvcor = ' '
      state%prvmth = ' '
      state%shape = 0
   end subroutine init_illumg_state

end module pepper_state_illumg
