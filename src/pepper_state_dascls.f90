!> Close a DAS file.
!>
!> The state of SPICELIB's DASCLS routines (entry points dascls),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dascls.f90.
module pepper_state_dascls

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'das.inc'
   integer(ip), parameter :: lbcell = -5

   public :: init_dascls_state

   !> The saved variables of DASCLS.
   type, public :: dascls_state
      integer(ip) :: fhset ( lbcell : ftsize )  !! set of the handles of the open DAS files (sized
                                                !! once)
      logical :: pass1  !! the handle set has not been sized yet
   end type dascls_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dascls_state(state)
      type(dascls_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%fhset = 0
      state%pass1 = .false.
      state%pass1 = .true.
   end subroutine init_dascls_state

end module pepper_state_dascls
