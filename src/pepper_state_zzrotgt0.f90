!> Find the rotation from a user specified frame to another frame at
!> a user specified epoch.
!>
!> The state of SPICELIB's ZZROTGT0 routines (entry points zzrotgt0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzrotgt0.f90.
module pepper_state_zzrotgt0

   use pepper_kinds, only: ip, wp
      use pepper_inc_frmtyp

   implicit none

   private


   public :: init_zzrotgt0_state

   !> The saved variables of ZZROTGT0.
   type, public :: zzrotgt0_state
      character(6) :: versn  !! version string quoted in the unsupported-frame-class error message
   end type zzrotgt0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzrotgt0_state(state)
      type(zzrotgt0_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%versn = ' '
      state%versn = '4.0.0'
   end subroutine init_zzrotgt0_state

end module pepper_state_zzrotgt0
