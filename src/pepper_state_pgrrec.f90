!> Convert planetographic coordinates to rectangular coordinates.
!>
!> The state of SPICELIB's PGRREC routines (entry points pgrrec),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of pgrrec.f90.
module pepper_state_pgrrec

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_pgrrec_state

   !> The saved variables of PGRREC.
   type, public :: pgrrec_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svbody  !! name of the body looked up last (ZZBODS2C)
      integer(ip) :: svbdid  !! ID code of the body looked up last
      logical :: svfnd1  !! found flag of the last body name lookup
      logical :: first  !! first call: the pool counter is not yet initialized
   end type pgrrec_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_pgrrec_state(state)
      type(pgrrec_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svbody = ' '
      state%svbdid = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_pgrrec_state

end module pepper_state_pgrrec
