!> Read the first line of text from the comment area
!> of a binary SPK or CK file.
!>
!> The state of SPICELIB's SPCRFL routines (entry points spcrfl, spcrnl),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spcrfl.f90.
module pepper_state_spcrfl

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: ifnlen = 60
   integer(ip), parameter :: maxcpr = 1000

   public :: init_spcrfl_state

   !> The saved variables of SPCRFL.
   type, public :: spcrfl_state
      character(1) :: eot  !! end-of-transmission character (CHAR(4)) that ends the comment area
      character(1) :: null  !! null character (CHAR(0)) that ends each comment line
      character(maxcpr) :: record  !! comment area record currently being read
      integer(ip) :: eol  !! position of the end of the last line read within RECORD
      integer(ip) :: fward  !! forward pointer of the file record (first summary record); the comments precede it
      integer(ip) :: hanbuf  !! handle of the file whose comments are being read
      integer(ip) :: iostat  !! work: IOSTAT of the last record read
      integer(ip) :: rec  !! number of the comment area record in RECORD
      logical :: called  !! SPCRFL has been called (SPCRNL may continue reading)
      logical :: eocsav  !! the end of the comments was reached by the last SPCRFL/SPCRNL call
   end type spcrfl_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spcrfl_state(state)
      type(spcrfl_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%eot = ' '
      state%null = ' '
      state%record = ' '
      state%eol = 0
      state%fward = 0
      state%hanbuf = 0
      state%iostat = 0
      state%rec = 0
      state%called = .false.
      state%eocsav = .false.
   end subroutine init_spcrfl_state

end module pepper_state_spcrfl
