!> Compute the Jacobian matrix of the transformation from
!> planetographic to rectangular coordinates.
!>
!> The state of SPICELIB's DRDPGR routines (entry points drdpgr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of drdpgr.f90.
module pepper_state_drdpgr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_drdpgr_state

   !> The saved variables of DRDPGR.
   type, public :: drdpgr_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svbody  !! name of the body looked up last (ZZBODS2C)
      integer(ip) :: svbdid  !! ID code of the body looked up last
      logical :: svfnd1  !! found flag of the last body name lookup
      logical :: first  !! first call: the pool counter is not yet initialized
   end type drdpgr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_drdpgr_state(state)
      type(drdpgr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svbody = ' '
      state%svbdid = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_drdpgr_state

end module pepper_state_drdpgr
