!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSCLK routines (entry points zzsclk),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsclk.f90.
module pepper_state_zzsclk

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: lbcell = -5
   integer(ip), parameter :: maxids = 10

   public :: init_zzsclk_state

   !> The saved variables of ZZSCLK.
   type, public :: zzsclk_state
      integer(ip) :: known  ( lbcell : maxids )  !! set of SCLK IDs watched in the kernel pool (by agent ZZSCLK<id>)
      integer(ip) :: passed ( lbcell : maxids )  !! set of SCLK IDs known to have all required SCLK kernel variables
      logical :: first  !! this is the first call (dtsize and the sets are not yet initialized)
      integer(ip) :: dtsize ( 7 )  !! required multiple of the size of each of the 7 SCLK kernel variables checked
   end type zzsclk_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsclk_state(state)
      type(zzsclk_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%known = 0
      state%passed = 0
      state%first = .false.
      state%dtsize = 0
      state%first = .true.
   end subroutine init_zzsclk_state

end module pepper_state_zzsclk
