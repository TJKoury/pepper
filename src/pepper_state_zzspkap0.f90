!> Deprecated: This routine has been superseded by SPKAPS. This
!> routine is supported for purposes of backward compatibility only.
!>
!> The state of SPICELIB's ZZSPKAP0 routines (entry points zzspkap0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkap0.f90.
module pepper_state_zzspkap0

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: corlen = 5
   integer(ip), parameter :: nflags = 9

   public :: init_zzspkap0_state

   !> The saved variables of ZZSPKAP0.
   type, public :: zzspkap0_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: flags  ( nflags )  !! the recognized aberration correction strings
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: usestl  !! the saved correction uses stellar aberration
      logical :: uselt  !! the saved correction uses light time
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkap0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkap0_state(state)
      type(zzspkap0_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%flags = ' '
      state%prvcor = ' '
      state%usecn = .false.
      state%usestl = .false.
      state%uselt = .false.
      state%xmit = .false.
      state%first = .true.
      state%flags = [ character(len(state%flags)) :: 'NONE', 'LT', 'LT+S', 'CN', 'CN+S', 'XLT', 'XLT+S', 'XCN', 'XCN+S' ]
      state%prvcor = ' '
   end subroutine init_zzspkap0_state

end module pepper_state_zzspkap0
