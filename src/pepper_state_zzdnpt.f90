!> Compute the velocity of an ellipsoid surface point nearest to a
!> specified position.
!>
!> The state of SPICELIB's ZZDNPT routines (entry points zzdnpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdnpt.f90.
module pepper_state_zzdnpt

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzdnpt_state

   !> The saved variables of ZZDNPT.
   type, public :: zzdnpt_state
      real(wp) :: gradm  ( 3, 3 )  !! diag(1/a**2, 1/b**2, 1/c**2): maps a surface point to (half) the ellipsoid gradient
      real(wp) :: m      ( 3, 3 )  !! inverse of (identity + l*gradm), diagonal (off-diagonal zeros set once)
   end type zzdnpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdnpt_state(state)
      type(zzdnpt_state), intent(inout) :: state  !! the state
      state%gradm = reshape ( [ 1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp ], shape ( state%gradm ) )
      state%m = reshape ( [ 1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp ], shape ( state%m ) )
   end subroutine init_zzdnpt_state

end module pepper_state_zzdnpt
