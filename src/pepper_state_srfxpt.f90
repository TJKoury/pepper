!> Deprecated: This routine has been superseded by the SPICELIB
!> routine SINCPT. This routine is supported for purposes of
!> backward compatibility only.
!>
!> The state of SPICELIB's SRFXPT routines (entry points srfxpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of srfxpt.f90.
module pepper_state_srfxpt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'frmtyp.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_srfxpt_state

   !> The saved variables of SRFXPT.
   type, public :: srfxpt_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      logical :: first  !! first call: the pool counters are not yet initialized
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svdref  !! name of the ray frame dref looked up last (ZZNAMFRM)
      integer(ip) :: svrefc  !! ID code of the ray frame dref looked up last
   end type srfxpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_srfxpt_state(state)
      type(srfxpt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%first = .false.
      state%svctr3 = 0
      state%svdref = ' '
      state%svrefc = 0
      state%first = .true.
   end subroutine init_srfxpt_state

end module pepper_state_srfxpt
