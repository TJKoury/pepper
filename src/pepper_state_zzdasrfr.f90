!> Return the contents of the file record of a specified DAS file.
!>
!> The state of SPICELIB's ZZDASRFR routines (entry points zzdasrfr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdasrfr.f90.
module pepper_state_zzdasrfr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzddhman.inc'

   public :: init_zzdasrfr_state

   !> The saved variables of ZZDASRFR.
   type, public :: zzdasrfr_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      integer(ip) :: natbff  !! code of the native binary file format
   end type zzdasrfr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdasrfr_state(state)
      type(zzdasrfr_state), intent(inout) :: state  !! the state
      state%first = .true.
      state%natbff = -1
   end subroutine init_zzdasrfr_state

end module pepper_state_zzdasrfr
