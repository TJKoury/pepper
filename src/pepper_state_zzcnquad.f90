!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZCNQUAD routines (entry points zzcnquad),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzcnquad.f90.
module pepper_state_zzcnquad

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzcnquad_state

   !> The saved variables of ZZCNQUAD.
   type, public :: zzcnquad_state
      logical :: first  !! first call: INVUB not yet computed
      real(wp) :: invub  !! upper bound on the magnitude of root inverses, sqrt(DPMAX)/200
   end type zzcnquad_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzcnquad_state(state)
      type(zzcnquad_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%invub = 0.0_wp
      state%first = .true.
      state%invub = -1.0_wp
   end subroutine init_zzcnquad_state

end module pepper_state_zzcnquad
