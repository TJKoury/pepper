!> Return the field-of-view (FOV) parameters for a specified
!> instrument. The instrument is specified by name.
!>
!> The state of SPICELIB's GETFVN routines (entry points getfvn),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of getfvn.f90.
module pepper_state_getfvn

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_getfvn_state

   !> The saved variables of GETFVN.
   type, public :: getfvn_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svinst  !! name of the instrument looked up last (ZZBODS2C)
      integer(ip) :: svinid  !! ID code of the instrument looked up last
      logical :: svfnd1  !! found flag of the last instrument name lookup
      logical :: first  !! first call: the pool counter is not yet initialized
   end type getfvn_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_getfvn_state(state)
      type(getfvn_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svinst = ' '
      state%svinid = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_getfvn_state

end module pepper_state_getfvn
