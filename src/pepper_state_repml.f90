!> Replace a marker with the text representation of a logical value.
!>
!> The state of SPICELIB's REPML routines (entry points repml),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of repml.f90.
module pepper_state_repml

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: ncase = 3

   public :: init_repml_state

   !> The saved variables of REPML.
   type, public :: repml_state
      character(1) :: casstr ( ncase )  !! constant list of the recognized case flags: 'U', 'L', 'C'
   end type repml_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_repml_state(state)
      type(repml_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%casstr = ' '
      state%casstr = [ character(len(state%casstr)) :: 'U', 'L', 'C' ]
   end subroutine init_repml_state

end module pepper_state_repml
