!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDSKBBL routines (entry points zzdskbbl),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdskbbl.f90.
module pepper_state_zzdskbbl

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr
      use pepper_inc_dla
      use pepper_inc_dskdsc
      use pepper_inc_dsk02

   implicit none

   private


   public :: init_zzdskbbl_state

   !> The saved variables of ZZDSKBBL.
   type, public :: zzdskbbl_state
      integer(ip) :: ctr    ( ctrsiz )  !! DSK state change counter (ZZDSKCHK)
      logical :: first  !! first call: the counter is not yet initialized
      integer(ip) :: prvbod  !! body ID code of the previous successful segment search
   end type zzdskbbl_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdskbbl_state(state)
      type(zzdskbbl_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ctr = 0
      state%first = .false.
      state%prvbod = 0
      state%ctr = 0
      state%first = .true.
      state%prvbod = 0
   end subroutine init_zzdskbbl_state

end module pepper_state_zzdskbbl
