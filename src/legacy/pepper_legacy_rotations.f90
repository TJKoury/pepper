      !> Legacy interface: calls ctx%xf2eul with the legacy context.
      subroutine xf2eul ( xform, axisa, axisb, axisc, eulang, unique )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: xform  ( 6, 6 )  !! A state transformation matrix.
      integer(ip) :: axisa  !! Axis A of the Euler angle factorization.
      integer(ip) :: axisb  !! Axis B of the Euler angle factorization.
      integer(ip) :: axisc  !! Axis C of the Euler angle factorization.
      real(wp) :: eulang ( 6 )  !! An array of Euler angles and their derivatives.
      logical :: unique  !! Indicates if EULANG is a unique representation.
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
      ! PEPPER: xform is passed as a copy: a SPICELIB caller may pass its output variable (in-place use)
      call ctx%xf2eul ( (xform), axisa, axisb, axisc, eulang, unique )
      end subroutine xf2eul

      !> Compute a state transformation from an Euler angle factorization
      !> of a rotation and the derivatives of those Euler angles.
      !>
      !> Legacy interface: calls ctx%eul2xf with the legacy context.
      subroutine eul2xf ( eulang, axisa, axisb, axisc, xform )
