!> The legacy interface's routines of the subsystem rotations (19 routines):
!> SPICELIB's names and arguments, on the default context. Programs use
!> them through [[pepper_legacy]].
module pepper_legacy_rotations

   use pepper_instance_module, only: pepper_context, pepper_zztwovxf => zztwovxf, &
      pepper_zzmobliq => zzmobliq, pepper_zzwahr => zzwahr, pepper_zzenut80 => zzenut80, &
      pepper_zzeprc76 => zzeprc76, pepper_zzdnpt => zzdnpt, pepper_zzstelab => zzstelab
   use pepper_legacy_context, only: legacy_context, legacy_spice

   implicit none

   private
   public :: rotate, rotmat, m2eul, eul2m, xf2eul, eul2xf, twovec, zztwovxf, irfrot, irfnum, &
      irfnam, irfdef, zzmobliq, zzwahr, zzenut80, zzeprc76, zzdnpt, dnearp, zzstelab

contains

      !> Calculate the 3x3 rotation matrix generated by a rotation
      !> of a specified angle about a specified axis. This rotation
      !> is thought of as rotating the coordinate system.
      !>
      !> Legacy interface: calls ctx%rotate with the legacy context.
      subroutine rotate ( angle, iaxis, mout )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: angle  !! Angle of rotation (radians).
      integer(ip) :: iaxis  !! Axis of rotation (X=1, Y=2, Z=3).
      real(wp) :: mout  ( 3,3 )  !! Resulting rotation matrix [ANGLE] IAXIS
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
      call ctx%rotate ( angle, iaxis, mout )
      end subroutine rotate

      !> Apply a rotation of ANGLE radians about axis IAXIS to a matrix.
      !> This rotation is thought of as rotating the coordinate system.
      !>
      !> Legacy interface: calls ctx%rotmat with the legacy context.
      subroutine rotmat ( m1, angle, iaxis, mout )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: m1    ( 3,3 )  !! Matrix to be rotated.
      real(wp) :: angle  !! Angle of rotation (radians).
      integer(ip) :: iaxis  !! Axis of rotation (X=1, Y=2, Z=3).
      real(wp) :: mout  ( 3,3 )  !! Resulting rotated matrix [ANGLE]      * M1 IAXIS
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
      ! PEPPER: m1 is passed as a copy: a SPICELIB caller may pass its output variable (in-place use)
      call ctx%rotmat ( (m1), angle, iaxis, mout )
      end subroutine rotmat

      !> Factor a rotation matrix as a product of three rotations about
      !> specified coordinate axes.
      !>
      !> Legacy interface: calls ctx%m2eul with the legacy context.
      subroutine m2eul (  r,  axis3,   axis2,   axis1, &
                              angle3,  angle2,  angle1  )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: r      ( 3, 3 )  !! A rotation matrix to be factored.
      integer(ip) :: axis3  !! Numbers of third, second, and first rotation axes.
      integer(ip) :: axis2  !! Numbers of third, second, and first rotation axes.
      integer(ip) :: axis1  !! Numbers of third, second, and first rotation axes.
      real(wp) :: angle3  !! Third, second, and first Euler angles, in radians.
      real(wp) :: angle2  !! Third, second, and first Euler angles, in radians.
      real(wp) :: angle1  !! Third, second, and first Euler angles, in radians.
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
      ! PEPPER: r is passed as a copy: a SPICELIB caller may pass its output variable (in-place use)
      call ctx%m2eul ( (r), axis3, axis2, axis1, angle3, angle2, angle1 )
      end subroutine m2eul

      !> Construct a rotation matrix from a set of Euler angles.
      !>
      !> Legacy interface: calls ctx%eul2m with the legacy context.
      subroutine eul2m (  angle3,   angle2,   angle1, &
                          axis3,    axis2,    axis1,   r  )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: angle3  !! Rotation angles about third, second, and first rotation axes (radians).
      real(wp) :: angle2  !! Rotation angles about third, second, and first rotation axes (radians).
      real(wp) :: angle1  !! Rotation angles about third, second, and first rotation axes (radians).
      integer(ip) :: axis3  !! Axis numbers of third, second, and first rotation axes.
      integer(ip) :: axis2  !! Axis numbers of third, second, and first rotation axes.
      integer(ip) :: axis1  !! Axis numbers of third, second, and first rotation axes.
      real(wp) :: r ( 3, 3 )  !! Product of the 3 rotations.
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
      call ctx%eul2m ( angle3, angle2, angle1, axis3, axis2, axis1, r )
      end subroutine eul2m

      !> Convert a state transformation matrix to Euler angles and their
      !> derivatives, given a specified set of axes.
