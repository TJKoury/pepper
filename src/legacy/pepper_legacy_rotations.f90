      !> Find the transformation to the right-handed frame having a
      !> given vector as a specified axis and having a second given
      !> vector lying in a specified coordinate plane.
      !>
      !> Legacy interface: calls ctx%twovec with the legacy context.
      subroutine twovec ( axdef, indexa, plndef, indexp, mout )
      use pepper_kinds, only: ip, wp
      implicit none
      real(wp) :: axdef  (   3 )  !! Vector defining a principal axis.
      integer(ip) :: indexa  !! Principal axis number of AXDEF (X=1, Y=2, Z=3).
      real(wp) :: plndef (   3 )  !! Vector defining (with AXDEF) a principal plane.
      integer(ip) :: indexp  !! Second axis number (with INDEXA) of principal plane.
      real(wp) :: mout   ( 3,3 )  !! Output rotation matrix.
      type(pepper_context), pointer :: ctx
      ctx => legacy_context()
