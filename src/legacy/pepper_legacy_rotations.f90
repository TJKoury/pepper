      implicit none
      real(wp) :: state ( 6 )  !! State of an object in body-fixed coordinates.
      real(wp) :: nearp ( 3 )  !! Near point on ellipsoid.
      real(wp) :: a  !! Length of semi-axis parallel to x-axis.
