!> Scan tokens in an EK query.
!>
!> The state of SPICELIB's ZZEKSCAN routines (entry points zzekscan),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzekscan.f90.
module pepper_state_zzekscan

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekkeyw.inc'
   include 'ektokn.inc'
   include 'ekqlimit.inc'
   integer(ip), parameter :: lnsize = 80
   integer(ip), parameter :: lbcell = -5
   integer(ip), parameter :: mxspec = 512

   public :: init_zzekscan_state

   !> The saved variables of ZZEKSCAN.
   type, public :: zzekscan_state
      integer(ip) :: idspec ( lbcell : mxspec )  !! identifier character spec for lxidnt (built by lxcsid on the first call)
      logical :: pass1  !! idspec has not been built yet
   end type zzekscan_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzekscan_state(state)
      type(zzekscan_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%idspec = 0
      state%pass1 = .false.
      state%pass1 = .true.
   end subroutine init_zzekscan_state

end module pepper_state_zzekscan
