!> Compute the values of the Stumpff functions C_0 through C_3 at
!> a specified point.
!>
!> The state of SPICELIB's STMP03 routines (entry points stmp03),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of stmp03.F90.
module pepper_state_stmp03

   use pepper_kinds, only: ip, wp

   implicit none

   private

   ! (SPICELIB: 10 for Intel Fortran on Windows, 11 elsewhere)
   integer(ip), parameter :: trunc = 11
   integer(ip), parameter :: npairs = 2*trunc - 2

   public :: init_stmp03_state

   !> The saved variables of STMP03.
   type, public :: stmp03_state
      logical :: first  !! this is the first call (pairs and lbound are not computed yet)
      real(wp) :: lbound  !! lower bound of x (below it cosh overflows)
      real(wp) :: pairs  ( npairs )  !! reciprocal pairs 1/(i*(i+1)) of the truncated Taylor series
   end type stmp03_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_stmp03_state(state)
      type(stmp03_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_stmp03_state

end module pepper_state_stmp03
