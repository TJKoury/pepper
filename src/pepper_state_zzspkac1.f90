!> Return the state (position and velocity) of a target body
!> relative to an observer, optionally corrected for light time
!> and stellar aberration, expressed relative to an inertial
!> reference frame.
!>
!> The state of SPICELIB's ZZSPKAC1 routines (entry points zzspkac1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkac1.f90.
module pepper_state_zzspkac1

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_zzspkac1_state

   !> The saved variables of ZZSPKAC1.
   type, public :: zzspkac1_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usestl  !! the saved correction includes stellar aberration
   end type zzspkac1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkac1_state(state)
      type(zzspkac1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%prvcor = ' '
      state%usestl = .false.
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_zzspkac1_state

end module pepper_state_zzspkac1
