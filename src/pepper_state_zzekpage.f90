!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZEKPAGE routines (entry points zzekpgin, zzekpgan, zzekpgal, zzekpgfr, zzekpgrc, zzekpgrd, zzekpgri, zzekpgwc, zzekpgwd, zzekpgwi, zzekpgbs, zzekpgpg, zzekpgst),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzekpage.f90.
module pepper_state_zzekpage

   use pepper_kinds, only: ip, wp
      use pepper_inc_ekarch
      use pepper_inc_ekpage
      use pepper_inc_ektype

   implicit none

   private


   public :: init_zzekpage_state

   !> The saved variables of ZZEKPAGE.
   type, public :: zzekpage_state
      character(pgsizc) :: cfill  !! note:  the integer fill buffer should be as large as the maximum of the integer page size and the metadata area size.
      real(wp) :: dfill  ( pgsizd )  !! zero-filled d.p. page used to append new d.p. pages to the file
      integer(ip) :: ifill  ( pgsizi )  !! zero-filled integer page used to append integer pages and the metadata area
   end type zzekpage_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzekpage_state(state)
      type(zzekpage_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%cfill = ' '
      state%dfill = 0.0_wp
      state%ifill = 0
   end subroutine init_zzekpage_state

end module pepper_state_zzekpage
