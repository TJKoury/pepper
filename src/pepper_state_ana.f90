!> Return the correct article "a" or "an" used to modify a word
!> and return it capitalized, lower case, or upper case.
!>
!> The state of SPICELIB's ANA routines (entry points ana),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of ana.f90.
module pepper_state_ana

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: wdsize = 32

   public :: init_ana_state

   !> The saved variables of ANA.
   type, public :: ana_state
      character(wdsize) :: start ( 7 )  !! work: the first 1 to 7 characters of the input word
   end type ana_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_ana_state(state)
      type(ana_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%start = ' '
   end subroutine init_ana_state

end module pepper_state_ana
