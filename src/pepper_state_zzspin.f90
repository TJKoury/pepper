!> Check/initialize the quantities describing an angular separation
!> between two spherical or point objects.
!>
!> The state of SPICELIB's ZZSPIN routines (entry points zzspin),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspin.f90.
module pepper_state_zzspin

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private

   integer(ip), parameter :: spshpn = 2

   public :: init_zzspin_state

   !> The saved variables of ZZSPIN.
   type, public :: zzspin_state
      character(32) :: svshap ( spshpn )  !! names of the supported target shapes (POINT, SPHERE), constant
   end type zzspin_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspin_state(state)
      type(zzspin_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svshap = ' '
      state%svshap = [ character(len(state%svshap)) :: 'POINT', 'SPHERE' ]
   end subroutine init_zzspin_state

end module pepper_state_zzspin
