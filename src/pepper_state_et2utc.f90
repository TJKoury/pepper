!> Convert an input time from ephemeris seconds past J2000
!> to Calendar, Day-of-Year, or Julian Date format, UTC.
!>
!> The state of SPICELIB's ET2UTC routines (entry points et2utc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of et2utc.f90.
module pepper_state_et2utc

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_et2utc_state

   !> The saved variables of ET2UTC.
   type, public :: et2utc_state
      character(80) :: str  !! work: output string of the Julian date format
      real(wp) :: tvec   ( 8 )  !! work: time vector converted from TDB to JDUTC
   end type et2utc_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_et2utc_state(state)
      type(et2utc_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%str = ' '
      state%tvec = 0.0_wp
   end subroutine init_et2utc_state

end module pepper_state_et2utc
