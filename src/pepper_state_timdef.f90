!> Set and retrieve the defaults associated with calendar
!> input strings.
!>
!> The state of SPICELIB's TIMDEF routines (entry points timdef),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of timdef.f90.
module pepper_state_timdef

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: wdsize = 16
   integer(ip), parameter :: nzones = 8

   public :: init_timdef_state

   !> The saved variables of TIMDEF.
   type, public :: timdef_state
      character(wdsize) :: defzon  !! setting: the default time zone, as UTC+HR[:MN] (blank when a system is set)
      character(wdsize) :: defsys  !! setting: the default time system (UTC, TDB, TDT or TT; blank when a zone is set)
      character(wdsize) :: defcal  !! setting: the default calendar (GREGORIAN, JULIAN or MIXED)
      character(wdsize) :: zones  ( nzones )  !! names of the U.S. time zones that TIMDEF translates to UTC offsets
   end type timdef_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_timdef_state(state)
      type(timdef_state), intent(inout) :: state  !! the state
      state%defzon = ' '
      state%defsys = 'UTC'
      state%defcal = 'GREGORIAN'
      state%zones = [ character(len(state%zones)) :: 'EST', 'EDT', 'CST', 'CDT', 'MST', 'MDT', 'PST', 'PDT' ]
   end subroutine init_timdef_state

end module pepper_state_timdef
