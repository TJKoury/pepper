!> Return the position of a target body relative to an observing
!> body, optionally corrected for light time (planetary aberration)
!> and stellar aberration.
!>
!> The state of SPICELIB's SPKEZP routines (entry points spkezp),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkezp.f90.
module pepper_state_spkezp

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'frmtyp.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_spkezp_state

   !> The saved variables of SPKEZP.
   type, public :: spkezp_state
      integer(ip) :: fj2000  !! frame ID code of J2000
      logical :: first  !! first call: J2000 code and counter not yet set up
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svref  !! saved output frame name for the zznamfrm lookup
      integer(ip) :: svreqf  !! saved output frame ID code for the zznamfrm lookup
   end type spkezp_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkezp_state(state)
      type(spkezp_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%fj2000 = 0
      state%first = .false.
      state%svctr1 = 0
      state%svref = ' '
      state%svreqf = 0
      state%first = .true.
   end subroutine init_spkezp_state

end module pepper_state_spkezp
