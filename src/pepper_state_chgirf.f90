!> Support changes among a standard set of inertial coordinate
!> reference frames.
!>
!> The state of SPICELIB's CHGIRF routines (entry points irfrot, irfnum, irfnam, irfdef),
!> held in pepper_spice (and, for some variables, in pepper_context). Generated by tools/modularize_ctx.py from the
!> saved variables of chgirf.f90.
module pepper_state_chgirf

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'ninert.inc'
   integer(ip), parameter :: maxf = ninert

   public :: init_chgirf_state
   public :: init_chgirf_context_state

   !> The saved variables of CHGIRF.
   type, public :: chgirf_state
      integer(ip) :: dframe  !! the default inertial frame (set by IRFDEF; 0: none)
   end type chgirf_state

   !> The saved variables of CHGIRF that are per context.
   type, public :: chgirf_context_state
      logical :: ready  !! the rotations have been computed
      real(wp) :: trans  ( 9, maxf )  !! rotation (3x3, by columns) from J2000 to each frame
   end type chgirf_context_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_chgirf_state(state)
      type(chgirf_state), intent(inout) :: state  !! the state
      state%dframe = 0
   end subroutine init_chgirf_state

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_chgirf_context_state(state)
      type(chgirf_context_state), intent(inout) :: state  !! the state
      state%ready = .false.
   end subroutine init_chgirf_context_state

end module pepper_state_chgirf
