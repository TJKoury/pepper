!> Compute a set of points on the umbral or penumbral terminator of
!> a specified target body, where the target shape is modeled as an
!> ellipsoid.
!>
!> The state of SPICELIB's EDTERM routines (entry points edterm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of edterm.f90.
module pepper_state_edterm

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_edterm_state

   !> The saved variables of EDTERM.
   type, public :: edterm_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtgid  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the light source
      character(maxl) :: svscre  !! name of the light source looked up last
      integer(ip) :: svsrci  !! ID code of the light source looked up last
      logical :: svfnd2  !! found flag of the last light source name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsi  !! ID code of the observer looked up last
      logical :: svfnd3  !! found flag of the last observer name lookup
      logical :: first  !! first call: the pool counters are not yet initialized
      integer(ip) :: svctr4 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame looked up last (ZZNAMFRM)
      integer(ip) :: svfrcd  !! ID code of the body-fixed frame looked up last
   end type edterm_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_edterm_state(state)
      type(edterm_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtgid = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svscre = ' '
      state%svsrci = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svobsr = ' '
      state%svobsi = 0
      state%svfnd3 = .false.
      state%first = .false.
      state%svctr4 = 0
      state%svfref = ' '
      state%svfrcd = 0
      state%first = .true.
   end subroutine init_edterm_state

end module pepper_state_edterm
