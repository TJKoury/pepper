!> Return a set containing the frame IDs of all built-in frames of a
!> specified class.
!>
!> The state of SPICELIB's BLTFRM routines (entry points bltfrm),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of bltfrm.f90.
module pepper_state_bltfrm

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'frmtyp.inc'
   include 'ninert.inc'
   include 'nninrt.inc'
   integer(ip), parameter :: nframe = ninert + nninrt
   integer(ip), parameter :: frnmln = 32
   integer(ip), parameter :: lbpool = -5
   integer(ip), parameter :: maxbfr = nframe+1

   public :: init_bltfrm_state

   !> The saved variables of BLTFRM.
   type, public :: bltfrm_state
      integer(ip) :: fclass ( nframe )  !! frame classes of the built-in frames
      integer(ip) :: fcode  ( nframe )  !! frame ID codes of the built-in frames
      logical :: pass1  !! first call: the built-in frame tables not yet loaded (ZZFDAT)
   end type bltfrm_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_bltfrm_state(state)
      type(bltfrm_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%fclass = 0
      state%fcode = 0
      state%pass1 = .false.
      state%pass1 = .true.
   end subroutine init_bltfrm_state

end module pepper_state_bltfrm
