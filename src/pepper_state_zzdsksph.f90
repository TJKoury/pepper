!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDSKSPH routines (entry points zzdsksph),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdsksph.f90.
module pepper_state_zzdsksph

   use pepper_kinds, only: ip, wp
      use pepper_inc_errhnd
      use pepper_inc_dla
      use pepper_inc_dsk
      use pepper_inc_dskdsc
      use pepper_inc_zzctr

   implicit none

   private


   public :: init_zzdsksph_state

   !> The saved variables of ZZDSKSPH.
   type, public :: zzdsksph_state
      integer(ip) :: ctr    ( ctrsiz )  !! DSK state change counter (ZZDSKCHK)
      logical :: first  !! first call: the counter is not yet initialized and nothing is saved
      integer(ip) :: prvbod  !! body ID code of the previous call
      integer(ip) :: prvlst ( maxsrf )  !! surface ID list of the previous call
      integer(ip) :: prvnls  !! number of surface IDs of the previous call (-1 if the saved radii are invalid)
      real(wp) :: svmaxr  !! maximum radius of the bounding spheres for the saved body and surfaces
      real(wp) :: svminr  !! minimum radius of the bounding spheres for the saved body and surfaces
   end type zzdsksph_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdsksph_state(state)
      type(zzdsksph_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ctr = 0
      state%first = .false.
      state%prvbod = 0
      state%prvlst = 0
      state%prvnls = 0
      state%svmaxr = 0.0_wp
      state%svminr = 0.0_wp
      state%ctr = -1
      state%first = .true.
      state%prvbod = 0
      state%prvlst = 0
      state%prvnls = -1
      state%svmaxr = -1.0_wp
      state%svminr = -1.0_wp
   end subroutine init_zzdsksph_state

end module pepper_state_zzdsksph
