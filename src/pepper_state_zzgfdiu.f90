!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFDIU routines (entry points zzgfdiin, zzgfdidc, zzgfdigq),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfdiu.f90.
module pepper_state_zzgfdiu

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzgfdiu_state

   !> The saved variables of ZZGFDIU.
   type, public :: zzgfdiu_state
      character(corlen) :: svcorr  !! aberration correction saved by ZZGFDIIN
      integer(ip) :: svobs  !! observer ID code saved by ZZGFDIIN
      integer(ip) :: svtarg  !! target ID code saved by ZZGFDIIN
   end type zzgfdiu_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfdiu_state(state)
      type(zzgfdiu_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svcorr = ' '
      state%svobs = 0
      state%svtarg = 0
   end subroutine init_zzgfdiu_state

end module pepper_state_zzgfdiu
