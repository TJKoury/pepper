!> Find the transformation from a user specified frame to
!> another frame at a user specified epoch.
!>
!> The state of SPICELIB's FRMGET routines (entry points frmget),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of frmget.f90.
module pepper_state_frmget

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'frmtyp.inc'

   public :: init_frmget_state

   !> The saved variables of FRMGET.
   type, public :: frmget_state
      real(wp) :: idnt66 ( 6, 6 )  !! 6x6 identity matrix, set on the first call
      logical :: pass1  !! true until the first-call initialization is done
      character(6) :: versn  !! FRMGET version string, used in error messages
   end type frmget_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_frmget_state(state)
      type(frmget_state), intent(inout) :: state  !! the state
      state%pass1 = .true.
      state%versn = '5.0.0'
   end subroutine init_frmget_state

end module pepper_state_frmget
