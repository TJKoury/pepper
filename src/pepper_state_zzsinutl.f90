!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSINUTL routines (entry points zzsuelin, zzsudski, zzraysfx, zzmaxrad, zzminrad, zzraynp),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsinutl.f90.
module pepper_state_zzsinutl

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dsk.inc'

   public :: init_zzsinutl_state

   !> The saved variables of ZZSINUTL.
   type, public :: zzsinutl_state
      integer(ip) :: savfid  !! body-fixed frame ID code of the target, saved by ZZSUDSKI
      real(wp) :: savmnr  !! minimum radius of the target (ellipsoid radii or DSK bounding radius), km
      real(wp) :: savmxr  !! maximum radius of the target (ellipsoid radii or DSK bounding radius), km
      integer(ip) :: savnsf  !! number of surface IDs in savsrf, saved by ZZSUDSKI
      real(wp) :: savrad ( 3 )  !! target ellipsoid radii (km), saved by ZZSUELIN (zeroed by ZZSUDSKI)
      integer(ip) :: savsrf ( maxsrf )  !! surface ID list of the DSK target, saved by ZZSUDSKI
      integer(ip) :: savtrg  !! target ID code, saved by ZZSUDSKI
      integer(ip) :: savtyp  !! target shape type: ellipsoid (ZZSUELIN) or DSK (ZZSUDSKI)
   end type zzsinutl_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsinutl_state(state)
      type(zzsinutl_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%savfid = 0
      state%savmnr = 0.0_wp
      state%savmxr = 0.0_wp
      state%savnsf = 0
      state%savrad = 0.0_wp
      state%savsrf = 0
      state%savtrg = 0
      state%savtyp = 0
   end subroutine init_zzsinutl_state

end module pepper_state_zzsinutl
