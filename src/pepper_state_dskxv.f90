!> Compute ray-surface intercepts for a set of rays, using data
!> provided by multiple loaded DSK segments.
!>
!> The state of SPICELIB's DSKXV routines (entry points dskxv),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dskxv.f90.
module pepper_state_dskxv

   use pepper_kinds, only: ip, wp
      use pepper_inc_dsktol
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_dskxv_state

   !> The saved variables of DSKXV.
   type, public :: dskxv_state
      logical :: first  !! first call: pool counters not initialized, no frame validated yet
      integer(ip) :: fixfid  !! frame ID code of the last validated body-fixed frame (fixref)
      integer(ip) :: frmctr ( ctrsiz )  !! pool counter for the frame kernel variables (ZZPCTRCK), triggers re-validating fixref
      character(frnmln) :: prvfrm  !! name of the body-fixed frame validated last
      integer(ip) :: prvtcd  !! ID code of the target for which the frame was validated last
      integer(ip) :: svtcde  !! ID code of the target looked up last (ZZBODS2C)
      logical :: svtfnd  !! found flag of the last target name lookup
      character(bdnmln) :: svtnam  !! name of the target looked up last
      integer(ip) :: trgctr ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the target
   end type dskxv_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dskxv_state(state)
      type(dskxv_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%fixfid = 0
      state%frmctr = 0
      state%prvfrm = ' '
      state%prvtcd = 0
      state%svtcde = 0
      state%svtfnd = .false.
      state%svtnam = ' '
      state%trgctr = 0
      state%first = .true.
      state%prvfrm = ' '
      state%prvtcd = 0
   end subroutine init_dskxv_state

end module pepper_state_dskxv
