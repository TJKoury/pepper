!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFPAU routines (entry points zzgfpain, zzgfpadc, zzgfpagq, zzgfpax),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfpau.f90.
module pepper_state_zzgfpau

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzabcorr

   implicit none

   private


   public :: init_zzgfpau_state

   !> The saved variables of ZZGFPAU.
   type, public :: zzgfpau_state
      logical :: svablk ( nabcor )  !! attribute flags of the aberration correction svabco (from ZZVALCOR)
      character(corlen) :: svabco  !! aberration correction saved by ZZGFPAIN
      integer(ip) :: svtarg  !! target ID code saved by ZZGFPAIN
      integer(ip) :: svobs  !! observer ID code saved by ZZGFPAIN
      integer(ip) :: svillm  !! illumination source ID code saved by ZZGFPAIN
   end type zzgfpau_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfpau_state(state)
      type(zzgfpau_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svablk = .false.
      state%svabco = ' '
      state%svtarg = 0
      state%svobs = 0
      state%svillm = 0
   end subroutine init_zzgfpau_state

end module pepper_state_zzgfpau
