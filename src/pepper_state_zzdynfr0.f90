!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDYNFR0 routines (entry points zzdynfr0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdynfr0.f90.
module pepper_state_zzdynfr0

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'frmtyp.inc'
   include 'zzabcorr.inc'
   include 'zzdyn.inc'

   public :: init_zzdynfr0_state

   !> The saved variables of ZZDYNFR0.
   type, public :: zzdynfr0_state
      character(1) :: axes   ( 3 )  !! axis names 'X', 'Y', 'Z' used to decode an axis kernel variable
      integer(ip) :: earth  !! NAIF ID code of the Earth (Earth-centered check for precession/nutation frames)
      logical :: first  !! first-call setup (J2000 and Earth codes, kernel variable names) not yet done
      integer(ip) :: j2000  !! frame ID code of J2000
      character(kvnmln) :: itmabc ( 2 )  !! kernel variable names PRI_ABCORR and SEC_ABCORR
      character(kvnmln) :: itmaxe ( 2 )  !! kernel variable names PRI_AXIS and SEC_AXIS
      character(kvnmln) :: itmcof ( 3 )  !! kernel variable names ANGLE_1_COEFFS, ANGLE_2_COEFFS, ANGLE_3_COEFFS (Euler frames)
      character(kvnmln) :: itmdec ( 2 )  !! kernel variable names PRI_DEC and SEC_DEC
      character(kvnmln) :: itmfrm ( 2 )  !! kernel variable names PRI_FRAME and SEC_FRAME
      character(kvnmln) :: itmlat ( 2 )  !! kernel variable names PRI_LATITUDE and SEC_LATITUDE
      character(kvnmln) :: itmlon ( 2 )  !! kernel variable names PRI_LONGITUDE and SEC_LONGITUDE
      character(kvnmln) :: itmobs ( 2 )  !! kernel variable names PRI_OBSERVER and SEC_OBSERVER
      character(kvnmln) :: itmra  ( 2 )  !! kernel variable names PRI_RA and SEC_RA
      character(kvnmln) :: itmsep  !! kernel variable name ANGLE_SEP_TOL (minimum angular separation of the defining vectors)
      character(kvnmln) :: itmspc ( 2 )  !! kernel variable names PRI_SPEC and SEC_SPEC
      character(kvnmln) :: itmtrg ( 2 )  !! kernel variable names PRI_TARGET and SEC_TARGET
      character(kvnmln) :: itmunt ( 2 )  !! kernel variable names PRI_UNITS and SEC_UNITS
      character(kvnmln) :: itmvdf ( 2 )  !! kernel variable names PRI_VECTOR_DEF and SEC_VECTOR_DEF
      character(kvnmln) :: itmvec ( 2 )  !! kernel variable names PRI_VECTOR and SEC_VECTOR
   end type zzdynfr0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdynfr0_state(state)
      type(zzdynfr0_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%axes = ' '
      state%earth = 0
      state%first = .false.
      state%j2000 = 0
      state%itmabc = ' '
      state%itmaxe = ' '
      state%itmcof = ' '
      state%itmdec = ' '
      state%itmfrm = ' '
      state%itmlat = ' '
      state%itmlon = ' '
      state%itmobs = ' '
      state%itmra = ' '
      state%itmsep = ' '
      state%itmspc = ' '
      state%itmtrg = ' '
      state%itmunt = ' '
      state%itmvdf = ' '
      state%itmvec = ' '
      state%axes = [ character(len(state%axes)) :: kvx, kvy, kvz ]
      state%first = .true.
      state%itmcof = [ character(len(state%itmcof)) :: kweac1, kweac2, kweac3 ]
      state%itmsep = kwatol
   end subroutine init_zzdynfr0_state

end module pepper_state_zzdynfr0
