!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZXLATED routines (entry points zzxlated),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzxlated.F90.
module pepper_state_zzxlated

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzxlated_state

   !> The saved variables of ZZXLATED.
   type, public :: zzxlated_state
      integer(ip) :: bigint  !! largest integer
      integer(ip) :: smlint  !! smallest integer
      character(strsiz) :: strbff ( numbff )  !! names of the binary file formats
      integer(ip) :: natbff  !! code of the native binary file format
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
   end type zzxlated_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzxlated_state(state)
      type(zzxlated_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%bigint = 0
      state%smlint = 0
      state%strbff = ' '
      state%natbff = 0
      state%first = .false.
      state%natbff = 0
      state%first = .true.
   end subroutine init_zzxlated_state

end module pepper_state_zzxlated
