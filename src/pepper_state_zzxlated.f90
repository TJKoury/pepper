!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZXLATED routines (entry points zzxlated),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzxlated.F90.
module pepper_state_zzxlated

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzxlated_state

   !> The saved variables of ZZXLATED.
   type, public :: zzxlated_state
      integer(ip) :: bigint  !! saved between calls by ZZXLATED
      integer(ip) :: smlint  !! saved between calls by ZZXLATED
      character(strsiz) :: strbff ( numbff )  !! saved between calls by ZZXLATED
      integer(ip) :: natbff  !! saved between calls by ZZXLATED
      logical :: first  !! saved between calls by ZZXLATED
   end type zzxlated_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzxlated_state(state)
      type(zzxlated_state), intent(inout) :: state  !! the state
      state%natbff = 0
      state%first = .true.
   end subroutine init_zzxlated_state

end module pepper_state_zzxlated
