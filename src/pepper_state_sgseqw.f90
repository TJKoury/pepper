!> This is the umbrella routine for managing the sequential writing
!> of generic segments to DAF files. It should never be called
!> directly, it provides the mechanism whereby data are shared by
!> its entry points.
!>
!> The state of SPICELIB's SGSEQW routines (entry points sgbwfs, sgbwvs, sgwfpk, sgwvpk, sgwes),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of sgseqw.f90.
module pepper_state_sgseqw

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: ftsize = 20
   include 'sgparam.inc'

   public :: init_sgseqw_state

   !> The saved variables of SGSEQW.
   type, public :: sgseqw_state
      logical :: explct  !! reference values of the current segment are explicit (not implicit)
      integer(ip) :: index  !! file table index of the segment being written to the last handle used
      integer(ip) :: numfxd  !! number of fixed size packet segments currently being written
      integer(ip) :: numvar  !! number of variable size packet segments currently being written
      integer(ip) :: lsthan  !! handle of the DAF used in the last call
      logical :: fxdseg  !! the current segment has fixed (rather than variable) size packets
      real(wp) :: ftrefs ( 2, ftsize )  !! file table declarations. The file table is used to keep track of the vital statistics for each of the generic segments being written.
      integer(ip) :: ftbadr ( ftsize )  !! file table: DAF begin address of each segment
      integer(ip) :: fthan  ( ftsize )  !! file table: handle of the DAF to which each segment is written
      integer(ip) :: ftmxsz ( ftsize )  !! file table: maximum packet size written so far (variable size segments)
      integer(ip) :: ftncon ( ftsize )  !! file table: number of constant values of each segment
      integer(ip) :: ftnpkt ( ftsize )  !! file table: number of packets written so far to each segment
      integer(ip) :: ftnref ( ftsize )  !! file table: number of reference values written so far to each segment
      integer(ip) :: ftnres ( ftsize )  !! file table: number of reserved values of each segment (always 0)
      integer(ip) :: ftityp ( ftsize )  !! file table: reference value index type of each segment
      logical :: ftexpl ( ftsize )  !! file table: each segment has explicit reference values
      integer(ip) :: ftoff  ( ftsize )  !! file table: packet offset (PKTOFF) of each segment
      integer(ip) :: ftpksz ( ftsize )  !! file table: packet size of each fixed size segment
      logical :: ftfixd ( ftsize )  !! file table: each segment has fixed size packets
      integer(ip) :: nft  !! number of segments in the file table
   end type sgseqw_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_sgseqw_state(state)
      type(sgseqw_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%explct = .false.
      state%index = 0
      state%numfxd = 0
      state%numvar = 0
      state%lsthan = 0
      state%fxdseg = .false.
      state%ftrefs = 0.0_wp
      state%ftbadr = 0
      state%fthan = 0
      state%ftmxsz = 0
      state%ftncon = 0
      state%ftnpkt = 0
      state%ftnref = 0
      state%ftnres = 0
      state%ftityp = 0
      state%ftexpl = .false.
      state%ftoff = 0
      state%ftpksz = 0
      state%ftfixd = .false.
      state%nft = 0
      state%numfxd = 0
      state%numvar = 0
      state%nft = 0
   end subroutine init_sgseqw_state

end module pepper_state_sgseqw
