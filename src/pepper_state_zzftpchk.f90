!> Check a character string that may contain the FTP validation
!> string for FTP based errors.
!>
!> The state of SPICELIB's ZZFTPCHK routines (entry points zzftpchk),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzftpchk.f90.
module pepper_state_zzftpchk

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzftprms.inc'

   public :: init_zzftpchk_state

   !> The saved variables of ZZFTPCHK.
   type, public :: zzftpchk_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      character(sizend) :: lftbkt  !! left bracket of the FTP validation string
      character(sizstr) :: memstr  !! the FTP validation string without its brackets
      character(sizend) :: rgtbkt  !! right bracket of the FTP validation string
   end type zzftpchk_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzftpchk_state(state)
      type(zzftpchk_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzftpchk_state

end module pepper_state_zzftpchk
