!> Return the value of Delta ET (ET-UTC) for an input epoch.
!>
!> The state of SPICELIB's DELTET routines (entry points deltet),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of deltet.f90.
module pepper_state_deltet

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_deltet_state

   !> The saved variables of DELTET.
   type, public :: deltet_state
      character(20) :: missed   ( 5 )  !! error message templates naming each missing DELTET kernel variable
   end type deltet_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_deltet_state(state)
      type(deltet_state), intent(inout) :: state  !! the state
      state%missed = [ character(len(state%missed)) :: 'DELTET/DELTA_T_A, #', 'DELTET/K, #', 'DELTET/EB, #', 'DELTET/M, #', 'DELTET/DELTA_AT, #' ]
   end subroutine init_deltet_state

end module pepper_state_deltet
