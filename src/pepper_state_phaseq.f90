!> Compute the apparent phase angle for a target, observer,
!> illuminator set of ephemeris objects.
!>
!> The state of SPICELIB's PHASEQ routines (entry points phaseq),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of phaseq.f90.
module pepper_state_phaseq

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzabcorr.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_phaseq_state

   !> The saved variables of PHASEQ.
   type, public :: phaseq_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! saved target name for the zzbods2c lookup
      integer(ip) :: svtgid  !! saved target ID code for the zzbods2c lookup
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the illumination source
      character(maxl) :: svilmn  !! saved illumination source name for the zzbods2c lookup
      integer(ip) :: svicde  !! saved illumination source ID code for the zzbods2c lookup
      logical :: svfnd2  !! found flag of the last illumination source name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! saved observer name for the zzbods2c lookup
      integer(ip) :: svobsn  !! saved observer ID code for the zzbods2c lookup
      logical :: svfnd3  !! found flag of the last observer name lookup
      logical :: first  !! first call: pool counters not yet initialized
   end type phaseq_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_phaseq_state(state)
      type(phaseq_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtgid = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svilmn = ' '
      state%svicde = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svobsr = ' '
      state%svobsn = 0
      state%svfnd3 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_phaseq_state

end module pepper_state_phaseq
