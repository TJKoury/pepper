!> Return the time step set by the most recent call to GFSSTP.
!>
!> The state of SPICELIB's GFSTEP routines (entry points gfstep, gfsstp),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of gfstep.f90.
module pepper_state_gfstep

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_gfstep_state

   !> The saved variables of GFSTEP.
   type, public :: gfstep_state
      real(wp) :: svstep  !! the step size (set by GFSSTP)
      logical :: svinit  !! the step size has been set
   end type gfstep_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_gfstep_state(state)
      type(gfstep_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svstep = 0.0_wp
      state%svinit = .false.
      state%svstep = -1.0_wp
      state%svinit = .false.
   end subroutine init_gfstep_state

end module pepper_state_gfstep
