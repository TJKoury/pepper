!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDDHMAN routines (entry points zzddhopn, zzddhcls, zzddhhlu, zzddhunl,
!> zzddhnfo, zzddhisn, zzddhfnh, zzddhluh),
!> held in pepper_spice (and, for some variables, in pepper_context). Generated by
!> tools/modularize_ctx.py from the
!> saved variables of zzddhman.f90.
module pepper_state_zzddhman

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzddhman_state
   public :: init_zzddhman_context_state

   !> The saved variables of ZZDDHMAN.
   type, public :: zzddhman_state
      integer(ip) :: nft  !! number of files in the file table
      integer(ip) :: ftabs  ( ftsize )  !! absolute value of each file's handle
      integer(ip) :: ftamh  ( ftsize )  !! access method of each file
      integer(ip) :: ftarc  ( ftsize )  !! architecture (DAF, DAS) of each file
      integer(ip) :: ftbff  ( ftsize )  !! binary file format of each file
      integer(ip) :: fthan  ( ftsize )  !! handle of each file
      character(filen) :: ftnam  ( ftsize )  !! name of each file
      integer(ip) :: ftrtm  ( ftsize )  !! length of each file name
      real(wp) :: ftmnm  ( ftsize )  !! unique number (from the file's attributes) of each file
      integer(ip) :: next  !! the next handle number (handles are never reused)
   end type zzddhman_state

   !> The saved variables of ZZDDHMAN that are per context.
   type, public :: zzddhman_context_state
      logical :: first  !! the tables of names have not been built yet
      logical :: opnfst  !! no file has been opened yet (platform check)
      character(strsiz) :: stramh ( numamh )  !! names of the access methods
      character(strsiz) :: strarc ( numarc )  !! names of the architectures
      character(strsiz) :: strbff ( numbff )  !! names of the binary file formats
      integer(ip) :: natbff  !! the native binary file format
      integer(ip) :: supbff ( numbff )  !! the supported binary file formats
      integer(ip) :: numsup  !! number of supported binary file formats
      integer(ip) :: nut  !! number of entries in the unit table
      integer(ip) :: utcst ( utsize )  !! cost (time of the last request) of each unit
      integer(ip) :: uthan ( utsize )  !! handle of the file connected to each unit
      logical :: utlck ( utsize )  !! the unit is locked to its file
      integer(ip) :: utlun ( utsize )  !! the units
      integer(ip) :: reqcnt  !! request counter (for the costs)
      integer(ip) :: closegen  !! the instance's close_generation the unit table reflects
   end type zzddhman_context_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzddhman_state(state)
      type(zzddhman_state), intent(inout) :: state  !! the state
      state%nft = 0
      state%next = 0
   end subroutine init_zzddhman_state

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzddhman_context_state(state)
      type(zzddhman_context_state), intent(inout) :: state  !! the state
      state%first = .true.
      state%opnfst = .true.
      state%nut = 0
      state%reqcnt = 0
      state%closegen = 0
   end subroutine init_zzddhman_context_state

end module pepper_state_zzddhman
