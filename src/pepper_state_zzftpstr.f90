!> Retrieve the components of the FTP validation string.
!>
!> The state of SPICELIB's ZZFTPSTR routines (entry points zzftpstr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzftpstr.f90.
module pepper_state_zzftpstr

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzftprms

   implicit none

   private


   public :: init_zzftpstr_state

   !> The saved variables of ZZFTPSTR.
   type, public :: zzftpstr_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      character(sizdlm) :: locdlm  !! delimiter of the pieces of the FTP validation string
      character(sizend) :: loclnd  !! left bracket of the FTP validation string
      character(sizend) :: locrnd  !! right bracket of the FTP validation string
      character(sizstr) :: locstr  !! the FTP validation string
   end type zzftpstr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzftpstr_state(state)
      type(zzftpstr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%locdlm = ' '
      state%loclnd = ' '
      state%locrnd = ' '
      state%locstr = ' '
      state%first = .true.
      state%locdlm = ':'
      state%loclnd = 'FTPSTR'
      state%locrnd = 'ENDFTP'
   end subroutine init_zzftpstr_state

end module pepper_state_zzftpstr
