!> Compute the state of a massless body at time t_0 + DT by applying
!> the two-body force model to a given central mass and a given body
!> state at time t_0.
!>
!> The state of SPICELIB's PROP2B routines (entry points prop2b),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of prop2b.f90.
module pepper_state_prop2b

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: bufsiz = 3

   public :: init_prop2b_state

   !> The saved variables of PROP2B.
   type, public :: prop2b_state
      real(wp) :: lower  !! lower end of the bracket of the Kepler equation root (a work variable; not used between calls)
      real(wp) :: upper  !! upper end of the bracket of the Kepler equation root (a work variable; not used between calls)
      real(wp) :: vel    ( 3 )  !! initial velocity (from pvinit) (a work array; not used between calls)
      real(wp) :: savepv ( 6, bufsiz )  !! initial states of the last calls, whose derived quantities (below) are kept for reuse
      real(wp) :: savegm (    bufsiz )  !! gm of each saved initial state
      real(wp) :: sbound (    bufsiz )  !! bound on the magnitude of x (avoids overflow) for each saved initial state
      real(wp) :: sb2rv  (    bufsiz )  !! b**2 * (r dot v) for each saved initial state (b = sqrt(q/gm))
      real(wp) :: sbq    (    bufsiz )  !! b*q for each saved initial state (q = periapsis distance)
      real(wp) :: sbr0   (    bufsiz )  !! b*r0 for each saved initial state (r0 = initial distance)
      real(wp) :: sf     (    bufsiz )  !! 1 - e for each saved initial state (e = eccentricity)
      real(wp) :: sqovr0 (    bufsiz )  !! q/r0 for each saved initial state
      integer(ip) :: newest (    bufsiz )  !! saved-state slots from most to least recently used
      integer(ip) :: nsaved  !! number of saved initial states
   end type prop2b_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_prop2b_state(state)
      type(prop2b_state), intent(inout) :: state  !! the state
      state%newest = [ 1, 2, 3 ]
      state%nsaved = 0
   end subroutine init_prop2b_state

end module pepper_state_prop2b
