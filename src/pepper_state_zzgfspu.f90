!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFSPU routines (entry points zzgfspin, zzgfspdc, zzgfspgq, zzgfspx),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfspu.f90.
module pepper_state_zzgfspu

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzabcorr.inc'

   public :: init_zzgfspu_state

   !> The saved variables of ZZGFSPU.
   type, public :: zzgfspu_state
      character(32) :: svabcr  !! aberration correction saved by ZZGFSPIN
      integer(ip) :: svbod1  !! ID code of the first body saved by ZZGFSPIN
      integer(ip) :: svbod2  !! ID code of the second body saved by ZZGFSPIN
      character(32) :: svref  !! reference frame of the states saved by ZZGFSPIN
      character(32) :: svref1  !! body-fixed frame name of the first body saved by ZZGFSPIN
      character(32) :: svref2  !! body-fixed frame name of the second body saved by ZZGFSPIN
      integer(ip) :: svobs  !! observer ID code saved by ZZGFSPIN
      real(wp) :: svrad1  !! radius of the first body (largest radius for a sphere, 0 for a point)
      real(wp) :: svrad2  !! radius of the second body (largest radius for a sphere, 0 for a point)
      integer(ip) :: svshp1  !! shape index of the first body (point or sphere)
      integer(ip) :: svshp2  !! shape index of the second body (point or sphere)
   end type zzgfspu_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfspu_state(state)
      type(zzgfspu_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svabcr = ' '
      state%svbod1 = 0
      state%svbod2 = 0
      state%svref = ' '
      state%svref1 = ' '
      state%svref2 = ' '
      state%svobs = 0
      state%svrad1 = 0.0_wp
      state%svrad2 = 0.0_wp
      state%svshp1 = 0
      state%svshp2 = 0
   end subroutine init_zzgfspu_state

end module pepper_state_zzgfspu
