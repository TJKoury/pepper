!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZCVSTAT routines (entry points zzcvxsta, zzcvssta),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzcvstat.f90.
module pepper_state_zzcvstat

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: frnmln = 32

   public :: init_zzcvstat_state

   !> The saved variables of ZZCVSTAT.
   type, public :: zzcvstat_state
      integer(ip) :: svctr  !! ID code of the center of motion of the stored constant-velocity state
      real(wp) :: svet  !! epoch of the stored constant-velocity state
      character(frnmln) :: svref  !! reference frame name of the stored constant-velocity state
      real(wp) :: svstat ( 6 )  !! constant-velocity state stored by ZZCVSSTA
   end type zzcvstat_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzcvstat_state(state)
      type(zzcvstat_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr = 0
      state%svet = 0.0_wp
      state%svref = ' '
      state%svstat = 0.0_wp
   end subroutine init_zzcvstat_state

end module pepper_state_zzcvstat
