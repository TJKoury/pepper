!> Obtain the value of a specified generic segment meta data item.
!>
!> The state of SPICELIB's SGMETA routines (entry points sgmeta),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of sgmeta.f90.
module pepper_state_sgmeta

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'sgparam.inc'

   public :: init_sgmeta_state

   !> The saved variables of SGMETA.
   type, public :: sgmeta_state
      integer(ip) :: lstbeg  !! begin address of the segment whose meta data are buffered
      integer(ip) :: lsthan  !! handle of the file whose descriptor layout is buffered
      integer(ip) :: meta   ( mxmeta )  !! buffered meta data of the segment (base addresses made absolute)
      integer(ip) :: metasz  !! number of meta data items of the buffered segment
      logical :: nieven  !! the number of integer descriptor components of file lsthan is even
      integer(ip) :: ioffst  !! index in the descriptor of the DP word holding the segment begin and end addresses
   end type sgmeta_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_sgmeta_state(state)
      type(sgmeta_state), intent(inout) :: state  !! the state
      state%lstbeg = -1
      state%lsthan = 0
   end subroutine init_sgmeta_state

end module pepper_state_sgmeta
