!> Convert a string representing a double precision number in a
!> base 16 "scientific notation" into its equivalent double
!> precision number.
!>
!> The state of SPICELIB's HX2DP routines (entry points hx2dp),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of hx2dp.f90.
module pepper_state_hx2dp

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: maxman = 31

   public :: init_hx2dp_state

   !> The saved variables of HX2DP.
   type, public :: hx2dp_state
      real(wp) :: maxdp  !! largest number divided by the base
      real(wp) :: mindp  !! smallest number divided by the base
      real(wp) :: scales(maxman)  !! negative powers of the base (16) for the digits of the mantissa
      integer(ip) :: digbeg  !! character code of '0'
      integer(ip) :: digend  !! character code of '9'
      integer(ip) :: iexpch  !! character code of the exponent character
      integer(ip) :: iminus  !! character code of '-'
      integer(ip) :: iplus  !! character code of '+'
      integer(ip) :: ispace  !! character code of ' '
      integer(ip) :: lccbeg  !! character code of 'a'
      integer(ip) :: lccend  !! character code of 'f'
      integer(ip) :: uccbeg  !! character code of 'A'
      integer(ip) :: uccend  !! character code of 'F'
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
   end type hx2dp_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_hx2dp_state(state)
      type(hx2dp_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%maxdp = 0.0_wp
      state%mindp = 0.0_wp
      state%scales = 0.0_wp
      state%digbeg = 0
      state%digend = 0
      state%iexpch = 0
      state%iminus = 0
      state%iplus = 0
      state%ispace = 0
      state%lccbeg = 0
      state%lccend = 0
      state%uccbeg = 0
      state%uccend = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_hx2dp_state

end module pepper_state_hx2dp
