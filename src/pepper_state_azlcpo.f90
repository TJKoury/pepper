!> Return the azimuth/elevation coordinates of a specified target
!> relative to an "observer," where the observer has constant
!> position in a specified reference frame. The observer's position
!> is provided by the calling program rather than by loaded SPK
!> files.
!>
!> The state of SPICELIB's AZLCPO routines (entry points azlcpo),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of azlcpo.f90.
module pepper_state_azlcpo

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_azlcpo_state

   !> The saved variables of AZLCPO.
   type, public :: azlcpo_state
      real(wp) :: z      ( 3    )  !! constant +Z unit vector (0,0,1)
   end type azlcpo_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_azlcpo_state(state)
      type(azlcpo_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%z = 0.0_wp
      state%z = [ 0.00_wp, 0.00_wp, 1.00_wp ]
   end subroutine init_azlcpo_state

end module pepper_state_azlcpo
