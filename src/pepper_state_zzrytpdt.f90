!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZRYTPDT routines (entry points zzrytpdt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzrytpdt.f90.
module pepper_state_zzrytpdt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'dsktol.inc'

   public :: init_zzrytpdt_state

   !> The saved variables of ZZRYTPDT.
   type, public :: zzrytpdt_state
      real(wp) :: z      ( 3 )  !! the +Z unit vector, constant
   end type zzrytpdt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzrytpdt_state(state)
      type(zzrytpdt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%z = 0.0_wp
      state%z = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_zzrytpdt_state

end module pepper_state_zzrytpdt
