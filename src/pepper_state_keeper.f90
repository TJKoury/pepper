!> This routine is an umbrella for a collection of entry points
!> that manage the loading and unloading of SPICE kernels from
!> an application program.
!>
!> The state of SPICELIB's KEEPER routines (entry points furnsh, ktotal, kdata, kinfo, kclear, unload),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of keeper.f90.
module pepper_state_keeper

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: filsiz = 255
   integer(ip), parameter :: ftsize = 5000
   integer(ip), parameter :: maxtxt = 300
   integer(ip), parameter :: maxfil = ftsize + maxtxt
   integer(ip), parameter :: typlen = 8
   integer(ip), parameter :: wdsize = 32
   integer(ip), parameter :: nknown = 3

   public :: init_keeper_state

   !> The saved variables of KEEPER.
   type, public :: keeper_state
      character(filsiz) :: files ( maxfil )  !! name of each kernel loaded through FURNSH
      integer(ip) :: handls( maxfil )  !! handle of each loaded kernel (0 for a text kernel)
      integer(ip) :: srces ( maxfil )  !! index in files of the meta-kernel each kernel was loaded from (0: loaded directly)
      character(typlen) :: types ( maxfil )  !! type (SPK, CK, PCK, DSK, EK, TEXT, META) of each loaded kernel
      integer(ip) :: loaded  !! number of kernels loaded
      character(wdsize) :: known ( nknown )  !! the meta-kernel variables (KERNELS_TO_LOAD, PATH_SYMBOLS, PATH_VALUES) watched by FURNSH
      logical :: first  !! the watcher has not been set yet
   end type keeper_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_keeper_state(state)
      type(keeper_state), intent(inout) :: state  !! the state
      state%loaded = 0
      state%first = .true.
   end subroutine init_keeper_state

end module pepper_state_keeper
