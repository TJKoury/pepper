!> Determine time intervals when a specified ephemeris object
!> intersects the space bounded by the field-of-view (FOV) of a
!> specified instrument.
!>
!> The state of SPICELIB's GFTFOV routines (entry points gftfov),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of gftfov.f90.
module pepper_state_gftfov

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'gf.inc'
   include               'zzholdd.inc'

   public :: init_gftfov_state

   !> The saved variables of GFTFOV.
   type, public :: gftfov_state
      real(wp) :: raydir ( 3 )  !! ray direction vector required by GFFOVE. This is an unused variable as far is this routine is concerned: the target is an ephemeris object. We initialize the ray to prevent portability problems.
   end type gftfov_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_gftfov_state(state)
      type(gftfov_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%raydir = 0.0_wp
      state%raydir = 0.0_wp
   end subroutine init_gftfov_state

end module pepper_state_gftfov
