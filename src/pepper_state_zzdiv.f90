!> Safely calculate the value NUMR/DENOM, avoiding the possibility
!> of floating point exceptions (FPE), due to numeric underflow,
!> numeric overflow, or divide-by-zero.
!>
!> The state of SPICELIB's ZZDIV routines (entry points zzdiv),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdiv.f90.
module pepper_state_zzdiv

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzdiv_state

   !> The saved variables of ZZDIV.
   type, public :: zzdiv_state
      real(wp) :: expnt  !! the bounds on the potential result of the calculation.
      logical :: first  !! first entry flag.
   end type zzdiv_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdiv_state(state)
      type(zzdiv_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%expnt = 0.0_wp
      state%first = .false.
      state%first = .true.
   end subroutine init_zzdiv_state

end module pepper_state_zzdiv
