!> Compute the rectangular coordinates of the sub-observer point on
!> a target body at a specified epoch, optionally corrected for
!> light time and stellar aberration.
!>
!> The state of SPICELIB's SUBPNT routines (entry points subpnt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of subpnt.f90.
module pepper_state_subpnt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'dsk.inc'
   include               'frmtyp.inc'
   include               'gf.inc'
   include               'zzabcorr.inc'
   include               'zzctr.inc'
   include               'zzdsk.inc'
   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_subpnt_state

   !> The saved variables of SUBPNT.
   type, public :: subpnt_state
      logical :: first  !! first call: counters not yet initialized and no correction/method parsed yet
      logical :: near  !! the previous METHOD selects the near point (rather than the intercept) sub-point
      integer(ip) :: nsurf  !! number of surface IDs in the previous METHOD string
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      character(mthlen) :: prvmth  !! METHOD string of the previous call
      integer(ip) :: shape  !! target shape code parsed from the previous METHOD (ellipsoid or DSK)
      integer(ip) :: srflst ( maxsrf )  !! surface ID list parsed from the previous METHOD string
      logical :: usecn  !! the saved correction uses converged Newtonian light time
      logical :: uselt  !! the saved correction uses light time
      logical :: usestl  !! the saved correction uses stellar aberration
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svfref  !! name of the body-fixed frame looked up last (ZZNAMFRM)
      integer(ip) :: svrefc  !! ID code of the body-fixed frame looked up last
      integer(ip) :: svctr4 ( ctrsiz )  !! saved surface name/ID item declarations.
   end type subpnt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_subpnt_state(state)
      type(subpnt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%near = .false.
      state%nsurf = 0
      state%prvcor = ' '
      state%prvmth = ' '
      state%shape = 0
      state%srflst = 0
      state%usecn = .false.
      state%uselt = .false.
      state%usestl = .false.
      state%xmit = .false.
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%svctr3 = 0
      state%svfref = ' '
      state%svrefc = 0
      state%svctr4 = 0
      state%first = .true.
      state%near = .true.
      state%prvcor = ' '
      state%prvmth = ' '
      state%shape = -1
   end subroutine init_subpnt_state

end module pepper_state_subpnt
