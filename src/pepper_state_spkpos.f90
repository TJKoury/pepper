!> Return the position of a target body relative to an observing
!> body, optionally corrected for light time (planetary aberration)
!> and stellar aberration.
!>
!> The state of SPICELIB's SPKPOS routines (entry points spkpos),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkpos.f90.
module pepper_state_spkpos

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_spkpos_state

   !> The saved variables of SPKPOS.
   type, public :: spkpos_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtgid  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsn  !! name of the observer looked up last
      integer(ip) :: svobsi  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      logical :: first  !! first call: the pool counters are not yet initialized
   end type spkpos_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkpos_state(state)
      type(spkpos_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtgid = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsn = ' '
      state%svobsi = 0
      state%svfnd2 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_spkpos_state

end module pepper_state_spkpos
