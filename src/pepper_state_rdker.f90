!> Open and read the contents of a SPICE ASCII kernel file.
!>
!> The state of SPICELIB's RDKER routines (entry points rdknew, rdkdat, rdklin),
!> held in pepper_spice. Generated by tools/modularize_ctx.py from the
!> saved variables of rdker.f90.
module pepper_state_rdker

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip) :: mrklen
   parameter ( mrklen = 10 )
   integer(ip) :: filsiz
   parameter ( filsiz = 255 )

   public :: init_rdker_state

   !> The saved variables of RDKER.
   type, public :: rdker_state
      character(filsiz) :: file  !! the text kernel being read
      integer(ip) :: linnum  !! number of the last line read
      integer(ip) :: status  !! reading text, data, or at the end of the file
      logical :: frstim  !! no kernel has been opened yet
      character(mrklen) :: begdat  !! the begin-data marker
      character(mrklen) :: begtxt  !! the begin-text marker
   end type rdker_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_rdker_state(state)
      type(rdker_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%file = ' '
      state%linnum = 0
      state%status = 0
      state%frstim = .false.
      state%begdat = ' '
      state%begtxt = ' '
      state%file = ' '
      state%linnum = 0
      state%frstim = .true.
   end subroutine init_rdker_state

end module pepper_state_rdker
