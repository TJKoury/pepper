!> Encode and write characters to a text file.
!>
!> The state of SPICELIB's WRENCC routines (entry points wrencc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of wrencc.f90.
module pepper_state_wrencc

   use pepper_kinds, only: ip, wp

   implicit none

   private

   public :: init_wrencc_state

   !> The saved variables of WRENCC.
   type, public :: wrencc_state
      integer(ip) :: intesc  !! character code of the escape character
      integer(ip) :: intfpc  !! character code of the first printable character
      integer(ip) :: intlpc  !! character code of the last printable character
      integer(ip) :: intquo  !! character code of the quote character
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
   end type wrencc_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_wrencc_state(state)
      type(wrencc_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%intesc = 0
      state%intfpc = 0
      state%intlpc = 0
      state%intquo = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_wrencc_state

end module pepper_state_wrencc
