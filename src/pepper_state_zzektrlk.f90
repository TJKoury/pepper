!> Locate a specified key.  Return metadata describing the node
!> containing the key.
!>
!> The state of SPICELIB's ZZEKTRLK routines (entry points zzektrlk),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzektrlk.f90.
module pepper_state_zzektrlk

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'ekpage.inc'
   include 'ektree.inc'
   include 'ektype.inc'
   integer(ip), parameter :: acclen = 15

   public :: init_zzektrlk_state

   !> The saved variables of ZZEKTRLK.
   type, public :: zzektrlk_state
      integer(ip) :: oldhan  !! handle of the EK of the last lookup
      integer(ip) :: oldidx  !! index within its node of the last key found
      integer(ip) :: oldlvl  !! tree level of the node containing the last key found
      integer(ip) :: oldmax  !! number of keys in the node containing the last key found
      integer(ip) :: oldnod  !! number of the node containing the last key found
      integer(ip) :: oldnof  !! key offset of the node containing the last key found
      integer(ip) :: oldtre  !! root node of the tree of the last lookup
      integer(ip) :: oldkey  !! last key found
      integer(ip) :: oldval  !! value of the last key found
      integer(ip) :: page   ( pgsizi )  !! last node page read (the node of the last key found, after a successful lookup)
      logical :: first  !! no lookup done yet (the file access method is not known)
      logical :: leaf  !! the node containing the last key found is a leaf
      logical :: rdonly  !! the file of the last lookup is open read-only, so the cached node can be trusted
   end type zzektrlk_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzektrlk_state(state)
      type(zzektrlk_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%oldhan = 0
      state%oldidx = 0
      state%oldlvl = 0
      state%oldmax = 0
      state%oldnod = 0
      state%oldnof = 0
      state%oldtre = 0
      state%oldkey = 0
      state%oldval = 0
      state%page = 0
      state%first = .false.
      state%leaf = .false.
      state%rdonly = .false.
      state%oldhan = 0
      state%oldidx = 0
      state%oldlvl = 0
      state%oldmax = 0
      state%oldnod = 0
      state%oldnof = 0
      state%oldtre = 0
      state%oldkey = 0
      state%oldval = 0
      state%page = 0
      state%first = .true.
   end subroutine init_zzektrlk_state

end module pepper_state_zzektrlk
