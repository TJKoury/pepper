!> Map a DAS address to a physical location in a specified DAS file.
!>
!> The state of SPICELIB's DASA2L routines (entry points dasa2l),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dasa2l.f90.
module pepper_state_dasa2l

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: nwc = 1024
   integer(ip), parameter :: nwd = 128
   integer(ip), parameter :: nwi = 256
   integer(ip), parameter :: chrrng = 3
   integer(ip), parameter :: dprng = chrrng + 2
   integer(ip), parameter :: intrng = dprng  + 2
   integer(ip), parameter :: acclen = 10
   integer(ip), parameter :: maxfil = 20

   public :: init_dasa2l_state

   !> The saved variables of DASA2L.
   type, public :: dasa2l_state
      integer(ip) :: fidx  !! saved between calls by DASA2L
      integer(ip) :: next   ( 3 )  !! saved between calls by DASA2L
      integer(ip) :: nfiles  !! saved between calls by DASA2L
      integer(ip) :: nw     ( 3 )  !! saved between calls by DASA2L
      integer(ip) :: prev   ( 3 )  !! saved between calls by DASA2L
      integer(ip) :: prvhan  !! saved between calls by DASA2L
      integer(ip) :: rngloc ( 3 )  !! saved between calls by DASA2L
      integer(ip) :: tbbase ( 3, maxfil )  !! saved between calls by DASA2L
      integer(ip) :: tbfwrd (    maxfil )  !! saved between calls by DASA2L
      integer(ip) :: tbhan  (    maxfil )  !! saved between calls by DASA2L
      integer(ip) :: tbmxad ( 3, maxfil )  !! saved between calls by DASA2L
      integer(ip) :: tbsize ( 3, maxfil )  !! saved between calls by DASA2L
      logical :: fast  !! saved between calls by DASA2L
      logical :: prvok  !! saved between calls by DASA2L
      logical :: tbfast ( maxfil )  !! saved between calls by DASA2L
      logical :: tbrdon ( maxfil )  !! saved between calls by DASA2L
   end type dasa2l_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dasa2l_state(state)
      type(dasa2l_state), intent(inout) :: state  !! the state
      state%fidx = 0
      state%next = [ 2, 3, 1 ]
      state%nfiles = 0
      state%nw = [ nwc, nwd, nwi ]
      state%prev = [ 3, 1, 2 ]
      state%prvhan = 0
      state%rngloc = [ chrrng, dprng, intrng ]
      state%tbbase = -1
      state%tbfwrd = -1
      state%tbhan = 0
      state%tbmxad = -1
      state%tbsize = -1
      state%fast = .false.
      state%prvok = .false.
      state%tbfast = .false.
      state%tbrdon = .false.
   end subroutine init_dasa2l_state

end module pepper_state_dasa2l
