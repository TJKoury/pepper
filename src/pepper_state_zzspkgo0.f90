!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKGO0 routines (entry points zzspkgo0),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkgo0.f90.
module pepper_state_zzspkgo0

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'ninert.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_zzspkgo0_state

   !> The saved variables of ZZSPKGO0.
   type, public :: zzspkgo0_state
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the reference frame
      character(frnmln) :: svref  !! saved reference frame name for the zznamfrm lookup
      integer(ip) :: svrefi  !! saved reference frame ID code for the zznamfrm lookup
      logical :: first  !! first call: the frame name counter is not yet initialized
   end type zzspkgo0_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkgo0_state(state)
      type(zzspkgo0_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svref = ' '
      state%svrefi = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_zzspkgo0_state

end module pepper_state_zzspkgo0
