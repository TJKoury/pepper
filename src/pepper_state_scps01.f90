!> Convert a character representation of a type 1 spacecraft clock
!> count to ticks.
!>
!> The state of SPICELIB's SCPS01 routines (entry points scps01),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of scps01.f90.
module pepper_state_scps01

   use pepper_kinds, only: ip, wp
      use pepper_inc_sclk

   implicit none

   private

   integer(ip), parameter :: errlen = 240
   integer(ip), parameter :: namlen = 60
   integer(ip), parameter :: nflidx = 1
   integer(ip), parameter :: offidx = nflidx + 1
   integer(ip), parameter :: modidx = offidx + 1
   integer(ip), parameter :: nkitem = modidx

   public :: init_scps01_state

   !> The saved variables of SCPS01.
   type, public :: scps01_state
      character(errlen) :: strerr  !! work: error message from parsing a clock string field (NPARSD)
      character(namlen) :: namlst ( nkitem )  !! constant kernel variable names: SCLK01_N_FIELDS, SCLK01_OFFSETS, SCLK01_MODULI
      real(wp) :: cmptks ( mxnfld )  !! work: number of ticks per unit of each clock field
      real(wp) :: cmpval ( mxnfld )  !! work: values of the clock string fields, offset-corrected
   end type scps01_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_scps01_state(state)
      type(scps01_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%strerr = ' '
      state%namlst = ' '
      state%cmptks = 0.0_wp
      state%cmpval = 0.0_wp
      state%namlst = [ character(len(state%namlst)) :: 'SCLK01_N_FIELDS', 'SCLK01_OFFSETS', 'SCLK01_MODULI' ]
   end subroutine init_scps01_state

end module pepper_state_scps01
