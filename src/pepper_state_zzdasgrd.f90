!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDASGRD routines (entry points zzdasgrd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdasgrd.f90.
module pepper_state_zzdasgrd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'das.inc'

   public :: init_zzdasgrd_state

   !> The saved variables of ZZDASGRD.
   type, public :: zzdasgrd_state
      logical :: first  !! saved between calls by ZZDASGRD
      integer(ip) :: intbff  !! saved between calls by ZZDASGRD
      integer(ip) :: natbff  !! saved between calls by ZZDASGRD
   end type zzdasgrd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdasgrd_state(state)
      type(zzdasgrd_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzdasgrd_state

end module pepper_state_zzdasgrd
