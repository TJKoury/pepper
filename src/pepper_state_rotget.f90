!> Find the rotation from a user specified frame to another frame at
!> a user specified epoch.
!>
!> The state of SPICELIB's ROTGET routines (entry points rotget),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of rotget.f90.
module pepper_state_rotget

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'frmtyp.inc'

   public :: init_rotget_state

   !> The saved variables of ROTGET.
   type, public :: rotget_state
      character(6) :: versn  !! ROTGET version string, used in error messages
   end type rotget_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_rotget_state(state)
      type(rotget_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%versn = ' '
      state%versn = '5.0.0'
   end subroutine init_rotget_state

end module pepper_state_rotget
