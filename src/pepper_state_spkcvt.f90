!> Return the state, relative to a specified observer, of a target
!> having constant velocity in a specified reference frame. The
!> target's state is provided by the calling program rather than by
!> loaded SPK files.
!>
!> The state of SPICELIB's SPKCVT routines (entry points spkcvt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkcvt.f90.
module pepper_state_spkcvt

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzabcorr.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: nevflg = 3
   integer(ip), parameter :: evlfln = 25
   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_spkcvt_state

   !> The saved variables of SPKCVT.
   type, public :: spkcvt_state
      character(evlfln) :: evlflg ( nevflg )  !! recognized frame evaluation loci (OBSERVER, TARGET, CENTER)
      integer(ip) :: j2code  !! inertial frame code (IRFNUM) of J2000
      logical :: first  !! first call: counters, correction flags and J2000 code not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: uselt  !! the saved correction includes light time correction
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtctr  !! name of the target's center of motion looked up last (ZZBODS2C)
      integer(ip) :: svccde  !! ID code of the target's center of motion looked up last
      logical :: svfnd1  !! found flag of the last target center name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svoref  !! name of the output frame looked up last (ZZNAMFRM)
      integer(ip) :: svorfc  !! ID code of the output frame looked up last
   end type spkcvt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkcvt_state(state)
      type(spkcvt_state), intent(inout) :: state  !! the state
      state%evlflg = [ character(len(state%evlflg)) :: 'OBSERVER', 'TARGET', 'CENTER' ]
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_spkcvt_state

end module pepper_state_spkcvt
