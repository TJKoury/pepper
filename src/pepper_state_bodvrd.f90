!> Fetch from the kernel pool the double precision values
!> of an item associated with a body.
!>
!> The state of SPICELIB's BODVRD routines (entry points bodvrd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of bodvrd.f90.
module pepper_state_bodvrd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzctr.inc'
   integer(ip), parameter :: maxl = 36

   public :: init_bodvrd_state

   !> The saved variables of BODVRD.
   type, public :: bodvrd_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svbdnm  !! saved between calls by BODVRD
      integer(ip) :: svbdid  !! saved between calls by BODVRD
      logical :: svfnd1  !! saved between calls by BODVRD
      logical :: first  !! saved between calls by BODVRD
   end type bodvrd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_bodvrd_state(state)
      type(bodvrd_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_bodvrd_state

end module pepper_state_bodvrd
