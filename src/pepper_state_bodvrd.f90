!> Fetch from the kernel pool the double precision values
!> of an item associated with a body.
!>
!> The state of SPICELIB's BODVRD routines (entry points bodvrd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of bodvrd.f90.
module pepper_state_bodvrd

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: maxl = 36

   public :: init_bodvrd_state

   !> The saved variables of BODVRD.
   type, public :: bodvrd_state
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C)
      character(maxl) :: svbdnm  !! the body name translated last
      integer(ip) :: svbdid  !! its NAIF ID code
      logical :: svfnd1  !! the name was found
      logical :: first  !! no name has been translated yet
   end type bodvrd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_bodvrd_state(state)
      type(bodvrd_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svbdnm = ' '
      state%svbdid = 0
      state%svfnd1 = .false.
      state%first = .false.
      state%first = .true.
   end subroutine init_bodvrd_state

end module pepper_state_bodvrd
