!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSFXCOR routines (entry points zzsfxcor),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsfxcor.f90.
module pepper_state_zzsfxcor

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'frmtyp.inc'
   include 'zzabcorr.inc'

   public :: init_zzsfxcor_state

   !> The saved variables of ZZSFXCOR.
   type, public :: zzsfxcor_state
      logical :: first  !! first call: no aberration correction has been parsed yet
      character(corlen) :: loccor  !! correction string for SPKEZP derived from the previous ABCORR (stellar aberration removed)
      character(corlen) :: prvcor  !! aberration correction string of the previous call
   end type zzsfxcor_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsfxcor_state(state)
      type(zzsfxcor_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%loccor = ' '
      state%prvcor = ' '
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_zzsfxcor_state

end module pepper_state_zzsfxcor
