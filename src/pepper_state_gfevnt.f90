!> Determine time intervals when a specified geometric quantity
!> satisfies a specified mathematical condition.
!>
!> The state of SPICELIB's GFEVNT routines (entry points gfevnt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of gfevnt.f90.
module pepper_state_gfevnt

   use pepper_kinds, only: ip, wp
      use pepper_inc_gf
      use pepper_inc_zzgf
      use pepper_inc_zzabcorr

   implicit none

   private

   integer(ip), parameter :: nq = 8
   integer(ip), parameter :: nc = 7
   integer(ip), parameter :: maxcln = 80

   public :: init_gfevnt_state

   !> The saved variables of GFEVNT.
   type, public :: gfevnt_state
      logical :: first  !! first call: progress report prefixes and suffixes not yet set up
      character(maxcln) :: cnames ( nc )  !! recognized relational operators (constant)
      character(maxcln) :: dref  !! frame of the DVEC ray for coordinate searches (DREF; kept if not supplied)
      character(maxcln) :: qnames ( nq     )  !! recognized geometric quantity names (constant)
      character(mxbegm) :: srcpre ( 2, nq )  !! progress report prefixes for each pass of each quantity
      character(mxendm) :: srcsuf ( 2, nq )  !! progress report suffixes for each pass of each quantity
   end type gfevnt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_gfevnt_state(state)
      type(gfevnt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%cnames = ' '
      state%dref = ' '
      state%qnames = ' '
      state%srcpre = ' '
      state%srcsuf = ' '
      state%first = .true.
      state%cnames = [ character(len(state%cnames)) :: '>', '=', '<', 'ABSMAX', 'ABSMIN', 'LOCMAX', 'LOCMIN' ]
      state%dref = ' '
      state%qnames = [ character(len(state%qnames)) :: 'ANGULAR SEPARATION', 'DISTANCE', 'COORDINATE', 'RANGE RATE', 'PHASE ANGLE', 'ILLUMINATION ANGLE', ' ', ' ' ]
   end subroutine init_gfevnt_state

end module pepper_state_gfevnt
