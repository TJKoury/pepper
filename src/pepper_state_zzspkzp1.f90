!> Return the position of a target body relative to an observing
!> body, optionally corrected for light time (planetary aberration)
!> and stellar aberration.
!>
!> The state of SPICELIB's ZZSPKZP1 routines (entry points zzspkzp1),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkzp1.f90.
module pepper_state_zzspkzp1

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'frmtyp.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_zzspkzp1_state

   !> The saved variables of ZZSPKZP1.
   type, public :: zzspkzp1_state
      integer(ip) :: fj2000  !! frame ID code of J2000
      logical :: first  !! first call: J2000 code and counter not yet set up
      integer(ip) :: svctr1 ( ctrsiz )  !! pool counter of the frame name lookup (ZZNAMFRM) of the reference frame
      character(frnmln) :: svref  !! saved output frame name for the zznamfrm lookup
      integer(ip) :: svreqf  !! saved output frame ID code for the zznamfrm lookup
   end type zzspkzp1_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkzp1_state(state)
      type(zzspkzp1_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%fj2000 = 0
      state%first = .false.
      state%svctr1 = 0
      state%svref = ' '
      state%svreqf = 0
      state%first = .true.
   end subroutine init_zzspkzp1_state

end module pepper_state_zzspkzp1
