!> Perform a coordinate search.
!>
!> The state of SPICELIB's ZZGFCSLV routines (entry points zzgfcslv),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfcslv.f90.
module pepper_state_zzgfcslv

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'gf.inc'
   include               'zzgf.inc'
   integer(ip), parameter :: mxpass = 3
   integer(ip), parameter :: nc = 7
   integer(ip), parameter :: maxop = 6

   public :: init_zzgfcslv_state

   !> The saved variables of ZZGFCSLV.
   type, public :: zzgfcslv_state
      character(maxop) :: cnames ( nc )  !! recognized relational operators (constant)
      character(mxbegm) :: rptpre ( mxpass )  !! progress report prefixes for each pass (constant)
      character(mxendm) :: rptsuf ( mxpass )  !! progress report suffixes for each pass (constant)
   end type zzgfcslv_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfcslv_state(state)
      type(zzgfcslv_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%cnames = ' '
      state%rptpre = ' '
      state%rptsuf = ' '
      state%cnames = [ character(len(state%cnames)) :: '>', '=', '<', 'ABSMAX', 'ABSMIN', 'LOCMAX', 'LOCMIN' ]
      state%rptpre = [ character(len(state%rptpre)) :: 'Coordinate pass 1 of # ', 'Coordinate pass 2 of # ', 'Intercept existence pass 1 of 1' ]
      state%rptsuf = 'done.'
   end subroutine init_zzgfcslv_state

end module pepper_state_zzgfcslv
