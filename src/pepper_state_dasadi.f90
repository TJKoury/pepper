!> Add an array of integers to a DAS file.
!>
!> The state of SPICELIB's DASADI routines (entry points dasadi),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of dasadi.f90.
module pepper_state_dasadi

   use pepper_kinds, only: ip, wp

   implicit none

   private

   integer(ip), parameter :: nwi = 256

   public :: init_dasadi_state

   !> The saved variables of DASADI.
   type, public :: dasadi_state
      integer(ip) :: record ( nwi )  !! work buffer of one integer record (saved in SPICELIB to keep
                                     !! it off the stack)
   end type dasadi_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_dasadi_state(state)
      type(dasadi_state), intent(inout) :: state  !! the state
      state%record = 0
   end subroutine init_dasadi_state

end module pepper_state_dasadi
