!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSPKFZO routines (entry points zzspkfzo),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzspkfzo.f90.
module pepper_state_zzspkfzo

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'frmtyp.inc'
   include              'zzabcorr.inc'

   public :: init_zzspkfzo_state

   !> The saved variables of ZZSPKFZO.
   type, public :: zzspkfzo_state
      integer(ip) :: fj2000  !! frame ID code of J2000
      logical :: pass1  !! first call: correction flags and J2000 code not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: usegeo  !! the saved correction is geometric (no aberration correction)
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
   end type zzspkfzo_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzspkfzo_state(state)
      type(zzspkfzo_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%fj2000 = 0
      state%pass1 = .false.
      state%prvcor = ' '
      state%usegeo = .false.
      state%xmit = .false.
      state%pass1 = .true.
      state%prvcor = ' '
   end subroutine init_zzspkfzo_state

end module pepper_state_zzspkfzo
