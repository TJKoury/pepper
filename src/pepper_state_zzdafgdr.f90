!> SPICE Private routine intended solely for the support of SPICE
!> routines.  Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDAFGDR routines (entry points zzdafgdr),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzdafgdr.f90.
module pepper_state_zzdafgdr

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include              'zzddhman.inc'

   public :: init_zzdafgdr_state

   !> The saved variables of ZZDAFGDR.
   type, public :: zzdafgdr_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      integer(ip) :: natbff  !! code of the native binary file format
      character(strsiz) :: strbff ( numbff )  !! names of the binary file formats
   end type zzdafgdr_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzdafgdr_state(state)
      type(zzdafgdr_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%first = .false.
      state%natbff = 0
      state%strbff = ' '
      state%first = .true.
      state%natbff = 0
   end subroutine init_zzdafgdr_state

end module pepper_state_zzdafgdr
