!> SPICE private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZHOLDD routines (entry points zzholdd),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzholdd.f90.
module pepper_state_zzholdd

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzholdd.inc'

   public :: init_zzholdd_state

   !> The saved variables of ZZHOLDD.
   type, public :: zzholdd_state
      real(wp) :: svalue  (nid)  !! the stored value of each ID (GF_REF, GF_TOL, GF_DT, ...)
      logical :: first   (nid)  !! no value has been put for the ID yet (or it was reset)
      logical :: init  !! first call: the FIRST flags not yet initialized
   end type zzholdd_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzholdd_state(state)
      type(zzholdd_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svalue = 0.0_wp
      state%first = .false.
      state%init = .false.
      state%init = .true.
   end subroutine init_zzholdd_state

end module pepper_state_zzholdd
