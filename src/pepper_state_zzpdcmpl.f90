!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZPDCMPL routines (entry points zzpdcmpl),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzpdcmpl.f90.
module pepper_state_zzpdcmpl

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzpdcmpl_state

   !> The saved variables of ZZPDCMPL.
   type, public :: zzpdcmpl_state
      real(wp) :: apex   ( 3 )  !! apex of the latitude cone (X and Y are zero; Z is set on each call)
   end type zzpdcmpl_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzpdcmpl_state(state)
      type(zzpdcmpl_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%apex = 0.0_wp
      state%apex = 0.0_wp
   end subroutine init_zzpdcmpl_state

end module pepper_state_zzpdcmpl
