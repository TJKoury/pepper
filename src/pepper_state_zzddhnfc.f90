!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZDDHNFC routines (entry points zzddhnfc),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzddhnfc.f90.
module pepper_state_zzddhnfc

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include 'zzddhman.inc'

   public :: init_zzddhnfc_state

   !> The saved variables of ZZDDHNFC.
   type, public :: zzddhnfc_state
      logical :: first  !! the tables have not been set up yet (they are set up on the first call)
      integer(ip) :: savbff  !! code of the native binary file format
      character(strsiz) :: strbff ( numbff )  !! names of the binary file formats
   end type zzddhnfc_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzddhnfc_state(state)
      type(zzddhnfc_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzddhnfc_state

end module pepper_state_zzddhnfc
