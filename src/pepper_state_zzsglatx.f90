!> SPICE Private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due
!> to the volatile nature of this routine.
!>
!> The state of SPICELIB's ZZSGLATX routines (entry points zzsglatx),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzsglatx.f90.
module pepper_state_zzsglatx

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzsglatx_state

   !> The saved variables of ZZSGLATX.
   type, public :: zzsglatx_state
      real(wp) :: z      ( 3 )  !! the +Z unit vector
   end type zzsglatx_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzsglatx_state(state)
      type(zzsglatx_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%z = 0.0_wp
      state%z = [ 0.0_wp, 0.0_wp, 1.0_wp ]
   end subroutine init_zzsglatx_state

end module pepper_state_zzsglatx
