!> Return the state of a specified target relative to an "observer,"
!> where the observer has constant velocity in a specified reference
!> frame. The observer's state is provided by the calling program
!> rather than by loaded SPK files.
!>
!> The state of SPICELIB's SPKCVO routines (entry points spkcvo),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkcvo.f90.
module pepper_state_spkcvo

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'zzabcorr.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: nevflg = 3
   integer(ip), parameter :: evlfln = 25
   integer(ip), parameter :: maxl = 36
   integer(ip), parameter :: frnmln = 32

   public :: init_spkcvo_state

   !> The saved variables of SPKCVO.
   type, public :: spkcvo_state
      character(evlfln) :: evlflg ( nevflg )  !! recognized frame evaluation loci (OBSERVER, TARGET, CENTER)
      integer(ip) :: j2code  !! inertial frame code (IRFNUM) of J2000
      logical :: first  !! first call: counters, correction flags and J2000 code not yet set up
      character(corlen) :: prvcor  !! aberration correction string of the previous call
      logical :: uselt  !! the saved correction includes light time correction
      logical :: xmit  !! the saved correction is for transmitted (rather than received) radiation
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svoctr  !! name of the observer's center of motion looked up last (ZZBODS2C)
      integer(ip) :: svccde  !! ID code of the observer's center of motion looked up last
      logical :: svfnd1  !! found flag of the last observer center name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the target
      character(maxl) :: svtarg  !! name of the target looked up last
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd2  !! found flag of the last target name lookup
      integer(ip) :: svctr3 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svoref  !! name of the output frame looked up last (ZZNAMFRM)
      integer(ip) :: svorfc  !! ID code of the output frame looked up last
   end type spkcvo_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkcvo_state(state)
      type(spkcvo_state), intent(inout) :: state  !! the state
      state%evlflg = [ character(len(state%evlflg)) :: 'OBSERVER', 'TARGET', 'CENTER' ]
      state%first = .true.
      state%prvcor = ' '
   end subroutine init_spkcvo_state

end module pepper_state_spkcvo
