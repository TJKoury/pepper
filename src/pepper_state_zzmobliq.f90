!> Return the mean obliquity of the ecliptic, and its time
!> derivative, at a specified epoch.
!>
!> The state of SPICELIB's ZZMOBLIQ routines (entry points zzmobliq),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzmobliq.f90.
module pepper_state_zzmobliq

   use pepper_kinds, only: ip, wp

   implicit none

   private


   public :: init_zzmobliq_state

   !> The saved variables of ZZMOBLIQ.
   type, public :: zzmobliq_state
      real(wp) :: rad  !! radians per degree
      real(wp) :: year  !! seconds per Julian year
      real(wp) :: persec  !! Julian centuries per second
      logical :: first  !! true until the constants above have been set
   end type zzmobliq_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzmobliq_state(state)
      type(zzmobliq_state), intent(inout) :: state  !! the state
      state%first = .true.
   end subroutine init_zzmobliq_state

end module pepper_state_zzmobliq
