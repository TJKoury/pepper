!> **Deprecated:** This routine has been superseded by the SPICELIB
!> routine SUBPNT. This routine is supported for purposes of
!> backward compatibility only.
!>
!> The state of SPICELIB's SUBPT routines (entry points subpt),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of subpt.f90.
module pepper_state_subpt

   use pepper_kinds, only: ip, wp
      use pepper_inc_zzctr

   implicit none

   private

   integer(ip), parameter :: maxl = 36

   public :: init_subpt_state

   !> The saved variables of SUBPT.
   type, public :: subpt_state
      real(wp) :: origin ( 3 )  !! the origin (zero vector), constant
      integer(ip) :: svctr1 ( ctrsiz )  !! saved name/ID item declarations.
      character(maxl) :: svtarg  !! name of the target looked up last (ZZBODS2C)
      integer(ip) :: svtcde  !! ID code of the target looked up last
      logical :: svfnd1  !! found flag of the last target name lookup
      integer(ip) :: svctr2 ( ctrsiz )  !! pool counter of the body name lookup (ZZBODS2C) of the observer
      character(maxl) :: svobsr  !! name of the observer looked up last
      integer(ip) :: svobsc  !! ID code of the observer looked up last
      logical :: svfnd2  !! found flag of the last observer name lookup
      logical :: first  !! first call: the pool counters are not yet initialized
   end type subpt_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_subpt_state(state)
      type(subpt_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%origin = 0.0_wp
      state%svctr1 = 0
      state%svtarg = ' '
      state%svtcde = 0
      state%svfnd1 = .false.
      state%svctr2 = 0
      state%svobsr = ' '
      state%svobsc = 0
      state%svfnd2 = .false.
      state%first = .false.
      state%origin = 0.0_wp
      state%first = .true.
   end subroutine init_subpt_state

end module pepper_state_subpt
