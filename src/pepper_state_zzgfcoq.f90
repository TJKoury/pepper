!> SPICE private routine intended solely for the support of SPICE
!> routines. Users should not call this routine directly due to the
!> volatile nature of this routine.
!>
!> The state of SPICELIB's ZZGFCOQ routines (entry points zzgfcoq),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of zzgfcoq.f90.
module pepper_state_zzgfcoq

   use pepper_kinds, only: ip, wp
      use pepper_inc_gf
      use pepper_inc_zzgf

   implicit none

   private

   integer(ip), parameter :: bdnmln = 36
   integer(ip), parameter :: crdlen = 32
   integer(ip), parameter :: nsys = 7

   public :: init_zzgfcoq_state

   !> The saved variables of ZZGFCOQ.
   type, public :: zzgfcoq_state
      character(bdnmln) :: ctrnam  !! name of the body with ID prvctr (center of the planetographic frame)
      logical :: first  !! first call: target, observer and center names not yet looked up
      character(bdnmln) :: obsnam  !! name of the observer with ID prvobs
      integer(ip) :: prvctr  !! frame center ID code of the previous call
      integer(ip) :: prvobs  !! observer ID code of the previous call
      integer(ip) :: prvtrg  !! target ID code of the previous call
      character(crdlen) :: sysnms (    nsys )  !! recognized coordinate system names (constant)
      character(bdnmln) :: trgnam  !! name of the target with ID prvtrg
   end type zzgfcoq_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_zzgfcoq_state(state)
      type(zzgfcoq_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%ctrnam = ' '
      state%first = .false.
      state%obsnam = ' '
      state%prvctr = 0
      state%prvobs = 0
      state%prvtrg = 0
      state%sysnms = ' '
      state%trgnam = ' '
      state%first = .true.
      state%obsnam = ' '
      state%prvctr = 0
      state%prvobs = 0
      state%prvtrg = 0
      state%sysnms = [ character(len(state%sysnms)) :: recsys, latsys, radsys, sphsys, cylsys, geosys, pgrsys ]
      state%trgnam = ' '
   end subroutine init_zzgfcoq_state

end module pepper_state_zzgfcoq
