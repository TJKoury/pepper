!> Compute the geometric position of a target body relative to an
!> observing body.
!>
!> The state of SPICELIB's SPKGPS routines (entry points spkgps),
!> held in pepper_context (one per thread). Generated by tools/modularize_ctx.py from the
!> saved variables of spkgps.f90.
module pepper_state_spkgps

   use pepper_kinds, only: ip, wp

   implicit none

   private

   include               'ninert.inc'
   include               'zzctr.inc'
   integer(ip), parameter :: frnmln = 32

   public :: init_spkgps_state

   !> The saved variables of SPKGPS.
   type, public :: spkgps_state
      integer(ip) :: svctr1 ( ctrsiz )  !! saved frame name/ID item declarations.
      character(frnmln) :: svref  !! saved reference frame name for the zznamfrm lookup
      integer(ip) :: svrefi  !! saved reference frame ID code for the zznamfrm lookup
      logical :: first  !! first call: the frame name counter is not yet initialized
   end type spkgps_state

contains

   !> Set the initial values (SPICELIB's DATA statements) of a new state.
   pure subroutine init_spkgps_state(state)
      type(spkgps_state), intent(inout) :: state  !! the state
      ! (every component first: SPICELIB's saved variables start as zero)
      state%svctr1 = 0
      state%svref = ' '
      state%svrefi = 0
      state%first = .false.
      state%first = .true.
   end subroutine init_spkgps_state

end module pepper_state_spkgps
